/** The routes, as data.
 *
 * **Authenticated unless the application cannot sign anyone in**: the gate is a
 * navigation guard that asks who the user is once and sends an anonymous visitor
 * to the login page. An app with no auth endpoints gets no guard and no login
 * page — that statement is about a scaffold's *routes*, and it cannot lock a
 * door that has no key. */
function routerTs(ctx) {
  const imports = ctx.tables
    .map((t) => `import ${t.pascal} from "./pages/${t.pascal}.vue";`)
    .join("\n");
  const routes = ctx.tables
    .map((t) => `  { path: "/${t.name}", component: ${t.pascal} },`)
    .join("\n");
  let out = `import { createRouter, createWebHistory } from "vue-router";

import Home from "./pages/Home.vue";
${imports}${imports ? "\n" : ""}`;
  if (ctx.auth) out += `import Login from "./Login.vue";\nimport { currentUser } from "./auth";\n`;
  out += `
export const router = createRouter({
  history: createWebHistory(),
  routes: [
    { path: "/", component: Home },
${routes}${routes ? "\n" : ""}`;
  if (ctx.auth) out += `    { path: "/login", component: Login, meta: { public: true } },\n`;
  out += `  ],
});
`;
  if (ctx.auth) {
    out += `
// Asked once and cached: \`currentUser\` calls the API the first time and answers
// from the ref afterwards, so a click between two pages does not become a second
// round trip.
router.beforeEach(async (to) => {
  if (to.meta.public) return true;
  return (await currentUser()) ? true : { path: "/login" };
});
`;
  }
  return out;
}

/** The auth layer: module-level state, because who is signed in is a property of
 * the session and not of any one component.
 *
 * Generated only when the application exposes `login` / `logout` / `whoami`
 * through its API — all three or none, since a partial set means the provider
 * changed underneath and half an auth layer against it does not compile. */
const AUTH_TS = `import { ref } from "vue";

import { api } from "./feldspar/composables";

export type User = { id: string; email: string; role: number };

/** The signed-in user: \`null\` when anonymous, \`undefined\` until asked. */
export const user = ref<User | null | undefined>(undefined);

/** The user, asking the server the first time and answering from the ref after.
 *
 * A 401 from \`whoami\` is the ordinary anonymous case, not an error to report. */
export async function currentUser(): Promise<User | null> {
  if (user.value === undefined) {
    user.value = await api.whoami().then(
      (u) => u,
      () => null,
    );
  }
  return user.value;
}

export async function signIn(email: string, password: string): Promise<void> {
  user.value = await api.login({ email, password });
}

export async function signOut(): Promise<void> {
  await api.logout();
  user.value = null;
}
`;

