/** `composables.ts`: a read, a write, and an invalidation, typed per table.
 *
 * The same three primitives React's `hooks.ts` supplies, over the same
 * one-version-counter-per-table cache — every read subscribes to its table,
 * every write bumps it. Keys are table names, which the server already
 * guarantees to be unique, so there is no query-key scheme to invent or get
 * wrong.
 *
 * Each composable answers **refs**, not unwrapped values, so a page destructures
 * them into top-level bindings (`const { data, loading } = useTasks()`) and Vue
 * unwraps them in the template. That is the one shape that is correct both in
 * `<script setup>` and in `<template>` without a `.value` sprinkled through the
 * markup. */
function composablesTs(ctx) {
  const rowTypes = ctx.tables.flatMap(usedRowTypes);
  let out = GENERATED;
  out += `
import { ref, shallowRef, watchEffect, type Ref } from "vue";
import { createClient, type ApiClient } from "./client";
`;
  if (rowTypes.length) out += `import type { ${rowTypes.join(", ")} } from "./client";\n`;
  out += `
/** The app's typed API client. Endpoint paths already include the API mount. */
export const api: ApiClient = createClient();

/** The state of one read: data, plus what is happening to it. */
export type Query<T> = {
  data: Ref<T | undefined>;
  error: Ref<Error | undefined>;
  loading: Ref<boolean>;
  /** Re-run this query (and any other on the same table). */
  refresh: () => void;
};

/** The state of one write. */
export type Mutation<A> = {
  run: (arg: A) => Promise<void>;
  pending: Ref<boolean>;
  error: Ref<Error | undefined>;
};

// One version counter per table: every read watches its table's counter, every
// write bumps it.
const versions = new Map<string, Ref<number>>();

function versionOf(table: string): Ref<number> {
  const known = versions.get(table);
  if (known) return known;
  const fresh = ref(0);
  versions.set(table, fresh);
  return fresh;
}

/** Discard what is cached for \`table\`, re-running every query over it. */
export function invalidate(table: string): void {
  versionOf(table).value += 1;
}

/**
 * Read something from the API, cached under \`table\` and re-run whenever
 * anything writes to that table.
 *
 * Exported because the per-table composables below cannot cover a custom
 * endpoint, and an app that adds one should be able to join the same cache
 * rather than build a second one beside it.
 */
export function useQuery<T>(table: string, load: () => Promise<T>): Query<T> {
  const data = shallowRef<T | undefined>(undefined);
  const error = shallowRef<Error | undefined>(undefined);
  const loading = ref(true);
  const version = versionOf(table);

  // Stopped automatically when the component that called this unmounts, which is
  // what makes a composable safe to call in \`setup\` and nowhere else.
  watchEffect((onCleanup) => {
    let cancelled = false;
    onCleanup(() => {
      cancelled = true;
    });
    // Read the counter, so this effect re-runs when the table is invalidated.
    void version.value;
    loading.value = true;
    load().then(
      (value) => {
        if (cancelled) return;
        data.value = value;
        error.value = undefined;
        loading.value = false;
      },
      (e: unknown) => {
        if (cancelled) return;
        data.value = undefined;
        error.value = e instanceof Error ? e : new Error(String(e));
        loading.value = false;
      },
    );
  });

  return { data, error, loading, refresh: () => invalidate(table) };
}

/**
 * Write through \`fn\`, then invalidate \`table\` so every query over it re-runs.
 * Exported for the same reason as \`useQuery\`.
 */
export function useMutation<A>(table: string, fn: (arg: A) => Promise<unknown>): Mutation<A> {
  const pending = ref(false);
  const error = shallowRef<Error | undefined>(undefined);
  const run = async (arg: A): Promise<void> => {
    pending.value = true;
    error.value = undefined;
    try {
      await fn(arg);
      invalidate(table);
    } catch (e: unknown) {
      error.value = e instanceof Error ? e : new Error(String(e));
    } finally {
      pending.value = false;
    }
  };
  return { run, pending, error };
}
`;
  for (const table of ctx.tables) out += `\n${tableComposables(table)}`;
  return out;
}

/** One table's composables, over that table's own object on the client. */
function tableComposables(table) {
  const { name, pascal, client, pk, pk_ts_type: key } = table;
  // What is re-exported follows the React generator's rule, because it follows
  // the *client's*: the insert and update types are emitted together for a table
  // the app lets anything write to.
  const exported = [`type ${pascal}Row`];
  if (table.ops.create || table.ops.update) {
    exported.push(`type ${pascal}Insert`, `type ${pascal}Update`);
  }

  let out = `// --- ${name} ---

// The row types come from the generated client, which derives them from this
// table's own columns; re-exported so a page imports its types and its
// composables from one place.
export { ${exported.join(", ")} } from "./client";

/** Every row of \`${name}\`, re-fetched when anything writes to it. */
export function use${pascal}(): Query<${pascal}Row[]> {
  return useQuery("${name}", () => api.${client}.list());
}
`;
  if (table.ops.create) {
    out += `
/** Insert a row into \`${name}\`. */
export function useCreate${pascal}(): Mutation<${pascal}Insert> {
  return useMutation("${name}", (row) => api.${client}.create(row));
}
`;
  }
  // Row-addressed operations: the API projects these only for a table with a
  // single-column primary key, so the composables follow the endpoints rather
  // than re-deciding it.
  if (pk) {
    if (table.ops.update) {
      out += `
/** Change a row of \`${name}\`. */
export function useUpdate${pascal}(): Mutation<{ id: ${key}; row: ${pascal}Update }> {
  return useMutation("${name}", ({ id, row }) => api.${client}.update(id, row));
}
`;
    }
    if (table.ops.delete) {
      out += `
/** Delete a row of \`${name}\`. */
export function useDelete${pascal}(): Mutation<${key}> {
  return useMutation("${name}", (id) => api.${client}.delete(id));
}
`;
    }
  }
  return out;
}

