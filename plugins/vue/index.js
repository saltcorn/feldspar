/** The whole project, written once when the application is created.
 *
 * Paths are relative to the project directory. The generated client, its helper,
 * `schema.sql` and `SKILL.md` are **not** here: Saltcorn writes those into
 * `ctx.runtime` for every framework, from the application's own API. */
function scaffold(ctx) {
  const files = [
    { path: "package.json", contents: packageJson(ctx) },
    { path: "vite.config.ts", contents: VITE_CONFIG },
    { path: "tsconfig.json", contents: TSCONFIG },
    { path: "index.html", contents: indexHtml(ctx) },
    { path: ".gitignore", contents: GITIGNORE },
    { path: "AGENTS.md", contents: agentsMd(ctx) },
    { path: "src/main.ts", contents: mainTs() },
    { path: "src/App.vue", contents: appVue(ctx) },
    { path: "src/router.ts", contents: routerTs(ctx) },
    { path: "src/app.css", contents: APP_CSS },
    { path: "src/pages/Home.vue", contents: homeVue(ctx) },
  ];
  if (ctx.auth) {
    files.push({ path: "src/auth.ts", contents: AUTH_TS });
    files.push({ path: "src/Login.vue", contents: LOGIN_VUE });
  }
  for (const table of ctx.tables) {
    files.push({ path: `src/pages/${table.pascal}.vue`, contents: pageVue(table) });
  }
  return files.concat(runtime(ctx));
}

/** The framework's own generated code, rewritten on every build and whenever the
 * application's definition changes — so a table added in the admin UI has a
 * `useNewTable()` at the next build, with nobody regenerating anything by hand. */
function runtime(ctx) {
  return [
    { path: at(ctx.runtime, "composables.ts"), contents: composablesTs(ctx) },
    { path: at(ctx.runtime, "README.md"), contents: runtimeReadme(ctx) },
  ];
}

