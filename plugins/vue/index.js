// **Vue as an application framework** — the bundled module that proves §13.3's
// framework seam reaches past the frameworks written in Rust.
//
// `react` is a Rust framework: a handful of functions in `sc-app` that the
// registry switches a name onto. This is the same seven answers written down
// (`frameworks`), and the point of it is what an admin sees — a third entry in
// the framework picker, with its own settings form, its own default CSP, and a
// project Saltcorn writes for them — none of which required a line of Rust.
//
// What it is *not*
// ----------------
// A second serving implementation. A built Vue app is a static bundle with an
// SPA fallback, which is exactly what a built React app is, so serving, mounting
// and reloading are Saltcorn's and identical for both. What differs is the
// project and its idiom.
//
// Nor is it a second client generator. `src/feldspar/client.ts`, its helper,
// `schema.sql`, `SKILL.md` and the GraphQL client are written by **Saltcorn**,
// from the application's own API, on the same schedule for every framework. This
// module writes the half that is Vue's: the composables, the pages, the shell.
//
// The conventions, for a project named `todo` in file store `apps`
// -----------------------------------------------------------------
// | path | what it is |
// |---|---|
// | `todo/` | the project (Vite + Vue 3 + vue-router) |
// | `todo/dist` | the bundle Saltcorn serves |
// | `todo/src/feldspar/` | generated: rewritten on every build, never edited |
// | `todo/src/pages/*.vue` | one page per exposed table — yours from here |

