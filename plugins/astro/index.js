// **Astro as an application framework** — for websites rather than apps: a
// landing page, a blog, a news site, a page with a contact form. What such a
// site needs is the opposite of what an SPA needs: the content in the HTML the
// server sends, little or no JavaScript, and a fast first byte.
//
// So this framework is not "an Astro project Saltcorn builds". It is Astro's
// *syntax* — `.astro` components, a frontmatter fence, file-based routing,
// scoped styles — with Saltcorn's *server*:
//
// - `.astro` files are compiled by `@astrojs/compiler` (the same compiler Astro
//   uses) and bundled by esbuild into **one JavaScript code body**
//   (`dist/_server/entry.js`). The server runs that body per request on the
//   code-action isolates, so a page's frontmatter has exactly what a JavaScript
//   code action has — `db`, `fetch`, `fs`, `Table`, `user`, `lib` — and reads
//   the database the same way:
//
//       ---
//       const posts = await db.posts.where({ published: true })
//         .orderBy("published_at", "desc").limit(10).rows();
//       ---
//
// - A page that says `export const prerender = true` is rendered **once, right
//   after the build**, through the same body, and served as a static file.
//   Every other page is rendered on each request. Either way the browser gets
//   finished HTML.
//
// - `<style>` is scoped and collected into one hashed stylesheet; a `<script>`
//   is bundled into a hashed file; so no inline script is needed and the CSP
//   stays strict.
//
// What is deliberately missing: Astro's own runtime, integrations, islands
// (`client:*`), Markdown/MDX pages and content collections. `docs/tutorial-astro.md`
// says what to write instead.
//
// The conventions, for a project named `site` in file store `apps`
// -----------------------------------------------------------------
// | path | what it is |
// |---|---|
// | `site/src/pages/` | routes: `index.astro` is `/`, `blog/[slug].astro` is `/blog/:slug`, `rss.xml.ts` is an endpoint |
// | `site/src/layouts/`, `site/src/components/` | yours; imported by the pages |
// | `site/public/` | copied to the site root as it is |
// | `site/src/feldspar/` | generated: rewritten on every build, never edited |
// | `site/dist/` | what the server serves; `dist/_server/` is never served |

