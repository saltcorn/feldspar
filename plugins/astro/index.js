/** A path under the project. `""` is the project root. */
const at = (dir, name) => (dir ? `${dir}/${name}` : name);

/** The public site URL setting, or `""` — in which case a page's links are
 * built from the address each request arrived on. */
const siteUrl = (ctx) => String((ctx.settings && ctx.settings.site) || "").trim().replace(/\/$/, "");

/** `db.tasks`, or `db.table("order items")` for a name that is not an
 * identifier. */
const dbRef = (name) =>
  /^[A-Za-z_$][\w$]*$/.test(name) ? `db.${name}` : `db.table(${JSON.stringify(name)})`;

/** HTML-escape a string written into a generated template's literal text. */
const html = (s) =>
  String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

/** A table's URL segment: lower case, dashes. */
const slug = (name) => name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

