/** The whole project, written once when the application is created. */
function scaffold(ctx) {
  const files = [
    { path: "package.json", contents: packageJson(ctx) },
    { path: ".gitignore", contents: GITIGNORE },
    { path: "tsconfig.json", contents: tsconfig(ctx) },
    { path: "AGENTS.md", contents: agentsMd(ctx) },
    { path: "src/layouts/Layout.astro", contents: layoutAstro(ctx) },
    { path: "src/components/Feature.astro", contents: FEATURE_ASTRO },
    { path: "src/pages/index.astro", contents: indexAstro(ctx) },
    { path: "src/pages/contact.astro", contents: CONTACT_ASTRO },
    { path: "src/pages/404.astro", contents: NOT_FOUND_ASTRO },
    { path: "src/styles/global.css", contents: GLOBAL_CSS },
    { path: "public/favicon.svg", contents: FAVICON_SVG },
  ];
  for (const table of ctx.tables) {
    files.push({ path: `src/pages/${slug(table.name)}/index.astro`, contents: tableAstro(table) });
  }
  return files.concat(runtime(ctx));
}

/** The framework's own code, rewritten on every build. */
function runtime(ctx) {
  const config = { site: siteUrl(ctx) };
  return [
    { path: at(ctx.runtime, "astro/build.mjs"), contents: ownFileText("files/build.mjs") },
    { path: at(ctx.runtime, "astro/server.mjs"), contents: ownFileText("files/server.mjs") },
    { path: at(ctx.runtime, "astro/config.json"), contents: JSON.stringify(config, null, 2) + "\n" },
    { path: at(ctx.runtime, "astro/env.d.ts"), contents: ENV_D_TS },
    { path: at(ctx.runtime, "README.md"), contents: runtimeReadme(ctx) },
  ];
}

