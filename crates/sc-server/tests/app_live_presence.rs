//! Milestone L4: **a page publishing, and who else is here** (TODO.md "Live
//! updates"), through the assembled router on a real port against a real
//! database, with real WebSocket clients — several users, several connections.
//!
//! The board: Alice owns board 1; Bob has a share that may only read it, Carol
//! one that may edit it, and Dave none. `board_presence` is an `internal`
//! stream with a topic per board, presence on (showing each user's `name`) and
//! pages allowed to publish.
//!
//! What is claimed, by task:
//!
//! - **L4.1** `can_publish` in `ready` is the row's **update** rule: Alice and
//!   Carol may, Bob may read but not publish — his publish is `unavailable` and
//!   reaches nobody. A published element is stamped `source: {user,
//!   connection}` by the server: a `source` in the frame is ignored, and what
//!   the others receive names the real sender. The sender does not get its own
//!   element back unless it subscribed with `echo`. A stream that does not let
//!   pages publish answers `unavailable`; a value of the wrong shape `invalid`.
//! - **L4.2** past the per-connection rate, a publish or a presence update is
//!   answered `rate_limited` and the connection stays up; a state over the size
//!   cap is `too_large`; quick presence updates are coalesced into the latest.
//! - **L4.3** a member list after `ready`, with the shown field; joins, states
//!   and leaves as `presence_diff`; closing a socket is a leave within a
//!   second; a revoked subscription leaves too. **Dave, who fails the topic's
//!   read check, never appears in the list and never receives it.**
//! - **L4.5** the admin's Observe socket shows who is on each topic.
