async fn setup() -> Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    sc_auth::bootstrap(&catalog).await?;
    sc_catalog::bootstrap_table_meta(&catalog).await?;
    sc_catalog::bootstrap_field_meta(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    // The field presence shows the others.
    db.client()
        .await?
        .batch_execute("ALTER TABLE users ADD COLUMN name text")
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    catalog.reload().await?;
    save_role(&catalog, &Role::new(ROLE_MEMBER, "Member")).await?;
    create_user(&catalog, ADMIN, PASSWORD, ROLE_ADMIN).await?;
    let mut users = HashMap::new();
    for email in [ALICE, BOB, CAROL, DAVE] {
        let user = create_user(&catalog, email, PASSWORD, ROLE_MEMBER).await?;
        users.insert(email, user.id);
    }

    let evaluator = sc_server::default_js_evaluator();
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let triggers =
        sc_server::install_triggers(&catalog, evaluator.clone(), &agents, &models).await?;

    let mut registry = StreamRegistry::new();
    registry.register(Arc::new(Internal) as Arc<dyn StreamProvider>)?;
    let registry = Arc::new(registry);
    let stream_services = sc_server::install_streams_with(
        &catalog,
        &triggers,
        registry.clone(),
        StreamConfig::default(),
    )
    .await?;
    for stream in streams() {
        save_stream(&catalog, &registry, &stream).await?;
    }
    stream_services.reload(&catalog).await?;

    let apps = Arc::new(
        sc_server::AppMounts::new(catalog.clone())
            .with_base_domain(Some(BASE_DOMAIN.to_owned()))
            .with_evaluator(evaluator)
            .with_triggers(triggers.clone())
            .with_models(models)
            .with_streams(stream_services)
            .with_live_limits(limits()),
    );
    let config = sc_server::ServerConfig {
        base_domain: Some(BASE_DOMAIN.to_owned()),
        ..sc_server::ServerConfig::default()
    };
    let sessions = Arc::new(SessionStore::database_with(
        catalog.clone(),
        chrono::Duration::hours(24),
        chrono::Duration::zero(),
        100,
    ));
    let router = sc_server::build_router_with_apps(
        &sc_api::admin_endpoints(),
        sc_server::admin_handlers(catalog.clone(), apps.clone()),
        sessions,
        &config,
        apps.clone(),
    )?;
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    let served = router.clone();
    tokio::spawn(async move {
        let _ = axum::serve(listener, served).await;
    });

    let server = Server {
        router,
        catalog: catalog.clone(),
        addr,
        users,
        db,
    };
    let (alice, bob, carol) = (server.id(ALICE), server.id(BOB), server.id(CAROL));
    server
        .sql(&format!(
            "UPDATE users SET name = 'Alice' WHERE email = '{ALICE}'; \
             UPDATE users SET name = 'Bob' WHERE email = '{BOB}'; \
             UPDATE users SET name = 'Carol' WHERE email = '{CAROL}'; \
             UPDATE users SET name = 'Dave' WHERE email = '{DAVE}'; \
             INSERT INTO boards (id, title, owner) VALUES (1, 'roadmap', '{alice}'); \
             INSERT INTO shares (board, member, can_edit) VALUES \
               (1, '{bob}', false), (1, '{carol}', true); \
             SELECT setval(pg_get_serial_sequence('boards', 'id'), 100);"
        ))
        .await;

    let mut admin = server.client(BASE_DOMAIN);
    admin.login(ADMIN).await;
    admin
        .ok(
            "PUT",
            "/api/tables/boards",
            Some(json!({
                "label": "", "description": "",
                "min_role_read": ROLE_ADMIN, "min_role_write": ROLE_ADMIN,
                "ownership_formula": BOARDS_RULE, "rls_enabled": false, "sync_enabled": false,
            })),
        )
        .await;

    let framework = Arc::new(CodeFramework::new(
        "code",
        AssetBundle::new().with("index.html", "<!doctype html>"),
    ));
    apps.mount(sc_server::MountedApp::new_with(
        app(),
        framework,
        &catalog,
        apps.evaluator(),
        apps.triggers(),
    )?)?;
    Ok(server)
}

// --- frames -------------------------------------------------------------------

async fn send(socket: &mut Socket, frame: Value) {
    socket
        .send(Message::text(frame.to_string()))
        .await
        .expect("the socket takes a frame");
}

async fn next_frame(socket: &mut Socket) -> Value {
    loop {
        let message = tokio::time::timeout(Duration::from_secs(20), socket.next())
            .await
            .expect("a frame arrives within the timeout")
            .expect("the socket is still open")
            .expect("the frame is readable");
        match message {
            Message::Text(text) => return serde_json::from_str(&text).unwrap(),
            Message::Ping(_) | Message::Pong(_) => continue,
            other => panic!("expected a text frame, got {other:?}"),
        }
    }
}

/// Subscribe and wait for `ready` or `error`; with presence, the member list
/// follows `ready` and is read by [`frame_for`].
async fn subscribe(socket: &mut Socket, frame: Value) -> Value {
    let sub = frame["sub"].clone();
    send(socket, frame).await;
    loop {
        let frame = next_frame(socket).await;
        if frame["sub"] == sub && (frame["type"] == "ready" || frame["type"] == "error") {
            return frame;
        }
    }
}

fn on_board(sub: &str) -> Value {
    json!({ "type": "subscribe", "sub": sub, "stream": "board_presence", "topic": 1 })
}

/// The next frame of `kind` about `sub`, skipping status frames and others'.
async fn frame_for(socket: &mut Socket, sub: &str, kind: &str) -> Value {
    loop {
        let frame = next_frame(socket).await;
        if frame["type"] == json!(kind) && frame["sub"] == json!(sub) {
            return frame;
        }
        assert!(
            !(frame["sub"] == json!(sub) && frame["type"] == "error"),
            "expected `{kind}` for {sub}, got an error: {frame}"
        );
    }
}

/// Every frame up to the answer to a `ping` — what has arrived by now.
async fn drain(socket: &mut Socket) -> Vec<Value> {
    send(socket, json!({ "type": "ping" })).await;
    let mut frames = Vec::new();
    loop {
        let frame = next_frame(socket).await;
        if frame["type"] == "pong" {
            return frames;
        }
        frames.push(frame);
    }
}

/// The next `presence_diff` about `sub` with something under `part`
/// (`joined`, `left` or `updated`) — skipping the diffs that raced ahead of
/// it, such as a join that arrived after a drain.
async fn diff_with(socket: &mut Socket, sub: &str, part: &str) -> Value {
    loop {
        let diff = frame_for(socket, sub, "presence_diff").await;
        if diff[part].as_array().is_some_and(|list| !list.is_empty()) {
            return diff;
        }
    }
}

/// Join board 1 as a page, answering the socket and its own connection id.
async fn join(server: &Server, email: &str) -> (Socket, String) {
    let mut socket = server.page(email).await;
    let ready = subscribe(&mut socket, on_board("b")).await;
    assert_eq!(ready["type"], "ready", "{email}: {ready}");
    let list = frame_for(&mut socket, "b", "presence").await;
    let me = list["connection"].as_str().unwrap().to_owned();
    (socket, me)
}

fn names(members: &Value) -> Vec<String> {
    let mut names: Vec<String> = members
        .as_array()
        .unwrap()
        .iter()
        .map(|m| m["name"].as_str().unwrap_or("?").to_owned())
        .collect();
    names.sort();
    names
}

// --- L4.1: who may publish, and what the others receive -----------------------

#[tokio::test]
async fn publishing_needs_update_access_and_the_source_is_the_servers() -> Result<()> {
    let server = setup().await?;
    let mut alice = server.page(ALICE).await;
    let mut bob = server.page(BOB).await;
    let mut carol = server.page(CAROL).await;

    // `can_publish` is the row's update rule: the owner and the share that may
    // edit, not the share that may only read — though all three may read.
    let ready = subscribe(&mut alice, on_board("b")).await;
    assert_eq!(ready["can_publish"], true, "{ready}");
    let ready = subscribe(&mut bob, on_board("b")).await;
    assert_eq!(ready["type"], "ready");
    assert_eq!(ready["can_publish"], false, "{ready}");
    let ready = subscribe(&mut carol, on_board("b")).await;
    assert_eq!(ready["can_publish"], true, "{ready}");
    let carol_me = frame_for(&mut carol, "b", "presence").await["connection"].clone();
    drain(&mut alice).await;
    drain(&mut bob).await;

    // Bob may read but not update: `unavailable`, and nobody hears it.
    send(
        &mut bob,
        json!({ "type": "publish", "sub": "b", "value": { "dragging": 1 } }),
    )
    .await;
    let refused = frame_for(&mut bob, "b", "error").await;
    assert_eq!(refused["code"], "unavailable", "{refused}");

    // Carol publishes with a forged `source`, beside the value and inside it.
    send(
        &mut carol,
        json!({
            "type": "publish", "sub": "b",
            "value": { "dragging": 7 },
            "source": { "user": server.id(ALICE), "connection": "forged" },
        }),
    )
    .await;
    let element = frame_for(&mut alice, "b", "element").await;
    assert_eq!(element["envelope"]["value"]["dragging"], 7);
    assert_eq!(element["envelope"]["topic"], "1");
    assert_eq!(
        element["envelope"]["source"],
        json!({ "user": server.id(CAROL), "connection": carol_me }),
        "the server's stamp, not the page's"
    );
    let at_bob = frame_for(&mut bob, "b", "element").await;
    assert_eq!(
        at_bob["envelope"]["source"]["user"],
        json!(server.id(CAROL))
    );
    // Bob's refused publish never arrived anywhere: Carol's is the only one.
    assert!(
        drain(&mut alice)
            .await
            .iter()
            .all(|f| f["type"] != "element"),
        "nothing but Carol's"
    );
    // Carol did not get her own element back.
    assert!(
        drain(&mut carol)
            .await
            .iter()
            .all(|f| f["type"] != "element"),
        "the sender is left out"
    );

    // With `echo`, a subscription of the sender's gets it back; the other does not.
    let ready = subscribe(
        &mut carol,
        json!({ "type": "subscribe", "sub": "echoed", "stream": "board_presence", "topic": "1",
                "echo": true }),
    )
    .await;
    assert_eq!(ready["type"], "ready");
    send(
        &mut carol,
        json!({ "type": "publish", "sub": "b", "value": { "dragging": 8 } }),
    )
    .await;
    let echoed = frame_for(&mut carol, "echoed", "element").await;
    assert_eq!(echoed["envelope"]["value"]["dragging"], 8);
    assert!(
        drain(&mut carol)
            .await
            .iter()
            .all(|f| !(f["type"] == "element" && f["sub"] == "b")),
        "only the subscription that asked"
    );

    // A value of the wrong shape is `invalid`; a stream pages may not publish
    // on is `unavailable`, worded like any absence.
    send(
        &mut carol,
        json!({ "type": "publish", "sub": "b", "value": { "dragging": "lots" } }),
    )
    .await;
    assert_eq!(frame_for(&mut carol, "b", "error").await["code"], "invalid");
    let ready = subscribe(
        &mut carol,
        json!({ "type": "subscribe", "sub": "news", "stream": "announcements" }),
    )
    .await;
    assert_eq!(ready["can_publish"], false);
    send(
        &mut carol,
        json!({ "type": "publish", "sub": "news", "value": { "message": "hi" } }),
    )
    .await;
    assert_eq!(
        frame_for(&mut carol, "news", "error").await["code"],
        "unavailable"
    );
    Ok(())
}

// --- L4.2: rates and sizes ----------------------------------------------------

#[tokio::test]
async fn past_the_rate_a_publish_or_a_state_is_refused_and_the_socket_stays() -> Result<()> {
    let server = setup().await?;
    let (mut alice, _) = join(&server, ALICE).await;
    let (mut carol, _) = join(&server, CAROL).await;
    drain(&mut alice).await;

    for n in 0..8 {
        send(
            &mut carol,
            json!({ "type": "publish", "sub": "b", "value": { "dragging": n } }),
        )
        .await;
    }
    let frames = drain(&mut carol).await;
    let limited = frames
        .iter()
        .filter(|f| f["type"] == "error" && f["code"] == "rate_limited")
        .count();
    // A bucket of five, refilling at five a second: eight sent at once lose
    // two or three, however slowly the test machine sends them.
    assert!(limited >= 2, "{frames:#?}");
    // The ones within the rate went out — no more — and the socket is up (it
    // answered the ping).
    for _ in 0..(8 - limited) {
        frame_for(&mut alice, "b", "element").await;
    }
    tokio::time::sleep(Duration::from_millis(200)).await;
    assert!(
        drain(&mut alice)
            .await
            .iter()
            .all(|f| f["type"] != "element"),
        "a refused publish was not published"
    );

    // A state over the cap is refused whole, and changes nothing.
    send(
        &mut carol,
        json!({ "type": "presence", "sub": "b", "state": { "note": "x".repeat(3000) } }),
    )
    .await;
    assert_eq!(
        frame_for(&mut carol, "b", "error").await["code"],
        "too_large"
    );

    // Quick states are coalesced: Alice ends at the latest, in at most two
    // diffs for three updates.
    tokio::time::sleep(Duration::from_millis(1100)).await;
    for n in 1..=3 {
        send(
            &mut carol,
            json!({ "type": "presence", "sub": "b", "state": { "dragging": n } }),
        )
        .await;
    }
    let mut updates = Vec::new();
    while updates.last() != Some(&json!({ "dragging": 3 })) {
        let diff = diff_with(&mut alice, "b", "updated").await;
        for update in diff["updated"].as_array().cloned().unwrap_or_default() {
            updates.push(update["state"].clone());
        }
    }
    assert!(updates.len() <= 2, "coalesced: {updates:?}");

    // Past the presence rate: `rate_limited`, and the socket stays.
    for n in 0..8 {
        send(
            &mut carol,
            json!({ "type": "presence", "sub": "b", "state": { "dragging": n } }),
        )
        .await;
    }
    let frames = drain(&mut carol).await;
    assert!(
        frames
            .iter()
            .any(|f| f["type"] == "error" && f["code"] == "rate_limited"),
        "{frames:#?}"
    );
    Ok(())
}

// --- L4.3: presence -----------------------------------------------------------

#[tokio::test]
async fn members_see_each_other_and_somebody_refused_is_never_listed() -> Result<()> {
    let server = setup().await?;
    let (mut alice, alice_me) = join(&server, ALICE).await;

    let (mut bob, bob_me) = join(&server, BOB).await;
    let joined = diff_with(&mut alice, "b", "joined").await;
    assert_eq!(joined["joined"][0]["connection"], json!(bob_me));
    assert_eq!(joined["joined"][0]["name"], "Bob");
    assert_eq!(joined["joined"][0]["user_id"], json!(server.id(BOB)));
    assert_eq!(joined["joined"][0]["state"], Value::Null);
    // Nothing about the user but the field the stream shows.
    assert!(joined["joined"][0].get("email").is_none(), "{joined}");

    // Dave cannot read board 1: the same `unavailable` as a missing board,
    // and he is never in anybody's list.
    let mut dave = server.page(DAVE).await;
    let refused = subscribe(&mut dave, on_board("b")).await;
    assert_eq!(refused["code"], "unavailable");
    let missing = subscribe(
        &mut dave,
        json!({ "type": "subscribe", "sub": "m", "stream": "board_presence", "topic": 999 }),
    )
    .await;
    assert_eq!(missing["code"], "unavailable");
    assert_eq!(missing["message"], refused["message"]);
    send(
        &mut dave,
        json!({ "type": "presence", "sub": "b", "state": { "x": 1 } }),
    )
    .await;
    assert_eq!(frame_for(&mut dave, "b", "error").await["code"], "invalid");

    // Carol joins: the list she is handed has all three of the readers, and
    // not Dave.
    let mut carol = server.page(CAROL).await;
    subscribe(&mut carol, on_board("b")).await;
    let list = frame_for(&mut carol, "b", "presence").await;
    assert_eq!(names(&list["members"]), vec!["Alice", "Bob", "Carol"]);
    let carol_me = list["connection"].as_str().unwrap().to_owned();
    for frames in [drain(&mut alice).await, drain(&mut bob).await] {
        let text = serde_json::to_string(&frames).unwrap();
        assert!(!text.contains("Dave"), "{text}");
        assert!(!text.contains(&server.id(DAVE)), "{text}");
    }
    // And Dave was sent nothing of it.
    let text = serde_json::to_string(&drain(&mut dave).await).unwrap();
    assert!(!text.contains("presence"), "{text}");

    // A state is everybody else's news.
    send(
        &mut carol,
        json!({ "type": "presence", "sub": "b", "state": { "dragging": 5 } }),
    )
    .await;
    let diff = diff_with(&mut alice, "b", "updated").await;
    assert_eq!(
        diff["updated"],
        json!([{ "connection": carol_me, "state": { "dragging": 5 } }])
    );

    // Closing a tab is a leave, within a second.
    drop(carol);
    let left = tokio::time::timeout(Duration::from_secs(1), async {
        loop {
            let diff = diff_with(&mut alice, "b", "left").await;
            if diff["left"] == json!([carol_me]) {
                return diff;
            }
        }
    })
    .await
    .expect("the leave arrives within a second");
    assert!(left.get("joined").is_none());

    // A revoked subscription leaves too: Bob's share goes, through the
    // admin's row editor — an ordinary write, which the hub sees.
    let share: i64 = server
        .db
        .client()
        .await
        .unwrap()
        .query_one(
            &format!("SELECT id FROM shares WHERE member = '{}'", server.id(BOB)),
            &[],
        )
        .await
        .unwrap()
        .get(0);
    let mut admin = server.client(BASE_DOMAIN);
    admin.login(ADMIN).await;
    admin
        .ok("DELETE", &format!("/api/tables/shares/rows/{share}"), None)
        .await;
    let revoked = frame_for(&mut bob, "b", "revoked").await;
    assert_eq!(revoked["sub"], "b");
    let diff = diff_with(&mut alice, "b", "left").await;
    assert_eq!(diff["left"], json!([bob_me]));
    assert_ne!(alice_me, bob_me);
    Ok(())
}

// --- L4.5: the admin sees who is here -----------------------------------------

#[tokio::test]
async fn the_admins_observe_socket_shows_who_is_on_each_topic() -> Result<()> {
    let server = setup().await?;
    let (_alice, alice_me) = join(&server, ALICE).await;
    let stream = sc_stream::load_stream_by_name(&server.catalog, "board_presence")
        .await?
        .unwrap();
    let session = server.client(BASE_DOMAIN).login(ADMIN).await;
    let mut observe = server
        .socket(
            &format!("/api/streams/{}/observe", stream.id.0),
            BASE_DOMAIN,
            &session,
        )
        .await;
    let ready = next_frame(&mut observe).await;
    assert_eq!(ready["type"], "ready");
    let presence = loop {
        let frame = next_frame(&mut observe).await;
        if frame["type"] == "presence" {
            break frame;
        }
    };
    assert_eq!(presence["topics"][0]["topic"], "1");
    assert_eq!(
        presence["topics"][0]["members"][0]["connection"],
        json!(alice_me)
    );
    assert_eq!(presence["topics"][0]["members"][0]["name"], "Alice");

    // Carol arrives: the next presence frame lists both.
    let (_carol, _) = join(&server, CAROL).await;
    let presence = loop {
        let frame = next_frame(&mut observe).await;
        if frame["type"] == "presence" {
            break frame;
        }
    };
    assert_eq!(
        names(&presence["topics"][0]["members"]),
        vec!["Alice", "Carol"]
    );
    Ok(())
}
