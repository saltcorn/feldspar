/// The tables every test works over: books with a Key to authors (so an
/// `only_if` has a Ⱶ-path to walk), an audit table for triggers to write into,
/// and one self-referential table for the cascade limit.
const SCHEMA: &str = "\
    CREATE TABLE authors (id bigint generated by default as identity primary key, \
        name text, tier text); \
    CREATE TABLE books (id bigint generated by default as identity primary key, \
        title text not null, pages bigint, author bigint references authors(id)); \
    CREATE TABLE audit (id bigint generated by default as identity primary key, \
        what text, title text, was text, pages bigint, who text); \
    CREATE TABLE links (id bigint generated by default as identity primary key, depth bigint); \
    INSERT INTO authors (name, tier) VALUES ('Ada', 'gold'), ('Bob', 'silver');";

const ADMIN: &str = "admin@example.com";
const PASSWORD: &str = "hunter2pass";

/// A cookie-jar-carrying client over the router, as `admin_api.rs` uses: it
/// keeps the CSRF and session cookies between requests and echoes the token on
/// mutations, exactly as the SPA does.
struct Client {
    router: Router,
    cookies: HashMap<String, String>,
}

impl Client {
    async fn send(&mut self, method: &str, path: &str, body: Option<Value>) -> (StatusCode, Value) {
        let mut builder = Request::builder().method(method).uri(path);
        if !self.cookies.is_empty() {
            let jar = self
                .cookies
                .iter()
                .map(|(k, v)| format!("{k}={v}"))
                .collect::<Vec<_>>()
                .join("; ");
            builder = builder.header(header::COOKIE, jar);
        }
        if method != "GET"
            && let Some(csrf) = self.cookies.get(CSRF_COOKIE)
        {
            builder = builder.header(CSRF_HEADER, csrf);
        }
        let request = match body {
            Some(ref b) => builder
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(serde_json::to_vec(b).unwrap()))
                .unwrap(),
            None => builder.body(Body::empty()).unwrap(),
        };
        let response = self.router.clone().oneshot(request).await.unwrap();
        let status = response.status();
        for raw in response.headers().get_all(header::SET_COOKIE) {
            if let Ok(text) = raw.to_str()
                && let Some((name, value)) = text.split(';').next().unwrap_or("").split_once('=')
            {
                self.cookies.insert(name.to_owned(), value.to_owned());
            }
        }
        let bytes = axum::body::to_bytes(response.into_body(), 256 * 1024)
            .await
            .unwrap();
        let value = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap_or(Value::Null)
        };
        (status, value)
    }

    /// Every row of `table`, through the API.
    async fn rows(&mut self, table: &str) -> Vec<Value> {
        let (status, body) = self
            .send("GET", &format!("/api/tables/{table}/rows"), None)
            .await;
        assert_eq!(status, StatusCode::OK, "{body}");
        body.as_array().cloned().unwrap_or_default()
    }
}

/// One booted server: the router, the catalog the triggers are stored in, and
/// the live dispatcher (so a test can add a trigger and reload the set the way
/// Phase 6's admin API will).
struct Server {
    client: Client,
    catalog: Arc<Catalog>,
    dispatcher: Arc<TriggerDispatcher>,
    _db: TestDb,
}

impl Server {
    /// Store `trigger` and put it in the live set — what saving one in the admin
    /// UI will do once Phase 6 exposes it.
    async fn add_trigger(&self, trigger: Trigger) -> sc_error::Result<()> {
        save_trigger(&self.catalog, &self.dispatcher.registry(), &trigger).await?;
        self.dispatcher.reload(&self.catalog).await
    }
}

async fn setup() -> sc_error::Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            // The multi-tenant v1 test template carries `users` tables in several
            // schemas; drop them all so bootstrap creates the clean MVP table.
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    sc_auth::bootstrap(&catalog).await?;

    // The boot path itself: the built-in actions, the stored triggers, and the
    // dispatcher installed into the catalog. Before this call nothing observes a
    // write — which is exactly what every other test in this suite relies on.
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let dispatcher = install_triggers(&catalog, default_js_evaluator(), &agents, &models).await?;

    let apps = Arc::new(AppMounts::new(catalog.clone()).with_triggers(dispatcher.clone()));
    let router = build_router(
        &sc_api::admin_endpoints(),
        admin_handlers(catalog.clone(), apps),
        Arc::new(SessionStore::default()),
        &ServerConfig::default(),
    )?;

    let mut client = Client {
        router,
        cookies: HashMap::new(),
    };
    // One GET first, for the CSRF cookie every mutation has to echo — the same
    // handshake the SPA makes when it loads.
    client.send("GET", "/api/auth/status", None).await;
    let (status, body) = client
        .send(
            "POST",
            "/api/first-user",
            Some(json!({ "email": ADMIN, "password": PASSWORD })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");

    Ok(Server {
        client,
        catalog,
        dispatcher,
        _db: db,
    })
}

/// An `insert_row` action writing one audit row from a field → formula map.
fn audit_action(trigger: Trigger, values: Value) -> Trigger {
    trigger.config("table", "audit").config("values", values)
}

#[tokio::test]
async fn an_insert_writes_the_audit_row_its_trigger_configures() -> sc_error::Result<()> {
    let mut server = setup().await?;
    server
        .add_trigger(audit_action(
            Trigger::new("audit_insert", EventKind::Insert, "insert_row").on("books"),
            json!({
                "what": "\"insert\"",
                "title": "row.title",
                "pages": "row.pages",
                // The caller only reaches here because a `CallerContext` travels
                // with every write, not only with the RLS ones.
                "who": "user.email",
            }),
        ))
        .await?;

    let (status, book) = server
        .client
        .send(
            "POST",
            "/api/tables/books/rows",
            Some(json!({ "title": "Dune", "pages": 412 })),
        )
        .await;
    assert_eq!(status, StatusCode::CREATED, "{book}");
    assert_eq!(book["title"], json!("Dune"));

    let audit = server.client.rows("audit").await;
    assert_eq!(audit.len(), 1, "{audit:?}");
    assert_eq!(audit[0]["what"], json!("insert"));
    assert_eq!(audit[0]["title"], json!("Dune"));
    assert_eq!(audit[0]["pages"], json!(412));
    assert_eq!(audit[0]["who"], json!(ADMIN), "the event knows who wrote");

    // Nothing listens for updates or deletes on `books`, so neither raises an
    // audit row — the match is by (kind, table), not by table alone.
    let id = book["id"].as_i64().unwrap();
    server
        .client
        .send(
            "PUT",
            &format!("/api/tables/books/rows/{id}"),
            Some(json!({ "pages": 500 })),
        )
        .await;
    server
        .client
        .send("DELETE", &format!("/api/tables/books/rows/{id}"), None)
        .await;
    assert_eq!(server.client.rows("audit").await.len(), 1);
    Ok(())
}

#[tokio::test]
async fn an_update_trigger_sees_both_the_new_row_and_the_one_it_replaced() -> sc_error::Result<()> {
    let mut server = setup().await?;
    server
        .add_trigger(audit_action(
            Trigger::new("audit_update", EventKind::Update, "insert_row").on("books"),
            json!({ "what": "\"update\"", "title": "row.title", "was": "old.title" }),
        ))
        .await?;

    let (_, book) = server
        .client
        .send(
            "POST",
            "/api/tables/books/rows",
            Some(json!({ "title": "Dune", "pages": 412 })),
        )
        .await;
    let id = book["id"].as_i64().unwrap();

    let (status, updated) = server
        .client
        .send(
            "PUT",
            &format!("/api/tables/books/rows/{id}"),
            Some(json!({ "title": "Dune (revised)" })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{updated}");

    let audit = server.client.rows("audit").await;
    assert_eq!(audit.len(), 1, "{audit:?}");
    // The pre-image is read *before* the update, and only because something is
    // listening for it: `old` is the row as it was, `row` as it now is.
    assert_eq!(audit[0]["was"], json!("Dune"));
    assert_eq!(audit[0]["title"], json!("Dune (revised)"));
    Ok(())
}

