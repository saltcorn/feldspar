//! Phase 4 end-to-end: a row written through the real router fires the triggers
//! that listen for it (§10.2, decision 1 and decision 2).
//!
//! Everything here goes in as an **HTTP request** to the admin API and is
//! asserted by reading the database back the same way, because the claim being
//! tested spans the whole stack: the row layer raises an event through a seam it
//! cannot see the other side of, the dispatcher matches it against the cached
//! trigger set, an `only_if` runs in the real V8 engine against the real row, and
//! the action writes through the same `rows` layer the request itself used. A
//! unit test of any one of those would assert a shape rather than the behaviour.
//!
//! What is pinned:
//!
//! - an **insert** trigger writing an audit row, with the event's row *and its
//!   caller* — who is only there because the caller travels with every write;
//! - an **update** trigger reading `old` and `row` in the same formula;
//! - a **delete** trigger carrying the row as it was, after it is gone;
//! - an **`only_if`** gating firing, both over the row's own fields and over a
//!   **Ⱶ-join path** (which the dispatcher has to prefetch, and which therefore
//!   only works if the row's key value is typed as its column);
//! - the **depth limit** stopping a self-feeding trigger, and naming the chain;
//! - a **failing action** neither failing the request nor losing the write.
#![allow(clippy::unwrap_used, clippy::expect_used)]

