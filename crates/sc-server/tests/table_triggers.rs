/// "Delete all rows" on the table page: one request empties the table, says how
/// many rows went, and still raises a delete event for each of them — a trigger
/// watching deletes is watching these too. A table nothing watches is emptied
/// the same way, and rows another table's key still points at are refused.
#[tokio::test]
async fn deleting_all_rows_empties_the_table_and_fires_each_delete() -> sc_error::Result<()> {
    let mut server = setup().await?;
    server
        .add_trigger(audit_action(
            Trigger::new("audit_delete", EventKind::Delete, "insert_row").on("books"),
            json!({ "what": "\"delete\"", "title": "row.title" }),
        ))
        .await?;
    for title in ["Dune", "Emma", "Ulysses"] {
        let (status, body) = server
            .client
            .send(
                "POST",
                "/api/tables/books/rows",
                Some(json!({ "title": title, "author": 1 })),
            )
            .await;
        assert_eq!(status, StatusCode::CREATED, "{body}");
    }

    // The authors are still referenced by the books, so the database refuses,
    // and nothing is deleted.
    let (status, body) = server
        .client
        .send("DELETE", "/api/tables/authors/rows", None)
        .await;
    assert_ne!(status, StatusCode::OK, "{body}");
    assert_eq!(server.client.rows("authors").await.len(), 2);

    let (status, body) = server
        .client
        .send("DELETE", "/api/tables/books/rows", None)
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body, json!({ "deleted": 3 }));
    assert!(server.client.rows("books").await.is_empty());
    let mut titles: Vec<String> = server
        .client
        .rows("audit")
        .await
        .iter()
        .map(|r| r["title"].as_str().unwrap_or_default().to_owned())
        .collect();
    titles.sort();
    assert_eq!(titles, ["Dune", "Emma", "Ulysses"], "one event per row");

    // Nothing watches `authors`, and with the books gone it empties too.
    let (status, body) = server
        .client
        .send("DELETE", "/api/tables/authors/rows", None)
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body, json!({ "deleted": 2 }));
    assert!(server.client.rows("authors").await.is_empty());

    // An empty table is emptied again without complaint.
    let (status, body) = server
        .client
        .send("DELETE", "/api/tables/authors/rows", None)
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body, json!({ "deleted": 0 }));
    Ok(())
}

#[tokio::test]
async fn an_only_if_decides_whether_the_action_runs() -> sc_error::Result<()> {
    let mut server = setup().await?;
    server
        .add_trigger(
            audit_action(
                Trigger::new("audit_long", EventKind::Insert, "insert_row").on("books"),
                json!({ "what": "\"long\"", "title": "row.title" }),
            )
            // A bare identifier is the affected row's own field (decision 7).
            .only_if("pages > 100"),
        )
        .await?;

    for (title, pages) in [("Dune", 412), ("A Pamphlet", 30)] {
        let (status, body) = server
            .client
            .send(
                "POST",
                "/api/tables/books/rows",
                Some(json!({ "title": title, "pages": pages })),
            )
            .await;
        assert_eq!(status, StatusCode::CREATED, "{body}");
    }

    // Both rows were written; only the one the predicate selects was audited,
    // and the other passed in silence — not as an error.
    assert_eq!(server.client.rows("books").await.len(), 2);
    let audit = server.client.rows("audit").await;
    assert_eq!(audit.len(), 1, "{audit:?}");
    assert_eq!(audit[0]["title"], json!("Dune"));
    Ok(())
}

#[tokio::test]
async fn an_only_if_can_read_through_a_join_path() -> sc_error::Result<()> {
    let mut server = setup().await?;
    server
        .add_trigger(
            audit_action(
                Trigger::new("audit_gold", EventKind::Insert, "insert_row").on("books"),
                json!({ "what": "\"gold\"", "title": "row.title" }),
            )
            // The value is not in the row: the dispatcher has to walk the Key
            // link to `authors`, correlating on the row's own `author` value —
            // which only works because that value is typed as its column.
            .only_if("authorⱵtier === \"gold\""),
        )
        .await?;

    let authors = server.client.rows("authors").await;
    let id_of = |name: &str| -> i64 {
        authors
            .iter()
            .find(|a| a["name"] == json!(name))
            .and_then(|a| a["id"].as_i64())
            .unwrap()
    };

    for (title, author) in [("Ada's Book", id_of("Ada")), ("Bob's Book", id_of("Bob"))] {
        let (status, body) = server
            .client
            .send(
                "POST",
                "/api/tables/books/rows",
                Some(json!({ "title": title, "pages": 100, "author": author })),
            )
            .await;
        assert_eq!(status, StatusCode::CREATED, "{body}");
    }

    let audit = server.client.rows("audit").await;
    assert_eq!(audit.len(), 1, "{audit:?}");
    assert_eq!(audit[0]["title"], json!("Ada's Book"));
    Ok(())
}

#[tokio::test]
async fn a_self_feeding_trigger_is_stopped_by_the_depth_limit() -> sc_error::Result<()> {
    let mut server = setup().await?;
    // Every insert into `links` inserts another one. Nothing about this trigger
    // is wrong — a write causing a write is the point of decision 5 — so what
    // stops it has to be the bound, not a refusal to save it.
    server
        .add_trigger(
            Trigger::new("feed", EventKind::Insert, "insert_row")
                .on("links")
                .config("table", "links")
                .config("values", json!({ "depth": "row.depth + 1" })),
        )
        .await?;

    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/links/rows",
            Some(json!({ "depth": 0 })),
        )
        .await;
    // The request that started it succeeds: the cascade is bounded, not fatal.
    assert_eq!(status, StatusCode::CREATED, "{body}");

    let depths: Vec<i64> = server
        .client
        .rows("links")
        .await
        .iter()
        .filter_map(|r| r["depth"].as_i64())
        .collect();
    // The original row plus one per firing, and firings stop at MAX_DEPTH.
    assert_eq!(
        depths,
        (0..=i64::try_from(sc_action::MAX_DEPTH).unwrap()).collect::<Vec<_>>()
    );

    // And the refusal names the whole chain, because "too deep" without the path
    // is a diagnosis the admin would have to redo by hand.
    let deep = Event::new(EventKind::Insert)
        .on("links")
        .row(json!({ "id": 1, "depth": 1 }))
        .chained(vec!["feed".into(); sc_action::MAX_DEPTH]);
    let runs = server.dispatcher.dispatch(&server.catalog, &deep).await;
    assert_eq!(runs.len(), 1);
    let message = runs[0].outcome.as_ref().unwrap_err().to_string();
    assert!(message.contains("feed → feed → feed"), "{message}");
    assert!(message.contains("was not run"), "{message}");
    Ok(())
}

#[tokio::test]
async fn a_failing_action_costs_the_trigger_and_nothing_else() -> sc_error::Result<()> {
    let mut server = setup().await?;
    // Two triggers on the same event: the first one throws, and the second must
    // still run — one trigger's failure is one trigger's failure.
    server
        .add_trigger(
            Trigger::new("boom", EventKind::Insert, "run_js_code")
                .on("books")
                .config("code", "throw new Error('the audit service is down');"),
        )
        .await?;
    server
        .add_trigger(audit_action(
            Trigger::new("still_runs", EventKind::Insert, "insert_row").on("books"),
            json!({ "what": "\"insert\"", "title": "row.title" }),
        ))
        .await?;

    let (status, book) = server
        .client
        .send(
            "POST",
            "/api/tables/books/rows",
            Some(json!({ "title": "Dune", "pages": 412 })),
        )
        .await;
    // The write happened and the request succeeded: dispatch is after the
    // commit, so a broken trigger cannot undo it or fail it.
    assert_eq!(status, StatusCode::CREATED, "{book}");
    assert_eq!(server.client.rows("books").await.len(), 1);
    assert_eq!(server.client.rows("audit").await.len(), 1);

    // The failure is not swallowed either — dispatch reports it per trigger,
    // which is what the emit path logs.
    let event = Event::new(EventKind::Insert)
        .on("books")
        .row(json!({ "id": 1, "title": "Dune", "pages": 412 }));
    let runs = server.dispatcher.dispatch(&server.catalog, &event).await;
    let names: Vec<&str> = runs.iter().map(|r| r.trigger.as_str()).collect();
    assert_eq!(names, vec!["boom", "still_runs"], "in name order");
    let message = runs[0].outcome.as_ref().unwrap_err().to_string();
    assert!(message.contains("the audit service is down"), "{message}");
    assert!(runs[1].fired(), "the second trigger still ran");
    Ok(())
}

/// "Rename table" on the table page: the table keeps its rows under the new
/// name, and what names it follows — a trigger on it still fires, a trigger
/// writing into it writes into the renamed table, another table's key and a
/// formula aggregating over it point at the new name, and so does an
/// application's table subset. A name that is taken, and a built-in table, are
/// refused.
#[tokio::test]
async fn renaming_a_table_moves_what_names_it() -> sc_error::Result<()> {
    let mut server = setup().await?;
    sc_catalog::bootstrap_table_meta(&server.catalog).await?;
    sc_catalog::bootstrap_field_meta(&server.catalog).await?;
    sc_app::bootstrap(&server.catalog).await?;
    server.catalog.reload().await?;
    server
        .add_trigger(audit_action(
            Trigger::new("audit_insert", EventKind::Insert, "insert_row").on("books"),
            json!({ "what": "\"insert\"", "title": "row.title" }),
        ))
        .await?;
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/authors/fields",
            Some(json!({
                "name": "book_count",
                "type": "int8",
                "kind": { "type": "calc", "expression": "booksↃauthor.length" }
            })),
        )
        .await;
    assert_eq!(status, StatusCode::CREATED, "{body}");
    sc_app::save_application(
        &server.catalog,
        &sc_app::Application::new(
            "Shelf",
            "shelf",
            sc_app::FrameworkRef::new("code")
                .with("store", "apps")
                .with("source", "web")
                .with("output", "web/dist")
                .with("command", "sh build.sh"),
        )
        .with_table(sc_catalog::TableId("books".to_owned())),
    )
    .await?;
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/books/rows",
            Some(json!({ "title": "Dune", "author": 1 })),
        )
        .await;
    assert_eq!(status, StatusCode::CREATED, "{body}");

    // The table being written by a trigger, and the table a trigger is on.
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/audit/rename",
            Some(json!({ "name": "audit_log" })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/books/rename",
            Some(json!({ "name": "titles" })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body["table"]["name"], json!("titles"), "{body}");
    let notes = body["notes"].to_string();
    assert!(
        notes.contains("is not rewritten"),
        "code is said to be left: {notes}"
    );

    // The rows came along, and the old name is gone.
    assert_eq!(server.client.rows("titles").await.len(), 1);
    let (status, _) = server
        .client
        .send("GET", "/api/tables/books/rows", None)
        .await;
    assert_eq!(status, StatusCode::NOT_FOUND);

    // The trigger is on `titles` now, and writes into `audit_log`.
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/titles/rows",
            Some(json!({ "title": "Emma", "author": 1 })),
        )
        .await;
    assert_eq!(status, StatusCode::CREATED, "{body}");
    let audit = server.client.rows("audit_log").await;
    assert_eq!(audit.len(), 2, "both inserts were audited: {audit:?}");
    assert_eq!(audit[1]["title"], json!("Emma"));

    // The formula aggregating over the table names it by its new name, and
    // still counts.
    let (_, fields) = server
        .client
        .send("GET", "/api/tables/authors/fields", None)
        .await;
    let calc = fields
        .as_array()
        .unwrap()
        .iter()
        .find(|f| f["name"] == json!("book_count"))
        .unwrap()
        .clone();
    assert_eq!(
        calc["kind"]["expression"],
        json!("titlesↃauthor.length"),
        "{calc}"
    );
    let ada = server
        .client
        .rows("authors")
        .await
        .into_iter()
        .find(|a| a["name"] == json!("Ada"))
        .unwrap();
    assert_eq!(ada["book_count"], json!(2), "{ada}");

    // Renaming the table a key points at repoints the key.
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/authors/rename",
            Some(json!({ "name": "writers" })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let (_, fields) = server
        .client
        .send("GET", "/api/tables/titles/fields", None)
        .await;
    let author = fields
        .as_array()
        .unwrap()
        .iter()
        .find(|f| f["name"] == json!("author"))
        .unwrap()
        .clone();
    assert_eq!(author["kind"]["target_table"], json!("writers"), "{author}");

    // The application's subset names the new table.
    let app = sc_app::list_applications(&server.catalog)
        .await?
        .into_iter()
        .find(|a| a.subdomain == "shelf")
        .unwrap();
    let tables: Vec<&str> = app.tables.iter().map(|t| t.0.as_str()).collect();
    assert_eq!(tables, vec!["titles"]);

    // Refused: a name that is taken, a built-in table, and a rename in a batch
    // with other operations.
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/titles/rename",
            Some(json!({ "name": "audit_log" })),
        )
        .await;
    assert_eq!(status, StatusCode::BAD_REQUEST, "{body}");
    assert!(body.to_string().contains("already exists"), "{body}");
    let (status, body) = server
        .client
        .send(
            "POST",
            "/api/tables/users/rename",
            Some(json!({ "name": "people" })),
        )
        .await;
    assert_eq!(status, StatusCode::BAD_REQUEST, "{body}");
    let err = sc_api::schema_edit::apply(
        &server.catalog,
        &[
            sc_api::schema_edit::Operation::RenameTable {
                table: "titles".into(),
                to: "books".into(),
            },
            sc_api::schema_edit::Operation::DropTable {
                table: "links".into(),
            },
        ],
        &sc_api::schema_edit::ApplyOptions::default(),
    )
    .await
    .unwrap_err();
    assert!(err.to_string().contains("batch of its own"), "{err}");
    Ok(())
}
