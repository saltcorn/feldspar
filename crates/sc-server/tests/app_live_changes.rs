//! Milestone L3, phase 2: **table change streams** (TODO.md "Live updates"
//! L3.4–L3.9), through the assembled router on a real port against a real
//! database, with real WebSocket clients — two users, two connections.
//!
//! What is claimed, by task:
//!
//! - **L3.4** a `table_changes` stream is subscribed without a topic; its
//!   `ready` announces the element type typed from the table (`row` has the
//!   table's columns), and the generated client's type follows a column added
//!   to the table. A stream whose table is outside the app's subset is the same
//!   `unavailable` as a misspelt name, and saving an app that exposes one is
//!   refused naming both. Saving a stream on a table that does not exist is
//!   refused.
//! - **L3.6** a filter naming a field REST would not filter on is `invalid`
//!   (the password hash included); a topic on a change stream is `invalid` too.
//! - **L3.7/L3.8** Alice (filtered to board 1) and Bob (unfiltered) watch the
//!   cards. A card on Alice's board reaches Alice and not Bob; moving it to
//!   Bob's board is a `leave` (the key only) for Alice and an `enter` for Bob;
//!   its delete reaches Bob only. Nothing about a card a user cannot read
//!   reaches their socket at all — each user's next frame is checked to be one
//!   of theirs.
//! - **L3.9** the Streams list and `streamStatus` carry what the checks
//!   decided.
