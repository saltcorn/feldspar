const BASE_DOMAIN: &str = "example.com";
const APP_HOST: &str = "kanban.example.com";
const ADMIN: &str = "admin@example.com";
const ALICE: &str = "alice@example.com";
const BOB: &str = "bob@example.com";
const PASSWORD: &str = "correct-horse";
const ROLE_MEMBER: u8 = 40;

const SCHEMA: &str = "\
    CREATE TABLE boards (id bigint generated by default as identity primary key, \
        title text, owner uuid); \
    CREATE TABLE cards (id bigint generated by default as identity primary key, \
        board bigint references boards(id), \"column\" text, position float8, title text); \
    CREATE TABLE secrets (id bigint generated by default as identity primary key, title text);";

/// The `cards` read rule: a card is readable by its board's owner.
const CARDS_RULE: &str = "boardⱵowner === user.id";

type Socket =
    tokio_tungstenite::WebSocketStream<tokio_tungstenite::MaybeTlsStream<tokio::net::TcpStream>>;

/// A cookie-carrying client addressing one host through `oneshot`.
struct Client {
    router: Router,
    host: &'static str,
    cookies: HashMap<String, String>,
}

impl Client {
    async fn send(&mut self, method: &str, path: &str, body: Option<Value>) -> (StatusCode, Value) {
        let mut builder = Request::builder()
            .method(method)
            .uri(path)
            .header(header::HOST, self.host);
        if !self.cookies.is_empty() {
            let jar = self
                .cookies
                .iter()
                .map(|(k, v)| format!("{k}={v}"))
                .collect::<Vec<_>>()
                .join("; ");
            builder = builder.header(header::COOKIE, jar);
        }
        if method != "GET"
            && let Some(csrf) = self.cookies.get(sc_server::CSRF_COOKIE)
        {
            builder = builder.header(sc_server::CSRF_HEADER, csrf);
        }
        let request = match body {
            Some(ref b) => builder
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(serde_json::to_vec(b).unwrap()))
                .unwrap(),
            None => builder.body(Body::empty()).unwrap(),
        };
        let response = self.router.clone().oneshot(request).await.unwrap();
        let status = response.status();
        for raw in response.headers().get_all(header::SET_COOKIE) {
            if let Ok(text) = raw.to_str()
                && let Some((name, value)) = text.split(';').next().unwrap_or("").split_once('=')
            {
                if value.is_empty() {
                    self.cookies.remove(name);
                } else {
                    self.cookies.insert(name.to_owned(), value.to_owned());
                }
            }
        }
        let bytes = axum::body::to_bytes(response.into_body(), 1024 * 1024)
            .await
            .unwrap();
        let value = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap_or(Value::Null)
        };
        (status, value)
    }

    async fn ok(&mut self, method: &str, path: &str, body: Option<Value>) -> Value {
        let (status, value) = self.send(method, path, body).await;
        assert!(status.is_success(), "{method} {path}: {status} {value}");
        value
    }

    /// Sign in through this host's own login, answering the session token.
    async fn login(&mut self, email: &str) -> String {
        self.send("GET", "/api/whoami", None).await;
        self.send("GET", "/api/auth/status", None).await;
        let (status, body) = self
            .send(
                "POST",
                "/api/login",
                Some(json!({ "email": email, "password": PASSWORD })),
            )
            .await;
        assert_eq!(status, StatusCode::OK, "{body}");
        self.cookies
            .get(sc_server::SESSION_COOKIE)
            .expect("the login set a session")
            .clone()
    }
}

struct Server {
    router: Router,
    catalog: Arc<Catalog>,
    addr: std::net::SocketAddr,
    alice: Uuid,
    bob: Uuid,
    db: TestDb,
    /// This server's providers. The process-wide registry `sc_app` falls back
    /// to is whichever server in this binary installed one last.
    registry: Arc<StreamRegistry>,
}

impl Server {
    fn app(&self) -> Client {
        Client {
            router: self.router.clone(),
            host: APP_HOST,
            cookies: HashMap::new(),
        }
    }

    async fn admin(&self) -> Client {
        let mut admin = Client {
            router: self.router.clone(),
            host: BASE_DOMAIN,
            cookies: HashMap::new(),
        };
        admin.login(ADMIN).await;
        admin
    }

    /// A page on the app, signed in as `email`.
    async fn page(&self, email: &str) -> Socket {
        let session = self.app().login(email).await;
        let mut request = format!("ws://{}/api/live", self.addr)
            .into_client_request()
            .unwrap();
        let headers = request.headers_mut();
        headers.insert(header::HOST, HeaderValue::from_static(APP_HOST));
        headers.insert(
            header::ORIGIN,
            HeaderValue::from_str(&format!("http://{APP_HOST}")).unwrap(),
        );
        headers.insert(
            header::COOKIE,
            HeaderValue::from_str(&format!("{}={session}", sc_server::SESSION_COOKIE)).unwrap(),
        );
        tokio_tungstenite::connect_async(request)
            .await
            .expect("the live socket opens from the app's own page")
            .0
    }

    async fn sql(&self, statement: &str) {
        self.db
            .client()
            .await
            .unwrap()
            .batch_execute(statement)
            .await
            .unwrap();
    }

    /// A card write through the application's REST API, as the admin — the
    /// row layer, so the write seam sees it.
    async fn cards(&self, method: &str, path: &str, body: Option<Value>) -> Value {
        let mut writer = self.app();
        writer.login(ADMIN).await;
        writer.ok(method, path, body).await
    }
}

fn change_stream(name: &str, table: &str) -> Stream {
    let mut stream = Stream::new(name, "table_changes").min_role(ROLE_MEMBER);
    stream.configuration = json!({ "table": table }).as_object().cloned().unwrap();
    stream
}

fn app() -> Application {
    // The framework's required settings, so that saving the app reaches the
    // check on its change streams rather than stopping at its framework.
    let framework = FrameworkRef::new("code")
        .with("store", "apps")
        .with("output", "dist")
        .with("command", "true");
    Application::new("Kanban", "kanban", framework)
        .with_api(ApiConfig::new("rest", "/api"))
        .with_table(TableId("boards".to_owned()))
        .with_table(TableId("cards".to_owned()))
        .with_stream(StreamRef::new("cards_live"))
        .with_stream(StreamRef::new("secret_changes"))
}

async fn setup() -> Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    sc_auth::bootstrap(&catalog).await?;
    sc_catalog::bootstrap_table_meta(&catalog).await?;
    sc_catalog::bootstrap_field_meta(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    save_role(&catalog, &Role::new(ROLE_MEMBER, "Member")).await?;
    create_user(&catalog, ADMIN, PASSWORD, ROLE_ADMIN).await?;
    let alice = create_user(&catalog, ALICE, PASSWORD, ROLE_MEMBER)
        .await?
        .id;
    let bob = create_user(&catalog, BOB, PASSWORD, ROLE_MEMBER).await?.id;

    let evaluator = sc_server::default_js_evaluator();
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let triggers =
        sc_server::install_triggers(&catalog, evaluator.clone(), &agents, &models).await?;

    let mut registry = StreamRegistry::new();
    registry.register(Arc::new(TableChanges) as Arc<dyn StreamProvider>)?;
    let registry = Arc::new(registry);
    let stream_services = sc_server::install_streams_with(
        &catalog,
        &triggers,
        registry.clone(),
        StreamConfig::default(),
    )
    .await?;
    // L3.4: a stream on a table that does not exist is refused on save.
    let err = save_stream(&catalog, &registry, &change_stream("ghosts", "ghosts"))
        .await
        .unwrap_err()
        .to_string();
    assert!(err.contains("no table `ghosts`"), "{err}");
    save_stream(&catalog, &registry, &change_stream("cards_live", "cards")).await?;
    save_stream(
        &catalog,
        &registry,
        &change_stream("secret_changes", "secrets"),
    )
    .await?;
    stream_services.reload(&catalog).await?;

    let apps = Arc::new(
        sc_server::AppMounts::new(catalog.clone())
            .with_base_domain(Some(BASE_DOMAIN.to_owned()))
            .with_evaluator(evaluator)
            .with_triggers(triggers.clone())
            .with_models(models)
            .with_streams(stream_services)
            .with_live_limits(LiveLimits {
                status_interval: Duration::from_millis(100),
                recheck_interval: Duration::from_secs(3600),
                ..LiveLimits::default()
            }),
    );
    let config = sc_server::ServerConfig {
        base_domain: Some(BASE_DOMAIN.to_owned()),
        ..sc_server::ServerConfig::default()
    };
    let sessions = Arc::new(SessionStore::database_with(
        catalog.clone(),
        chrono::Duration::hours(24),
        chrono::Duration::zero(),
        100,
    ));
    let router = sc_server::build_router_with_apps(
        &sc_api::admin_endpoints(),
        sc_server::admin_handlers(catalog.clone(), apps.clone()),
        sessions,
        &config,
        apps.clone(),
    )?;
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    let served = router.clone();
    tokio::spawn(async move {
        let _ = axum::serve(listener, served).await;
    });
    let server = Server {
        router,
        catalog: catalog.clone(),
        addr,
        alice,
        bob,
        db,
        registry,
    };

    // Board 1 is Alice's, board 2 is Bob's.
    server
        .sql(&format!(
            "INSERT INTO boards (id, title, owner) VALUES (1, 'alice', '{alice}'), (2, 'bob', '{bob}'); \
             SELECT setval(pg_get_serial_sequence('boards', 'id'), 100);"
        ))
        .await;
    let mut admin = server.admin().await;
    for (table, formula) in [("boards", "owner === user.id"), ("cards", CARDS_RULE)] {
        admin
            .ok(
                "PUT",
                &format!("/api/tables/{table}"),
                Some(json!({
                    "label": "", "description": "",
                    "min_role_read": ROLE_ADMIN, "min_role_write": ROLE_ADMIN,
                    "ownership_formula": formula, "rls_enabled": false, "sync_enabled": false,
                })),
            )
            .await;
    }

    let framework = Arc::new(CodeFramework::new(
        "code",
        AssetBundle::new().with("index.html", "<!doctype html>"),
    ));
    // Mounted directly, not saved: `secret_changes` (whose table is outside
    // the app) is what saving refuses, and the socket must refuse it as well.
    apps.mount(sc_server::MountedApp::new_with(
        app(),
        framework,
        &catalog,
        apps.evaluator(),
        apps.triggers(),
    )?)?;
    Ok(server)
}

// --- frames -------------------------------------------------------------------

async fn send(socket: &mut Socket, frame: Value) {
    socket
        .send(Message::text(frame.to_string()))
        .await
        .expect("the socket takes a frame");
}

async fn next_frame(socket: &mut Socket) -> Value {
    loop {
        let message = tokio::time::timeout(Duration::from_secs(20), socket.next())
            .await
            .expect("a frame arrives within the timeout")
            .expect("the socket is still open")
            .expect("the frame is readable");
        match message {
            Message::Text(text) => return serde_json::from_str(&text).unwrap(),
            Message::Ping(_) | Message::Pong(_) => continue,
            other => panic!("expected a text frame, got {other:?}"),
        }
    }
}

/// Subscribe (with a topic and a filter, or not) and wait for `ready` or
/// `error`.
async fn subscribe(
    socket: &mut Socket,
    sub: &str,
    stream: &str,
    topic: Option<Value>,
    filter: Option<Value>,
) -> Value {
    let mut frame = json!({ "type": "subscribe", "sub": sub, "stream": stream });
    if let Some(topic) = topic {
        frame["topic"] = topic;
    }
    if let Some(filter) = filter {
        frame["filter"] = filter;
    }
    send(socket, frame).await;
    loop {
        let frame = next_frame(socket).await;
        if frame["sub"] == json!(sub) && (frame["type"] == "ready" || frame["type"] == "error") {
            return frame;
        }
    }
}

/// The next `element` frame about `sub`: its `{op, key, row?}`. Every other
/// frame for this subscription in between (a status) is skipped; an element
/// for another subscription is a failure.
async fn next_change(socket: &mut Socket, sub: &str) -> Value {
    loop {
        let frame = next_frame(socket).await;
        if frame["type"] == "element" {
            assert_eq!(frame["sub"], json!(sub), "an element for {sub}: {frame}");
            assert!(
                frame["envelope"].get("topic").is_none(),
                "a change has no topic: {frame}"
            );
            return frame["envelope"]["value"].clone();
        }
        assert_ne!(frame["type"], "error", "{frame}");
        assert_ne!(frame["type"], "revoked", "{frame}");
    }
}

/// The next change is about card `key`, with `op`.
async fn next_is(socket: &mut Socket, sub: &str, op: &str, key: i64) -> Value {
    let value = next_change(socket, sub).await;
    assert_eq!(
        (value["op"].as_str(), value["key"].as_i64()),
        (Some(op), Some(key)),
        "expected {op} of card {key}, got {value}"
    );
    value
}

// --- L3.4/L3.6: subscribing, and every way it is refused ---------------------

#[tokio::test]
async fn a_change_stream_is_subscribed_with_a_filter_and_refused_like_any_absence() -> Result<()> {
    let server = setup().await?;
    let mut alice = server.page(ALICE).await;

    let ready = subscribe(
        &mut alice,
        "s1",
        "cards_live",
        None,
        Some(json!({ "board": 1 })),
    )
    .await;
    assert_eq!(ready["type"], "ready", "{ready}");
    assert_eq!(ready["replayed"], 0, "a change stream replays nothing");
    // The element type is the table's: `row` carries the columns.
    let keys = &ready["element_type"]["keys"];
    assert_eq!(keys[0]["name"], "op");
    assert_eq!(keys[2]["name"], "row");
    let columns: Vec<&str> = keys[2]["keys"]
        .as_array()
        .expect("row has keys")
        .iter()
        .filter_map(|key| key["name"].as_str())
        .collect();
    assert_eq!(columns, vec!["id", "board", "column", "position", "title"]);

    // A table outside the app is absent — the same frame a misspelt name gets.
    let outside = subscribe(&mut alice, "s2", "secret_changes", None, None).await;
    let misspelt = subscribe(&mut alice, "s3", "cards_lvie", None, None).await;
    assert_eq!(outside["code"], "unavailable", "{outside}");
    assert_eq!(misspelt["code"], "unavailable", "{misspelt}");
    assert_eq!(
        outside["message"]
            .as_str()
            .unwrap()
            .replace("secret_changes", "?"),
        misspelt["message"]
            .as_str()
            .unwrap()
            .replace("cards_lvie", "?"),
        "denial looks like absence"
    );

    // A topic is malformed on a change stream, and so is a filter on a field
    // the REST read does not filter on.
    let topic = subscribe(&mut alice, "s4", "cards_live", Some(json!(1)), None).await;
    assert_eq!(topic["code"], "invalid", "{topic}");
    let unknown = subscribe(
        &mut alice,
        "s5",
        "cards_live",
        None,
        Some(json!({ "colour": "red" })),
    )
    .await;
    assert_eq!(unknown["code"], "invalid", "{unknown}");
    assert!(
        unknown["message"].as_str().unwrap().contains("colour"),
        "{unknown}"
    );

    // Saving an app that exposes a change stream on a table it does not
    // include is refused, naming both.
    let err = sc_app::save_application(&server.catalog, &app())
        .await
        .unwrap_err()
        .to_string();
    assert!(
        err.contains("secret_changes") && err.contains("secrets"),
        "{err}"
    );
    Ok(())
}

// --- L3.7/L3.8: what each user is sent ----------------------------------------

#[tokio::test]
async fn a_card_moving_between_boards_leaves_one_view_and_enters_the_other() -> Result<()> {
    let server = setup().await?;
    let mut alice = server.page(ALICE).await;
    let mut bob = server.page(BOB).await;
    let ready = subscribe(
        &mut alice,
        "board1",
        "cards_live",
        None,
        Some(json!({ "board": 1 })),
    )
    .await;
    assert_eq!(ready["type"], "ready", "{ready}");
    let ready = subscribe(&mut bob, "mine", "cards_live", None, None).await;
    assert_eq!(ready["type"], "ready", "{ready}");

    server
        .cards(
            "POST",
            "/api/cards",
            Some(json!({ "id": 1, "board": 1, "column": "todo", "position": 1.0, "title": "Write it" })),
        )
        .await;
    let inserted = next_is(&mut alice, "board1", "insert", 1).await;
    assert_eq!(inserted["row"]["title"], "Write it");

    server
        .cards("PUT", "/api/cards/1", Some(json!({ "column": "done" })))
        .await;
    assert_eq!(
        next_is(&mut alice, "board1", "update", 1).await["row"]["column"],
        "done"
    );

    // To Bob's board: Alice is told it left, and nothing of where it went.
    server
        .cards("PUT", "/api/cards/1", Some(json!({ "board": 2 })))
        .await;
    assert_eq!(
        next_change(&mut alice, "board1").await,
        json!({ "op": "leave", "key": 1 })
    );
    let entered = next_is(&mut bob, "mine", "enter", 1).await;
    assert_eq!(entered["row"]["board"], 2);

    server.cards("DELETE", "/api/cards/1", None).await;
    assert_eq!(
        next_change(&mut bob, "mine").await,
        json!({ "op": "delete", "key": 1 })
    );

    // Neither socket carried anything about a card its user could not read:
    // the next change each gets is its own.
    server
        .cards(
            "POST",
            "/api/cards",
            Some(json!({ "id": 2, "board": 1, "title": "hers" })),
        )
        .await;
    server
        .cards(
            "POST",
            "/api/cards",
            Some(json!({ "id": 3, "board": 2, "title": "his" })),
        )
        .await;
    next_is(&mut alice, "board1", "insert", 2).await;
    next_is(&mut bob, "mine", "insert", 3).await;

    // L3.9: the admin sees what the checks decided.
    let mut admin = server.admin().await;
    let listed = admin.ok("GET", "/api/streams", None).await;
    let row = listed
        .as_array()
        .unwrap()
        .iter()
        .find(|stream| stream["name"] == "cards_live")
        .expect("listed")
        .clone();
    let changes = &row["changes"];
    assert_eq!(changes["checked"], 12, "{changes}");
    assert_eq!(changes["delivered"], 7, "{changes}");
    assert_eq!(
        changes["suppressed_access"].as_u64().unwrap()
            + changes["suppressed_filter"].as_u64().unwrap(),
        5,
        "{changes}"
    );
    let id = row["id"].as_str().unwrap().to_owned();
    let status = admin
        .ok("GET", &format!("/api/streams/{id}/status"), None)
        .await;
    assert_eq!(status["changes"], *changes);
    assert_eq!(status["subscribers"], 2);
    let _ = (server.alice, server.bob);
    Ok(())
}

// --- L3.4: the generated type follows the schema ------------------------------

#[tokio::test]
async fn a_column_added_to_the_table_reaches_the_generated_element_type() -> Result<()> {
    let server = setup().await?;
    let mut app = app();
    app.streams.retain(|stream| stream.0 == "cards_live");
    let row_keys = |streams: &[sc_app::ExposedStream]| -> Vec<String> {
        streams[0]
            .element_type
            .keys()
            .iter()
            .find(|key| key.name == "row")
            .expect("a row key")
            .keys
            .iter()
            .map(|key| key.name.clone())
            .collect()
    };
    let before = sc_app::app_streams_with(&app, &server.catalog, &server.registry).await?;
    assert!(!row_keys(&before).contains(&"due".to_owned()));
    server.sql("ALTER TABLE cards ADD COLUMN due date;").await;
    server.catalog.reload().await?;
    let after = sc_app::app_streams_with(&app, &server.catalog, &server.registry).await?;
    assert!(
        row_keys(&after).contains(&"due".to_owned()),
        "{:?}",
        row_keys(&after)
    );
    // …and it is what the client generator writes.
    let client = sc_api::generate_client_with_streams(
        &sc_api::EndpointSet::default(),
        &sc_app::stream_exports(&app, &after),
    );
    assert!(
        client.contains("due"),
        "the generated client types `row.due`"
    );
    Ok(())
}
