//! Milestone L2: **internal streams, topics and server-side publishing**
//! (TODO.md "Live updates"), driven through the assembled router on a real port
//! against a real database, with real WebSocket clients — two users, two
//! connections, as the ground rules ask.
//!
//! What is claimed, by task:
//!
//! - **L2.1/L2.2** an `internal` stream is published to through the hub, and
//!   every way a publish can be wrong is an error the publisher sees: an unknown
//!   stream, a stream Saltcorn does not publish to, a disabled one, a topic of
//!   the wrong kind, a value that does not match (counted as `malformed`).
//! - **L2.3/L2.4** a `user` stream puts each subscriber on their own id: Alice's
//!   elements never reach Bob, **including through `retain_last`**, and a page
//!   opened late is handed its own latest element first (counted in
//!   `replayed`). Anonymous is the same `unavailable` as a misspelt name.
//! - **L2.5** a `row` topic is let in only when the caller's REST read of the
//!   row returns it — on a runtime-checked table (an ownership formula through
//!   a `shares` table) and on an RLS table — and a missing row is the same
//!   `unavailable` as a forbidden one; a table outside the app is absent too.
//! - **L2.6** removing Bob's share revokes his subscription at once, with the
//!   clock re-check set to an hour so nothing else could have done it.
//! - **L2.7** a workflow started by Alice publishes "Started", waits, publishes
//!   "Done", and only Alice's socket hears either; a `user` publish with nobody
//!   to tell is an error naming the trigger.
//! - **L2.8** a `run_js_code` loop's ten progress elements arrive in order.
//! - **L2.9** the trigger form's action list offers `publish`, its stream picker
//!   filled with the internal streams.
//! - **L3.2** (done here, because L2.6 needed it) with the live hub observing a
//!   table, that table's trigger still fires: the write seam holds both.
