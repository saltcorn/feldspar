/// A cookie-carrying client addressing one host through `oneshot`.
struct Client {
    router: Router,
    host: &'static str,
    cookies: HashMap<String, String>,
}

impl Client {
    async fn send(&mut self, method: &str, path: &str, body: Option<Value>) -> (StatusCode, Value) {
        let mut builder = Request::builder()
            .method(method)
            .uri(path)
            .header(header::HOST, self.host);
        if !self.cookies.is_empty() {
            let jar = self
                .cookies
                .iter()
                .map(|(k, v)| format!("{k}={v}"))
                .collect::<Vec<_>>()
                .join("; ");
            builder = builder.header(header::COOKIE, jar);
        }
        if method != "GET"
            && let Some(csrf) = self.cookies.get(sc_server::CSRF_COOKIE)
        {
            builder = builder.header(sc_server::CSRF_HEADER, csrf);
        }
        let request = match body {
            Some(ref b) => builder
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(serde_json::to_vec(b).unwrap()))
                .unwrap(),
            None => builder.body(Body::empty()).unwrap(),
        };
        let response = self.router.clone().oneshot(request).await.unwrap();
        let status = response.status();
        for raw in response.headers().get_all(header::SET_COOKIE) {
            if let Ok(text) = raw.to_str()
                && let Some((name, value)) = text.split(';').next().unwrap_or("").split_once('=')
            {
                if value.is_empty() {
                    self.cookies.remove(name);
                } else {
                    self.cookies.insert(name.to_owned(), value.to_owned());
                }
            }
        }
        let bytes = axum::body::to_bytes(response.into_body(), 1024 * 1024)
            .await
            .unwrap();
        let value = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap_or(Value::Null)
        };
        (status, value)
    }

    async fn ok(&mut self, method: &str, path: &str, body: Option<Value>) -> Value {
        let (status, value) = self.send(method, path, body).await;
        assert!(status.is_success(), "{method} {path}: {status} {value}");
        value
    }

    /// Sign in through this host's own login, answering the session token.
    async fn login(&mut self, email: &str) -> String {
        // Either host's CSRF cookie, before the first mutating request.
        self.send("GET", "/api/whoami", None).await;
        self.send("GET", "/api/auth/status", None).await;
        let (status, body) = self
            .send(
                "POST",
                "/api/login",
                Some(json!({ "email": email, "password": PASSWORD })),
            )
            .await;
        assert_eq!(status, StatusCode::OK, "{body}");
        self.cookies
            .get(sc_server::SESSION_COOKIE)
            .expect("the login set a session")
            .clone()
    }
}

struct Server {
    router: Router,
    apps: Arc<sc_server::AppMounts>,
    addr: std::net::SocketAddr,
    alice: Uuid,
    bob: Uuid,
    _engine: Arc<sc_workflow::WorkflowEngineTask>,
    db: TestDb,
}

impl Server {
    fn app(&self) -> Client {
        Client {
            router: self.router.clone(),
            host: APP_HOST,
            cookies: HashMap::new(),
        }
    }

    async fn admin(&self) -> Client {
        let mut admin = Client {
            router: self.router.clone(),
            host: BASE_DOMAIN,
            cookies: HashMap::new(),
        };
        admin.login(ADMIN).await;
        admin
    }

    /// A page on the app, signed in as `session` (or not).
    async fn page(&self, session: Option<&str>) -> Socket {
        let mut request = format!("ws://{}/api/live", self.addr)
            .into_client_request()
            .unwrap();
        let headers = request.headers_mut();
        headers.insert(header::HOST, HeaderValue::from_static(APP_HOST));
        headers.insert(
            header::ORIGIN,
            HeaderValue::from_str(&format!("http://{APP_HOST}")).unwrap(),
        );
        if let Some(token) = session {
            headers.insert(
                header::COOKIE,
                HeaderValue::from_str(&format!("{}={token}", sc_server::SESSION_COOKIE)).unwrap(),
            );
        }
        tokio_tungstenite::connect_async(request)
            .await
            .expect("the live socket opens from the app's own page")
            .0
    }

    /// Publish through the hub, as the `publish` action and `live.publish` do.
    fn publish(&self, stream: &str, topic: Option<String>, value: Value) -> Result<Option<String>> {
        self.apps.live().hub().publish(stream, topic, value)
    }

    async fn sql(&self, statement: &str) {
        self.db
            .client()
            .await
            .unwrap()
            .batch_execute(statement)
            .await
            .unwrap();
    }

    async fn count(&self, table: &str) -> i64 {
        self.db
            .client()
            .await
            .unwrap()
            .query_one(&format!("SELECT count(*) FROM {table}"), &[])
            .await
            .unwrap()
            .get(0)
    }
}

/// Every internal stream the app exposes, and one scripted stream Saltcorn may
/// not publish to.
fn streams() -> Vec<Stream> {
    let message_keys = json!([
        { "name": "message", "type": "text", "required": true },
        { "name": "progress", "type": "float" }
    ]);
    let internal = |name: &str, config: Value, min_role: u8| {
        let mut stream = Stream::new(name, "internal").min_role(min_role);
        stream.configuration = config.as_object().cloned().unwrap();
        stream
    };
    let mut dormant = internal(
        "dormant_status",
        json!({ "keys": message_keys, "topics": "single" }),
        ROLE_PUBLIC,
    );
    dormant
        .attributes
        .insert(sc_stream::ATTR_ENABLED.to_owned(), Value::Bool(false));
    vec![
        internal(
            "job_status",
            json!({ "keys": message_keys, "topics": "user", "retain_last": true }),
            ROLE_MEMBER,
        ),
        internal(
            "announcements",
            json!({ "keys": message_keys, "topics": "single" }),
            ROLE_PUBLIC,
        ),
        internal(
            "board_activity",
            json!({ "keys": message_keys, "topics": "row", "table": "boards" }),
            ROLE_MEMBER,
        ),
        internal(
            "rls_activity",
            json!({ "keys": message_keys, "topics": "row", "table": "rls_boards" }),
            ROLE_MEMBER,
        ),
        internal(
            "secret_activity",
            json!({ "keys": message_keys, "topics": "row", "table": "secrets" }),
            ROLE_PUBLIC,
        ),
        dormant,
        Stream::new("boiler", "scripted").min_role(ROLE_PUBLIC),
    ]
}

fn app() -> Application {
    let mut app = Application::new("Boards", "boards", FrameworkRef::new("code"))
        .with_api(ApiConfig::new("rest", "/api"))
        .with_table(TableId("boards".to_owned()))
        .with_table(TableId("rls_boards".to_owned()))
        .with_trigger(TriggerRef::new("long_report"))
        .with_trigger(TriggerRef::new("progress_js"))
        .with_trigger(TriggerRef::new("announce_nobody"));
    for stream in streams() {
        app = app.with_stream(StreamRef::new(&stream.name));
    }
    app
}

/// Limits with the status clock turned down to test speed and the re-check
/// clock turned **up**, so anything revoked in a test was revoked by a write.
fn limits() -> LiveLimits {
    LiveLimits {
        status_interval: Duration::from_millis(100),
        recheck_interval: Duration::from_secs(3600),
        ..LiveLimits::default()
    }
}

async fn setup() -> Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    sc_auth::bootstrap(&catalog).await?;
    sc_catalog::bootstrap_table_meta(&catalog).await?;
    sc_catalog::bootstrap_field_meta(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    save_role(&catalog, &Role::new(ROLE_MEMBER, "Member")).await?;
    create_user(&catalog, ADMIN, PASSWORD, ROLE_ADMIN).await?;
    let alice = create_user(&catalog, ALICE, PASSWORD, ROLE_MEMBER)
        .await?
        .id;
    let bob = create_user(&catalog, BOB, PASSWORD, ROLE_MEMBER).await?.id;

    let evaluator = sc_server::default_js_evaluator();
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let triggers =
        sc_server::install_triggers(&catalog, evaluator.clone(), &agents, &models).await?;
    let (engine, _) = sc_server::start_workflow_engine(&catalog, &triggers);

    let mut registry = StreamRegistry::new();
    registry.register(Arc::new(Internal) as Arc<dyn StreamProvider>)?;
    registry.register(Arc::new(
        ScriptedProvider::new("scripted", ElementType::text()).every(Duration::from_secs(3600)),
    ) as Arc<dyn StreamProvider>)?;
    let registry = Arc::new(registry);
    let stream_services = sc_server::install_streams_with(
        &catalog,
        &triggers,
        registry.clone(),
        StreamConfig::default(),
    )
    .await?;
    for stream in streams() {
        save_stream(&catalog, &registry, &stream).await?;
    }
    stream_services.reload(&catalog).await?;

    let apps = Arc::new(
        sc_server::AppMounts::new(catalog.clone())
            .with_base_domain(Some(BASE_DOMAIN.to_owned()))
            .with_evaluator(evaluator)
            .with_triggers(triggers.clone())
            .with_models(models)
            .with_streams(stream_services)
            .with_live_limits(limits()),
    );
    let config = sc_server::ServerConfig {
        base_domain: Some(BASE_DOMAIN.to_owned()),
        ..sc_server::ServerConfig::default()
    };
    let sessions = Arc::new(SessionStore::database_with(
        catalog.clone(),
        chrono::Duration::hours(24),
        chrono::Duration::zero(),
        100,
    ));
    let router = sc_server::build_router_with_apps(
        &sc_api::admin_endpoints(),
        sc_server::admin_handlers(catalog.clone(), apps.clone()),
        sessions,
        &config,
        apps.clone(),
    )?;
    let listener = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    let served = router.clone();
    tokio::spawn(async move {
        let _ = axum::serve(listener, served).await;
    });

    let server = Server {
        router,
        apps: apps.clone(),
        addr,
        alice,
        bob,
        _engine: engine,
        db,
    };

    // The rows first — an RLS table refuses a raw insert once it is on.
    // Board 1 is Alice's, 2 is Bob's, 3 is Alice's and shared with Bob.
    server
        .sql(&format!(
            "INSERT INTO boards (id, title, owner) VALUES \
               (1, 'alice', '{alice}'), (2, 'bob', '{bob}'), (3, 'shared', '{alice}'); \
             INSERT INTO shares (board, member) VALUES (3, '{bob}'); \
             INSERT INTO rls_boards (id, title, owner) VALUES (1, 'alice', '{alice}'), (2, 'bob', '{bob}'); \
             INSERT INTO secrets (id, title) VALUES (1, 'nobody here sees this'); \
             SELECT setval(pg_get_serial_sequence('boards', 'id'), 100); \
             SELECT setval(pg_get_serial_sequence('rls_boards', 'id'), 100);"
        ))
        .await;

    // The read rules, through the admin API as an admin sets them.
    let mut admin = server.admin().await;
    for (table, formula, rls, read) in [
        ("boards", BOARDS_RULE, false, ROLE_ADMIN),
        ("rls_boards", "owner === user.id", true, ROLE_ADMIN),
        ("secrets", "", false, ROLE_PUBLIC),
    ] {
        admin
            .ok(
                "PUT",
                &format!("/api/tables/{table}"),
                Some(json!({
                    "label": "", "description": "",
                    "min_role_read": read, "min_role_write": 1,
                    "ownership_formula": formula, "rls_enabled": rls, "sync_enabled": false,
                })),
            )
            .await;
    }
    // The triggers the app exposes, saved through the admin API so `publish`
    // is validated against the live streams.
    let message = |text: &str| json!({ "message": format!("\"{text}\"") });
    admin
        .ok(
            "POST",
            "/api/triggers",
            Some(json!({
                "name": "progress_js", "description": "", "when": "none", "channel": null,
                "only_if": null, "body": "action", "action": "run_js_code",
                "configuration": { "code":
                    "for (let i = 1; i <= 10; i++) {\n\
                       live.publish(\"job_status\", user.id, { message: \"step \" + i, progress: i / 10 });\n\
                     }\n\
                     return \"published\";" },
                "min_role": ROLE_MEMBER, "enabled": true,
            })),
        )
        .await;
    admin
        .ok(
            "POST",
            "/api/triggers",
            Some(json!({
                "name": "announce_nobody", "description": "", "when": "none", "channel": null,
                "only_if": null, "body": "action", "action": "publish",
                "configuration": { "stream": "job_status", "value": message("hello?") },
                "min_role": ROLE_PUBLIC, "enabled": true,
            })),
        )
        .await;
    let created = admin
        .ok(
            "POST",
            "/api/triggers",
            Some(json!({
                "name": "long_report", "description": "", "when": "none", "channel": null,
                "only_if": null, "body": "workflow", "action": null, "configuration": null,
                "min_role": ROLE_MEMBER, "enabled": true,
            })),
        )
        .await;
    let id = created["id"].as_str().unwrap().to_owned();
    let saved = admin
        .ok(
            "POST",
            &format!("/api/workflows/{id}"),
            Some(json!({ "description": "", "workflow": {
                "start": "started",
                "trace": true,
                "steps": [
                    { "name": "started",
                      "kind": { "type": "action", "action": "publish",
                                "configuration": { "stream": "job_status", "value": message("Started") } },
                      "next": { "type": "step", "step": "working" } },
                    { "name": "working", "kind": { "type": "wait", "until": "300" },
                      "next": { "type": "step", "step": "done" } },
                    { "name": "done",
                      "kind": { "type": "action", "action": "publish",
                                "configuration": { "stream": "job_status", "value": message("Done") } },
                      "next": { "type": "end" } }
                ]
            }})),
        )
        .await;
    assert_eq!(saved["issues"], json!([]), "{saved}");

    // A table trigger on `boards`, for L3.2: it must still fire while the live
    // hub observes the same table.
    save_trigger(
        &catalog,
        &triggers.registry(),
        &Trigger::new("log_board", EventKind::Insert, "insert_row")
            .on("boards")
            .config("table", "board_log")
            .config("values", json!({ "title": "row.title" })),
    )
    .await?;
    triggers.reload(&catalog).await?;

    let framework = Arc::new(CodeFramework::new(
        "code",
        AssetBundle::new().with("index.html", "<!doctype html>"),
    ));
    apps.mount(sc_server::MountedApp::new_with(
        app(),
        framework,
        &catalog,
        apps.evaluator(),
        apps.triggers(),
    )?)?;
    Ok(server)
}

// --- frames -------------------------------------------------------------------

async fn send(socket: &mut Socket, frame: Value) {
    socket
        .send(Message::text(frame.to_string()))
        .await
        .expect("the socket takes a frame");
}

async fn next_frame(socket: &mut Socket) -> Value {
    loop {
        let message = tokio::time::timeout(Duration::from_secs(20), socket.next())
            .await
            .expect("a frame arrives within the timeout")
            .expect("the socket is still open")
            .expect("the frame is readable");
        match message {
            Message::Text(text) => return serde_json::from_str(&text).unwrap(),
            Message::Ping(_) | Message::Pong(_) => continue,
            other => panic!("expected a text frame, got {other:?}"),
        }
    }
}

/// Subscribe and wait for `ready` or `error`.
async fn subscribe(socket: &mut Socket, sub: &str, stream: &str, topic: Option<Value>) -> Value {
    let mut frame = json!({ "type": "subscribe", "sub": sub, "stream": stream });
    if let Some(topic) = topic {
        frame["topic"] = topic;
    }
    send(socket, frame).await;
    loop {
        let frame = next_frame(socket).await;
        if frame["sub"] == json!(sub) && (frame["type"] == "ready" || frame["type"] == "error") {
            return frame;
        }
    }
}

/// The next frame of `kind` about `sub`, skipping status frames and others'.
async fn frame_for(socket: &mut Socket, sub: &str, kind: &str) -> Value {
    loop {
        let frame = next_frame(socket).await;
        if frame["type"] == json!(kind) && frame["sub"] == json!(sub) {
            return frame;
        }
        assert!(
            !(frame["sub"] == json!(sub) && frame["type"] == "error"),
            "expected `{kind}` for {sub}, got an error: {frame}"
        );
    }
}

/// Every frame up to the answer to a `ping` — what has arrived by now, read
/// without waiting on a timeout.
async fn drain(socket: &mut Socket) -> Vec<Value> {
    send(socket, json!({ "type": "ping" })).await;
    let mut frames = Vec::new();
    loop {
        let frame = next_frame(socket).await;
        if frame["type"] == "pong" {
            return frames;
        }
        frames.push(frame);
    }
}

fn elements(frames: &[Value]) -> Vec<&Value> {
    frames.iter().filter(|f| f["type"] == "element").collect()
}

// --- L2.1/L2.2: publishing, and every way it can be refused -------------------

#[tokio::test]
async fn a_publish_is_refused_whenever_it_cannot_be_delivered() -> Result<()> {
    let server = setup().await?;
    let ok = json!({ "message": "hi" });
    let alice = Some(server.alice.to_string());

    // Each refusal is an error the publisher sees, worded for them.
    let cases: Vec<(&str, Option<String>, Value, &str)> = vec![
        ("nowhere", None, ok.clone(), "no stream `nowhere`"),
        ("boiler", None, ok.clone(), "only an `internal` stream"),
        (
            "dormant_status",
            None,
            ok.clone(),
            "no stream `dormant_status` running",
        ),
        (
            "announcements",
            Some("7".into()),
            ok.clone(),
            "has no topics",
        ),
        ("job_status", None, ok.clone(), "needs the user"),
        (
            "job_status",
            Some("bob".into()),
            ok.clone(),
            "is not a user id",
        ),
        ("board_activity", None, ok.clone(), "key of the row"),
        (
            "job_status",
            alice.clone(),
            json!({ "progress": 0.5 }),
            "does not match",
        ),
        (
            "job_status",
            alice.clone(),
            json!({ "message": 7 }),
            "does not match",
        ),
    ];
    for (stream, topic, value, needle) in cases {
        let error = server
            .publish(stream, topic.clone(), value.clone())
            .expect_err(&format!("{stream} {topic:?} {value}"))
            .to_string();
        assert!(error.contains(needle), "{stream} {topic:?}: {error}");
    }
    // The two that did not match were counted as malformed, as a broker's bad
    // payload is.
    let running = server
        .apps
        .streams()
        .unwrap()
        .supervisor()
        .by_name("job_status")
        .unwrap();
    assert_eq!(running.counters().malformed, 2);

    // And one that is right goes out, its topic in the canonical spelling.
    let shouted = server.alice.to_string().to_uppercase();
    assert_eq!(
        server.publish("job_status", Some(shouted), ok)?,
        Some(server.alice.hyphenated().to_string())
    );
    Ok(())
}

// --- L2.3/L2.4: user topics, and what is retained -----------------------------

#[tokio::test]
async fn a_user_topic_reaches_its_own_user_only_including_what_is_retained() -> Result<()> {
    let server = setup().await?;
    let alice_id = server.alice.hyphenated().to_string();
    let bob_id = server.bob.hyphenated().to_string();

    // Published before anybody is watching: kept, per topic.
    server.publish(
        "job_status",
        Some(alice_id.clone()),
        json!({ "message": "alice 40%", "progress": 0.4 }),
    )?;
    server.publish(
        "job_status",
        Some(bob_id.clone()),
        json!({ "message": "bob 10%", "progress": 0.1 }),
    )?;

    let alice_session = server.app().login(ALICE).await;
    let bob_session = server.app().login(BOB).await;
    let mut alice = server.page(Some(&alice_session)).await;
    let mut bob = server.page(Some(&bob_session)).await;

    // Each is handed their own retained element first, counted as history.
    let ready = subscribe(&mut alice, "s1", "job_status", None).await;
    assert_eq!(ready["type"], "ready", "{ready}");
    assert_eq!(ready["replayed"], 1);
    let first = frame_for(&mut alice, "s1", "element").await;
    assert_eq!(first["envelope"]["value"]["message"], "alice 40%");
    assert_eq!(first["envelope"]["topic"], json!(alice_id));
    let ready = subscribe(&mut bob, "s1", "job_status", None).await;
    assert_eq!(ready["replayed"], 1);
    let first = frame_for(&mut bob, "s1", "element").await;
    assert_eq!(first["envelope"]["value"]["message"], "bob 10%");

    // Live: Alice's next element reaches Alice and nobody else.
    server.publish(
        "job_status",
        Some(alice_id.clone()),
        json!({ "message": "alice 50%", "progress": 0.5 }),
    )?;
    let next = frame_for(&mut alice, "s1", "element").await;
    assert_eq!(next["envelope"]["value"]["message"], "alice 50%");
    assert!(
        elements(&drain(&mut bob).await).is_empty(),
        "nothing of Alice's reached Bob"
    );

    // A page Alice reloads is handed her latest, and only hers.
    let mut reloaded = server.page(Some(&alice_session)).await;
    let ready = subscribe(&mut reloaded, "s1", "job_status", None).await;
    assert_eq!(ready["replayed"], 1);
    let latest = frame_for(&mut reloaded, "s1", "element").await;
    assert_eq!(latest["envelope"]["value"]["progress"], 0.5);
    assert!(
        elements(&drain(&mut reloaded).await).is_empty(),
        "one, not the history"
    );

    // A topic is the subscriber's own, never named — Bob cannot ask for Alice's.
    let named = subscribe(&mut bob, "s2", "job_status", Some(json!(alice_id))).await;
    assert_eq!(named["code"], "invalid", "{named}");

    // Anonymous has no topic, and is told the stream is not there — in the same
    // words as a name that does not exist.
    let mut anonymous = server.page(None).await;
    let denied = subscribe(&mut anonymous, "s1", "job_status", None).await;
    let missing = subscribe(&mut anonymous, "s2", "job_statuz", None).await;
    assert_eq!(denied["code"], "unavailable");
    assert_eq!(missing["code"], "unavailable");
    assert_eq!(
        denied["message"]
            .as_str()
            .unwrap()
            .replace("job_status", "?"),
        missing["message"]
            .as_str()
            .unwrap()
            .replace("job_statuz", "?")
    );

    // A stream that retains nothing replays nothing.
    server.publish("announcements", None, json!({ "message": "before" }))?;
    let ready = subscribe(&mut anonymous, "s3", "announcements", None).await;
    assert_eq!(ready["replayed"], 0, "{ready}");
    Ok(())
}

// --- L2.5: row topics, by the REST read of the row ----------------------------

#[tokio::test]
async fn a_row_topic_needs_the_rest_read_of_its_row() -> Result<()> {
    let server = setup().await?;
    let alice_session = server.app().login(ALICE).await;
    let bob_session = server.app().login(BOB).await;
    let mut alice = server.page(Some(&alice_session)).await;
    let mut bob = server.page(Some(&bob_session)).await;

    // The owner may; a key given as a number names the same row as its text.
    let ready = subscribe(&mut alice, "own", "board_activity", Some(json!(1))).await;
    assert_eq!(ready["type"], "ready", "{ready}");
    // Shared through `shares`: Bob may read board 3, so he may subscribe.
    let ready = subscribe(&mut bob, "shared", "board_activity", Some(json!("3"))).await;
    assert_eq!(ready["type"], "ready", "{ready}");

    // Bob may not read board 1, and board 999 does not exist: one answer.
    let forbidden = subscribe(&mut bob, "a", "board_activity", Some(json!(1))).await;
    let missing = subscribe(&mut bob, "b", "board_activity", Some(json!(999))).await;
    let garbled = subscribe(&mut bob, "c", "board_activity", Some(json!("not-a-key"))).await;
    for frame in [&forbidden, &missing, &garbled] {
        assert_eq!(frame["code"], "unavailable", "{frame}");
        assert_eq!(
            frame["message"], forbidden["message"],
            "denial looks like absence"
        );
    }
    // A row stream needs its row named.
    let unnamed = subscribe(&mut bob, "d", "board_activity", None).await;
    assert_eq!(unnamed["code"], "invalid", "{unnamed}");

    // What is published on a row reaches the subscriptions on that row only.
    server.publish(
        "board_activity",
        Some("1".into()),
        json!({ "message": "on board 1" }),
    )?;
    server.publish(
        "board_activity",
        Some("3".into()),
        json!({ "message": "on board 3" }),
    )?;
    let alices = frame_for(&mut alice, "own", "element").await;
    assert_eq!(alices["envelope"]["topic"], "1");
    let bobs = frame_for(&mut bob, "shared", "element").await;
    assert_eq!(bobs["envelope"]["value"]["message"], "on board 3");
    let rest = drain(&mut bob).await;
    assert!(
        elements(&rest).is_empty(),
        "board 1's element never reached Bob: {rest:?}"
    );

    // An RLS table: the database's policies decide, through the same read.
    let ready = subscribe(&mut alice, "rls", "rls_activity", Some(json!(1))).await;
    assert_eq!(ready["type"], "ready", "{ready}");
    let refused = subscribe(&mut bob, "rls", "rls_activity", Some(json!(1))).await;
    assert_eq!(refused["code"], "unavailable", "{refused}");
    let own = subscribe(&mut bob, "rls2", "rls_activity", Some(json!(2))).await;
    assert_eq!(own["type"], "ready", "{own}");

    // A table outside the application's subset does not exist for its pages —
    // even for an admin, who may read every row of it elsewhere.
    let admin_session = server.app().login(ADMIN).await;
    let mut admin = server.page(Some(&admin_session)).await;
    let absent = subscribe(&mut admin, "s", "secret_activity", Some(json!(1))).await;
    assert_eq!(absent["code"], "unavailable", "{absent}");
    let readable = subscribe(&mut admin, "t", "board_activity", Some(json!(2))).await;
    assert_eq!(
        readable["type"], "ready",
        "an admin meets every floor: {readable}"
    );
    Ok(())
}

// --- L2.6: re-checked when a write could have changed it ----------------------

#[tokio::test]
async fn removing_a_share_revokes_the_subscription_without_waiting_for_the_clock() -> Result<()> {
    let server = setup().await?;
    let bob_session = server.app().login(BOB).await;
    let mut bob = server.page(Some(&bob_session)).await;
    let ready = subscribe(&mut bob, "shared", "board_activity", Some(json!(3))).await;
    assert_eq!(ready["type"], "ready", "{ready}");
    let own = subscribe(&mut bob, "own", "board_activity", Some(json!(2))).await;
    assert_eq!(own["type"], "ready", "{own}");
    assert!(
        server.apps.live().hub().watches("shares"),
        "the read rule's other table is watched"
    );

    // The share goes, through the admin's row editor — an ordinary write.
    let share: i64 = server
        .db
        .client()
        .await
        .unwrap()
        .query_one("SELECT id FROM shares WHERE board = 3", &[])
        .await
        .unwrap()
        .get(0);
    let mut admin = server.admin().await;
    admin
        .ok("DELETE", &format!("/api/tables/shares/rows/{share}"), None)
        .await;

    // Revoked at once — the clock is an hour away — and only the subscription
    // that depended on the share.
    let revoked = tokio::time::timeout(
        Duration::from_secs(10),
        frame_for(&mut bob, "shared", "revoked"),
    )
    .await
    .expect("revoked by the write, not by the clock");
    assert_eq!(revoked["sub"], "shared");
    server.publish(
        "board_activity",
        Some("2".into()),
        json!({ "message": "still yours" }),
    )?;
    let still = frame_for(&mut bob, "own", "element").await;
    assert_eq!(still["envelope"]["value"]["message"], "still yours");
    server.publish(
        "board_activity",
        Some("3".into()),
        json!({ "message": "not any more" }),
    )?;
    let rest = drain(&mut bob).await;
    assert!(elements(&rest).is_empty(), "{rest:?}");

    // Moving board 2 to Alice revokes Bob's last one: its own row changed.
    admin
        .ok(
            "PUT",
            "/api/tables/boards/rows/2",
            Some(json!({ "owner": server.alice.to_string() })),
        )
        .await;
    let revoked = tokio::time::timeout(
        Duration::from_secs(10),
        frame_for(&mut bob, "own", "revoked"),
    )
    .await
    .expect("revoked by the write to its own row");
    assert_eq!(revoked["sub"], "own");
    // With nothing left watching them, the hub stops observing the tables.
    drain(&mut bob).await;
    assert!(!server.apps.live().hub().watches("boards"));
    assert!(!server.apps.live().hub().watches("shares"));
    Ok(())
}

// --- L2.7: the `publish` action, from a workflow started by one user ----------

#[tokio::test]
async fn a_workflow_tells_the_user_who_started_it_and_nobody_else() -> Result<()> {
    let server = setup().await?;
    let mut alice_client = server.app();
    let alice_session = alice_client.login(ALICE).await;
    let bob_session = server.app().login(BOB).await;
    let mut alice = server.page(Some(&alice_session)).await;
    let mut bob = server.page(Some(&bob_session)).await;
    assert_eq!(
        subscribe(&mut alice, "jobs", "job_status", None).await["type"],
        "ready"
    );
    assert_eq!(
        subscribe(&mut bob, "jobs", "job_status", None).await["type"],
        "ready"
    );

    // Alice clicks the button.
    let (status, body) = alice_client
        .send("POST", "/api/actions/long_report", Some(json!({})))
        .await;
    assert!(status.is_success(), "{status} {body}");

    // "Started", then — after the durable wait — "Done", both to Alice.
    let started = frame_for(&mut alice, "jobs", "element").await;
    assert_eq!(started["envelope"]["value"]["message"], "Started");
    assert_eq!(
        started["envelope"]["topic"],
        json!(server.alice.hyphenated().to_string())
    );
    let done = frame_for(&mut alice, "jobs", "element").await;
    assert_eq!(done["envelope"]["value"]["message"], "Done");
    let heard = drain(&mut bob).await;
    assert!(elements(&heard).is_empty(), "Bob heard nothing: {heard:?}");

    // A per-user publish with nobody to tell is an error naming the trigger,
    // not a message dropped on the floor.
    let mut anonymous = server.app();
    anonymous.send("GET", "/api/whoami", None).await;
    let (status, body) = anonymous
        .send("POST", "/api/actions/announce_nobody", Some(json!({})))
        .await;
    assert!(!status.is_success(), "{status} {body}");
    let text = body.to_string();
    assert!(
        text.contains("announce_nobody") && text.contains("no user"),
        "{text}"
    );
    Ok(())
}

