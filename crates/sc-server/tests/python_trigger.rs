//! A **Python** trigger through the assembled server (the Python code adapter,
//! phase 2.5).
//!
//! `code_body_tables.rs` presses the admin's Run button on a `run_js_code` body
//! and reads the written rows back over HTTP. This file asks the same question
//! of the same schema in the other language, because what phase 2.5 wires is not
//! the interpreter — that is `sc-python`'s own suite — but the **boot**: that the
//! adapter is built from this process's flags, registered on the dispatcher
//! whether or not this binary has an interpreter linked in, and that a stored
//! Python trigger is therefore a meaningful configuration in every build.
//!
//! So the assertions are deliberately different in the two builds, and both are
//! the point:
//!
//! - built **with** `--features python`: the body runs, and the rows are there —
//!   the same rows, from the same plans, as the JavaScript body's;
//! - built **without** it (the default, and what the release tarball ships): the
//!   trigger still exists, still validates, and firing it answers with the
//!   sentence naming the rebuild.
//!
//! The interpreter is **not** started by booting a server, in either build, and
//! that is asserted before anything fires.

#![allow(clippy::unwrap_used, clippy::expect_used)]

