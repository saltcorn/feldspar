struct Client {
    router: Router,
    cookies: HashMap<String, String>,
}

impl Client {
    async fn send(&mut self, method: &str, path: &str, body: Option<Value>) -> (StatusCode, Value) {
        let mut builder = Request::builder().method(method).uri(path);
        if !self.cookies.is_empty() {
            let jar = self
                .cookies
                .iter()
                .map(|(k, v)| format!("{k}={v}"))
                .collect::<Vec<_>>()
                .join("; ");
            builder = builder.header(header::COOKIE, jar);
        }
        if method != "GET"
            && let Some(csrf) = self.cookies.get(CSRF_COOKIE)
        {
            builder = builder.header(CSRF_HEADER, csrf);
        }
        let request = match body {
            Some(ref b) => builder
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(serde_json::to_vec(b).unwrap()))
                .unwrap(),
            None => builder.body(Body::empty()).unwrap(),
        };
        let response = self.router.clone().oneshot(request).await.unwrap();
        let status = response.status();
        for raw in response.headers().get_all(header::SET_COOKIE) {
            if let Ok(text) = raw.to_str()
                && let Some((name, value)) = text.split(';').next().unwrap_or("").split_once('=')
            {
                self.cookies.insert(name.to_owned(), value.to_owned());
            }
        }
        let bytes = axum::body::to_bytes(response.into_body(), 512 * 1024)
            .await
            .unwrap();
        let value = if bytes.is_empty() {
            Value::Null
        } else {
            serde_json::from_slice(&bytes).unwrap_or(Value::Null)
        };
        (status, value)
    }

    async fn ok(&mut self, method: &str, path: &str, body: Option<Value>) -> Value {
        let (status, value) = self.send(method, path, body).await;
        assert!(status.is_success(), "{method} {path}: {status} {value}");
        value
    }
}

struct Server {
    client: Client,
    _engine: Arc<sc_workflow::WorkflowEngineTask>,
    _db: TestDb,
}

async fn setup() -> sc_error::Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    sc_auth::bootstrap(&catalog).await?;
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let dispatcher = install_triggers(&catalog, default_js_evaluator(), &agents, &models).await?;
    // The tutorial's reader is running `serve`, which is the only thing that
    // starts the engine (§10.3, phase 3.3).
    let (engine, _handle) = start_workflow_engine(&catalog, &dispatcher);

    let apps = Arc::new(AppMounts::new(catalog.clone()).with_triggers(dispatcher.clone()));
    let router = build_router_with_apps(
        &sc_api::admin_endpoints(),
        admin_handlers(catalog.clone(), apps.clone()),
        Arc::new(SessionStore::default()),
        &ServerConfig::default(),
        apps,
    )?;

    let mut client = Client {
        router,
        cookies: HashMap::new(),
    };
    client.send("GET", "/api/auth/status", None).await;
    let (status, body) = client
        .send(
            "POST",
            "/api/first-user",
            Some(json!({ "email": ADMIN, "password": PASSWORD })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");

    Ok(Server {
        client,
        _engine: engine,
        _db: db,
    })
}

/// Steps 2 and 8: the trigger, and the program saved into it. Answers the
/// trigger's id.
async fn drawn(server: &mut Server) -> String {
    let created = server
        .client
        .ok("POST", "/api/triggers", Some(tutorial_trigger()))
        .await;
    let id = created["id"].as_str().expect("an id").to_owned();
    let saved = server
        .client
        .ok(
            "POST",
            &format!("/api/workflows/{id}"),
            Some(json!({ "workflow": tutorial_workflow(), "description": "the tutorial" })),
        )
        .await;
    // Everything the tutorial types holds together: no unreachable step, no
    // formula that will not resolve, no action setting that does not validate.
    assert_eq!(saved["issues"], json!([]), "{saved}");
    assert_eq!(saved["version"], json!(2), "creating the trigger minted v1");
    id
}

/// Step 9: an order with its lines, then the update that submits it.
async fn submit(server: &mut Server, total: i64, quantities: &[i64]) -> i64 {
    let order = server
        .client
        .ok(
            "POST",
            "/api/tables/orders/rows",
            Some(json!({ "customer": "Acme", "email": "buyer@example.com", "total": total })),
        )
        .await;
    let id = order["id"].as_i64().expect("the order's id");
    for (n, qty) in quantities.iter().enumerate() {
        server
            .client
            .ok(
                "POST",
                "/api/tables/order_lines/rows",
                Some(json!({ "order": id, "item": format!("thing {n}"), "qty": qty })),
            )
            .await;
    }
    server
        .client
        .ok(
            "PUT",
            &format!("/api/tables/orders/rows/{id}"),
            Some(json!({ "status": "submitted" })),
        )
        .await;
    id
}

/// The one run of this workflow.
async fn the_run(server: &mut Server, trigger: &str) -> Value {
    let runs = server
        .client
        .ok("GET", &format!("/api/workflows/{trigger}/runs"), None)
        .await;
    let runs = runs.as_array().cloned().unwrap_or_default();
    assert_eq!(runs.len(), 1, "{runs:?}");
    runs[0].clone()
}

async fn order(server: &mut Server, id: i64) -> Value {
    let rows = server
        .client
        .ok("GET", "/api/tables/orders/rows", None)
        .await;
    rows.as_array()
        .and_then(|rows| {
            rows.iter()
                .find(|row| row["id"].as_i64() == Some(id))
                .cloned()
        })
        .expect("the order")
}

