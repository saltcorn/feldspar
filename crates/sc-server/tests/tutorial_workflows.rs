//! The workflows tutorial, executed: the program `docs/tutorial-workflows.md`
//! asks the reader to draw, saved and run for real (§10.3, TODO 8.1).
//!
//! The precedent is `sc-core-actions`' `tutorial_triggers.rs`, and the reason is
//! the same: a tutorial is a promise that the words in the boxes work, and the
//! ways it stops being true are quiet ones — a formula rule tightens, an action
//! renames a setting, a step kind gains a required field. None of those break a
//! test that only reads the markdown, so this one **copies the program out of the
//! document** and puts it through the admin API the tutorial drives by hand:
//! create the trigger, save the workflow, submit an order, watch the run suspend
//! at the approval, answer it, and read back the two rows the workflow wrote.
//!
//! What it pins, in the tutorial's own order:
//!
//! - the `only_if` that keeps the workflow's own write from starting a second run
//!   — the hazard a workflow on a table it also writes actually has;
//! - a code step whose **return value** is the context key later steps read;
//! - the loop: a `Set` before it, a `for_each` over the code step's answer, and a
//!   body that accumulates — one advance, one write and one trace row per item;
//! - the branch, the approval form's declaration, and the answer merged under
//!   `context.approval`;
//! - the two endings, one of which is the tutorial's example of an **idempotent**
//!   step (an update keyed by the event's row) and the other of which is its
//!   example of a step made idempotent **by hand** (a code body that checks
//!   before it writes);
//! - and the rule its "trips people up" section states about scope: an action
//!   step's settings read `context` like every other formula a step contains,
//!   and the same action outside a workflow has no run to read.
//!
//! Those last two are what the tutorial's paragraphs promise, so they fail here
//! before a reader finds them wrong.

