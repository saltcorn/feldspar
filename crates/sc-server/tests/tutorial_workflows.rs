/// Step 2's trigger: an **update** that becomes `submitted`, so the order's lines
/// exist by the time the run reads them and the workflow's own write to `status`
/// does not start a second run.
fn tutorial_trigger() -> Value {
    json!({
        "name": "order_approval",
        "description": "",
        "when": "update",
        "channel": "orders",
        "only_if": "status === 'submitted' && old.status !== 'submitted'",
        "body": "workflow",
        "action": Value::Null,
        "configuration": Value::Null,
        "min_role": Value::Null,
        "enabled": true,
    })
}

