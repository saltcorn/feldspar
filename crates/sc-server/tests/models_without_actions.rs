//! Milestone 31's definition of done, walked end to end through the assembled
//! router: models without actions of their own.
//!
//! - The models tutorial's `houses`, with the `House prices` linear regression
//!   over a dataset holding `neighbourhoodⱵaverage_income` and
//!   `viewingsↃhouse.length`, filtered to the sold houses.
//! - A non-stored calculated field `estimated_price = predict("House prices")`:
//!   listing `houses` answers a number in every row, the unsold house
//!   included, for **one** provider call; filtering on it is refused naming it.
//! - A nightly `fit_model` with `activate: if_clean`: the new fit becomes
//!   active and the next read follows it with nothing edited, while a stub
//!   provider that warns leaves its new fit inactive.
//! - Radon, over the stub posterior provider (no CmdStan): a workflow runs
//!   `fit_model`, then a `run_js_code` step writes the posterior back through
//!   `models.get("Radon")`, filling `counties.alpha_mean` and firing the
//!   `counties` update trigger. The same body learns that a posterior does not
//!   predict (pointing at `m.draws`) and that a regression's handle has no
//!   `draws`. The Python body does the same through `m.write_posterior` (with
//!   `--features python`; without it, the sentence naming the rebuild).
//! - `listActions` has `fit_model` and neither `predict_row` nor
//!   `write_posterior`.
//!
//! The Radon half against a real CmdStan is `stan_models.rs`'s `#[ignore]`d
//! `radon_is_refitted_by_a_workflow_and_written_back_from_code`.
