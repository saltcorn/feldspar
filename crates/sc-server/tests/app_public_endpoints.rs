/// The exemption is not a hole, and does not anonymise a signed-in user: a
/// request carrying a session but not its token — a stale token in an old
/// tab — is refused with 403 and the token, on a public endpoint as anywhere
/// stricter, so the client retries as the user. Without a session cookie the
/// same request is anybody's.
#[tokio::test]
async fn a_session_with_a_stale_token_is_refused_not_anonymised() -> sc_error::Result<()> {
    let server = setup().await?;
    let r = &server.router;
    let (session, csrf) = server.editor_session().await;
    let jar = [
        (SESSION_COOKIE, session.as_str()),
        (CSRF_COOKIE, csrf.as_str()),
    ];

    // With the token, the editor is the caller.
    let (status, body, _) = send(
        r,
        "POST",
        "/api/actions/sign",
        Some(json!({ "message": "signed" })),
        &jar,
        Some(&csrf),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");

    // A stale token, or none, on the public trigger and the public query alike:
    // refused before anything runs, not run as nobody.
    for token in [Some("stale-token"), None] {
        let (status, body, set) = send(
            r,
            "POST",
            "/api/actions/sign",
            Some(json!({ "message": "as nobody" })),
            &jar,
            token,
        )
        .await;
        assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
        assert!(body.to_string().contains("CSRF"), "{body}");
        assert_eq!(cookie(&set, SESSION_COOKIE), None, "{set:?}");
        let (status, body, _) = send(r, "POST", "/api/stats/latest", None, &jar, token).await;
        assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
    }
    assert_eq!(server.guestbook().await.len(), 1);

    // Retried with the cookie's token, the query is the editor's.
    let (status, body, _) = send(r, "POST", "/api/stats/latest", None, &jar, Some(&csrf)).await;
    assert_eq!(status, StatusCode::OK, "{body}");

    // The editor's own trigger, without the token: refused, as it always was.
    let (status, body, _) = send(
        r,
        "POST",
        "/api/actions/sign_as_editor",
        Some(json!({ "message": "forged" })),
        &jar,
        None,
    )
    .await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");

    // With no session cookie, the public trigger is anybody's, token or not.
    let (status, body, _) = send(
        r,
        "POST",
        "/api/actions/sign",
        Some(json!({ "message": "guest" })),
        &[(CSRF_COOKIE, csrf.as_str())],
        Some("stale-token"),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(
        server.guestbook().await,
        vec![
            ("signed".to_owned(), Some(EDITOR.to_owned())),
            ("guest".to_owned(), None),
        ]
    );

    // And the session survived it all.
    let (status, body, _) = send(r, "GET", "/api/whoami", None, &jar, None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(body["email"], json!(EDITOR), "{body}");
    Ok(())
}

/// One `POST` from a native app: the client-kind header, exactly the cookies
/// given, and the CSRF header when there is one. Answers the status, the token
/// the response names, and the cookies it sets.
async fn native_post(
    router: &Router,
    path: &str,
    body: Value,
    cookies: &[(&str, &str)],
    csrf: Option<&str>,
) -> (StatusCode, Option<String>, Vec<String>) {
    let mut builder = Request::builder()
        .method("POST")
        .uri(path)
        .header(header::HOST, APP_HOST)
        .header(header::CONTENT_TYPE, "application/json")
        .header(
            sc_api::auth::CLIENT_KIND_HEADER,
            sc_api::auth::NATIVE_CLIENT,
        );
    if !cookies.is_empty() {
        let jar = cookies
            .iter()
            .map(|(k, v)| format!("{k}={v}"))
            .collect::<Vec<_>>()
            .join("; ");
        builder = builder.header(header::COOKIE, jar);
    }
    if let Some(token) = csrf {
        builder = builder.header(CSRF_HEADER, token);
    }
    let request = builder
        .body(Body::from(serde_json::to_vec(&body).unwrap()))
        .unwrap();
    let response = router.clone().oneshot(request).await.unwrap();
    let token = response
        .headers()
        .get(CSRF_HEADER)
        .and_then(|v| v.to_str().ok())
        .map(str::to_owned);
    let set_cookies = response
        .headers()
        .get_all(header::SET_COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok().map(str::to_owned))
        .collect();
    (response.status(), token, set_cookies)
}

/// A native app reopened while signed in keeps its session cookie but not its
/// token. Its write to a public endpoint is **refused**, naming a token, rather
/// than served as nobody while the app shows the user signed in; with that token
/// it is the user's. A native app with no session is still anybody.
#[tokio::test]
async fn a_signed_in_native_app_without_its_token_is_refused_not_anonymised() -> sc_error::Result<()>
{
    let server = setup().await?;
    let r = &server.router;
    let (session, _) = server.editor_session().await;

    // After the restart: the session, and no CSRF cookie or token.
    let restarted = [(SESSION_COOKIE, session.as_str())];
    let (status, token, set) = native_post(
        r,
        "/api/actions/sign",
        json!({ "message": "lost" }),
        &restarted,
        None,
    )
    .await;
    assert_eq!(status, StatusCode::FORBIDDEN);
    assert!(
        server.guestbook().await.is_empty(),
        "nothing written as nobody"
    );
    let token = token.expect("the refusal names a token");
    assert_eq!(cookie(&set, CSRF_COOKIE).as_deref(), Some(token.as_str()));

    // Retried with it, the write is the editor's.
    let jar = [
        (SESSION_COOKIE, session.as_str()),
        (CSRF_COOKIE, token.as_str()),
    ];
    let (status, _, _) = native_post(
        r,
        "/api/actions/sign",
        json!({ "message": "mine" }),
        &jar,
        Some(&token),
    )
    .await;
    assert_eq!(status, StatusCode::OK);

    // Signed out, a native app is anybody, as a browser is.
    let (status, _, _) = native_post(
        r,
        "/api/actions/sign",
        json!({ "message": "guest" }),
        &[],
        None,
    )
    .await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(
        server.guestbook().await,
        vec![
            ("mine".to_owned(), Some(EDITOR.to_owned())),
            ("guest".to_owned(), None),
        ]
    );
    Ok(())
}
