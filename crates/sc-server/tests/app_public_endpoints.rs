//! An application endpoint whose role floor is the **public** role (100) is open
//! to anybody: no user, no password, no session, and no CSRF token (§7).
//!
//! Role 100 is the role a caller nobody is logged in as holds, so a floor at it
//! is not "any logged-in user of role 100" — it is "everybody". Driven through
//! the assembled router against a real database, for each of the three places
//! an application sets such a floor:
//!
//! - a **table** whose `min_role_read` / `min_role_write` is 100 — its REST
//!   endpoints;
//! - a **custom query** whose `min_role` is 100;
//! - an exposed **trigger** whose `min_role` is 100.
//!
//! The custom queries include two written in **JavaScript** (§13.4), which run
//! on the `run_js_code` action with the request in scope as `body` and `query`.
//!
//! Each is called with no cookie at all, which is how a `curl`, a webhook or a
//! third-party page calls it. And the CSRF exemption is bounded: a request that
//! carries a session but no token is served as the anonymous caller it would be
//! without one — its cookie lends it no authority — while an endpoint with any
//! stricter floor still refuses a request without the token.

