const ADMIN: &str = "admin@example.com";
const PASSWORD: &str = "correct-horse";
const ROLE_EDITOR: u8 = 80;

/// One request, spelled out: exactly the cookies and the CSRF header given, and
/// nothing a helper might add behind the test's back.
async fn send(
    router: &Router,
    method: &str,
    path: &str,
    body: Option<Value>,
    cookies: &[(&str, &str)],
    csrf: Option<&str>,
) -> (StatusCode, Value, Vec<String>) {
    let mut builder = Request::builder()
        .method(method)
        .uri(path)
        .header(header::HOST, APP_HOST);
    if !cookies.is_empty() {
        let jar = cookies
            .iter()
            .map(|(k, v)| format!("{k}={v}"))
            .collect::<Vec<_>>()
            .join("; ");
        builder = builder.header(header::COOKIE, jar);
    }
    if let Some(token) = csrf {
        builder = builder.header(CSRF_HEADER, token);
    }
    let request = match body {
        Some(b) => builder
            .header(header::CONTENT_TYPE, "application/json")
            .body(Body::from(serde_json::to_vec(&b).unwrap()))
            .unwrap(),
        None => builder.body(Body::empty()).unwrap(),
    };
    let response = router.clone().oneshot(request).await.unwrap();
    let status = response.status();
    let set_cookies = response
        .headers()
        .get_all(header::SET_COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok().map(str::to_owned))
        .collect();
    let bytes = axum::body::to_bytes(response.into_body(), 256 * 1024)
        .await
        .unwrap();
    let value = serde_json::from_slice(&bytes)
        .unwrap_or_else(|_| Value::String(String::from_utf8_lossy(&bytes).into_owned()));
    (status, value, set_cookies)
}

/// The value `name` is set to among a response's `Set-Cookie` headers.
fn cookie(set_cookies: &[String], name: &str) -> Option<String> {
    set_cookies.iter().find_map(|raw| {
        let (k, v) = raw.split(';').next()?.split_once('=')?;
        (k == name && !v.is_empty()).then(|| v.to_owned())
    })
}

/// A trigger writing a guestbook row from the payload and the caller.
fn sign_trigger(name: &str, min_role: u8) -> Trigger {
    Trigger::new(name, EventKind::None, "insert_row")
        .config("table", "guestbook")
        .config(
            "values",
            json!({ "message": "payload.message", "who": "user?.email ?? null" }),
        )
        .min_role(min_role)
}

fn guests_app() -> Application {
    let mut api = ApiConfig::new("rest", "/api");
    set_custom_queries(
        &mut api.config,
        &[
            CustomQuery::new(
                "countSignatures",
                Method::Get,
                "/stats/count",
                "SELECT count(*) AS n FROM guestbook",
            )
            .min_role(ROLE_PUBLIC),
            // A POST, so the CSRF middleware has something to say about it.
            CustomQuery::new(
                "latestSignature",
                Method::Post,
                "/stats/latest",
                "SELECT message FROM guestbook ORDER BY id DESC LIMIT 1",
            )
            .min_role(ROLE_PUBLIC),
            // JavaScript: a GET reading its query string, the declared
            // parameter arriving as a number…
            CustomQuery::new(
                "greet",
                Method::Get,
                "/js/greet",
                "return { hello: query.name ?? 'nobody', next: query.n + 1, \
                          who: user?.email ?? null, body };",
            )
            .language(QueryLanguage::Javascript)
            .params([CustomParam::new("n", ValueType::Int)])
            .min_role(ROLE_PUBLIC),
            // …and a POST writing through the row layer from its body.
            CustomQuery::new(
                "signJs",
                Method::Post,
                "/js/sign",
                "if (!body.message) throw new Error('say something');\n\
                 await db.guestbook.insert({ message: body.message, who: user?.email ?? null });\n\
                 return { signatures: await db.guestbook.count() };",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
            // TODO F1.1, F1.2 and F1.4: no params, yet the body arrives; the
            // web codecs; and a status of the body's choosing.
            CustomQuery::new(
                "created",
                Method::Post,
                "/js/created",
                "return response({ status: 201, headers: { 'X-Id': '7' }, \
                   body: { uuid: crypto.randomUUID().length, b: btoa('hi'), echo: body } });",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
            CustomQuery::new(
                "deny",
                Method::Get,
                "/js/deny",
                "throw httpError(401, 'sign in');",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
            CustomQuery::new(
                "taken",
                Method::Post,
                "/js/taken",
                "httpError(409, 'taken', { field: 'email', taken: true });",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
            CustomQuery::new(
                "cookie",
                Method::Get,
                "/js/cookie",
                "return response({ headers: { 'set-cookie': 'sid=forged' }, body: {} });",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
            CustomQuery::new("spin", Method::Get, "/js/spin", "while (true) {}")
                .language(QueryLanguage::Javascript)
                .min_role(ROLE_PUBLIC),
            // A read of the admin-only table, run as an anonymous caller: the
            // refusal let through, and the same refusal caught and replaced.
            CustomQuery::new(
                "peek",
                Method::Get,
                "/js/peek",
                "return await db.secrets.rows();",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
            CustomQuery::new(
                "peekCaught",
                Method::Get,
                "/js/peek-caught",
                "try { await db.secrets.rows(); } catch (e) { throw new Error('no secrets'); }",
            )
            .language(QueryLanguage::Javascript)
            .min_role(ROLE_PUBLIC),
        ],
    )
    .unwrap();
    Application::new("Guests", "guests", FrameworkRef::new("code"))
        .with_table(TableId("guestbook".to_owned()))
        .with_table(TableId("secrets".to_owned()))
        .with_api(api)
        .with_trigger(TriggerRef::new("sign"))
        .with_trigger(TriggerRef::new("sign_as_editor"))
        .with_trigger(TriggerRef::new("refuse"))
}

struct Server {
    router: Router,
    db: TestDb,
}

impl Server {
    async fn guestbook(&self) -> Vec<(String, Option<String>)> {
        let rows = self
            .db
            .client()
            .await
            .unwrap()
            .query("SELECT message, who FROM guestbook ORDER BY id", &[])
            .await
            .unwrap();
        rows.iter().map(|r| (r.get(0), r.get(1))).collect()
    }

    /// Log the editor in through the app's own login, returning the session and
    /// CSRF cookies a browser would then hold.
    async fn editor_session(&self) -> (String, String) {
        self.session_of(EDITOR).await
    }

    /// Log `email` in through the app's own login, returning the session and
    /// CSRF cookies a browser would then hold.
    async fn session_of(&self, email: &str) -> (String, String) {
        let (_, _, primed) = send(&self.router, "GET", "/api/whoami", None, &[], None).await;
        let csrf = cookie(&primed, CSRF_COOKIE).expect("a first contact mints the CSRF cookie");
        let (status, body, set) = send(
            &self.router,
            "POST",
            "/api/login",
            Some(json!({ "email": email, "password": PASSWORD })),
            &[(CSRF_COOKIE, &csrf)],
            Some(&csrf),
        )
        .await;
        assert_eq!(status, StatusCode::OK, "{body}");
        (
            cookie(&set, SESSION_COOKIE).expect("a login sets the session"),
            csrf,
        )
    }
}

async fn setup() -> sc_error::Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    sc_auth::bootstrap(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    bootstrap_table_meta(&catalog).await?;
    save_role(&catalog, &Role::new(ROLE_EDITOR, "Editor")).await?;
    create_user(&catalog, EDITOR, PASSWORD, ROLE_EDITOR).await?;
    create_user(&catalog, ADMIN, PASSWORD, sc_auth::ROLE_ADMIN).await?;

    // The guestbook is open to everybody, both ways; `secrets` keeps the
    // default, admin-only.
    save_table_meta(
        &catalog,
        &TableMeta::new("guestbook").access(ROLE_PUBLIC, ROLE_PUBLIC),
    )
    .await?;

    let evaluator = default_js_evaluator();
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let dispatcher = install_triggers(&catalog, evaluator.clone(), &agents, &models).await?;
    for trigger in [
        sign_trigger("sign", ROLE_PUBLIC),
        sign_trigger("sign_as_editor", ROLE_EDITOR),
    ] {
        save_trigger(&catalog, &dispatcher.registry(), &trigger).await?;
    }
    // An exposed trigger whose body answers with a status (TODO F1.4).
    save_trigger(
        &catalog,
        &dispatcher.registry(),
        &Trigger::new("refuse", EventKind::None, "run_js_code")
            .config(
                "code",
                "if (payload.boom) throw new Error('kaboom'); throw httpError(402, 'pay first');",
            )
            .min_role(ROLE_PUBLIC),
    )
    .await?;
    dispatcher.reload(&catalog).await?;

    let apps = Arc::new(
        AppMounts::new(catalog.clone())
            .with_evaluator(evaluator)
            .with_triggers(dispatcher.clone()),
    );
    let framework = Arc::new(CodeFramework::new(
        "code",
        AssetBundle::new().with("index.html", "<!doctype html>"),
    ));
    apps.mount(MountedApp::new_with(
        guests_app(),
        framework,
        &catalog,
        apps.evaluator(),
        apps.triggers(),
    )?)?;

    let config = ServerConfig {
        base_domain: Some(BASE_DOMAIN.to_owned()),
        ..ServerConfig::default()
    };
    let router = build_router_with_apps(
        &sc_api::admin_endpoints(),
        admin_handlers(catalog.clone(), apps.clone()),
        Arc::new(SessionStore::default()),
        &config,
        apps,
    )?;
    Ok(Server { router, db })
}

#[tokio::test]
async fn a_public_table_is_read_and_written_with_no_cookie_at_all() -> sc_error::Result<()> {
    let server = setup().await?;
    let r = &server.router;

    // No cookie, no token: a first contact that writes.
    let (status, body, _) = send(
        r,
        "POST",
        "/api/guestbook",
        Some(json!({ "message": "hello" })),
        &[],
        None,
    )
    .await;
    assert!(status.is_success(), "{status}: {body}");

    let (status, body, _) = send(r, "GET", "/api/guestbook", None, &[], None).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body.as_array().map(Vec::len), Some(1), "{body}");

    // The admin-only table beside it is still closed, to a reader and a writer.
    let (status, _, _) = send(r, "GET", "/api/secrets", None, &[], None).await;
    assert_eq!(status, StatusCode::UNAUTHORIZED);
    let (status, _, _) = send(
        r,
        "POST",
        "/api/secrets",
        Some(json!({ "message": "x" })),
        &[],
        None,
    )
    .await;
    assert_eq!(
        status,
        StatusCode::FORBIDDEN,
        "no token, not public: CSRF refuses"
    );
    Ok(())
}

