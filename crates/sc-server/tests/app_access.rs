//! Who may use an application at all (TODO F9): its `min_role`, `max_role` and
//! `access_if`, driven through the assembled router against a real database.
//!
//! - **`min_role`** refuses a less privileged account its sign-in (no session
//!   is started) and every endpoint — including when it arrives holding a
//!   session started somewhere else, as a shared cookie would.
//! - An anonymous caller of an application that does not admit the public
//!   reaches its sign-in and nothing else, even a table open to role 100.
//! - **`max_role`** serves an admin as the capped role: `whoami` says so, and
//!   an admin-only table is refused.
//! - **`access_if`** decides on a user field, and a formula naming something
//!   that is not in scope is refused on save.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;

use axum::Router;
use axum::body::Body;
use axum::http::{Request, StatusCode, header};
use sc_app::{ApiConfig, Application, AssetBundle, CodeFramework, FrameworkRef};
use sc_auth::{ROLE_ADMIN, ROLE_PUBLIC, Role, SessionStore, create_user, save_role};
use sc_catalog::{Catalog, TableId, TableMeta, bootstrap_table_meta, save_table_meta};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_server::{
    AppMounts, CSRF_COOKIE, CSRF_HEADER, MountedApp, SESSION_COOKIE, ServerConfig, admin_handlers,
    build_router_with_apps, default_js_evaluator,
};
use sc_test_harness::TestDb;
use serde_json::{Value, json};
use tower::ServiceExt;

const BASE_DOMAIN: &str = "example.com";
/// `min_role` 40, `max_role` 20.
const STAFF_HOST: &str = "staff.example.com";
/// `access_if` on the department.
const FINANCE_HOST: &str = "finance.example.com";
/// None of the three.
const OPEN_HOST: &str = "open.example.com";

const SCHEMA: &str = "\
    CREATE TABLE notice (id bigint generated by default as identity primary key, \
        message text not null); \
    CREATE TABLE ledger (id bigint generated by default as identity primary key, \
        amount int not null);";

const ADMIN: &str = "admin@example.com";
const ACCOUNTANT: &str = "accountant@example.com";
const ENGINEER: &str = "engineer@example.com";
const MEMBER: &str = "member@example.com";
const PASSWORD: &str = "correct-horse";
const ROLE_STAFF: u8 = 40;
const ROLE_CAPPED: u8 = 20;
const ROLE_MEMBER: u8 = 80;

/// One request to `host`, with exactly the cookies and CSRF header given.
async fn send(
    router: &Router,
    host: &str,
    method: &str,
    path: &str,
    body: Option<Value>,
    cookies: &[(&str, &str)],
    csrf: Option<&str>,
) -> (StatusCode, Value, Vec<String>) {
    let mut builder = Request::builder()
        .method(method)
        .uri(path)
        .header(header::HOST, host);
    if !cookies.is_empty() {
        let jar = cookies
            .iter()
            .map(|(k, v)| format!("{k}={v}"))
            .collect::<Vec<_>>()
            .join("; ");
        builder = builder.header(header::COOKIE, jar);
    }
    if let Some(token) = csrf {
        builder = builder.header(CSRF_HEADER, token);
    }
    let request = match body {
        Some(b) => builder
            .header(header::CONTENT_TYPE, "application/json")
            .body(Body::from(serde_json::to_vec(&b).unwrap()))
            .unwrap(),
        None => builder.body(Body::empty()).unwrap(),
    };
    let response = router.clone().oneshot(request).await.unwrap();
    let status = response.status();
    let set_cookies = response
        .headers()
        .get_all(header::SET_COOKIE)
        .iter()
        .filter_map(|v| v.to_str().ok().map(str::to_owned))
        .collect();
    let bytes = axum::body::to_bytes(response.into_body(), 256 * 1024)
        .await
        .unwrap();
    let value = serde_json::from_slice(&bytes)
        .unwrap_or_else(|_| Value::String(String::from_utf8_lossy(&bytes).into_owned()));
    (status, value, set_cookies)
}

/// The value `name` is set to among a response's `Set-Cookie` headers.
fn cookie(set_cookies: &[String], name: &str) -> Option<String> {
    set_cookies.iter().find_map(|raw| {
        let (k, v) = raw.split(';').next()?.split_once('=')?;
        (k == name && !v.is_empty()).then(|| v.to_owned())
    })
}

fn app(name: &str, subdomain: &str) -> Application {
    // Saved through `save_application`, so a framework whose settings check;
    // what is mounted below serves a bundle all the same.
    let framework = FrameworkRef::new("none")
        .with("store", "site")
        .with("source", subdomain);
    Application::new(name, subdomain, framework)
        .with_table(TableId("notice".to_owned()))
        .with_table(TableId("ledger".to_owned()))
        .with_api(ApiConfig::new("rest", "/api"))
}

struct Server {
    router: Router,
    sessions: Arc<SessionStore>,
    catalog: Arc<Catalog>,
    _db: TestDb,
}

impl Server {
    /// A CSRF cookie for `host`, minted by a first contact.
    async fn csrf(&self, host: &str) -> String {
        let (_, _, primed) = send(&self.router, host, "GET", "/", None, &[], None).await;
        cookie(&primed, CSRF_COOKIE).expect("a first contact mints the CSRF cookie")
    }

    /// Sign `email` in through the application's own login: the status, the
    /// body, and the session cookie it set, if any.
    async fn sign_in(&self, host: &str, email: &str) -> (StatusCode, Value, Option<String>) {
        let csrf = self.csrf(host).await;
        let (status, body, set) = send(
            &self.router,
            host,
            "POST",
            "/api/login",
            Some(json!({ "email": email, "password": PASSWORD })),
            &[(CSRF_COOKIE, &csrf)],
            Some(&csrf),
        )
        .await;
        (status, body, cookie(&set, SESSION_COOKIE))
    }

    async fn get(&self, host: &str, path: &str, session: Option<&str>) -> (StatusCode, Value) {
        let cookies: Vec<(&str, &str)> = session.map(|s| (SESSION_COOKIE, s)).into_iter().collect();
        let (status, body, _) = send(&self.router, host, "GET", path, None, &cookies, None).await;
        (status, body)
    }
}

async fn setup() -> sc_error::Result<Server> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; {SCHEMA}"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    sc_auth::bootstrap(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    bootstrap_table_meta(&catalog).await?;
    db.client()
        .await?
        .batch_execute("ALTER TABLE users ADD COLUMN department text")
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    catalog.reload().await?;
    save_role(&catalog, &Role::new(ROLE_CAPPED, "Manager")).await?;
    save_role(&catalog, &Role::new(ROLE_STAFF, "Staff")).await?;
    save_role(&catalog, &Role::new(ROLE_MEMBER, "Member")).await?;
    create_user(&catalog, ADMIN, PASSWORD, ROLE_ADMIN).await?;
    create_user(&catalog, ACCOUNTANT, PASSWORD, ROLE_STAFF).await?;
    create_user(&catalog, ENGINEER, PASSWORD, ROLE_STAFF).await?;
    create_user(&catalog, MEMBER, PASSWORD, ROLE_MEMBER).await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "UPDATE users SET department = 'Finance' WHERE email IN ('{ACCOUNTANT}', '{MEMBER}'); \
             UPDATE users SET department = 'IT' WHERE email = '{ENGINEER}'; \
             INSERT INTO notice (message) VALUES ('hello'); \
             INSERT INTO ledger (amount) VALUES (100);"
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;

    // The notice is open to everybody; the ledger is admin-only.
    save_table_meta(
        &catalog,
        &TableMeta::new("notice").access(ROLE_PUBLIC, ROLE_PUBLIC),
    )
    .await?;
    save_table_meta(
        &catalog,
        &TableMeta::new("ledger").access(ROLE_ADMIN, ROLE_ADMIN),
    )
    .await?;

    let staff = sc_app::save_application(
        &catalog,
        &app("Staff", "staff")
            .min_role(ROLE_STAFF)
            .max_role(ROLE_CAPPED),
    )
    .await?;
    let finance = sc_app::save_application(
        &catalog,
        &app("Finance", "finance").access_if("user && user.department === \"Finance\""),
    )
    .await?;

    let open = sc_app::save_application(&catalog, &app("Open", "open")).await?;

    let evaluator = default_js_evaluator();
    let apps = Arc::new(AppMounts::new(catalog.clone()).with_evaluator(evaluator));
    for stored in [staff, finance, open] {
        // Mounted as loaded back, so the stored columns are what is served.
        let loaded = sc_app::load_application(&catalog, stored.id)
            .await?
            .unwrap();
        let framework = Arc::new(CodeFramework::new(
            "code",
            AssetBundle::new().with("index.html", "<!doctype html>"),
        ));
        apps.mount(MountedApp::new_with(
            loaded,
            framework,
            &catalog,
            apps.evaluator(),
            apps.triggers(),
        )?)?;
    }

    let config = ServerConfig {
        base_domain: Some(BASE_DOMAIN.to_owned()),
        ..ServerConfig::default()
    };
    let sessions = Arc::new(SessionStore::default());
    let router = build_router_with_apps(
        &sc_api::admin_endpoints(),
        admin_handlers(catalog.clone(), apps.clone()),
        sessions.clone(),
        &config,
        apps,
    )?;
    Ok(Server {
        router,
        sessions,
        catalog,
        _db: db,
    })
}

#[tokio::test]
async fn min_role_refuses_a_less_privileged_account_its_sign_in_and_every_endpoint()
-> sc_error::Result<()> {
    let server = setup().await?;

    // Staff sign in and use the application.
    let (status, body, session) = server.sign_in(STAFF_HOST, ACCOUNTANT).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let session = session.expect("a session is started");
    let (status, body) = server.get(STAFF_HOST, "/api/notice", Some(&session)).await;
    assert_eq!(status, StatusCode::OK, "{body}");

    // A member is refused the sign-in itself, and no session is started.
    let (status, body, session) = server.sign_in(STAFF_HOST, MEMBER).await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
    assert!(session.is_none(), "a refused sign-in starts no session");

    // A member arriving with a session started elsewhere (a shared cookie) is
    // refused every endpoint, a public table included.
    let member = sc_auth::load_user_by_email(&server.catalog, MEMBER)
        .await?
        .unwrap();
    let elsewhere = server.sessions.login(member).await?;
    let (status, body) = server
        .get(STAFF_HOST, "/api/notice", Some(&elsewhere))
        .await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
    let (status, body) = server
        .get(STAFF_HOST, "/api/whoami", Some(&elsewhere))
        .await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");

    // …and the same session is served on an application that admits members.
    let (status, body) = server.get(OPEN_HOST, "/api/notice", Some(&elsewhere)).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    Ok(())
}

#[tokio::test]
async fn an_anonymous_caller_of_a_gated_application_reaches_only_the_sign_in()
-> sc_error::Result<()> {
    let server = setup().await?;

    // The notice table is open to role 100, but the application is not.
    let (status, body) = server.get(STAFF_HOST, "/api/notice", None).await;
    assert_eq!(status, StatusCode::UNAUTHORIZED, "{body}");
    // The bundle that draws the sign-in is served.
    let (status, _) = server.get(STAFF_HOST, "/", None).await;
    assert_eq!(status, StatusCode::OK);
    // And the sign-in is reachable: a wrong password is the login's own answer,
    // not the application's refusal.
    let csrf = server.csrf(STAFF_HOST).await;
    let (status, body, _) = send(
        &server.router,
        STAFF_HOST,
        "POST",
        "/api/login",
        Some(json!({ "email": ACCOUNTANT, "password": "wrong" })),
        &[(CSRF_COOKIE, &csrf)],
        Some(&csrf),
    )
    .await;
    assert_eq!(status, StatusCode::UNAUTHORIZED, "{body}");
    assert!(
        !body.to_string().contains("may use this application"),
        "{body}"
    );
    Ok(())
}

#[tokio::test]
async fn max_role_serves_an_admin_as_the_capped_role() -> sc_error::Result<()> {
    let server = setup().await?;

    let (status, body, session) = server.sign_in(STAFF_HOST, ADMIN).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let session = session.unwrap();
    let (status, body) = server.get(STAFF_HOST, "/api/whoami", Some(&session)).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    assert_eq!(body["role"], json!(ROLE_CAPPED), "{body}");
    // The admin-only ledger is refused to role 20…
    let (status, body) = server.get(STAFF_HOST, "/api/ledger", Some(&session)).await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
    // …and served to the same session on an application that caps nobody.
    let (status, body) = server.get(OPEN_HOST, "/api/ledger", Some(&session)).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let (status, body) = server.get(OPEN_HOST, "/api/whoami", Some(&session)).await;
    assert_eq!(body["role"], json!(ROLE_ADMIN), "{status}: {body}");
    Ok(())
}

#[tokio::test]
async fn access_if_decides_on_a_user_field() -> sc_error::Result<()> {
    let server = setup().await?;

    let (status, body, session) = server.sign_in(FINANCE_HOST, ACCOUNTANT).await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let (status, body) = server
        .get(FINANCE_HOST, "/api/notice", session.as_deref())
        .await;
    assert_eq!(status, StatusCode::OK, "{body}");

    // Same role, another department.
    let (status, body, session) = server.sign_in(FINANCE_HOST, ENGINEER).await;
    assert_eq!(status, StatusCode::FORBIDDEN, "{body}");
    assert!(session.is_none());

    // Nobody signed in has no department either.
    let (status, body) = server.get(FINANCE_HOST, "/api/notice", None).await;
    assert_eq!(status, StatusCode::UNAUTHORIZED, "{body}");
    Ok(())
}

#[tokio::test]
async fn an_access_if_naming_what_is_not_in_scope_is_refused_on_save() -> sc_error::Result<()> {
    let server = setup().await?;
    let unknown = sc_app::save_application(
        &server.catalog,
        &app("Typo", "typo").access_if("user.departmnet === \"Finance\""),
    )
    .await
    .unwrap_err();
    assert!(unknown.to_string().contains("access_if"), "{unknown}");
    // A bare identifier: there is no row in scope.
    let bare = sc_app::save_application(
        &server.catalog,
        &app("Bare", "bare").access_if("amount > 3"),
    )
    .await
    .unwrap_err();
    assert!(bare.to_string().contains("access_if"), "{bare}");
    // The time is in scope.
    sc_app::save_application(
        &server.catalog,
        &app("Hours", "hours").access_if("new Date().getUTCHours() >= 0"),
    )
    .await?;
    Ok(())
}
