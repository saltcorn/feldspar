//! Phase 5: the admin API for workflows, driven through the assembled router
//! against a real database (§10.3).
//!
//! This is the milestone's **definition of done, minus the browser**: create a
//! trigger whose body is a workflow, save a program into it, insert a row, watch
//! the run suspend waiting for a person, answer the form the API renders from the
//! step's own declaration, and read the finished context and its trace back.
//!
//! What else is pinned here: a workflow that does not hold together is refused
//! *with every problem at once* and stores nothing; versions are **append-only**,
//! so a revert is a new version rather than a rewrite; `listActions` says which
//! actions the step palette may offer; and the three buttons an admin has for a
//! stuck run — resume, cancel, retry — each answer the run's new state.

#![allow(clippy::unwrap_used, clippy::expect_used)]

