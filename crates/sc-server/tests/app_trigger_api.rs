//! Phase 7: an application exposes a subset of the server's triggers as API
//! endpoints (§10.2/§13.4), driven through the assembled router against a real
//! database.
//!
//! The claim being tested is narrower than "a trigger can be called over HTTP".
//! It is that **an app's API surface is the app's declaration**:
//!
//! - a trigger the app names is one `POST {mount}/actions/{name}`, the body is
//!   the event's payload, and the answer is what the action returned — including
//!   the row it wrote through the ordinary write path;
//! - the endpoint is guarded by the **trigger's own** `min_role`, and a trigger
//!   with none is admin-only rather than open;
//! - a trigger the app does *not* name is a **404** — not a 403 — even though the
//!   server has it and can run it;
//! - and the set is live: changing a trigger's role through the admin API changes
//!   what the mounted app enforces, with no restart.

