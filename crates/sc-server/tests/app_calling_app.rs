//! The **calling application** in an event (TODO-payments P1.3, design C5): an
//! exposed trigger run through an application's API sees which application it
//! was, at the base URL the request reached it on, and the URL scheme of its
//! native apps — what a checkout's success URL is built from.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;

use axum::Router;
use axum::body::Body;
use axum::http::{Request, StatusCode, header};
use sc_action::{EventKind, Trigger, save_trigger};
use sc_app::{ApiConfig, Application, AssetBundle, CodeFramework, FrameworkRef, TriggerRef};
use sc_auth::SessionStore;
use sc_catalog::{Catalog, TableId};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_server::{
    AppMounts, MountedApp, ServerConfig, admin_handlers, build_router_with_apps,
    default_js_evaluator, install_triggers,
};
use sc_test_harness::TestDb;
use serde_json::{Value, json};
use tower::ServiceExt;

async fn post(router: &Router, host: &str, path: &str, body: Value) -> (StatusCode, Value) {
    let request = Request::builder()
        .method("POST")
        .uri(path)
        .header(header::HOST, host)
        .header(header::CONTENT_TYPE, "application/json")
        .body(Body::from(serde_json::to_vec(&body).unwrap()))
        .unwrap();
    let response = router.clone().oneshot(request).await.unwrap();
    let status = response.status();
    let bytes = axum::body::to_bytes(response.into_body(), 256 * 1024)
        .await
        .unwrap();
    (
        status,
        serde_json::from_slice(&bytes).unwrap_or(Value::Null),
    )
}

async fn setup() -> sc_error::Result<(Router, Arc<Catalog>, sc_app::AppId, TestDb)> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(
            "CREATE TABLE visits (id bigint generated by default as identity primary key, \
                 note text, app_url text)",
        )
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    sc_auth::bootstrap(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    let evaluator = default_js_evaluator();
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let dispatcher = install_triggers(&catalog, evaluator.clone(), &agents, &models).await?;
    for trigger in [
        // What the body is told about where it was called from.
        Trigger::new("whereami", EventKind::None, "run_js_code")
            .config("code", "return { app, session };")
            .min_role(100),
        // And what a write it makes passes on to the event *that* raises: the
        // insert trigger below records the application it sees.
        Trigger::new("visit", EventKind::None, "run_js_code")
            .config(
                "code",
                "await db.visits.insert({ note: payload.note }); return true;",
            )
            .min_role(100),
        Trigger::new("stamp_visit", EventKind::Insert, "run_js_code")
            .on("visits")
            .config(
                "code",
                "await db.visits.where({ id: row.id }).update({ app_url: app && app.url });",
            ),
    ] {
        save_trigger(&catalog, &dispatcher.registry(), &trigger).await?;
    }
    dispatcher.reload(&catalog).await?;

    let apps = Arc::new(
        AppMounts::new(catalog.clone())
            .with_evaluator(evaluator)
            .with_triggers(dispatcher.clone()),
    );
    let app = Application::new("Shop", "shop", FrameworkRef::new("code"))
        .with_table(TableId("visits".to_owned()))
        .with_api(ApiConfig::new("rest", "/api"))
        .with_trigger(TriggerRef::new("whereami"))
        .with_trigger(TriggerRef::new("visit"))
        .attribute(sc_server::URL_SCHEME_ATTRIBUTE, "myshop");
    let id = app.id;
    let framework = Arc::new(CodeFramework::new(
        "code",
        AssetBundle::new().with("index.html", "<!doctype html>"),
    ));
    apps.mount(MountedApp::new_with(
        app,
        framework,
        &catalog,
        apps.evaluator(),
        apps.triggers(),
    )?)?;
    let config = ServerConfig {
        base_domain: Some("example.com".to_owned()),
        // The same applications answer under a second domain too.
        extra_base_domains: vec!["example.org".to_owned()],
        ..ServerConfig::default()
    };
    let router = build_router_with_apps(
        &sc_api::admin_endpoints(),
        admin_handlers(catalog.clone(), apps.clone()),
        Arc::new(SessionStore::default()),
        &config,
        apps,
    )?;
    Ok((router, catalog, id, db))
}

#[tokio::test]
async fn an_exposed_trigger_sees_its_application_at_the_host_it_was_called_on()
-> sc_error::Result<()> {
    let (router, _catalog, id, _db) = setup().await?;

    for host in ["shop.example.com", "shop.example.org"] {
        let (status, body) = post(&router, host, "/api/actions/whereami", json!({})).await;
        assert_eq!(status, StatusCode::OK, "{host}: {body}");
        assert_eq!(body["app"]["id"], json!(id.0), "{host}: {body}");
        assert_eq!(
            body["app"]["url"],
            json!(format!("http://{host}")),
            "{body}"
        );
        assert_eq!(body["app"]["scheme"], json!("myshop"), "{body}");
        // Nobody here has a guest session.
        assert_eq!(body["session"], Value::Null, "{body}");
    }
    Ok(())
}

#[tokio::test]
async fn the_application_travels_to_the_events_its_trigger_raises() -> sc_error::Result<()> {
    let (router, _catalog, _id, db) = setup().await?;
    let (status, body) = post(
        &router,
        "shop.example.org",
        "/api/actions/visit",
        json!({ "note": "hello" }),
    )
    .await;
    assert_eq!(status, StatusCode::OK, "{body}");
    let rows = db
        .client()
        .await?
        .query("SELECT note, app_url FROM visits", &[])
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    assert_eq!(rows.len(), 1);
    let note: String = rows[0].get(0);
    let url: Option<String> = rows[0].get(1);
    assert_eq!(note, "hello");
    assert_eq!(url.as_deref(), Some("http://shop.example.org"));
    Ok(())
}
