//! An application's own code getting and keeping a user's OAuth 2.0 tokens
//! (TODO OA1), end to end through the assembled router against a fake provider
//! on a real port:
//!
//! - a code action's `oauth.begin(…)`, reading the client secret from a Secret
//!   field → `/_feldspar/oauth/consent/{id}` in the caller's browser → the
//!   provider → the shared callback → the completion, which writes the tokens
//!   into the application's row, sealed;
//! - the same from a custom query, which runs as its caller, so the row is
//!   written as the caller; and refused before any browser is involved for a
//!   row the caller may not reach, a non-Secret token field and a module- or
//!   system table;
//! - `oauth.accessToken(…)`: the stored token while it is good, a renewal at
//!   the token endpoint once it is due (written back, sealed), and a refresh
//!   token the provider refuses told as "connect again";
//! - and the hand-rolled alternative: a public GET custom query answering
//!   `response({ status: 302, headers: { location } })` is a real redirect.
#![allow(clippy::unwrap_used, clippy::expect_used)]
#![allow(
    clippy::disallowed_methods,
    reason = "test code: it drives its own servers, tasks and channels; the replacements are for production paths"
)]

