//! LLM credits end to end (TODO-payments P6.2, P6.4): an admin grants credits
//! and sets a user's threshold from the users screen's endpoints, each user
//! reads only their own buckets through an application's REST API, and a debit
//! that takes the balance below the threshold writes a `low_balance` entry an
//! application trigger reacts to — what an auto top-up hangs off.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::collections::HashMap;
use std::sync::Arc;

use axum::Router;
use axum::body::Body;
use axum::http::{Request, StatusCode, header};
use rust_decimal::Decimal;
use sc_action::{EventKind, Trigger, save_trigger};
use sc_app::{ApiConfig, Application, AssetBundle, CodeFramework, FrameworkRef};
use sc_auth::{CreditDebit, ROLE_ADMIN, Role, SessionStore, create_user, save_role};
use sc_catalog::{Catalog, TableId};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_server::{
    AppMounts, CSRF_COOKIE, CSRF_HEADER, MountedApp, ServerConfig, admin_handlers,
    build_router_with_apps, default_js_evaluator, install_triggers,
};
use sc_test_harness::TestDb;
use serde_json::{Value, json};
use tower::ServiceExt;

const BASE_DOMAIN: &str = "example.com";
const APP_HOST: &str = "agents.example.com";

/// A cookie-carrying client addressing one host, echoing CSRF on mutations.
struct Client {
    router: Router,
    host: String,
    cookies: HashMap<String, String>,
}

impl Client {
    fn new(router: Router, host: &str) -> Client {
        Client {
            router,
            host: host.to_owned(),
            cookies: HashMap::new(),
        }
    }

    async fn send(&mut self, method: &str, path: &str, body: Option<Value>) -> (StatusCode, Value) {
        let mut builder = Request::builder()
            .method(method)
            .uri(path)
            .header(header::HOST, &self.host);
        if !self.cookies.is_empty() {
            let jar = self
                .cookies
                .iter()
                .map(|(k, v)| format!("{k}={v}"))
                .collect::<Vec<_>>()
                .join("; ");
            builder = builder.header(header::COOKIE, jar);
        }
        if method != "GET"
            && let Some(csrf) = self.cookies.get(CSRF_COOKIE)
        {
            builder = builder.header(CSRF_HEADER, csrf);
        }
        let request = match body {
            Some(ref b) => builder
                .header(header::CONTENT_TYPE, "application/json")
                .body(Body::from(serde_json::to_vec(b).unwrap()))
                .unwrap(),
            None => builder.body(Body::empty()).unwrap(),
        };
        let response = self.router.clone().oneshot(request).await.unwrap();
        let status = response.status();
        for raw in response.headers().get_all(header::SET_COOKIE) {
            if let Ok(text) = raw.to_str()
                && let Some((name, value)) = text.split(';').next().unwrap_or("").split_once('=')
            {
                if value.is_empty() {
                    self.cookies.remove(name);
                } else {
                    self.cookies.insert(name.to_owned(), value.to_owned());
                }
            }
        }
        let bytes = axum::body::to_bytes(response.into_body(), 256 * 1024)
            .await
            .unwrap();
        (
            status,
            serde_json::from_slice(&bytes).unwrap_or(Value::Null),
        )
    }

    async fn login(&mut self, email: &str, password: &str) {
        self.send("GET", "/", None).await;
        let (status, body) = self
            .send(
                "POST",
                "/api/login",
                Some(json!({ "email": email, "password": password })),
            )
            .await;
        assert_eq!(status, StatusCode::OK, "{email}: {body}");
    }
}

async fn setup() -> sc_error::Result<(Router, Arc<Catalog>, TestDb)> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(
            "DO $$ DECLARE r record; BEGIN \
               FOR r IN SELECT table_schema FROM information_schema.tables \
               WHERE table_name = 'users' AND table_type = 'BASE TABLE' LOOP \
                 EXECUTE format('DROP TABLE IF EXISTS %I.users CASCADE', r.table_schema); \
               END LOOP; END $$; \
             CREATE TABLE notices (id bigint generated by default as identity primary key, \
               user_id uuid, balance numeric)",
        )
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    sc_auth::bootstrap(&catalog).await?;
    sc_app::bootstrap(&catalog).await?;
    sc_catalog::bootstrap_table_meta(&catalog).await?;
    let evaluator = default_js_evaluator();
    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, sc_model::DEFAULT_MAX_ROWS).await?;
    let dispatcher = install_triggers(&catalog, evaluator.clone(), &agents, &models).await?;
    // The application's auto top-up, reduced to a note of who ran low.
    let low = Trigger::new("when_low", EventKind::Insert, "run_js_code")
        .on(sc_auth::CREDIT_ENTRIES_TABLE)
        .only_if("row.kind === \"low_balance\"")
        .config(
            "code",
            // A numeric column takes a decimal string: a JavaScript number is
            // not an exact decimal.
            "await db.notices.insert({ user_id: row.user_id, balance: String(row.balance) });",
        );
    save_trigger(&catalog, &dispatcher.registry(), &low).await?;
    dispatcher.reload(&catalog).await?;

    let apps = Arc::new(
        AppMounts::new(catalog.clone())
            .with_evaluator(evaluator)
            .with_triggers(dispatcher.clone()),
    );
    let app = Application::new("Agents", "agents", FrameworkRef::new("code"))
        .with_table(TableId(sc_auth::CREDIT_BUCKETS_TABLE.to_owned()))
        .with_table(TableId(sc_auth::CREDIT_ENTRIES_TABLE.to_owned()))
        .with_api(ApiConfig::new("rest", "/api"));
    let framework = Arc::new(CodeFramework::new(
        "code",
        AssetBundle::new().with("index.html", "<!doctype html>"),
    ));
    apps.mount(MountedApp::new_with(
        app,
        framework,
        &catalog,
        apps.evaluator(),
        apps.triggers(),
    )?)?;
    let config = ServerConfig {
        base_domain: Some(BASE_DOMAIN.to_owned()),
        ..ServerConfig::default()
    };
    let router = build_router_with_apps(
        &sc_api::admin_endpoints(),
        admin_handlers(catalog.clone(), apps.clone()),
        Arc::new(SessionStore::default()),
        &config,
        apps,
    )?;
    Ok((router, catalog, db))
}

#[tokio::test]
async fn an_admin_grants_credits_each_user_reads_their_own_and_running_low_fires_a_trigger()
-> sc_error::Result<()> {
    let (router, catalog, _db) = setup().await?;
    create_user(&catalog, "admin@example.com", "admin-pw", ROLE_ADMIN).await?;
    save_role(&catalog, &Role::new(80, "Member")).await?;
    let ada = create_user(&catalog, "ada@example.com", "ada-pw", 80).await?;
    create_user(&catalog, "bob@example.com", "bob-pw", 80).await?;

    // The admin grants credits by hand, exactly, and sets a threshold.
    let mut admin = Client::new(router.clone(), BASE_DOMAIN);
    admin.login("admin@example.com", "admin-pw").await;
    let path = format!("/api/users/{}/credits", ada.id);
    let (status, credits) = admin
        .send(
            "POST",
            &path,
            Some(json!({ "amount": "10.5", "expires_in_days": 30, "note": "welcome" })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{credits}");
    assert_eq!(credits["balance"], json!("10.5"));
    assert_eq!(credits["buckets"][0]["kind"], json!("admin"));
    assert_eq!(credits["buckets"][0]["note"], json!("welcome"));
    assert!(credits["buckets"][0]["expires_at"].is_string());
    assert_eq!(credits["entries"][0]["kind"], json!("grant"));
    let (status, body) = admin
        .send("POST", &path, Some(json!({ "amount": "lots" })))
        .await;
    assert_eq!(status, StatusCode::BAD_REQUEST, "{body}");
    let (status, credits) = admin
        .send(
            "POST",
            &format!("{path}/threshold"),
            Some(json!({ "threshold": "5" })),
        )
        .await;
    assert_eq!(status, StatusCode::OK, "{credits}");
    assert_eq!(credits["low_balance_threshold"], json!("5"));

    // Each user reads their own buckets through the application, and only them.
    let mut reader = Client::new(router.clone(), APP_HOST);
    reader.login("ada@example.com", "ada-pw").await;
    let (status, rows) = reader.send("GET", "/api/credit_buckets", None).await;
    assert_eq!(status, StatusCode::OK, "{rows}");
    assert_eq!(rows.as_array().map(Vec::len), Some(1), "{rows}");
    let mut other = Client::new(router.clone(), APP_HOST);
    other.login("bob@example.com", "bob-pw").await;
    let (status, rows) = other.send("GET", "/api/credit_buckets", None).await;
    assert_eq!(status, StatusCode::OK, "{rows}");
    assert_eq!(rows, json!([]), "none of Ada's");
    // And nobody but an admin writes them.
    let (status, _) = reader
        .send(
            "POST",
            "/api/credit_buckets",
            Some(json!({ "user_id": ada.id, "amount": "1000", "remaining": "1000" })),
        )
        .await;
    assert!(status.is_client_error(), "{status}");

    // An agent run's debit takes Ada from 10.5 to 4.5, below her threshold: the
    // `low_balance` entry fires the application's trigger, once.
    let debit = |amount: i64, key: &str| CreditDebit {
        user_id: ada.id,
        amount: Decimal::from(amount),
        key: key.to_owned(),
        ..CreditDebit::default()
    };
    let debited = sc_auth::debit_credits(&catalog, debit(6, "run:1"), None).await?;
    assert!(debited.low_balance);
    sc_auth::debit_credits(&catalog, debit(1, "run:2"), None).await?;
    let notices = _db
        .client()
        .await?
        .query("SELECT user_id::text, balance::text FROM notices", &[])
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    assert_eq!(notices.len(), 1, "one notice for one fall");
    assert_eq!(notices[0].get::<_, String>(0), ada.id.to_string());
    assert_eq!(notices[0].get::<_, String>(1), "4.5");

    let (status, credits) = admin.send("GET", &path, None).await;
    assert_eq!(status, StatusCode::OK);
    assert_eq!(credits["balance"], json!("3.5"));
    let kinds: Vec<&str> = credits["entries"]
        .as_array()
        .unwrap()
        .iter()
        .filter_map(|e| e["kind"].as_str())
        .collect();
    assert_eq!(kinds.iter().filter(|k| **k == "debit").count(), 2);
    assert_eq!(kinds.iter().filter(|k| **k == "low_balance").count(), 1);
    Ok(())
}
