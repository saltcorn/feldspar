//! `feldspar build-app SUBDOMAIN`: building one application from a terminal.
//!
//! Driven through the **real binary**, because that is the whole point of the
//! command — a build an admin can run where its output can be piped, grepped and
//! kept, when the UI that would otherwise run it is not the tool at hand.
//!
//! The failure paths run everywhere; the build itself skips when `npm` is not on
//! `PATH`.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::Arc;

use sc_app::{ApiConfig, Application, FrameworkRef, save_application, scaffold_app};
use sc_catalog::{DataField, FileStoreId, TableId};
use sc_cli::{DbConfig, connect_catalog};
use sc_files::LocalFileStore;
use sc_test_harness::TestDb;
use sc_types::{BasicType, TypeRef};

/// A scratch directory removed when the guard drops.
struct TempDir(PathBuf);

impl TempDir {
    fn new(tag: &str) -> sc_error::Result<TempDir> {
        let dir = std::env::temp_dir().join(format!(
            "sc-cli-build-app-{}-{tag}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        std::fs::remove_dir_all(&dir).ok();
        std::fs::create_dir_all(&dir)?;
        Ok(TempDir(dir))
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        std::fs::remove_dir_all(&self.0).ok();
    }
}

fn npm_available() -> bool {
    std::env::var_os("PATH")
        .map(|paths| {
            std::env::split_paths(&paths)
                .any(|dir| dir.join("npm").is_file() || dir.join("npm.cmd").is_file())
        })
        .unwrap_or(false)
}

/// Run the binary's `build-app` with the given arguments, returning
/// (success, stdout, stderr).
fn build_app(args: &[&str]) -> (bool, String, String) {
    let out = Command::new(env!("CARGO_BIN_EXE_feldspar"))
        .arg("build-app")
        .args(args)
        .output()
        .expect("run the feldspar binary");
    (
        out.status.success(),
        String::from_utf8_lossy(&out.stdout).into_owned(),
        String::from_utf8_lossy(&out.stderr).into_owned(),
    )
}

#[test]
fn without_a_subdomain_it_says_what_it_wanted() {
    let (ok, _, stderr) = build_app(&[]);
    assert!(!ok);
    assert!(stderr.contains("subdomain"), "{stderr}");
    // A flag in the subdomain's place is the same mistake, not a database error.
    // The URL is never connected — the argument check comes first.
    let (ok, _, stderr) = build_app(&[
        "--database-url",
        "postgres://saltcorn:saltcorn@localhost:5432/saltcorn_test",
    ]);
    assert!(!ok);
    assert!(stderr.contains("subdomain"), "{stderr}");
}

#[tokio::test]
async fn an_unknown_subdomain_is_reported_as_such() -> sc_error::Result<()> {
    let db = TestDb::new().await?;
    // Bootstrap the tables so the failure is genuinely "no such app" rather than
    // "no such table".
    connect_catalog(&DbConfig::from_url(db.url())).await?;

    let (ok, _, stderr) = build_app(&["nosuchapp", "--database-url", &db.url()]);
    assert!(!ok);
    assert!(stderr.contains("nosuchapp"), "{stderr}");
    Ok(())
}

#[tokio::test]
async fn it_builds_a_scaffolded_app_and_prints_the_tool_output() -> sc_error::Result<()> {
    if !npm_available() {
        eprintln!("skipping: `npm` is not on PATH");
        return Ok(());
    }

    let db = TestDb::new().await?;
    let tmp = TempDir::new("ok")?;
    let catalog = connect_catalog(&DbConfig::from_url(db.url())).await?;

    // The tutorial's data model and application, set up through the library, then
    // handed to the *binary* to build.
    let id = DataField::plain(
        "id",
        TypeRef::from_sql_type("bigint generated by default as identity"),
    )
    .required()
    .primary_key();
    catalog.create_table("tasks", &[id]).await?;
    catalog
        .create_field(
            "tasks",
            &DataField::plain("title", TypeRef::Basic(BasicType::Text)).required(),
        )
        .await?;
    catalog.connect_file_store(Arc::new(LocalFileStore::new("apps", tmp.path())?))?;

    let app = Application::new(
        "Todo",
        "todo",
        FrameworkRef::new("react")
            .with("store", "apps")
            .with("project", "todo"),
    )
    .with_table(TableId("tasks".to_owned()))
    .with_file_store(FileStoreId("apps".to_owned()))
    .with_api(ApiConfig::new("rest", "/api"));
    save_application(&catalog, &app).await?;
    scaffold_app(&catalog, &app, None).await?;

    let store_flag = format!("apps={}", tmp.path().display());
    let (ok, stdout, stderr) = build_app(&[
        "todo",
        "--database-url",
        &db.url(),
        "--file-store",
        &store_flag,
    ]);
    assert!(ok, "build failed:\n{stderr}\n{stdout}");
    // The bundler's own output reaches the terminal — the reason to run this
    // rather than click Build.
    assert!(stdout.contains("vite"), "no bundler output:\n{stdout}");
    assert!(stderr.contains("built"), "{stderr}");
    // And it really produced a bundle.
    assert!(tmp.path().join("todo/dist/index.html").is_file());
    Ok(())
}

/// An app that exposes a trigger builds from the terminal too: the command
/// loads the live trigger set, as the MCP `buildApplication` does, rather than
/// refusing with "no trigger set is available in this context".
#[tokio::test]
async fn an_app_exposing_a_trigger_builds_with_its_run_method() -> sc_error::Result<()> {
    if !npm_available() {
        eprintln!("skipping: `npm` is not on PATH");
        return Ok(());
    }

    let db = TestDb::new().await?;
    let tmp = TempDir::new("trigger")?;
    let catalog = connect_catalog(&DbConfig::from_url(db.url())).await?;
    let id = DataField::plain(
        "id",
        TypeRef::from_sql_type("bigint generated by default as identity"),
    )
    .required()
    .primary_key();
    catalog.create_table("tasks", &[id]).await?;
    catalog.connect_file_store(Arc::new(LocalFileStore::new("apps", tmp.path())?))?;

    let agents = sc_server::install_agents(&catalog).await?;
    let models = sc_server::install_models(&catalog, 100_000).await?;
    let dispatcher = sc_server::install_triggers(
        &catalog,
        sc_server::default_js_evaluator(),
        &agents,
        &models,
    )
    .await?;
    sc_action::save_trigger(
        &catalog,
        &dispatcher.registry(),
        &sc_action::Trigger::new("open_door", sc_action::EventKind::None, "run_js_code")
            .config("code", "return { opened: payload.door };"),
    )
    .await?;
    dispatcher.reload(&catalog).await?;

    let app = Application::new(
        "Door",
        "door",
        FrameworkRef::new("react")
            .with("store", "apps")
            .with("project", "door"),
    )
    .with_table(TableId("tasks".to_owned()))
    .with_file_store(FileStoreId("apps".to_owned()))
    .with_api(ApiConfig::new("rest", "/api"))
    .with_trigger(sc_app::TriggerRef("open_door".to_owned()));
    save_application(&catalog, &app).await?;
    scaffold_app(&catalog, &app, Some(&dispatcher)).await?;

    let store_flag = format!("apps={}", tmp.path().display());
    let (ok, stdout, stderr) = build_app(&[
        "door",
        "--database-url",
        &db.url(),
        "--file-store",
        &store_flag,
    ]);
    assert!(ok, "build failed:\n{stderr}\n{stdout}");
    assert!(!stderr.contains("no trigger set"), "{stderr}");
    let client = std::fs::read_to_string(tmp.path().join("door/src/feldspar/client.ts"))?;
    assert!(client.contains("runOpenDoor"), "{client}");
    Ok(())
}
