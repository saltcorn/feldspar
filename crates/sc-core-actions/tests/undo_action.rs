//! The `undo` action (row history H4, design §14.12 "The Undo action"): it
//! steps back through the caller's own session, one action at a time.
//!
//! - undoing twice steps back two actions, and never the running request's own
//!   changeset;
//! - another session's changesets are never picked;
//! - a table-scoped undo leaves the other tables' entries, and a later
//!   unscoped undo reverses the rest;
//! - an anonymous caller, a caller with no session, nothing to undo and a
//!   conflict are each refused with a sentence;
//! - a `table` without history is refused when the trigger is saved.

#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;

use sc_action::{ActionContext, Event, EventKind, Trigger, validate_trigger};
use sc_api::{rows, schema_edit};
use sc_catalog::{
    CallerContext, Catalog, Changeset, ChangesetSource, bootstrap_change_log, bootstrap_field_meta,
    bootstrap_table_meta, changeset,
};
use sc_core_actions::builtin_actions;
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Result};
use sc_test_harness::TestDb;
use sc_types::Attrs;
use serde_json::{Value as Json, json};

const ADMIN: &str = "00000000-0000-4000-8000-0000000000ad";

async fn history_on(catalog: &Catalog, table: &str) -> Result<()> {
    let op = schema_edit::Operation::AlterTable {
        table: table.to_owned(),
        settings: schema_edit::TableSettings {
            history_enabled: Some(true),
            ..Default::default()
        },
    };
    schema_edit::apply(catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    Ok(())
}

/// `projects` and `tasks` keep history; `notes` does not.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    db.client()
        .await?
        .batch_execute(
            "CREATE TABLE projects (id bigint generated by default as identity primary key,
                                    name text, budget int);
             CREATE TABLE tasks (id bigint generated by default as identity primary key,
                                 project bigint references projects(id), title text);
             CREATE TABLE notes (id bigint generated by default as identity primary key,
                                 body text);",
        )
        .await
        .map_err(|e| Error::database(format!("{e:?}")))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    catalog.reload().await?;
    history_on(&catalog, "projects").await?;
    history_on(&catalog, "tasks").await?;
    Ok(catalog)
}

fn admin_fields() -> Json {
    json!({ "id": ADMIN, "role": 1 })
}

fn caller() -> CallerContext {
    CallerContext::new(1, Some(admin_fields()))
}

/// A request in `session`: the changeset the server's middleware mints.
fn request(session: &str) -> Arc<Changeset> {
    Arc::new(Changeset::new(ChangesetSource::Request).session(Some(session.to_owned())))
}

async fn insert(catalog: &Catalog, table: &str, body: Json) -> Result<String> {
    let table = catalog.require(table)?;
    let row = rows::create_row_ctx(catalog, &table, &body, Some(&caller())).await?;
    Ok(row["id"].to_string())
}

async fn update(catalog: &Catalog, table: &str, id: &str, body: Json) -> Result<()> {
    let table = catalog.require(table)?;
    rows::update_row_ctx(catalog, &table, id, &body, Some(&caller())).await?;
    Ok(())
}

/// Row `id` of `table` now, or `None`.
async fn get(catalog: &Catalog, table: &str, id: &str) -> Result<Option<Json>> {
    let table = catalog.require(table)?;
    let rows = rows::list_rows(catalog, &table).await?;
    Ok(rows
        .as_array()
        .unwrap()
        .iter()
        .find(|r| r["id"] == json!(id.parse::<i64>().unwrap()))
        .cloned())
}

fn config(table: Option<&str>) -> Attrs {
    let mut config = Attrs::new();
    if let Some(table) = table {
        config.insert("table".into(), json!(table));
    }
    config
}

/// Run the `undo` action as `user` in a request of `session` (or none), the
/// way a button's trigger runs it: the event carries the request's changeset,
/// and the action runs inside it.
async fn run_undo_as(
    catalog: &Catalog,
    user: Option<Json>,
    session: Option<&str>,
    table: Option<&str>,
    before: impl std::future::Future<Output = Result<()>>,
) -> Result<Json> {
    let changeset =
        Arc::new(Changeset::new(ChangesetSource::Request).session(session.map(str::to_owned)));
    let event = Event::new(EventKind::None)
        .caller(if user.is_some() { 1 } else { 100 }, user)
        .in_changeset(Some(changeset.clone()));
    let config = config(table);
    let registry = builtin_actions()?;
    let action = registry.require("undo")?.clone();
    changeset::scope(changeset, async {
        before.await?;
        let mut ctx = ActionContext::new(catalog, &event, &config, "undo-button");
        action.run(&mut ctx).await
    })
    .await
}

async fn run_undo(catalog: &Catalog, session: &str, table: Option<&str>) -> Result<Json> {
    run_undo_as(catalog, Some(admin_fields()), Some(session), table, async {
        Ok(())
    })
    .await
}

fn refusal(result: Result<Json>) -> String {
    let err = result.expect_err("the undo should have been refused");
    assert_eq!(err.kind(), sc_error::ErrorKind::Application, "{err}");
    err.to_string()
}

#[tokio::test]
async fn undoing_twice_steps_back_two_actions() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;

    let id = changeset::scope(request("s1"), async {
        insert(
            &catalog,
            "projects",
            json!({ "name": "Roof", "budget": 10 }),
        )
        .await
    })
    .await?;
    changeset::scope(request("s1"), async {
        update(&catalog, "projects", &id, json!({ "name": "New roof" })).await
    })
    .await?;

    // A request that writes, then runs the action: its own write is not
    // what it undoes, the rename before it is.
    let undid = run_undo_as(&catalog, Some(admin_fields()), Some("s1"), None, async {
        insert(&catalog, "tasks", json!({ "title": "Gutter" })).await?;
        Ok(())
    })
    .await?;
    assert_eq!(undid["entries"], json!(1), "{undid}");
    let row = get(&catalog, "projects", &id).await?.unwrap();
    assert_eq!(row["name"], json!("Roof"));
    assert!(get(&catalog, "tasks", "1").await?.is_some());

    // The next undo skips the undo just made, and takes the request that
    // added the task (the most recent one not undone).
    run_undo(&catalog, "s1", None).await?;
    assert!(get(&catalog, "tasks", "1").await?.is_none());
    // And the one after that removes the project the first request added.
    run_undo(&catalog, "s1", None).await?;
    assert!(get(&catalog, "projects", &id).await?.is_none());

    let msg = refusal(run_undo(&catalog, "s1", None).await);
    assert!(msg.contains("nothing to undo"), "{msg}");
    Ok(())
}

#[tokio::test]
async fn another_sessions_changesets_are_never_picked() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;

    let mine = changeset::scope(request("laptop"), async {
        insert(&catalog, "projects", json!({ "name": "Mine" })).await
    })
    .await?;
    // The same user, later, on another device.
    let theirs = changeset::scope(request("phone"), async {
        insert(&catalog, "projects", json!({ "name": "Phone" })).await
    })
    .await?;

    run_undo(&catalog, "laptop", None).await?;
    assert!(get(&catalog, "projects", &mine).await?.is_none());
    assert!(get(&catalog, "projects", &theirs).await?.is_some());

    let msg = refusal(run_undo(&catalog, "laptop", None).await);
    assert!(msg.contains("nothing to undo"), "{msg}");
    let msg = refusal(run_undo(&catalog, "tablet", None).await);
    assert!(msg.contains("nothing to undo"), "{msg}");
    assert!(get(&catalog, "projects", &theirs).await?.is_some());
    Ok(())
}

#[tokio::test]
async fn a_table_scoped_undo_leaves_the_rest_for_a_later_undo() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;

    // One action across two tables, then a later one in `projects` only.
    let (project, task) = changeset::scope(request("s1"), async {
        let project = insert(&catalog, "projects", json!({ "name": "Roof" })).await?;
        let task = insert(
            &catalog,
            "tasks",
            json!({ "project": project.parse::<i64>().unwrap(), "title": "Tiles" }),
        )
        .await?;
        Ok::<_, Error>((project, task))
    })
    .await?;
    changeset::scope(request("s1"), async {
        update(&catalog, "projects", &project, json!({ "budget": 5 })).await
    })
    .await?;

    // `tasks` only: the most recent changeset with a task in it is the first.
    let undid = run_undo(&catalog, "s1", Some("tasks")).await?;
    assert_eq!(undid["entries"], json!(1), "{undid}");
    assert!(get(&catalog, "tasks", &task).await?.is_none());
    let row = get(&catalog, "projects", &project).await?.unwrap();
    assert_eq!(row["budget"], json!(5), "the later change is left alone");
    let msg = refusal(run_undo(&catalog, "s1", Some("tasks")).await);
    assert!(msg.contains("nothing in `tasks` to undo"), "{msg}");

    // Unscoped: first the budget, then what is left of the first action.
    run_undo(&catalog, "s1", None).await?;
    let row = get(&catalog, "projects", &project).await?.unwrap();
    assert_eq!(row["budget"], Json::Null);
    let undid = run_undo(&catalog, "s1", None).await?;
    assert_eq!(
        undid["entries"],
        json!(1),
        "only the project is left: {undid}"
    );
    assert!(get(&catalog, "projects", &project).await?.is_none());
    let msg = refusal(run_undo(&catalog, "s1", None).await);
    assert!(msg.contains("nothing to undo"), "{msg}");
    Ok(())
}

#[tokio::test]
async fn anonymous_and_sessionless_callers_are_refused() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    changeset::scope(request("s1"), async {
        insert(&catalog, "projects", json!({ "name": "Roof" })).await
    })
    .await?;

    let anonymous = run_undo_as(&catalog, None, Some("s1"), None, async { Ok(()) }).await;
    let msg = refusal(anonymous);
    assert!(msg.contains("signing in"), "{msg}");
    let sessionless =
        run_undo_as(&catalog, Some(admin_fields()), None, None, async { Ok(()) }).await;
    let msg = refusal(sessionless);
    assert!(msg.contains("signing in"), "{msg}");
    // Nothing was undone.
    assert!(get(&catalog, "projects", "1").await?.is_some());
    Ok(())
}

#[tokio::test]
async fn a_conflict_refuses_the_undo_with_a_sentence() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let id = changeset::scope(request("s1"), async {
        insert(&catalog, "projects", json!({ "name": "Roof", "budget": 1 })).await
    })
    .await?;
    changeset::scope(request("s1"), async {
        update(&catalog, "projects", &id, json!({ "budget": 10 })).await
    })
    .await?;
    // Someone else changes it since.
    changeset::scope(request("s2"), async {
        update(&catalog, "projects", &id, json!({ "budget": 20 })).await
    })
    .await?;

    let msg = refusal(run_undo(&catalog, "s1", None).await);
    assert!(msg.contains("changed since"), "{msg}");
    assert!(msg.contains("`budget`"), "{msg}");
    let row = get(&catalog, "projects", &id).await?.unwrap();
    assert_eq!(row["budget"], json!(20), "no force: nothing is overwritten");
    Ok(())
}

#[tokio::test]
async fn the_table_must_keep_history_when_the_trigger_is_saved() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let registry = builtin_actions()?;

    let unscoped = Trigger::new("undo-button", EventKind::None, "undo");
    validate_trigger(&catalog, &registry, &unscoped).await?;
    let scoped = unscoped.clone().with_configuration(config(Some("tasks")));
    validate_trigger(&catalog, &registry, &scoped).await?;

    let without = Trigger::new("undo-notes", EventKind::None, "undo")
        .with_configuration(config(Some("notes")));
    let msg = validate_trigger(&catalog, &registry, &without)
        .await
        .unwrap_err()
        .to_string();
    assert!(msg.contains("notes") && msg.contains("history"), "{msg}");
    let missing = Trigger::new("undo-nowhere", EventKind::None, "undo")
        .with_configuration(config(Some("nowhere")));
    assert!(
        validate_trigger(&catalog, &registry, &missing)
            .await
            .is_err()
    );
    Ok(())
}
