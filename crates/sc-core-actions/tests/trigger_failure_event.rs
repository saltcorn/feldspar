//! A trigger that fails where nobody is waiting raises the `error` event (§16).
//!
//! The case it exists for: an update trigger sends a mail when a row's status
//! becomes `sending`. The write that fires it has committed by the time the
//! mail is attempted, so a refused or unreachable mail server cannot fail it —
//! and without an event, nothing the application can read would ever say the
//! mail was not accepted. With one, an `error` trigger writes the outcome back
//! to the row the failure names, which is what this test does, with nothing
//! but built-in actions.

use std::sync::Arc;

use sc_action::{Event, EventKind, Trigger, TriggerDispatcher, bootstrap_triggers, save_trigger};
use sc_api::rows;
use sc_catalog::{Catalog, TableEvents};
use sc_core_actions::builtin_actions;
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_email::{Mailer, SettingsMailer};
use sc_error::{Error, ErrorKind, Result};
use sc_expr::DenoEvaluator;
use sc_test_harness::TestDb;
use serde_json::json;

const SCHEMA: &str = "
    CREATE TABLE mails (id bigint generated by default as identity primary key,
        recipient text, status text, error text, failed_trigger text);
";

/// Send when the status becomes `sending` — the shape from the report.
fn send() -> Trigger {
    Trigger::new("send_mail", EventKind::Update, "send_email")
        .on("mails")
        .only_if("status === 'sending' && old.status !== 'sending'")
        .config("to", "{{ recipient }}")
        .config("subject", "Hello")
        .config("text", "Hello")
}

/// Record a failed send on the row it was for, from the `error` event's payload
/// — the trigger docs/tutorial-triggers.md shows ("When a trigger fails"), so
/// the `where` it tells people to write is the one tested here.
fn record_failure() -> Trigger {
    Trigger::new("record_failure", EventKind::Error, "update_rows")
        .config("table", "mails")
        .config(
            "where",
            "id === payload.key && payload.method === \"TRIGGER\"",
        )
        .config(
            "assignments",
            json!({
                "status": "'failed'",
                "error": "payload.message",
                "failed_trigger": "payload.trigger",
            }),
        )
}

/// The `mails` table, the two triggers, and a mailer with no SMTP host — every
/// send fails, as one to an unreachable server does.
async fn setup() -> Result<(TestDb, Arc<Catalog>, Arc<TriggerDispatcher>)> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    // The settings `SettingsMailer` reads, with no SMTP host in them.
    sc_config::bootstrap_config(&catalog).await?;
    bootstrap_triggers(&catalog).await?;
    let registry = Arc::new(builtin_actions()?);
    let mailer: Arc<dyn Mailer> = Arc::new(SettingsMailer::new(Arc::clone(&catalog)));
    let dispatcher = Arc::new(
        TriggerDispatcher::new(Arc::clone(&registry))
            .with_evaluator(Arc::new(DenoEvaluator::new()))
            .with_mailer(mailer),
    );
    save_trigger(&catalog, &registry, &send()).await?;
    save_trigger(&catalog, &registry, &record_failure()).await?;
    dispatcher.reload(&catalog).await?;
    catalog.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn TableEvents>,
    )?;
    Ok((db, catalog, dispatcher))
}

#[tokio::test]
async fn a_failed_send_on_a_row_update_raises_the_error_event_naming_the_row() -> Result<()> {
    let (_db, catalog, _dispatcher) = setup().await?;
    let mails = catalog.require("mails")?;

    let first = rows::create_row(
        &catalog,
        &mails,
        &json!({ "recipient": "ada@example.com", "status": "draft" }),
    )
    .await?;
    let second = rows::create_row(
        &catalog,
        &mails,
        &json!({ "recipient": "bob@example.com", "status": "draft" }),
    )
    .await?;
    let id = first["id"].as_i64().expect("an id").to_string();

    // The write itself succeeds: the failure happens after it committed.
    rows::update_row(&catalog, &mails, &id, &json!({ "status": "sending" })).await?;

    let all = rows::list_rows(&catalog, &mails).await?;
    let row = |id: &serde_json::Value| {
        all.as_array()
            .and_then(|a| a.iter().find(|r| r["id"] == *id))
            .cloned()
            .expect("the row")
    };
    let failed = row(&first["id"]);
    assert_eq!(failed["status"], json!("failed"), "{failed}");
    assert_eq!(failed["failed_trigger"], json!("send_mail"), "{failed}");
    let error = failed["error"].as_str().unwrap_or_default();
    assert!(error.contains("send_mail"), "the trigger is named: {error}");
    assert!(error.contains("Email"), "the mail failure is said: {error}");
    // And only the row the failure was for.
    assert_eq!(row(&second["id"])["status"], json!("draft"));
    Ok(())
}

/// A request's `error` event has no `key`: the documented `where` matches no
/// row for it, and does so without failing.
#[tokio::test]
async fn a_request_error_leaves_the_rows_alone() -> Result<()> {
    let (_db, catalog, dispatcher) = setup().await?;
    let mails = catalog.require("mails")?;
    rows::create_row(
        &catalog,
        &mails,
        &json!({ "recipient": "ada@example.com", "status": "draft" }),
    )
    .await?;

    let event = Event::error(
        ErrorKind::Application,
        "no such book",
        "GET",
        "/api/books/9",
    );
    let runs = dispatcher.dispatch_in(&catalog, &event, None).await;
    assert_eq!(runs.len(), 1);
    assert!(runs[0].outcome.is_ok(), "{:?}", runs[0].outcome);

    let all = rows::list_rows(&catalog, &mails).await?;
    assert_eq!(all[0]["status"], json!("draft"), "{all}");
    Ok(())
}
