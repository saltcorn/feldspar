use std::sync::Arc;
use std::time::{Duration, Instant};

use sc_action::{ActionContext, Event, EventKind, Trigger, validate_trigger};
use sc_catalog::{Catalog, TableMeta, bootstrap_table_meta, save_table_meta};
use sc_core_actions::builtin_actions;
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Result};
use sc_expr::{DenoEvaluator, JsEvaluator};
use sc_test_harness::TestDb;
use sc_types::Attrs;

use serde_json::{Value as Json, json};

/// One table with one row in it: something for the sandbox to fail to reach.
const SCHEMA: &str = "CREATE TABLE books (id bigint primary key, title text, pages bigint);\
                      INSERT INTO books VALUES (7, 'A Book', 100);";

async fn setup(db: &TestDb) -> Result<Catalog> {
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    Catalog::init(driver as Arc<dyn DatabaseDriver>).await
}

/// A table an ownership formula divides: three notes, two of them ada's.
const OWNED_SCHEMA: &str = "\
    CREATE TABLE notes (id bigint generated by default as identity primary key, \
        what text, owner text); \
    INSERT INTO notes (what, owner) VALUES \
        ('ada one', 'ada@example.com'), \
        ('bob one', 'bob@example.com'), \
        ('ada two', 'ada@example.com');";

/// [`OWNED_SCHEMA`], with `owner === user.email` live as the ownership formula —
/// what `asUser()` has to obey and what the trigger's own authority does not.
async fn owned_setup(db: &TestDb) -> Result<Catalog> {
    db.client()
        .await?
        .batch_execute(OWNED_SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Catalog::init(driver as Arc<dyn DatabaseDriver>).await?;
    bootstrap_table_meta(&catalog).await?;
    let mut notes = TableMeta::new("notes");
    notes.set_ownership_formula(Some("owner === user.email"));
    save_table_meta(&catalog, &notes).await?;
    assert!(
        catalog.require("notes")?.ownership.is_some(),
        "the formula is live"
    );
    Ok(catalog)
}

/// The event most tests fire for: an insert of a book by a known admin.
fn book_insert() -> Event {
    Event::new(EventKind::Insert)
        .on("books")
        .row(json!({ "id": 7, "title": "A Book", "pages": 100 }))
        .caller(
            Role::ADMIN,
            Some(json!({ "email": "admin@example.com", "id": 3 })),
        )
}

fn config(code: &str) -> Attrs {
    [("code".to_owned(), json!(code))].into_iter().collect()
}

/// The same, plus the settings a test names explicitly (`timeout_ms`).
fn config_with(code: &str, extra: &[(&str, Json)]) -> Attrs {
    let mut cfg = config(code);
    for (name, value) in extra {
        cfg.insert((*name).to_owned(), value.clone());
    }
    cfg
}

/// Run `run_js_code` through the registry — the path a firing trigger takes.
async fn run(catalog: &Catalog, event: &Event, code: &str) -> Result<Json> {
    run_with(catalog, event, code, &Arc::new(DenoEvaluator::new())).await
}

async fn run_with(
    catalog: &Catalog,
    event: &Event,
    code: &str,
    engine: &Arc<DenoEvaluator>,
) -> Result<Json> {
    run_configured(catalog, event, config(code), engine).await
}

/// Run the action with a configuration built by the caller — the path a test that
/// is about a *setting* rather than about the code takes.
async fn run_configured(
    catalog: &Catalog,
    event: &Event,
    cfg: Attrs,
    engine: &Arc<DenoEvaluator>,
) -> Result<Json> {
    let engine: Arc<dyn JsEvaluator> = engine.clone();
    let registry = builtin_actions()?;
    let action = registry.require("run_js_code")?.clone();
    let mut ctx = ActionContext::new(catalog, event, &cfg, "compute").with_evaluator(&engine);
    action.run(&mut ctx).await
}

#[tokio::test]
async fn code_computes_a_result_from_the_event() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;

    // Statements, a loop, a local declaration and a `return` — everything a
    // formula (one expression) cannot be, which is what this action is for.
    let result = run(
        &catalog,
        &book_insert(),
        "const words = row.title.split(' ');\n\
         let initials = '';\n\
         for (const word of words) { initials += word[0]; }\n\
         return { initials, per_page: row.pages / words.length, by: user.email };",
    )
    .await?;
    assert_eq!(
        result,
        // 100 / 2 is 50, and JSON says so: a JS number that is integral comes
        // back as an integer, not as `50.0`.
        json!({ "initials": "AB", "per_page": 50, "by": "admin@example.com" })
    );

    // The result is whatever JSON the body returns — including a scalar, and
    // including nothing at all (an action that only had an effect).
    assert_eq!(
        run(&catalog, &book_insert(), "return row.id * 6;").await?,
        json!(42)
    );
    assert_eq!(
        run(&catalog, &book_insert(), "const x = 1;").await?,
        Json::Null
    );
    Ok(())
}

#[tokio::test]
async fn the_event_binds_what_it_has_and_nothing_else() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;

    // On an insert `old` is in scope *and null* — a value the code can branch on,
    // which is the whole reason presence and nullity are different things here.
    assert_eq!(
        run(&catalog, &book_insert(), "return old === null;").await?,
        json!(true)
    );
    // On an update it is the row that was replaced.
    let update = Event::new(EventKind::Update)
        .on("books")
        .row(json!({ "id": 7, "title": "A Book", "pages": 120 }))
        .old_row(json!({ "id": 7, "title": "A Book", "pages": 100 }));
    assert_eq!(
        run(&catalog, &update, "return row.pages - old.pages;").await?,
        json!(20)
    );

    // A `none` trigger: the payload it was called with is in scope, and `user` is
    // null when nobody is logged in.
    let called = Event::new(EventKind::None).payload(json!({ "n": 5 }));
    assert_eq!(
        run(
            &catalog,
            &called,
            "return { double: payload.n * 2, who: user };"
        )
        .await?,
        json!({ "double": 10, "who": Json::Null })
    );
    // …and naming a row it does not have is an error naming `row`, not the
    // silent `undefined` that would make the trigger quietly do the wrong thing.
    let err = run(&catalog, &called, "return row.id;").await.unwrap_err();
    let msg = err.to_string();
    assert!(msg.contains("compute") && msg.contains("`code`"), "{msg}");
    assert!(msg.contains("row"), "{msg}");
    Ok(())
}

#[tokio::test]
async fn the_sandbox_has_three_host_surfaces_and_nothing_else() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;

    // The bound this action keeps. There are exactly three ways out of a body —
    // `db`, `fetch` and `fs` — and everything else a JavaScript runtime usually
    // has is still absent: no subprocess, no timers, no second way to the
    // network that would have its own rules, and no path to a *file* except
    // through a store an admin connected.
    let probes = [
        "Deno",
        "process",
        "XMLHttpRequest",
        "WebSocket",
        "EventSource",
        "setTimeout",
        "globalThis.saltcorn",
        "globalThis.books",
        // The disk, except through `fs`: no module and no path, and `fs`
        // itself is a parameter rather than a global, so a body cannot reach
        // another run's stores by taking one off `globalThis`.
        "globalThis.fs",
    ];
    for probe in probes {
        let code = format!("return typeof {probe} === 'undefined';");
        assert_eq!(
            run(&catalog, &book_insert(), &code).await?,
            json!(true),
            "sandbox leak: {probe}"
        );
    }
    // And the surfaces that *are* there are reached by name, not by a global per
    // table: `db.books` is a query builder, `books` is nothing.
    assert_eq!(
        run(&catalog, &book_insert(), "return typeof db.books.rows;").await?,
        json!("function")
    );
    // `fetch` is the web's name for the web's shape, with the two classes that
    // go with it — an author who knows the browser knows this.
    assert_eq!(
        run(
            &catalog,
            &book_insert(),
            "return [typeof fetch, typeof Headers, typeof Response];"
        )
        .await?,
        json!(["function", "function", "function"])
    );
    // It is a **parameter**, not a global: a body cannot reach another run's
    // network by taking one off `globalThis`.
    assert_eq!(
        run(
            &catalog,
            &book_insert(),
            "return typeof globalThis.fetch === 'undefined';"
        )
        .await?,
        json!(true)
    );
    // `fs` is the third, and it is a function because this server has many
    // stores and no default one. This catalog has none connected, so `fs.stores`
    // is empty — and a body that names one is refused when it asks the store for
    // anything, naming the store it could not find.
    assert_eq!(
        run(
            &catalog,
            &book_insert(),
            "return [typeof fs, fs.stores.length];"
        )
        .await?,
        json!(["function", 0]),
        "a server with no connected store has an empty list, not no `fs`"
    );
    let refused = run(
        &catalog,
        &book_insert(),
        r#"try { await fs("nope").open("a.txt").text(); return "read it"; }
           catch (e) { return e.message; }"#,
    )
    .await?;
    assert!(
        refused.as_str().unwrap_or_default().contains("nope"),
        "a store nothing connected cannot be read: {refused}"
    );
    // `require` is the one name a body reaches for that exists and reaches
    // nothing: it is a refusal that says what to write instead, because the
    // first line of eight years of Saltcorn 1 code is a `require` and an admin
    // who pastes one deserves the answer rather than `require is not a
    // function`.
    let said = run(
        &catalog,
        &book_insert(),
        r#"try { require("@saltcorn/data/models/table"); return "loaded it"; }
           catch (e) { return e.message; }"#,
    )
    .await?;
    let said = said.as_str().unwrap_or_default();
    assert!(said.contains("not available in a code body"), "{said}");
    assert!(said.contains("already in scope"), "{said}");
    // What the event bound is still exactly what it bound.
    assert_eq!(
        run(&catalog, &book_insert(), "return Object.keys(row);").await?,
        json!(["id", "title", "pages"])
    );
    Ok(())
}

