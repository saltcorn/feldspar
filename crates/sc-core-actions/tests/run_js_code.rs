/// Nine rows whose sort key **ties and goes missing**: four share a rank, three
/// have none at all, and the two that are unique sit at either end.
///
/// Both properties are the ones streaming gets wrong. A batch boundary that falls
/// inside a tie serves some of those rows twice and skips the rest unless the
/// order is total; a null compares as neither greater nor smaller than the cursor
/// it is resumed from, so the whole block of them vanishes unless the predicate
/// says where they sort. Nine rows read two at a time straddles both.
const TIED_SCHEMA: &str = "\
    CREATE TABLE entries (id bigint generated by default as identity primary key, \
        label text, rank bigint); \
    INSERT INTO entries (label, rank) VALUES \
        ('a', NULL), ('b', 5), ('c', 5), ('d', 1), ('e', NULL), \
        ('f', 5), ('g', 9), ('h', NULL), ('i', 5);";

async fn tied_setup(db: &TestDb) -> Result<Catalog> {
    db.client()
        .await?
        .batch_execute(TIED_SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    Catalog::init(driver as Arc<dyn DatabaseDriver>).await
}

#[tokio::test]
async fn iter_streams_the_same_rows_the_unstreamed_read_answers() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = tied_setup(&db).await?;

    // The claim, in the only form worth making: what an `.iter()` yields is what
    // `.rows()` answers — every row, once, in the same order — for an ordering
    // that ties and for a column that is null in places, in both directions. The
    // comparison is against the *total* order (`.orderBy(rank).orderBy(id)`),
    // because that is the order streaming imposes, and comparing against an order
    // that leaves ties unbroken would be comparing against something the database
    // is free to answer two ways.
    let out = run(
        &catalog,
        &book_insert(),
        "const ids = async (q) => (await q.rows()).map((r) => r.id);\n\
         const walk = async (q, n) => { const out = []; for await (const r of q.iter(n)) out.push(r.id); \
                                  return out; };\n\
         return {\n\
           asc: await ids(db.entries.orderBy('rank').orderBy('id')),\n\
           asc_streamed: await walk(db.entries.orderBy('rank'), 2),\n\
           desc: await ids(db.entries.orderBy('rank', 'desc').orderBy('id')),\n\
           desc_streamed: await walk(db.entries.orderBy('rank', 'desc'), 2),\n\
           by_pk: await ids(db.entries.orderBy('id')),\n\
           by_pk_streamed: await walk(db.entries, 4),\n\
           filtered: await ids(db.entries.where({ rank: 5 }).orderBy('id')),\n\
           filtered_streamed: await walk(db.entries.where({ rank: 5 }), 1),\n\
           capped: await walk(db.entries.orderBy('rank').limit(3), 2),\n\
         };",
    )
    .await?;

    assert_eq!(out["asc_streamed"], out["asc"], "ascending, nulls last");
    assert_eq!(out["desc_streamed"], out["desc"], "descending, nulls first");
    assert_eq!(
        out["by_pk_streamed"], out["by_pk"],
        "no ordering of its own"
    );
    assert_eq!(
        out["filtered_streamed"], out["filtered"],
        "the filter rides along on every batch, one row at a time"
    );
    // Nine rows, none missing and none twice — asserted here as well as against
    // `.rows()`, because two reads that were wrong the same way would agree.
    let asc: Vec<i64> = serde_json::from_value(out["asc_streamed"].clone()).unwrap();
    let mut sorted = asc.clone();
    sorted.sort_unstable();
    assert_eq!(
        sorted,
        (1..=9).collect::<Vec<i64>>(),
        "every row exactly once"
    );
    // The nulls sort last ascending and first descending, so the two directions
    // are not each other's reverse — which is the thing a predicate that quietly
    // dropped the nulls would still get right.
    assert_eq!(&asc[6..], &[1, 5, 8], "the nulls are last, in key order");

    // A `.limit()` bounds the iteration rather than the batch: three rows, and
    // they are the first three of the same order.
    assert_eq!(out["capped"], json!(asc[..3].to_vec()));

    // A narrowed `.select()` is the case the cursor cannot be read off the
    // answer: the rows carry `label` and nothing else, while resuming needs
    // `rank` and the primary key. Both are projected under reserved aliases and
    // dropped again, so what the body sees is exactly what it asked for.
    let out = run(
        &catalog,
        &book_insert(),
        "const rows = [];
         for await (const r of db.entries.select('label').orderBy('rank').iter(2)) rows.push(r);
         return { labels: rows.map((r) => r.label), keys: Object.keys(rows[0]) };",
    )
    .await?;
    assert_eq!(
        out["keys"],
        json!(["label"]),
        "no cursor column leaked into the row"
    );
    assert_eq!(
        out["labels"].as_array().map(Vec::len),
        Some(9),
        "and the stream still walked the whole table: {out}"
    );
    Ok(())
}

#[tokio::test]
async fn iter_pays_one_database_call_per_batch_and_stops_when_the_loop_does() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = tied_setup(&db).await?;

    // The bound a streamed read is really under: the call budget. Nine rows in
    // batches of two is five calls — four full and the short one that ends the
    // stream — and a body that stops after the first row has spent one.
    let out = run(
        &catalog,
        &book_insert(),
        "let n = 0;\n\
         for await (const r of db.entries.iter(2)) n += 1;\n\
         let first = null;\n\
         for await (const r of db.entries.iter(2)) { first = r.id; break; }\n\
         return { n: n, first: first };",
    )
    .await?;
    assert_eq!(out["n"], json!(9));
    assert_eq!(out["first"], json!(1));

    // A batch is a database call like any other, so an iteration is bounded by
    // the call budget rather than by the isolate's memory — which is the trade
    // `.iter()` makes, and the reason a body may walk a table it could never
    // hold. Nine rows one at a time is ten calls; twenty-five walks of it is
    // more than the two hundred a run may spend, and it is stopped there.
    let refused = run(
        &catalog,
        &book_insert(),
        "let n = 0;\n\
         for (let i = 0; i < 25; i++) { for await (const r of db.entries.iter(1)) n += 1; }\n\
         return n;",
    )
    .await
    .expect_err("the budget is spent");
    assert!(
        refused.to_string().contains("database calls in one run"),
        "{refused}"
    );
    Ok(())
}

#[tokio::test]
async fn a_delegated_stream_obeys_the_ownership_formula_or_says_it_cannot() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = owned_setup(&db).await?;
    // Ada, at a role below the table's floors — the same caller delegation is
    // tested with above, because whose rows these are is the whole question.
    let event = Event::new(EventKind::None).payload(Json::Null).caller(
        Role::of(40),
        Some(json!({
            "id": "6b1c2d64-3f3a-4a52-9a8b-0f4d2b7f1a11",
            "role": 40,
            "email": "ada@example.com",
        })),
    );

    // `owner === user.email` translates, so the database can bound each batch
    // over the rows the caller may see: ada's two notes and no more.
    let out = run(
        &catalog,
        &event,
        "const mine = []; \
         for await (const n of db.asUser().notes.iter(1)) mine.push(n.what); \
         return mine;",
    )
    .await?;
    assert_eq!(out, json!(["ada one", "ada two"]));

    // The trigger's own authority sees all three, which is the same body without
    // the delegation — so the narrowing above is the formula and not an accident
    // of the paging.
    let out = run(
        &catalog,
        &event,
        "const all = []; for await (const n of db.notes.iter(1)) all.push(n.what); return all;",
    )
    .await?;
    assert_eq!(out, json!(["ada one", "bob one", "ada two"]));
    Ok(())
}
