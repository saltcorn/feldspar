//! The `run_js_code` action against the real V8 engine (TODO Phase 3, and the
//! "Tables in code" milestone's phase 5).
//!
//! Pinned against a `DenoEvaluator` rather than a stub, because everything that
//! can be wrong here is inside the isolate: whether statements and a `return`
//! actually run, what the event binds and what it deliberately does not, what a
//! throw or a runaway loop does to the caller — and now, the wiring this action
//! gained with `db`: that a body reads and writes its tables at all, that
//! `asUser()` delegates to **this event's** caller rather than to whoever the
//! server is, and that the configured timeout is the bound on a run. A mock
//! evaluator would assert those against an isolate that never existed.
//!
//! The catalog is real too, so the sandbox assertions are made in a process that
//! genuinely has a database — and the `db` assertions in one where the rows are
//! really there afterwards.

#![allow(clippy::unwrap_used, clippy::expect_used)]

