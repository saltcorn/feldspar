//! An `insert_or_update` trigger, fired for real: the geocoding archetype the
//! event kind exists for.
//!
//! A `places` row has an address and coordinates derived from it. The trigger
//! listens for both writes, so the coordinates are computed when a place is
//! created *and* whenever its address changes; its own write-back is an update
//! too, and what keeps that from firing it again is the `only_if` — the address
//! did not change — not anything special about the kind. A save that changes
//! some other field does not re-run it either, and a delete never does.

use std::sync::Arc;

use sc_action::{EventKind, Trigger, TriggerDispatcher, bootstrap_triggers, save_trigger};
use sc_api::rows;
use sc_catalog::{Catalog, TableEvents};
use sc_core_actions::builtin_actions;
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Result};
use sc_expr::DenoEvaluator;
use sc_test_harness::TestDb;
use serde_json::{Value as Json, json};

const SCHEMA: &str = "
    CREATE TABLE places (id bigint generated by default as identity primary key,
        name text, address text, lat double precision, lng double precision,
        lookups bigint not null default 0);
";

/// The "geocoder": the coordinates are the address's length, which is enough to
/// tell one lookup from another, and `lookups` counts how often it ran.
fn geocode() -> Trigger {
    Trigger::new("geocode", EventKind::InsertOrUpdate, "update_rows")
        .on("places")
        .only_if("address !== old.address")
        .config("table", "places")
        .config("where", "id === row.id")
        .config(
            "assignments",
            json!({
                "lat": "row.address.length",
                "lng": "-row.address.length",
                "lookups": "lookups + 1",
            }),
        )
}

async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_triggers(&catalog).await?;
    let registry = Arc::new(builtin_actions()?);
    let dispatcher = Arc::new(
        TriggerDispatcher::new(Arc::clone(&registry))
            .with_evaluator(Arc::new(DenoEvaluator::new())),
    );
    // Saving validates: `old` is in scope for this kind, as it is for `update`.
    save_trigger(&catalog, &registry, &geocode()).await?;
    dispatcher.reload(&catalog).await?;
    catalog.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn TableEvents>,
    )?;
    Ok(catalog)
}

/// The one place, as stored.
async fn place(catalog: &Catalog) -> Result<Json> {
    let places = catalog.require("places")?;
    let all = rows::list_rows(catalog, &places).await?;
    Ok(all
        .as_array()
        .and_then(|a| a.first())
        .cloned()
        .unwrap_or(Json::Null))
}

#[tokio::test]
async fn coordinates_follow_the_address_on_insert_and_update_and_only_then() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let places = catalog.require("places")?;

    // Created: the insert fires it.
    let created = rows::create_row(
        &catalog,
        &places,
        &json!({ "name": "HQ", "address": "Berlin" }),
    )
    .await?;
    let id = created["id"].as_i64().expect("an id").to_string();
    let p = place(&catalog).await?;
    assert_eq!(
        (p["lat"].clone(), p["lng"].clone()),
        (json!(6.0), json!(-6.0)),
        "{p}"
    );
    // Once: its own write-back was an update of the same address, which the
    // `only_if` declined.
    assert_eq!(p["lookups"], json!(1), "{p}");

    // The address changes: the update fires it.
    rows::update_row(&catalog, &places, &id, &json!({ "address": "Hamburg" })).await?;
    let p = place(&catalog).await?;
    assert_eq!(p["lat"], json!(7.0), "{p}");
    assert_eq!(p["lookups"], json!(2), "{p}");

    // Some other field changes: an update, but the address is the same.
    rows::update_row(&catalog, &places, &id, &json!({ "name": "Head office" })).await?;
    let p = place(&catalog).await?;
    assert_eq!(p["lookups"], json!(2), "{p}");
    assert_eq!(p["name"], json!("Head office"));

    // A delete is neither write, and is not listened for.
    rows::delete_row(&catalog, &places, &id).await?;
    assert_eq!(place(&catalog).await?, Json::Null);
    Ok(())
}
