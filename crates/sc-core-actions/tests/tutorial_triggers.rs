/// The tables the tutorial builds: `tasks` as the reader already has it (the
/// React tutorial's `title`/`done` plus the ownership tutorial's `owner`), and
/// the `task_audit` table step 1 creates — with `at` as a **bigint**, which is
/// the point the tutorial makes about `Date.now()`.
const SCHEMA: &str = "
    CREATE TABLE tasks (id bigint generated by default as identity primary key,
        title text not null, done boolean, owner text);
    CREATE TABLE task_audit (id bigint generated by default as identity primary key,
        task bigint, what text, who text, at bigint);
";

/// Step 2's trigger, verbatim from the document.
fn audit_completed() -> Trigger {
    Trigger::new("audit_completed", EventKind::Update, "insert_row")
        .on("tasks")
        .only_if("done && !old.done")
        .config("table", "task_audit")
        .config(
            "values",
            json!({
                "task": "row.id",
                "what": "'completed: ' + row.title",
                "who": "user ? user.email : 'nobody'",
                "at": "Date.now()"
            }),
        )
}

/// Step 3's trigger, verbatim.
fn archive_done() -> Trigger {
    Trigger::new("archive_done", EventKind::None, "delete_rows")
        .min_role(Role::of(40))
        .config("table", "tasks")
        .config("where", "done && owner === user.email")
}

/// Step 4's trigger, verbatim.
fn nightly_sweep() -> Trigger {
    Trigger::new("nightly_sweep", EventKind::Daily, "delete_rows")
        .timing(ATTR_HOUR, 3)
        .timing(ATTR_MINUTE, 30)
        .config("table", "task_audit")
        .config("where", "at < Date.now() - 30*24*3600*1000")
}

/// Step 5's trigger, verbatim — the body included, because the point of the step
/// is the body.
fn sweep_report() -> Trigger {
    Trigger::new("sweep_report", EventKind::None, "run_js_code").config(
        "code",
        r#"
const stale = await db.tasks
  .where({ done: true })
  .select("id", "title", "owner")
  .orderBy("id")
  .limit(50)
  .rows();

for (const task of stale) {
  await db.task_audit.insert({
    task: task.id,
    what: "swept: " + task.title,
    who: task.owner,
    at: Date.now(),
  });
}
return { swept: stale.length, left: await db.tasks.where({ done: false }).count() };
"#,
    )
}

/// The tutorial's streamed sweep, verbatim — the same work as [`sweep_report`]
/// written for a table too big to read at once.
fn sweep_streamed() -> Trigger {
    Trigger::new("sweep_streamed", EventKind::None, "run_js_code").config(
        "code",
        r#"
let swept = 0;
for await (const task of db.tasks.where({ done: true }).orderBy("title").iter()) {
  await db.task_audit.insert({ task: task.id, what: "swept: " + task.title, who: task.owner });
  swept += 1;
}
return { swept: swept };
"#,
    )
}

/// The tutorial's "running another trigger" example, verbatim — the two lines
/// the document prints, wrapped in the `return` a trigger needs to report
/// anything.
fn run_others() -> Trigger {
    Trigger::new("run_others", EventKind::None, "run_js_code").config(
        "code",
        r#"
const archived = await trigger("archive_done").run({ before: payload.today });
const report = await trigger("sweep_report").run();
return { archived: archived, report: report };
"#,
    )
}

/// The tutorial's grouped read, verbatim: one row per owner, bounded by a
/// condition on the count rather than on the rows.
fn open_by_owner() -> Trigger {
    Trigger::new("open_by_owner", EventKind::None, "run_js_code").config(
        "code",
        r#"
return await db.tasks
  .where({ done: false })
  .groupBy("owner")
  .aggregate({ open: "count()" })
  .having({ open: { gt: 1 } })
  .orderBy("open", "desc")
  .rows();
"#,
    )
}

struct Tutorial {
    catalog: Arc<Catalog>,
    dispatcher: Arc<TriggerDispatcher>,
    _db: TestDb,
}

impl Tutorial {
    /// The audit rows, oldest first, as `(task, what, who)`.
    async fn audit(&self) -> Result<Vec<(i64, String, String)>> {
        let rows = self
            ._db
            .client()
            .await?
            .query("SELECT task, what, who FROM task_audit ORDER BY id", &[])
            .await
            .map_err(|e| Error::database(e.to_string()))?;
        Ok(rows
            .iter()
            .map(|r| (r.get(0), r.get(1), r.get(2)))
            .collect())
    }

    /// Update a task the way the app does: through the row layer, with the
    /// signed-in member as the caller — which is what makes the audit row know
    /// who ticked the box.
    async fn tick(&self, id: &str, done: bool, member: &str) -> Result<()> {
        let tasks = self.catalog.require("tasks")?;
        let caller = Principal::new(Role::of(40), Some(json!({ "email": member })));
        rows::update_row(
            &self.catalog,
            &tasks,
            id,
            &json!({ "done": done }),
            sc_catalog::Unchecked::vouched(&caller, "test"),
        )
        .await?;
        Ok(())
    }
}

async fn setup() -> Result<Tutorial> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_triggers(&catalog).await?;

    let registry = Arc::new(builtin_actions()?);
    let dispatcher = Arc::new(
        TriggerDispatcher::new(Arc::clone(&registry))
            .with_evaluator(Arc::new(DenoEvaluator::new())),
    );

    // Saving validates — this is the admin's Save button — and every formula in
    // the tutorial goes through it.
    for trigger in [
        audit_completed(),
        archive_done(),
        nightly_sweep(),
        sweep_report(),
        sweep_streamed(),
        open_by_owner(),
        run_others(),
    ] {
        save_trigger(&catalog, &registry, &trigger).await?;
    }
    dispatcher.reload(&catalog).await?;
    // Nothing observes a write until the dispatcher is installed; from here the
    // reader's `tasks` table is live.
    catalog.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn TableEvents>,
    )?;

    Ok(Tutorial {
        catalog,
        dispatcher,
        _db: db,
    })
}

#[tokio::test]
async fn the_audit_trigger_fires_on_becoming_done_and_only_then() -> Result<()> {
    let t = setup().await?;
    let tasks = t.catalog.require("tasks")?;
    let member = "member@example.com";
    let created = rows::create_row(
        &t.catalog,
        &tasks,
        &json!({ "title": "Draft the report", "done": false, "owner": member }),
        sc_catalog::Unchecked::system("test"),
    )
    .await?;
    let id = created["id"].as_i64().expect("an id").to_string();
    assert!(t.audit().await?.is_empty(), "creating one audits nothing");

    // Tick it off, as the member, through the app's write path.
    t.tick(&id, true, member).await?;
    let audit = t.audit().await?;
    assert_eq!(audit.len(), 1, "{audit:?}");
    let (task, what, who) = &audit[0];
    assert_eq!(task.to_string(), id);
    // The formula concatenated a literal and the row's title…
    assert_eq!(what, "completed: Draft the report");
    // …and `user` is the member who ticked it, not the server.
    assert_eq!(who, member);

    // Saving an already-done task does not audit again: `!old.done` is what makes
    // the condition "became done" rather than "is done". This is the claim the
    // tutorial makes about untick-and-re-tick, in one direction…
    t.tick(&id, true, member).await?;
    assert_eq!(t.audit().await?.len(), 1);
    // …and the other: unticking is not a completion, and re-ticking is one more.
    t.tick(&id, false, member).await?;
    assert_eq!(t.audit().await?.len(), 1);
    t.tick(&id, true, member).await?;
    assert_eq!(t.audit().await?.len(), 2);
    Ok(())
}

#[tokio::test]
async fn the_none_trigger_archives_the_callers_own_finished_tasks() -> Result<()> {
    let t = setup().await?;
    let tasks = t.catalog.require("tasks")?;
    let member = "member@example.com";
    let other = "member2@example.com";
    for (title, done, owner) in [
        ("Draft the report", true, member),
        ("Book the venue", false, member),
        ("Renew the domain", true, other),
    ] {
        rows::create_row(
            &t.catalog,
            &tasks,
            &json!({ "title": title, "done": done, "owner": owner }),
            sc_catalog::Unchecked::system("test"),
        )
        .await?;
    }

    // What the app's `POST /api/actions/archive_done` does, with the member as
    // the caller: the same `run_trigger` the admin's Run button calls.
    let caller = Principal::new(Role::of(40), Some(json!({ "email": member })));
    let result = t
        .dispatcher
        .run_trigger(
            &t.catalog,
            "archive_done",
            json!({}),
            Authority::Caller(&caller),
        )
        .await?;
    assert_eq!(result["deleted"], json!(1), "{result}");

    // The member's finished task is gone; their unfinished one and the other
    // member's finished one are untouched — `owner === user.email` is doing the
    // selecting.
    let left = rows::list_rows(&t.catalog, &tasks, sc_catalog::Unchecked::system("test")).await?;
    let titles: Vec<&str> = left
        .as_array()
        .expect("an array")
        .iter()
        .filter_map(|r| r["title"].as_str())
        .collect();
    assert_eq!(titles, vec!["Book the venue", "Renew the domain"]);
    Ok(())
}

#[tokio::test]
async fn the_nightly_trigger_is_saved_with_the_timing_the_tutorial_states() -> Result<()> {
    let t = setup().await?;
    // It saved (so the `where` resolves against `task_audit`), and its timing
    // reads back as the 03:30 UTC the document says.
    let stored = t
        .dispatcher
        .triggers()?
        .by_name("nightly_sweep")
        .cloned()
        .expect("the daily trigger is in the live set");
    assert_eq!(
        Schedule::of(&stored)?,
        Some(Schedule::Daily {
            hour: 3,
            minute: 30
        })
    );
    // And it describes itself the way the list does, in UTC.
    assert_eq!(
        Schedule::of(&stored)?.expect("a schedule").to_string(),
        "daily at 03:30 UTC"
    );
    Ok(())
}

#[tokio::test]
async fn the_code_body_reads_the_tasks_and_writes_an_audit_row_for_each() -> Result<()> {
    let t = setup().await?;
    let tasks = t.catalog.require("tasks")?;
    let member = "member@example.com";
    for (title, done) in [
        ("Draft the report", true),
        ("Book the venue", false),
        ("Renew the domain", true),
    ] {
        rows::create_row(
            &t.catalog,
            &tasks,
            &json!({ "title": title, "done": done, "owner": member }),
            sc_catalog::Unchecked::system("test"),
        )
        .await?;
    }

    // Pressing Run, as the document says to.
    let caller = Principal::new(Role::of(40), Some(json!({ "email": member })));
    let result = t
        .dispatcher
        .run_trigger(
            &t.catalog,
            "sweep_report",
            json!({}),
            Authority::Caller(&caller),
        )
        .await?;
    assert_eq!(
        result,
        json!({ "swept": 2, "left": 1 }),
        "the body's own answer: {result}"
    );

    // …and the rows the reader is told to go and look at are there, one per
    // finished task, in the order the `.orderBy("id")` asked for.
    let audit = t.audit().await?;
    let what: Vec<&str> = audit.iter().map(|(_, what, _)| what.as_str()).collect();
    assert_eq!(
        what,
        vec!["swept: Draft the report", "swept: Renew the domain"]
    );
    assert!(
        audit.iter().all(|(_, _, who)| who == member),
        "the owner rode along: {audit:?}"
    );
    Ok(())
}

