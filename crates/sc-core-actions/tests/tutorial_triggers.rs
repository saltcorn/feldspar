//! The triggers tutorial, executed: every formula `docs/tutorial-triggers.md`
//! asks the reader to type, saved and fired for real.
//!
//! A tutorial is a promise that the words in the boxes work, and the ways it can
//! stop being true are quiet ones: the formula language gains a rule, an action
//! renames a setting, validation tightens. None of those break a test that only
//! reads the markdown — so this one **copies the formulas out of the document**
//! and puts them through `save_trigger` (which is the validator the admin's Save
//! button runs) and then through a real write.
//!
//! What it pins, in the tutorial's own order:
//!
//! - the audit trigger: `done && !old.done` fires on *becoming* done and not on
//!   any later save, and its four field values — including `Date.now()`, which is
//!   why the tutorial's `at` column is a `bigint` and not a `timestamptz`;
//! - the `none` trigger the app exposes: a `where` over the target table naming
//!   `user`, deleting the caller's rows and nobody else's;
//! - the daily one: the same action with a periodic event and its timing;
//! - step 5's code body: the `db` chain the document prints, reading `tasks` and
//!   writing an audit row per finished one — which is the step whose text is
//!   least like a setting and so the easiest to let drift.

#![allow(clippy::unwrap_used, clippy::expect_used)]

