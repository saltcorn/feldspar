use serde_json::{Value as Json, json};

const ADA: &str = "00000000-0000-4000-8000-00000000000a";
const BOB: &str = "00000000-0000-4000-8000-00000000000b";

/// `books` is what RLS protects: two of ada's, one of bob's. The rest carry a
/// cascade and record what its last step saw.
fn schema() -> String {
    format!(
        "CREATE TABLE books (id bigint generated by default as identity primary key, \
             title text, owner text); \
         CREATE TABLE notes (id bigint generated by default as identity primary key, what text); \
         CREATE TABLE relay (id bigint generated by default as identity primary key, what text); \
         CREATE TABLE seen (id bigint generated by default as identity primary key, \
             n bigint, by_user text, who text); \
         CREATE TABLE orders (id bigint generated by default as identity primary key, what text); \
         CREATE TABLE shipped (id bigint generated by default as identity primary key, what text); \
         INSERT INTO books (title, owner) VALUES \
             ('Dune', '{ADA}'), ('Emma', '{BOB}'), ('Ilium', '{ADA}');"
    )
}

/// The titles a body reads from `books`, at its default authority.
const READ_BOOKS: &str =
    "return (await db.books.where({}).orderBy('id').rows()).map(b => b.title);";

fn triggers() -> Vec<Trigger> {
    vec![
        // A code action someone runs: its default authority is the admin's.
        Trigger::new("read_books", EventKind::None, "run_js_code")
            .min_role(Role::PUBLIC)
            .config("code", READ_BOOKS),
        // The same body on a schedule: no human cause.
        Trigger::new("nightly", EventKind::Daily, "run_js_code").config("code", READ_BOOKS),
        // A cascade: started by a person, three triggers deep, and the last
        // step reads `books` and records what it saw and who it ran for.
        Trigger::new("start", EventKind::None, "run_js_code")
            .min_role(Role::PUBLIC)
            .config("code", "await db.notes.insert({ what: 'go' }); return 'started';"),
        Trigger::new("on_note", EventKind::Insert, "run_js_code")
            .on("notes")
            .config("code", "await db.relay.insert({ what: row.what });"),
        // H8.2: `asAdmin()` over an RLS table, from a body, by each surface.
        Trigger::new("on_book", EventKind::Insert, "run_js_code")
            .on("books")
            .config("code", "return 'ran';"),
        Trigger::new("as_admin", EventKind::None, "run_js_code")
            .min_role(Role::PUBLIC)
            .config(
                "code",
                r#"const said = async (f) => { try { await f(); return "ran"; } catch (e) { return e.message; } };
                   return {
                     db: await said(() => db.asAdmin().books.rows()),
                     query: await said(() => db.books.asAdmin().count()),
                     trigger: await said(() => trigger("on_book").asAdmin().run()),
                     other: await said(() => db.asAdmin().notes.rows()),
                   };"#,
            ),
        // H8.10: an order's trigger asks to run as system, counts every book
        // and writes `shipped`, whose own trigger is not approved.
        Trigger::new("place_order", EventKind::None, "run_js_code")
            .min_role(Role::PUBLIC)
            .config("code", "await db.orders.insert({ what: 'tea' }); return 'placed';"),
        system(
            Trigger::new("stock", EventKind::Insert, "run_js_code")
                .on("orders")
                .config("code", STOCK),
        ),
        Trigger::new("on_shipped", EventKind::Insert, "run_js_code")
            .on("shipped")
            .config(
                "code",
                "const n = (await db.books.rows()).length; \
                 await db.seen.insert({ n: n, by_user: user && user.id, who: 'on_shipped' });",
            ),
        Trigger::new("on_relay", EventKind::Insert, "run_js_code")
            .on("relay")
            .config(
                "code",
                "const n = (await db.books.rows()).length; \
                 await db.seen.insert({ n: n, by_user: user && user.id });",
            ),
    ]
}

/// What `stock` runs: it reads every book there is to read, records how many
/// and for whom, and ships the order.
const STOCK: &str = "const n = (await db.books.rows()).length; \
                     await db.seen.insert({ n: n, by_user: user && user.id, who: 'stock' }); \
                     await db.shipped.insert({ what: row.what });";

/// `trigger`, asking to run as system.
fn system(mut trigger: Trigger) -> Trigger {
    trigger.set_runs_as_system(true);
    trigger
}

struct World {
    catalog: Arc<Catalog>,
    dispatcher: Arc<TriggerDispatcher>,
    db: TestDb,
}

async fn setup() -> Result<World> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(&schema())
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    bootstrap_table_meta(&catalog).await?;
    bootstrap_triggers(&catalog).await?;

    let mut books = TableMeta::new("books");
    books.set_ownership_formula(Some("owner === user.id"));
    books.set_rls_enabled(true);
    save_table_meta(&catalog, &books).await?;
    enable_rls(&catalog, &catalog.require("books")?).await?;

    let registry = Arc::new(builtin_actions()?);
    let dispatcher = Arc::new(
        TriggerDispatcher::new(Arc::clone(&registry))
            .with_evaluator(Arc::new(DenoEvaluator::new())),
    );
    for trigger in triggers() {
        save_trigger(&catalog, &registry, &trigger).await?;
    }
    dispatcher.reload(&catalog).await?;
    catalog.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn TableEvents>,
    )?;
    Ok(World {
        catalog,
        dispatcher,
        db,
    })
}

/// Ada, signed in at role 80: below `books`' admin floors, so what she may
/// read there is what the formula grants her.
fn ada() -> Principal {
    Principal::recorded(Role::of(80), Some(json!({ "id": ADA, "role": 80 })))
}

#[tokio::test]
async fn a_code_action_run_by_a_role_80_user_reads_only_their_rows() -> Result<()> {
    let world = setup().await?;
    let titles = world
        .dispatcher
        .run_trigger(
            &world.catalog,
            "read_books",
            Json::Null,
            Authority::Caller(&ada()),
        )
        .await?;
    // Admin in ada's name — but `books` has RLS, so the policies read ada.
    assert_eq!(titles, json!(["Dune", "Ilium"]));

    // An administrator who runs it reads every row, as before.
    let admin = Principal::recorded(Role::ADMIN, Some(json!({ "id": BOB, "role": 1 })));
    let titles = world
        .dispatcher
        .run_trigger(
            &world.catalog,
            "read_books",
            Json::Null,
            Authority::Caller(&admin),
        )
        .await?;
    assert_eq!(titles, json!(["Dune", "Emma", "Ilium"]));
    Ok(())
}

#[tokio::test]
async fn a_scheduled_trigger_reads_every_row() -> Result<()> {
    let world = setup().await?;
    // The scheduler's own call (`scheduler.rs`): nobody asked, so the system.
    let titles = world
        .dispatcher
        .run_trigger(
            &world.catalog,
            "nightly",
            Json::Null,
            Authority::system("scheduled trigger"),
        )
        .await?;
    assert_eq!(titles, json!(["Dune", "Emma", "Ilium"]));
    Ok(())
}

#[tokio::test]
async fn a_cascade_started_by_a_user_stays_that_user_across_spawn_scoped() -> Result<()> {
    let world = setup().await?;
    let (catalog, dispatcher) = (Arc::clone(&world.catalog), Arc::clone(&world.dispatcher));
    // Started on a task of its own, as a request handler hands work on.
    let started = sc_catalog::spawn_scoped(async move {
        dispatcher
            .run_trigger(&catalog, "start", Json::Null, Authority::Caller(&ada()))
            .await
    })
    .await
    .expect("the task ran")?;
    assert_eq!(started, json!("started"));

    // `start` wrote `notes` as admin in ada's name; `on_note` fired on it and
    // wrote `relay`; `on_relay` fired on that and read `books`. Each action's
    // authority was elevated over the event before it, and every event was
    // caused by ada, so the last read saw her two rows and not three.
    let rows = world
        .db
        .client()
        .await?
        .query("SELECT n, by_user FROM seen", &[])
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let seen: Vec<(i64, Option<String>)> = rows.iter().map(|r| (r.get(0), r.get(1))).collect();
    assert_eq!(seen, vec![(2, Some(ADA.to_owned()))]);
    Ok(())
}

/// The value type: elevation keeps the cause, and the policy reads it.
#[test]
fn an_elevated_principal_shows_the_policies_its_cause() {
    let elevated = Principal::elevated(&ada(), "a test's rule");
    assert!(
        elevated.role().is_admin(),
        "the row layer sees an administrator"
    );
    assert_eq!(elevated.policy_role(), Role::of(80));
    assert_eq!(
        elevated.policy_user().and_then(|u| u.get("id")),
        Some(&json!(ADA))
    );
    // Elevating again does not stack: the cause is still ada.
    let again = Principal::elevated(elevated.principal(), "a test's rule");
    assert_eq!(again.policy_role(), Role::of(80));
    // An application's maximum role caps the cause as well.
    let capped =
        Principal::recorded(Role::ADMIN, Some(json!({ "id": BOB }))).capped_at(Role::of(40));
    assert_eq!(
        Principal::elevated(&capped, "a test's rule").policy_role(),
        Role::of(40)
    );
}

#[tokio::test]
async fn as_admin_on_an_rls_table_is_refused_by_every_surface_of_a_body() -> Result<()> {
    let world = setup().await?;
    let said = world
        .dispatcher
        .run_trigger(
            &world.catalog,
            "as_admin",
            Json::Null,
            Authority::Caller(&ada()),
        )
        .await?;
    for surface in ["db", "query", "trigger"] {
        let message = said[surface].as_str().unwrap_or_default();
        assert!(
            message.contains("`books` has row-level security") && message.contains("asAdmin()"),
            "{surface}: {said}"
        );
    }
    // A table without RLS is the admin's to reach, as before.
    assert_eq!(said["other"], json!("ran"));
    Ok(())
}

