impl World {
    /// What `seen` recorded, as `(who, n, by_user)`, oldest first.
    async fn seen(&self) -> Result<Vec<(String, i64, Option<String>)>> {
        let rows = self
            .db
            .client()
            .await?
            .query("SELECT who, n, by_user FROM seen ORDER BY id", &[])
            .await
            .map_err(|e| Error::database(e.to_string()))?;
        Ok(rows
            .iter()
            .map(|r| (r.get(0), r.get(1), r.get(2)))
            .collect())
    }

    async fn clear_seen(&self) -> Result<()> {
        self.db
            .client()
            .await?
            .batch_execute("DELETE FROM seen")
            .await
            .map_err(|e| Error::database(e.to_string()))
    }

    /// Ada places an order, which fires `stock`.
    async fn order_as_ada(&self) -> Result<()> {
        self.dispatcher
            .run_trigger(
                &self.catalog,
                "place_order",
                Json::Null,
                Authority::Caller(&ada()),
            )
            .await?;
        Ok(())
    }

    async fn stock(&self) -> Result<Trigger> {
        Ok(sc_action::load_trigger_by_name(&self.catalog, "stock")
            .await?
            .expect("the trigger"))
    }
}

/// The operator, who approves at the CLI.
fn operator() -> sc_catalog::Editor {
    sc_catalog::Editor::Operator(sc_catalog::Operator::at_cli("a test's operator"))
}

#[tokio::test]
async fn an_approved_trigger_reads_every_row_and_lapses_when_its_code_changes() -> Result<()> {
    let world = setup().await?;
    let stock = world.stock().await?;

    // Asked for, and not approved: a pending request, at the cause's authority.
    assert_eq!(
        world
            .dispatcher
            .system_state(&world.catalog, &stock)
            .await?,
        sc_action::SystemState::Pending
    );
    // Something that is not a person cannot approve it.
    let hash = world
        .dispatcher
        .configuration_hash(&world.catalog, &stock)
        .await?;
    let refused = sc_action::approve_system_trigger(
        &world.catalog,
        &sc_catalog::Editor::Delegated("an MCP client"),
        stock.id,
        &hash,
    )
    .await
    .expect_err("only a person approves");
    assert!(refused.to_string().contains("only a person"), "{refused}");
    world.order_as_ada().await?;
    assert_eq!(
        world.seen().await?,
        vec![
            ("stock".to_owned(), 2, Some(ADA.to_owned())),
            ("on_shipped".to_owned(), 2, Some(ADA.to_owned())),
        ],
        "pending: ada's view, at every level"
    );

    // A person approves it: fired by ada's insert, its own statements read
    // every row; the trigger its write fires still runs as ada.
    sc_action::approve_system_trigger(&world.catalog, &operator(), stock.id, &hash).await?;
    world.dispatcher.reload(&world.catalog).await?;
    world.clear_seen().await?;
    world.order_as_ada().await?;
    assert_eq!(
        world.seen().await?,
        vec![
            ("stock".to_owned(), 3, Some(ADA.to_owned())),
            ("on_shipped".to_owned(), 2, Some(ADA.to_owned())),
        ],
        "approved: the system's view for its own statements only; `user` is still ada"
    );

    // An agent edits its code (any save that is not a person's re-approval):
    // the approval is for the old code, so it lapses.
    let mut edited = world.stock().await?;
    edited.body = sc_action::TriggerBody::parse(
        "action",
        Some("run_js_code"),
        [(
            "code".to_owned(),
            json!(format!("{STOCK} // and one more line")),
        )]
        .into_iter()
        .collect(),
    )?;
    sc_action::save_trigger(&world.catalog, &builtin_actions()?, &edited).await?;
    world.dispatcher.reload(&world.catalog).await?;
    assert_eq!(
        world
            .dispatcher
            .system_state(&world.catalog, &world.stock().await?)
            .await?,
        sc_action::SystemState::Pending
    );
    world.clear_seen().await?;
    world.order_as_ada().await?;
    assert_eq!(
        world.seen().await?[0],
        ("stock".to_owned(), 2, Some(ADA.to_owned())),
        "lapsed: ada's view again"
    );
    Ok(())
}
