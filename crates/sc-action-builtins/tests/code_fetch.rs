//! `fetch` **inside a code body**, against a real socket and the real engine.
//!
//! Pinned to bytes on a wire for the reason the `fetch` action's tests are: what
//! can be wrong here is what was sent and what was made of the reply, and a
//! mocked client would assert those about a request that never happened. What is
//! new is that the request is written in **JavaScript by the trigger's author**,
//! so what is really under test is the whole path — the guest's `fetch`, the
//! plan it builds, the host that sends it, and the `Response` the body reads
//! back.
//!
//! Asserted here: a body's GET and POST arrive as written (method, path,
//! headers, body); the response's status, headers and JSON come back to the
//! body; a non-2xx is a value rather than a throw, so a body can branch on it; a
//! request the endpoint never answers fails inside the body's own time limit and
//! is catchable; and what a body fetches can be written to a table in the same
//! run, which is the point of having it here rather than in an action.
#![allow(
    clippy::disallowed_methods,
    reason = "test code: it drives its own servers, tasks and channels; the replacements are for production paths"
)]
#![allow(clippy::unwrap_used, clippy::expect_used)]

