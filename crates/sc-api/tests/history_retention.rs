//! Row history H5: files, schema edits and retention (design §14.12 "Files",
//! "Schema edits and retention"). A file survives its row's delete while
//! history can restore it and goes when the delete entry expires; the one
//! cleanup job serves sync and history; a renamed column keeps the history
//! readable; a dropped table takes its entries with it.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::path::PathBuf;
use std::sync::Arc;

use sc_api::history::HistoryReader;
use sc_api::undo::Reverser;
use sc_api::{rows, schema_edit};
use sc_auth::User;
use sc_catalog::retention::{Cleanup, clean_change_log};
use sc_catalog::{
    CallerContext, Catalog, Changeset, ChangesetSource, DataFieldKind, FieldMeta, FileOnDelete,
    FileStoreId, bootstrap_change_log, bootstrap_field_meta, bootstrap_table_meta, changeset,
    save_field_meta,
};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Result};
use sc_files::LocalFileStore;
use sc_test_harness::TestDb;
use serde_json::{Value as Json, json};

const ADMIN: &str = "00000000-0000-4000-8000-0000000000ad";

async fn sql(db: &TestDb, statements: &str) -> Result<()> {
    db.client()
        .await?
        .batch_execute(statements)
        .await
        .map_err(|e| Error::database(format!("{e:?}")))
}

async fn count(db: &TestDb, query: &str) -> Result<i64> {
    let row = db
        .client()
        .await?
        .query_one(query, &[])
        .await
        .map_err(|e| Error::database(format!("{e:?}")))?;
    Ok(row.get(0))
}

async fn alter(catalog: &Catalog, table: &str, settings: schema_edit::TableSettings) -> Result<()> {
    let op = schema_edit::Operation::AlterTable {
        table: table.to_owned(),
        settings,
    };
    schema_edit::apply(catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    Ok(())
}

fn history(keep_days: u32) -> schema_edit::TableSettings {
    schema_edit::TableSettings {
        history_enabled: Some(true),
        history_keep_days: Some(keep_days),
        ..Default::default()
    }
}

async fn catalog(db: &TestDb, ddl: &str) -> Result<Arc<Catalog>> {
    sql(db, ddl).await?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    catalog.reload().await?;
    Ok(catalog)
}

/// A file store in a fresh directory, connected as `files`.
fn file_store(catalog: &Catalog, tag: &str) -> Result<PathBuf> {
    let dir = std::env::temp_dir().join(format!("sc-history-files-{tag}-{}", uuid::Uuid::new_v4()));
    std::fs::create_dir_all(&dir).unwrap();
    catalog.connect_file_store(Arc::new(LocalFileStore::new("files", &dir)?))?;
    Ok(dir)
}

/// `docs(id, title, attachment)`, `attachment` a file removed with its row.
async fn docs(db: &TestDb, tag: &str) -> Result<(Arc<Catalog>, PathBuf)> {
    let catalog = catalog(
        db,
        "CREATE TABLE docs (id bigint generated by default as identity primary key,
                            title text, attachment text);",
    )
    .await?;
    let dir = file_store(&catalog, tag)?;
    let meta = FieldMeta::new("docs", "attachment").kind(DataFieldKind::File {
        store: FileStoreId("files".to_owned()),
        folder: None,
        mime_allow: Vec::new(),
        on_delete: FileOnDelete::RemoveFile,
        on_conflict: Default::default(),
    });
    save_field_meta(&catalog, &meta).await?;
    Ok((catalog, dir))
}

fn admin() -> User {
    User::new(ADMIN.parse().unwrap(), 1).unwrap()
}

fn caller() -> CallerContext {
    CallerContext::new(1, Some(json!({ "id": ADMIN, "role": 1 })))
}

/// The writes `f` makes, as one request changeset.
async fn action<T>(f: impl std::future::Future<Output = Result<T>>) -> Result<T> {
    changeset::scope(Arc::new(Changeset::new(ChangesetSource::Request)), f).await
}

async fn insert(catalog: &Catalog, table: &str, body: Json) -> Result<String> {
    let table = catalog.require(table)?;
    action(async {
        let row = rows::create_row_ctx(catalog, &table, &body, Some(&caller())).await?;
        Ok(row["id"].to_string())
    })
    .await
}

async fn update(catalog: &Catalog, table: &str, id: &str, body: Json) -> Result<()> {
    let table = catalog.require(table)?;
    action(async {
        rows::update_row_ctx(catalog, &table, id, &body, Some(&caller())).await?;
        Ok(())
    })
    .await
}

async fn delete(catalog: &Catalog, table: &str, id: &str) -> Result<()> {
    let table = catalog.require(table)?;
    action(async {
        rows::delete_row_ctx(catalog, &table, id, Some(&caller())).await?;
        Ok(())
    })
    .await
}

/// A doc whose attachment is `path`, with the file written into the store.
async fn doc_with_file(catalog: &Catalog, dir: &std::path::Path, path: &str) -> Result<String> {
    std::fs::write(dir.join(path), b"contents").unwrap();
    insert(
        catalog,
        "docs",
        json!({ "title": path, "attachment": path }),
    )
    .await
}

/// A delete keeps the file while history can restore the row, and the
/// restore gets it back. With history off, the file goes with the row.
#[tokio::test]
async fn a_file_survives_the_delete_and_a_restore_gets_it_back() -> Result<()> {
    let db = TestDb::new().await?;
    let (catalog, dir) = docs(&db, "restore").await?;
    alter(&catalog, "docs", history(0)).await?;

    let id = doc_with_file(&catalog, &dir, "a.txt").await?;
    delete(&catalog, "docs", &id).await?;
    assert!(dir.join("a.txt").exists(), "kept for a restore");

    let user = admin();
    let restored = Reverser::new(&catalog, Some(&user), None)
        .restore_row("docs", &id)
        .await?;
    assert_eq!(restored.row["attachment"], "a.txt");
    assert!(dir.join("a.txt").exists());

    // Nothing will restore it once history is off: the file goes at once.
    alter(
        &catalog,
        "docs",
        schema_edit::TableSettings {
            history_enabled: Some(false),
            ..Default::default()
        },
    )
    .await?;
    delete(&catalog, "docs", &id).await?;
    assert!(!dir.join("a.txt").exists());
    Ok(())
}

/// The cleanup removes entries older than `keep_days`, then the files of
/// those deletes that nothing references any more, then the changesets left
/// empty. A row, or an entry still kept, that names the path keeps the file.
#[tokio::test]
async fn the_file_is_removed_after_expiry_unless_something_still_references_it() -> Result<()> {
    let db = TestDb::new().await?;
    let (catalog, dir) = docs(&db, "expiry").await?;
    alter(&catalog, "docs", history(30)).await?;

    let a = doc_with_file(&catalog, &dir, "a.txt").await?;
    let shared = doc_with_file(&catalog, &dir, "shared.txt").await?;
    let _keeps_shared = insert(
        &catalog,
        "docs",
        json!({ "title": "other", "attachment": "shared.txt" }),
    )
    .await?;
    let d_old = doc_with_file(&catalog, &dir, "d.txt").await?;
    let d_new = insert(
        &catalog,
        "docs",
        json!({ "title": "d again", "attachment": "d.txt" }),
    )
    .await?;
    for id in [&a, &shared, &d_old, &d_new] {
        delete(&catalog, "docs", id).await?;
    }
    let now = chrono::Utc::now();
    assert_eq!(clean_change_log(&catalog, now).await?, Cleanup::default());

    // Everything is old but the last delete of `d.txt`.
    sql(
        &db,
        &format!(
            "UPDATE _fd_changes SET at = now() - interval '40 days' \
              WHERE NOT (row_key = '{d_new}' AND op = 'd');
             UPDATE _fd_changesets SET at = now() - interval '40 days';"
        ),
    )
    .await?;
    let done = clean_change_log(&catalog, now).await?;
    // Five inserts and three deletes, and the eight changesets they leave
    // empty: one change each.
    assert_eq!(done.entries, 8, "{done:?}");
    assert_eq!(done.changesets, 8, "{done:?}");
    assert_eq!(done.files, 1, "{done:?}");
    assert!(!dir.join("a.txt").exists());
    assert!(dir.join("shared.txt").exists(), "a row still has it");
    assert!(
        dir.join("d.txt").exists(),
        "a kept delete entry still has it"
    );

    let user = admin();
    let deleted = HistoryReader::new(&catalog, Some(&user), None)
        .deleted_rows("docs", None, 0)
        .await?;
    assert_eq!(deleted.as_array().map(Vec::len), Some(1), "{deleted}");

    sql(
        &db,
        "UPDATE _fd_changes SET at = now() - interval '40 days';",
    )
    .await?;
    let done = clean_change_log(&catalog, now).await?;
    assert_eq!((done.entries, done.files), (1, 1), "{done:?}");
    assert!(!dir.join("d.txt").exists());
    assert_eq!(count(&db, "SELECT count(*) FROM _fd_changesets").await?, 0);
    Ok(())
}

/// With sync and history both on, an entry goes only once both are done with
/// it: past `keep_days`, superseded and past sync's retention. History kept
/// forever keeps everything; with both off, everything of the table goes.
#[tokio::test]
async fn retention_with_both_features_on() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = catalog(
        &db,
        "CREATE TABLE notes (id bigint generated by default as identity primary key, body text);
         CREATE TABLE forever (id bigint generated by default as identity primary key, body text);",
    )
    .await?;
    let both = |keep_days| schema_edit::TableSettings {
        sync_enabled: Some(true),
        ..history(keep_days)
    };
    alter(&catalog, "notes", both(30)).await?;
    alter(&catalog, "forever", both(0)).await?;
    for table in ["notes", "forever"] {
        let id = insert(&catalog, table, json!({ "body": "one" })).await?;
        update(&catalog, table, &id, json!({ "body": "two" })).await?;
        update(&catalog, table, &id, json!({ "body": "three" })).await?;
    }
    let entries =
        |table: &str| format!("SELECT count(*) FROM _fd_changes WHERE table_name = '{table}'");

    // Old for history, but not yet for sync: sync still wants them.
    sql(
        &db,
        "UPDATE _fd_changes SET at = now() - interval '20 days';",
    )
    .await?;
    sql(
        &db,
        "UPDATE _fd_changes SET at = now() - interval '35 days' WHERE table_name = 'notes';",
    )
    .await?;
    assert_eq!(
        clean_change_log(&catalog, chrono::Utc::now())
            .await?
            .entries,
        2
    );
    // The two superseded entries are past both retentions; the latest stays,
    // because a device needs it, whatever history says.
    assert_eq!(count(&db, &entries("notes")).await?, 1);
    assert_eq!(
        count(&db, &entries("forever")).await?,
        3,
        "history keeps forever"
    );

    // Sync's key pairs go after its retention too.
    sql(
        &db,
        &format!(
            "INSERT INTO _fd_sync_keys (client_id, mutation, table_name, row_key, at) VALUES
               (gen_random_uuid(), 1, 'notes', '1', now() - interval '{} days'),
               (gen_random_uuid(), 2, 'notes', '2', now());",
            sc_catalog::retention::SYNC_KEEP_DAYS + 1
        ),
    )
    .await?;
    sql(
        &db,
        "UPDATE _fd_changes SET at = now() - interval '400 days';",
    )
    .await?;
    let done = clean_change_log(&catalog, chrono::Utc::now()).await?;
    assert_eq!((done.entries, done.sync_keys), (0, 1), "{done:?}");

    // Neither feature on: the table's entries are nobody's.
    alter(
        &catalog,
        "notes",
        schema_edit::TableSettings {
            sync_enabled: Some(false),
            history_enabled: Some(false),
            ..Default::default()
        },
    )
    .await?;
    assert_eq!(
        clean_change_log(&catalog, chrono::Utc::now())
            .await?
            .entries,
        1
    );
    assert_eq!(count(&db, &entries("notes")).await?, 0);
    assert_eq!(count(&db, &entries("forever")).await?, 3);
    Ok(())
}

/// Renaming a column rewrites the key in the table's entries in the same
/// batch, so the history and `as_of` read the field under its new name. A
/// dropped table's entries go with it, and a new table of the same name
/// starts with no history.
#[tokio::test]
async fn a_rename_keeps_history_readable_and_a_drop_forgets_it() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = catalog(
        &db,
        "CREATE TABLE projects (id bigint generated by default as identity primary key,
                                name text, budget int);",
    )
    .await?;
    alter(&catalog, "projects", history(0)).await?;
    let id = insert(&catalog, "projects", json!({ "name": "p", "budget": 5 })).await?;
    update(&catalog, "projects", &id, json!({ "budget": 7 })).await?;

    let rename = |from: &str, to: &str| schema_edit::Operation::AlterField {
        table: "projects".into(),
        field: from.into(),
        settings: schema_edit::FieldSettings {
            name: Some(to.into()),
            ..Default::default()
        },
    };
    let options = schema_edit::ApplyOptions::default();
    let taken = schema_edit::apply(&catalog, &[rename("budget", "name")], &options)
        .await
        .unwrap_err();
    assert!(
        taken.to_string().contains("already has a field `name`"),
        "{taken}"
    );

    let applied = schema_edit::apply(&catalog, &[rename("budget", "cost")], &options).await?;
    assert!(
        applied.notes.iter().any(|n| n.contains("`projects.cost`")),
        "{applied:?}"
    );
    let table = catalog.require("projects")?;
    assert!(table.field("cost").is_some() && table.field("budget").is_none());

    let user = admin();
    let reader = HistoryReader::new(&catalog, Some(&user), None);
    let entries = reader.row_history("projects", &id).await?;
    let changes = &entries[0]["changes"];
    assert!(changes.to_string().contains("\"cost\""), "{entries}");
    assert!(!changes.to_string().contains("budget"), "{entries}");
    assert!(!changes.to_string().contains("removed\":true"), "{entries}");
    let first = entries[1]["seq"].as_i64().unwrap();
    let as_of = reader
        .row_as_of("projects", &id, &first.to_string())
        .await?;
    assert_eq!(as_of["row"]["cost"], 5, "{as_of}");
    assert_eq!(as_of["removed"], json!({}), "{as_of}");

    // A row written after the rename is recorded under the new name too.
    update(&catalog, "projects", &id, json!({ "cost": 9 })).await?;
    assert_eq!(
        count(
            &db,
            "SELECT count(*) FROM _fd_changes WHERE new_values ? 'budget' OR old_values ? 'budget'"
        )
        .await?,
        0
    );

    schema_edit::apply(
        &catalog,
        &[schema_edit::Operation::DropTable {
            table: "projects".into(),
        }],
        &options,
    )
    .await?;
    assert_eq!(count(&db, "SELECT count(*) FROM _fd_changes").await?, 0);
    sql(
        &db,
        "CREATE TABLE projects (id bigint generated by default as identity primary key, name text);",
    )
    .await?;
    catalog.reload().await?;
    alter(&catalog, "projects", history(0)).await?;
    let entries = reader.row_history("projects", &id).await?;
    assert_eq!(entries, json!([]), "{entries}");
    Ok(())
}

/// Renaming the key column re-creates the change-log trigger on the new
/// name, so later writes are still recorded under the row's key.
#[tokio::test]
async fn renaming_the_key_keeps_recording() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = catalog(
        &db,
        "CREATE TABLE tags (id bigint generated by default as identity primary key, label text);",
    )
    .await?;
    alter(&catalog, "tags", history(0)).await?;
    let id = insert(&catalog, "tags", json!({ "label": "a" })).await?;
    schema_edit::apply(
        &catalog,
        &[schema_edit::Operation::AlterField {
            table: "tags".into(),
            field: "id".into(),
            settings: schema_edit::FieldSettings {
                name: Some("tag_id".into()),
                ..Default::default()
            },
        }],
        &schema_edit::ApplyOptions::default(),
    )
    .await?;
    assert_eq!(
        catalog.require("tags")?.primary_key,
        vec!["tag_id".to_owned()]
    );
    sql(
        &db,
        &format!("UPDATE tags SET label = 'b' WHERE tag_id = {id};"),
    )
    .await?;
    let user = admin();
    let entries = HistoryReader::new(&catalog, Some(&user), None)
        .row_history("tags", &id)
        .await?;
    assert_eq!(entries.as_array().map(Vec::len), Some(2), "{entries}");
    assert!(
        entries[1]["changes"].to_string().contains("tag_id"),
        "{entries}"
    );
    Ok(())
}
