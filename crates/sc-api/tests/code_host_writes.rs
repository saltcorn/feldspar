/// Books with an author key, an audit table for a trigger to write into, and one
/// self-referential table for the cascade bound — the same shape the server's own
/// trigger tests use, for the same reasons.
const SCHEMA: &str = "\
    CREATE TABLE authors (id bigint generated by default as identity primary key, name text); \
    CREATE TABLE books (id bigint generated by default as identity primary key, \
        title text not null, pages bigint, published date, price numeric, \
        author bigint references authors(id)); \
    CREATE TABLE audit (id bigint generated by default as identity primary key, \
        what text, title text, who text); \
    CREATE TABLE links (id bigint generated by default as identity primary key, depth bigint); \
    INSERT INTO authors (name) VALUES ('Woolf'), ('Herbert');";

/// The catalog over a fresh database with [`SCHEMA`] in it.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    Ok(Arc::new(
        Catalog::init(driver as Arc<dyn DatabaseDriver>).await?,
    ))
}

/// One plan, answered — what `__scDbCall(plan)` gets back.
async fn ask(host: &TableHost<'_>, plan: Json) -> Result<Json> {
    host.call(plan).await
}

/// Every row of a table, by the shortest route that is not the code host itself:
/// a test that asserted its own writes through its own reads could agree with
/// itself about a write that never happened.
async fn rows_of(db: &TestDb, sql: &str) -> Vec<Vec<Option<String>>> {
    db.client()
        .await
        .unwrap()
        .query(sql, &[])
        .await
        .unwrap()
        .iter()
        .map(|row| {
            (0..row.len())
                .map(|i| row.get::<_, Option<String>>(i))
                .collect()
        })
        .collect()
}

#[tokio::test]
async fn an_insert_returns_the_written_row_with_its_values_typed_by_their_columns() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let host = TableHost::new(&catalog);

    // `db.books.insert({ … })` — one row in, one row out (not an array of one),
    // with the database-generated key filled in.
    let written = ask(
        &host,
        json!({
            "op": "insert", "table": "books",
            "values": {
                "title": "Orlando", "pages": 333, "published": "1928-10-11",
                "price": "12.50", "author": 1,
            },
        }),
    )
    .await?;
    assert_eq!(written["id"], json!(1), "the key the database generated");
    assert_eq!(written["title"], json!("Orlando"));
    // The REST wire shape, as a read's rows are: a Date is ISO and a Decimal is
    // exact text rather than a float that has quietly stopped being exact.
    assert_eq!(written["published"], json!("1928-10-11"));
    assert_eq!(written["price"], json!("12.50"));

    // The values reached the columns **typed**: the date is a date in the
    // database, not text that looks like one — which is what lets a date filter
    // find it. (A string bound to a date column would not compare this way.)
    let found = ask(
        &host,
        json!({
            "op": "select", "table": "books",
            "where": { "published": { "lt": "1930-01-01" } },
            "select": ["title"],
        }),
    )
    .await?;
    assert_eq!(found, json!([{ "title": "Orlando" }]));
    assert_eq!(
        rows_of(&db, "SELECT pg_typeof(published)::text FROM books").await,
        vec![vec![Some("date".to_owned())]],
    );

    // An array in is an array out, one statement per row.
    let many = ask(
        &host,
        json!({
            "op": "insert", "table": "books",
            "values": [
                { "title": "The Waves", "author": 1 },
                { "title": "Dune", "author": 2 },
            ],
        }),
    )
    .await?;
    let many = many.as_array().expect("an array of written rows");
    assert_eq!(many.len(), 2);
    assert_eq!(many[0]["id"], json!(2));
    assert_eq!(many[1]["title"], json!("Dune"));
    Ok(())
}

#[tokio::test]
async fn a_bulk_update_and_delete_answer_what_they_touched() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let host = TableHost::new(&catalog);
    ask(
        &host,
        json!({
            "op": "insert", "table": "books",
            "values": [
                { "title": "Orlando", "pages": 333, "author": 1 },
                { "title": "The Waves", "pages": 297, "author": 1 },
                { "title": "Dune", "pages": 412, "author": 2 },
            ],
        }),
    )
    .await?;

    // `db.books.where({ author: 1 }).orderBy("id").update({ pages: 100 })` —
    // `{ updated, ids }`, the shape the `update_rows` action already answers.
    let updated = ask(
        &host,
        json!({
            "op": "update", "table": "books",
            "where": { "author": 1 },
            "order": [ { "field": "id" } ],
            "values": { "pages": 100 },
        }),
    )
    .await?;
    assert_eq!(updated, json!({ "updated": 2, "ids": [1, 2] }));
    assert_eq!(
        rows_of(&db, "SELECT pages::text FROM books ORDER BY id").await,
        vec![
            vec![Some("100".to_owned())],
            vec![Some("100".to_owned())],
            vec![Some("412".to_owned())],
        ],
    );

    // A `.limit()` bounds a bulk write as it bounds a read — "the oldest one".
    let limited = ask(
        &host,
        json!({
            "op": "update", "table": "books",
            "where": { "author": 1 }, "order": [ { "field": "id" } ], "limit": 1,
            "values": { "title": "Orlando (rev.)" },
        }),
    )
    .await?;
    assert_eq!(limited, json!({ "updated": 1, "ids": [1] }));

    let deleted = ask(
        &host,
        json!({
            "op": "delete", "table": "books",
            "where": { "pages": { "gt": 300 } },
        }),
    )
    .await?;
    assert_eq!(deleted, json!({ "deleted": 1, "ids": [3] }));
    assert_eq!(
        rows_of(&db, "SELECT title FROM books ORDER BY id").await,
        vec![
            vec![Some("Orlando (rev.)".to_owned())],
            vec![Some("The Waves".to_owned())],
        ],
    );
    Ok(())
}

#[tokio::test]
async fn a_write_with_no_filter_or_a_bad_value_touches_nothing() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let host = TableHost::new(&catalog);
    ask(
        &host,
        json!({
            "op": "insert", "table": "books",
            "values": [ { "title": "Orlando", "pages": 333 }, { "title": "Dune", "pages": 412 } ],
        }),
    )
    .await?;

    // §4: a whole table rewritten or emptied is not something an omitted call
    // should be able to cause. The prelude says so in front of the author; this
    // is the host saying it to a plan that arrived without one anyway.
    for op in ["update", "delete"] {
        let err = ask(
            &host,
            json!({ "op": op, "table": "books", "values": { "pages": 1 } }),
        )
        .await
        .expect_err("refused");
        assert!(err.to_string().contains("every row of `books`"), "{err}");
    }

    // A bulk insert whose *last* row is wrong writes none of them: there is no
    // transaction here (§6), so the check has to come before the first statement.
    let err = ask(
        &host,
        json!({
            "op": "insert", "table": "books",
            "values": [ { "title": "Mrs Dalloway" }, { "title": "Jacob's Room", "pages": "lots" } ],
        }),
    )
    .await
    .expect_err("refused");
    assert!(err.to_string().contains("`pages`"), "{err}");

    assert_eq!(
        rows_of(&db, "SELECT title FROM books ORDER BY id").await,
        vec![
            vec![Some("Orlando".to_owned())],
            vec![Some("Dune".to_owned())],
        ],
        "nothing was written by any of the refused plans",
    );
    Ok(())
}

