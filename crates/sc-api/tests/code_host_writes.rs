/// A trigger action that records what it was handed: the event's row, its
/// caller, and how deep in a cascade it already was.
struct Recorder(Arc<Mutex<Vec<Json>>>);

#[async_trait::async_trait]
impl Action for Recorder {
    fn name(&self) -> &str {
        "record"
    }
    fn description(&self) -> &str {
        "Record the event, for a test to read back"
    }
    fn config_spec(&self) -> Vec<FormField> {
        Vec::new()
    }
    async fn run(&self, ctx: &mut ActionContext<'_>) -> Result<Json> {
        let seen = json!({
            "kind": ctx.event.kind.as_str(),
            "row": ctx.event.row,
            "user": ctx.event.user,
            "chain": ctx.chain,
            "depth": ctx.event.depth(),
        });
        self.0.lock().unwrap().push(seen.clone());
        Ok(seen)
    }
}

/// A trigger action that writes the table it fired on, **through a code host**,
/// carrying the chain it was given — a code body that feeds itself.
struct Feed {
    catalog: Arc<Catalog>,
    chains: Arc<Mutex<Vec<Vec<String>>>>,
}

#[async_trait::async_trait]
impl Action for Feed {
    fn name(&self) -> &str {
        "feed"
    }
    fn description(&self) -> &str {
        "Insert another row into the table that fired, from a code host"
    }
    fn config_spec(&self) -> Vec<FormField> {
        Vec::new()
    }
    async fn run(&self, ctx: &mut ActionContext<'_>) -> Result<Json> {
        self.chains.lock().unwrap().push(ctx.chain.clone());
        let depth = ctx
            .event
            .row
            .as_ref()
            .and_then(|row| row["depth"].as_i64())
            .unwrap_or(0);
        // Exactly what phase 5 will build for `run_js_code`: the event's caller
        // and *this trigger's chain*, so the event this write raises knows how
        // deep it is.
        let host = TableHost::new(&self.catalog)
            .caused_by(ctx.event.role, ctx.event.user.clone())
            .chained(ctx.chain.clone());
        host.call(json!({
            "op": "insert", "table": "links", "values": { "depth": depth + 1 },
        }))
        .await
    }
}

/// The catalog with a real dispatcher installed over `actions`, and one trigger
/// per `(name, kind, table)` saved and loaded the way the admin's are.
async fn with_triggers(
    catalog: &Arc<Catalog>,
    actions: Vec<Arc<dyn Action>>,
    triggers: Vec<Trigger>,
) -> Result<Arc<TriggerDispatcher>> {
    let mut registry = ActionRegistry::new();
    for action in actions {
        registry.register(action)?;
    }
    let dispatcher = Arc::new(TriggerDispatcher::new(Arc::new(registry)));
    bootstrap_triggers(catalog).await?;
    for trigger in &triggers {
        save_trigger(catalog, &dispatcher.registry(), trigger).await?;
    }
    dispatcher.reload(catalog).await?;
    catalog.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn sc_catalog::TableEvents>,
    )?;
    Ok(dispatcher)
}

#[tokio::test]
async fn an_insert_from_a_code_body_fires_the_tables_own_trigger() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let seen = Arc::new(Mutex::new(Vec::new()));
    with_triggers(
        &catalog,
        vec![Arc::new(Recorder(Arc::clone(&seen)))],
        vec![
            Trigger::new("watch_insert", EventKind::Insert, "record").on("books"),
            Trigger::new("watch_update", EventKind::Update, "record").on("books"),
            Trigger::new("watch_delete", EventKind::Delete, "record").on("books"),
        ],
    )
    .await?;

    // The host carries the event's caller, as phase 5 will build it from the
    // event that ran the trigger.
    let host = TableHost::new(&catalog).caused_by(
        Role::of(40),
        Some(json!({ "id": 7, "email": "who@example.com" })),
    );

    ask(
        &host,
        json!({ "op": "insert", "table": "books", "values": { "title": "Orlando" } }),
    )
    .await?;
    ask(
        &host,
        json!({
            "op": "update", "table": "books",
            "where": { "title": "Orlando" }, "values": { "pages": 333 },
        }),
    )
    .await?;
    ask(
        &host,
        json!({ "op": "delete", "table": "books", "where": { "title": "Orlando" } }),
    )
    .await?;

    let seen = seen.lock().unwrap().clone();
    let kinds: Vec<&str> = seen
        .iter()
        .map(|e| e["kind"].as_str().unwrap_or_default())
        .collect();
    assert_eq!(
        kinds,
        vec!["insert", "update", "delete"],
        "each write through the row layer is the event it always was: {seen:?}"
    );
    // The row the event carries is the row that was written, and the caller is
    // the one this run was given — which is why an audit trigger on a code body's
    // write can say who caused it.
    assert_eq!(seen[0]["row"]["title"], json!("Orlando"));
    assert_eq!(seen[1]["row"]["pages"], json!(333));
    assert_eq!(
        seen[2]["row"]["title"],
        json!("Orlando"),
        "the row as it was"
    );
    assert_eq!(seen[0]["user"]["email"], json!("who@example.com"));
    // Nothing led here but a request, so these events are at depth 0.
    assert_eq!(seen[0]["depth"], json!(0));
    Ok(())
}

/// Every firing is a write inside the one before it, all on one stack, so it runs
/// on a worker with the stack the server gives its workers (`sc-cli`'s
/// `WORKER_STACK_BYTES`, 8 MiB): at `MAX_DEPTH` 10 a debug build overflows the
/// test thread's 2 MiB.
#[test]
fn a_code_body_writing_its_own_table_is_stopped_by_the_cascade_bound() -> Result<()> {
    tokio::runtime::Builder::new_multi_thread()
        .worker_threads(1)
        .thread_stack_size(8 * 1024 * 1024)
        .enable_all()
        .build()
        .expect("a runtime")
        .block_on(async {
            tokio::spawn(code_body_writing_its_own_table())
                .await
                .expect("joined")
        })
}

async fn code_body_writing_its_own_table() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let chains = Arc::new(Mutex::new(Vec::new()));
    let dispatcher = with_triggers(
        &catalog,
        vec![Arc::new(Feed {
            catalog: Arc::clone(&catalog),
            chains: Arc::clone(&chains),
        })],
        vec![Trigger::new("feed", EventKind::Insert, "feed").on("links")],
    )
    .await?;

    // The first write is a code body's, at depth 0 — and every write it causes is
    // one too, so nothing but the bound stops this.
    let host = TableHost::new(&catalog);
    ask(
        &host,
        json!({ "op": "insert", "table": "links", "values": { "depth": 0 } }),
    )
    .await?;

    let depths = rows_of(&db, "SELECT depth::text FROM links ORDER BY id").await;
    assert_eq!(
        depths.len(),
        MAX_DEPTH + 1,
        "the first row plus one per firing, and firings stop at the bound: {depths:?}"
    );

    // The chain grew by one trigger per level — which is the mechanism, not a
    // coincidence: a host's write carries it, so the event it raises is one
    // deeper than the one that caused it.
    let chains = chains.lock().unwrap().clone();
    assert_eq!(chains.len(), MAX_DEPTH);
    assert_eq!(chains.first().map(Vec::len), Some(1));
    let deepest = chains.last().cloned().expect("a deepest run");
    assert_eq!(deepest.len(), MAX_DEPTH);

    // And what stopped it names the whole chain. The production path *reports*
    // that refusal rather than returning it — the write it would have followed
    // has already committed — so it is asked for here the way the admin's log
    // will get it: one more dispatch of the event the last write raised.
    let event = Event::new(EventKind::Insert)
        .on("links")
        .row(json!({ "id": MAX_DEPTH + 1, "depth": MAX_DEPTH }))
        .chained(deepest);
    let runs = dispatcher.dispatch(&catalog, &event).await;
    assert_eq!(runs.len(), 1);
    let message = runs[0].outcome.as_ref().unwrap_err().to_string();
    assert!(message.contains("feed → feed → feed"), "{message}");
    assert!(message.contains("was not run"), "{message}");
    Ok(())
}
