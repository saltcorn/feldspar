//! A code body's writes, end to end (the milestone "Tables in code", phase 3).
//!
//! Reads could be proved against a plan and a statement; writes cannot. The
//! whole claim of §4 is that a write from a code body is **an event like any
//! other** — coerced against its columns, observed by the table's own triggers,
//! carrying the caller and the trigger chain that led there, and bounded by the
//! same cascade limit an action's write is. Every one of those is a property of
//! the row layer being the thing that runs, so the only honest test of it is a
//! real database with real triggers installed.
//!
//! So: the trigger dispatcher is the real one, the triggers are saved and loaded
//! the way the admin's are, and the actions behind them are test doubles that do
//! one thing each — record what they were given, or write again so a cascade has
//! something to run away with.
#![allow(clippy::unwrap_used, clippy::expect_used)]

