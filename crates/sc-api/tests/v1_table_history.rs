//! Saltcorn 1's `Table` history methods over a real change log (TODO-history
//! H6.1): `get_history`, `restore_row_version`, `undo_row_changes` and
//! `redo_row_changes`, through the same `TableHost` a `db` chain goes through.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;

use sc_api::code_host::{TableHost, schema_snapshot};
use sc_api::schema_edit;
use sc_catalog::{Catalog, bootstrap_change_log, bootstrap_field_meta, bootstrap_table_meta};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Result};
use sc_expr::{CodeCall, CodeRuntime};
use sc_test_harness::TestDb;
use serde_json::{Value as Json, json};

async fn sql(db: &TestDb, statements: &str) -> Result<()> {
    db.client()
        .await?
        .batch_execute(statements)
        .await
        .map_err(|e| Error::database(format!("{e:?}")))
}

/// `notes` keeping history, with one row written three times: `a`, `b`, `c`.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    sql(
        db,
        "CREATE TABLE notes (id bigint generated by default as identity primary key,
                             what text);",
    )
    .await?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    sc_auth::bootstrap(&catalog).await?;
    catalog.reload().await?;
    let op = schema_edit::Operation::AlterTable {
        table: "notes".to_owned(),
        settings: schema_edit::TableSettings {
            history_enabled: Some(true),
            ..Default::default()
        },
    };
    schema_edit::apply(&catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    sql(db, "INSERT INTO notes (what) VALUES ('a')").await?;
    sql(db, "UPDATE notes SET what = 'b'").await?;
    sql(db, "UPDATE notes SET what = 'c'").await?;
    Ok(catalog)
}

/// Run `body` with the v1 `Table` over this catalog, as the admin.
async fn v1(cat: &Catalog, body: &str) -> Result<Json> {
    let host = TableHost::new(cat);
    let snapshot = schema_snapshot(cat)?;
    CodeRuntime::with_workers(1)
        .run(CodeCall {
            code: format!(
                "const {{ Table }} = __scMakeV1Api(db.__scSend, __scSchema({}), null);\n\
                 const notes = Table.findOne(\"notes\");\n{body}",
                snapshot.generation()
            ),
            host: Some(&host),
            schema: Some(&snapshot),
            ..CodeCall::default()
        })
        .await
}

async fn what(db: &TestDb) -> Vec<String> {
    db.client()
        .await
        .unwrap()
        .query("SELECT what FROM notes", &[])
        .await
        .unwrap()
        .iter()
        .map(|r| r.get(0))
        .collect()
}

#[tokio::test]
async fn get_history_answers_every_version_oldest_first() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    let out = v1(
        &cat,
        r#"const h = await notes.get_history(1);
           return h.map((v) => ({
             what: v.what, id: v.id, version: v._version, deleted: v._deleted,
             op: v._op, time: v._time instanceof Date, source: v._source,
           }));"#,
    )
    .await?;
    assert_eq!(
        out,
        json!([
            { "what": "a", "id": 1, "version": 1, "deleted": false, "op": "i", "time": true,
              "source": "sql" },
            { "what": "b", "id": 1, "version": 2, "deleted": false, "op": "u", "time": true,
              "source": "sql" },
            { "what": "c", "id": 1, "version": 3, "deleted": false, "op": "u", "time": true,
              "source": "sql" },
        ])
    );
    // Without an id it says why, rather than answering every row's.
    let err = v1(&cat, "return await notes.get_history();")
        .await
        .unwrap_err()
        .to_string();
    assert!(err.contains("takes the primary key"), "{err}");
    Ok(())
}

#[tokio::test]
async fn undo_and_redo_step_through_versions_and_restore_goes_to_one() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    v1(&cat, "await notes.undo_row_changes(1);").await?;
    assert_eq!(what(&db).await, vec!["b"]);
    v1(&cat, "await notes.undo_row_changes(1);").await?;
    assert_eq!(what(&db).await, vec!["a"]);
    // At the first version there is nothing before it, and that is no error.
    v1(&cat, "return await notes.undo_row_changes(1);").await?;
    assert_eq!(what(&db).await, vec!["a"]);
    v1(&cat, "await notes.redo_row_changes(1);").await?;
    assert_eq!(what(&db).await, vec!["b"]);
    v1(&cat, "await notes.redo_row_changes(1);").await?;
    assert_eq!(what(&db).await, vec!["c"]);
    // Nothing undone is left to redo.
    v1(&cat, "await notes.redo_row_changes(1);").await?;
    assert_eq!(what(&db).await, vec!["c"]);

    v1(&cat, "await notes.restore_row_version(1, 1);").await?;
    assert_eq!(what(&db).await, vec!["a"]);
    // Restoring the version the row is at writes nothing.
    let before = v1(&cat, "return (await notes.get_history(1)).length;").await?;
    v1(&cat, "await notes.restore_row_version(1, 1);").await?;
    let after = v1(&cat, "return (await notes.get_history(1)).length;").await?;
    assert_eq!(before, after);

    // A deleted row comes back by restoring a version from before its delete.
    sql(&db, "DELETE FROM notes").await?;
    let last = v1(
        &cat,
        "const h = await notes.get_history(1); return h[h.length - 1]._deleted;",
    )
    .await?;
    assert_eq!(last, json!(true));
    v1(&cat, "await notes.restore_row_version(1, 2);").await?;
    assert_eq!(what(&db).await, vec!["b"]);
    Ok(())
}
