//! Row history H3: restore and undo (design §14.12 "Restore and undo"). An
//! undo across two tables, the conflict check and `force`, undoing an undo,
//! foreign-key order, one table's entries, restoring a deleted row and
//! reverting a row to a version.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;

use sc_api::history::HistoryReader;
use sc_api::undo::{Reverser, UndoOutcome};
use sc_api::{rows, schema_edit};
use sc_auth::User;
use sc_catalog::{
    CallerContext, Catalog, Changeset, ChangesetSource, bootstrap_change_log, bootstrap_field_meta,
    bootstrap_table_meta, changeset,
};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Repr, Result};
use sc_test_harness::TestDb;
use serde_json::{Value as Json, json};
use uuid::Uuid;

const ADMIN: &str = "00000000-0000-4000-8000-0000000000ad";
const ANN: &str = "00000000-0000-4000-8000-0000000000a1";

async fn sql(db: &TestDb, statements: &str) -> Result<()> {
    db.client()
        .await?
        .batch_execute(statements)
        .await
        .map_err(|e| Error::database(format!("{e:?}")))
}

async fn history_on(catalog: &Catalog, table: &str) -> Result<()> {
    let op = schema_edit::Operation::AlterTable {
        table: table.to_owned(),
        settings: schema_edit::TableSettings {
            history_enabled: Some(true),
            ..Default::default()
        },
    };
    schema_edit::apply(catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    Ok(())
}

/// `projects(id, name, budget)` and `tasks(id, project → projects, title,
/// done)`, both keeping history.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    sql(
        db,
        "CREATE TABLE projects (id bigint generated by default as identity primary key,
                                name text, budget int);
         CREATE TABLE tasks (id bigint generated by default as identity primary key,
                             project bigint references projects(id), title text,
                             done boolean);",
    )
    .await?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    catalog.reload().await?;
    history_on(&catalog, "projects").await?;
    history_on(&catalog, "tasks").await?;
    Ok(catalog)
}

fn admin() -> User {
    User::new(ADMIN.parse().unwrap(), 1).unwrap()
}

fn caller() -> CallerContext {
    CallerContext::new(1, Some(json!({ "id": ADMIN, "role": 1 })))
}

/// The writes `f` makes, as one request changeset; answers its id.
async fn action(f: impl std::future::Future<Output = Result<()>>) -> Result<Uuid> {
    let changeset = Arc::new(Changeset::new(ChangesetSource::Request));
    let id = changeset.id;
    changeset::scope(changeset, f).await?;
    Ok(id)
}

async fn insert(catalog: &Catalog, table: &str, body: Json) -> Result<String> {
    let table = catalog.require(table)?;
    let row = rows::create_row_ctx(catalog, &table, &body, Some(&caller())).await?;
    Ok(row["id"].to_string())
}

async fn update(catalog: &Catalog, table: &str, id: &str, body: Json) -> Result<()> {
    let table = catalog.require(table)?;
    rows::update_row_ctx(catalog, &table, id, &body, Some(&caller())).await?;
    Ok(())
}

async fn delete(catalog: &Catalog, table: &str, id: &str) -> Result<()> {
    let table = catalog.require(table)?;
    rows::delete_row_ctx(catalog, &table, id, Some(&caller())).await?;
    Ok(())
}

/// Row `id` of `table` now, or `None`.
async fn get(catalog: &Catalog, table: &str, id: &str) -> Result<Option<Json>> {
    let table = catalog.require(table)?;
    let rows = rows::list_rows(catalog, &table).await?;
    Ok(rows
        .as_array()
        .unwrap()
        .iter()
        .find(|r| r["id"] == json!(id.parse::<i64>().unwrap()))
        .cloned())
}

/// Undo as the admin, in a request of its own, as the admin API runs it.
async fn undo(
    catalog: &Catalog,
    id: Uuid,
    table: Option<&str>,
    force: bool,
) -> Result<UndoOutcome> {
    let user = admin();
    let reverser = Reverser::new(catalog, Some(&user), None);
    changeset::scope(
        Arc::new(Changeset::new(ChangesetSource::Request)),
        reverser.undo_changeset(id, table, force),
    )
    .await
}

fn undone(outcome: &UndoOutcome) -> Uuid {
    match outcome {
        UndoOutcome::Undone { changeset, .. } => *changeset,
        UndoOutcome::Refused(c) => panic!("refused: {c:?}"),
    }
}

/// One undo takes back a changeset's update, insert and delete across two
/// tables, in one `undo` changeset caused by it. Undoing that puts the change
/// back, and a second undo of the original is refused.
#[tokio::test]
async fn undo_reverses_a_changeset_across_tables_and_can_itself_be_undone() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let mut project = String::new();
    let mut old_task = String::new();
    action(async {
        project = insert(&catalog, "projects", json!({ "name": "p", "budget": 10 })).await?;
        old_task = insert(
            &catalog,
            "tasks",
            json!({ "project": project.parse::<i64>().unwrap(), "title": "old" }),
        )
        .await?;
        Ok(())
    })
    .await?;

    let mut new_task = String::new();
    let change = action(async {
        update(&catalog, "projects", &project, json!({ "budget": 20 })).await?;
        new_task = insert(
            &catalog,
            "tasks",
            json!({ "project": project.parse::<i64>().unwrap(), "title": "new" }),
        )
        .await?;
        delete(&catalog, "tasks", &old_task).await?;
        Ok(())
    })
    .await?;

    let outcome = undo(&catalog, change, None, false).await?;
    let undo_id = undone(&outcome);
    assert!(matches!(outcome, UndoOutcome::Undone { entries: 3, .. }));
    assert_eq!(
        get(&catalog, "projects", &project).await?.unwrap()["budget"],
        10
    );
    assert!(get(&catalog, "tasks", &new_task).await?.is_none());
    assert_eq!(
        get(&catalog, "tasks", &old_task).await?.unwrap()["title"],
        "old"
    );

    // The undo is a changeset of its own, caused by what it undid.
    let user = admin();
    let reader = HistoryReader::new(&catalog, Some(&user), None);
    let recorded = reader.changeset(&undo_id.to_string()).await?;
    assert_eq!(recorded["source"], "undo");
    assert_eq!(recorded["cause"], json!(change));
    assert_eq!(recorded["entries"].as_array().unwrap().len(), 3);

    // Undone already.
    let err = undo(&catalog, change, None, false).await.unwrap_err();
    assert!(err.to_string().contains("undone already"), "{err}");

    // Undoing the undo puts the change back.
    undone(&undo(&catalog, undo_id, None, false).await?);
    assert_eq!(
        get(&catalog, "projects", &project).await?.unwrap()["budget"],
        20
    );
    assert_eq!(
        get(&catalog, "tasks", &new_task).await?.unwrap()["title"],
        "new"
    );
    assert!(get(&catalog, "tasks", &old_task).await?.is_none());
    Ok(())
}

/// A field changed since refuses the undo, naming it, and writes nothing.
/// `force` overwrites it; below the admin, `force` is refused.
#[tokio::test]
async fn a_conflict_refuses_the_undo_and_force_overwrites() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let mut project = String::new();
    action(async {
        project = insert(&catalog, "projects", json!({ "name": "p", "budget": 10 })).await?;
        Ok(())
    })
    .await?;
    let change = action(async {
        update(
            &catalog,
            "projects",
            &project,
            json!({ "name": "q", "budget": 20 }),
        )
        .await
    })
    .await?;
    action(async { update(&catalog, "projects", &project, json!({ "budget": 30 })).await }).await?;

    let UndoOutcome::Refused(conflicts) = undo(&catalog, change, None, false).await? else {
        panic!("the undo went through");
    };
    assert_eq!(conflicts.len(), 1);
    assert_eq!(conflicts[0].field.as_deref(), Some("budget"));
    assert_eq!(
        (conflicts[0].expected.clone(), conflicts[0].actual.clone()),
        (json!(20), json!(30))
    );
    assert!(
        conflicts[0].reason.contains("`budget`"),
        "{}",
        conflicts[0].reason
    );
    // Nothing was written.
    let now = get(&catalog, "projects", &project).await?.unwrap();
    assert_eq!(
        (now["name"].clone(), now["budget"].clone()),
        (json!("q"), json!(30))
    );

    // Not for a user below the admin.
    let ann = User::new(ANN.parse().unwrap(), 40).unwrap();
    let err = Reverser::new(&catalog, Some(&ann), None)
        .undo_changeset(change, None, true)
        .await
        .unwrap_err();
    assert!(matches!(err.repr(), Repr::Auth(_)), "{err}");

    undone(&undo(&catalog, change, None, true).await?);
    let now = get(&catalog, "projects", &project).await?.unwrap();
    assert_eq!(
        (now["name"].clone(), now["budget"].clone()),
        (json!("p"), json!(10))
    );
    Ok(())
}

/// Undoing inserts deletes the child before the parent, and undoing deletes
/// puts the parent back before the child: the foreign key holds throughout.
#[tokio::test]
async fn undo_orders_inserts_and_deletes_by_foreign_key_depth() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let (mut project, mut task) = (String::new(), String::new());
    let made = action(async {
        project = insert(&catalog, "projects", json!({ "name": "p" })).await?;
        task = insert(
            &catalog,
            "tasks",
            json!({ "project": project.parse::<i64>().unwrap(), "title": "t" }),
        )
        .await?;
        Ok(())
    })
    .await?;
    let removed = action(async {
        delete(&catalog, "tasks", &task).await?;
        delete(&catalog, "projects", &project).await
    })
    .await?;

    // The deletes: the project comes back first, then its task.
    undone(&undo(&catalog, removed, None, false).await?);
    assert_eq!(
        get(&catalog, "tasks", &task).await?.unwrap()["project"].to_string(),
        project
    );

    // The inserts: the task goes first, then its project.
    undone(&undo(&catalog, made, None, false).await?);
    assert!(get(&catalog, "projects", &project).await?.is_none());
    assert!(get(&catalog, "tasks", &task).await?.is_none());
    Ok(())
}

/// `table` limits an undo to one table's entries; a later undo of the whole
/// changeset reverses the rest.
#[tokio::test]
async fn an_undo_of_one_table_leaves_the_others_for_later() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let (mut project, mut task) = (String::new(), String::new());
    action(async {
        project = insert(&catalog, "projects", json!({ "name": "p", "budget": 1 })).await?;
        task = insert(
            &catalog,
            "tasks",
            json!({ "project": project.parse::<i64>().unwrap(), "done": false }),
        )
        .await?;
        Ok(())
    })
    .await?;
    let change = action(async {
        update(&catalog, "projects", &project, json!({ "budget": 2 })).await?;
        update(&catalog, "tasks", &task, json!({ "done": true })).await
    })
    .await?;

    let scoped = undo(&catalog, change, Some("tasks"), false).await?;
    assert!(matches!(scoped, UndoOutcome::Undone { entries: 1, .. }));
    let user = admin();
    let recorded = HistoryReader::new(&catalog, Some(&user), None)
        .changeset(&undone(&scoped).to_string())
        .await?;
    assert_eq!(recorded["undo_table"], "tasks");
    assert_eq!(get(&catalog, "tasks", &task).await?.unwrap()["done"], false);
    assert_eq!(
        get(&catalog, "projects", &project).await?.unwrap()["budget"],
        2
    );

    let rest = undo(&catalog, change, None, false).await?;
    assert!(matches!(rest, UndoOutcome::Undone { entries: 1, .. }));
    assert_eq!(
        get(&catalog, "projects", &project).await?.unwrap()["budget"],
        1
    );
    Ok(())
}

/// A deleted row is restored with its key, in a `restore` changeset caused by
/// the delete; a column dropped since is left out and reported. A restore is
/// refused, with the reason, when the row it refers to is gone.
#[tokio::test]
async fn restore_puts_a_deleted_row_back_unless_its_parent_is_gone() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let (mut project, mut task) = (String::new(), String::new());
    action(async {
        project = insert(&catalog, "projects", json!({ "name": "p", "budget": 5 })).await?;
        task = insert(
            &catalog,
            "tasks",
            json!({ "project": project.parse::<i64>().unwrap(), "title": "t" }),
        )
        .await?;
        Ok(())
    })
    .await?;
    let deleted = action(async { delete(&catalog, "tasks", &task).await }).await?;
    action(async { delete(&catalog, "projects", &project).await }).await?;
    schema_edit::apply(
        &catalog,
        &[schema_edit::Operation::DropField {
            table: "projects".into(),
            field: "budget".into(),
        }],
        &schema_edit::ApplyOptions::default(),
    )
    .await?;

    let user = admin();
    let reverser = Reverser::new(&catalog, Some(&user), None);
    let err = reverser.restore_row("tasks", &task).await.unwrap_err();
    assert!(
        err.to_string().contains("`tasks.project` refers to row"),
        "{err}"
    );
    assert!(get(&catalog, "tasks", &task).await?.is_none());

    let restored = reverser.restore_row("projects", &project).await?;
    assert_eq!(restored.dropped, vec!["budget".to_owned()]);
    assert_eq!(restored.row["name"], "p");
    let restored = reverser.restore_row("tasks", &task).await?;
    assert_eq!(restored.row["title"], "t");
    let recorded = HistoryReader::new(&catalog, Some(&user), None)
        .changeset(&restored.changeset.to_string())
        .await?;
    assert_eq!(recorded["source"], "restore");
    assert_eq!(recorded["cause"], json!(deleted));

    // Not deleted any more.
    let err = reverser.restore_row("tasks", &task).await.unwrap_err();
    assert!(err.to_string().contains("not deleted"), "{err}");
    Ok(())
}

/// Reverting sets a row back to a version as one update, and is recorded as a
/// new version of its own.
#[tokio::test]
async fn revert_sets_a_row_back_to_a_version() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let mut project = String::new();
    action(async {
        project = insert(&catalog, "projects", json!({ "name": "a", "budget": 1 })).await?;
        Ok(())
    })
    .await?;
    action(async { update(&catalog, "projects", &project, json!({ "name": "b" })).await }).await?;
    action(async { update(&catalog, "projects", &project, json!({ "budget": 3 })).await }).await?;

    let user = admin();
    let reverser = Reverser::new(&catalog, Some(&user), None);
    let reverted = reverser.revert_row("projects", &project, 1).await?;
    assert_eq!(
        (reverted.row["name"].clone(), reverted.row["budget"].clone()),
        (json!("a"), json!(1))
    );
    let history = HistoryReader::new(&catalog, Some(&user), None)
        .row_history("projects", &project)
        .await?;
    assert_eq!(history[0]["version"], 4);
    assert_eq!(history[0]["changeset"]["source"], "restore");

    let err = reverser
        .revert_row("projects", &project, 4)
        .await
        .unwrap_err();
    assert!(err.to_string().contains("already as it was"), "{err}");
    assert!(reverser.revert_row("projects", &project, 9).await.is_err());
    Ok(())
}
