//! Saltcorn 1's `Table` **writing a real database** (the milestone "the v1
//! `Table` API", phase 4).
//!
//! The lowering is proved in `sc-expr`: a spy behind the sender asserts the plan
//! each v1 write sends and the shape it answers in. What is proved here is the
//! half a spy cannot — that the plan then *writes*, through the very same
//! `TableHost` a `db` chain goes through, which means three things a v1 plugin
//! author is entitled to:
//!
//! - **a write is an event.** Every one of these goes through the row layer, so
//!   the trigger an admin wrote sees a v1 plugin's `insertRow` exactly as it sees
//!   a `db.books.insert(…)`. That is the whole reason to have this method rather
//!   than a SQL statement.
//! - **whose write it is, is v1's argument.** `insertRow(row, user)` lowers to
//!   the plan's `{ user: id }` authority, and the named user goes through
//!   `sc_api::ownership`'s `*_as` functions — §7.3's rule, checked on the row as
//!   it is *and* on the row as it would become.
//! - **a refusal reads as v1's refusal.** `updateRow` answers a string and
//!   `tryUpdateRow` an `{ error }`, because that is what a v1 plugin branches on.
//!
//! The api is built here the way phase 6 will build it: over the run's own
//! sender (`db.__scSend`), the run's own trigger sender (`trigger.__scRun`) and
//! the run's own schema snapshot.
#![allow(clippy::unwrap_used, clippy::expect_used)]

