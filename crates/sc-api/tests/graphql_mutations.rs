//! Writing rows over GraphQL, against a real Postgres (TODO "GraphQL API"
//! Phase 6).
//!
//! The claim under test is not "a mutation works". It is that a GraphQL write
//! and a REST write are **the same write** — same coercion, same rich-type
//! rules, same `File`-field checks, same §7.3 ownership decision, same table
//! events — because they are the same code with two front doors. So the first
//! test does both and compares the *rows and the events*, and every test after
//! it asks whether one of those rules survived the trip.
//!
//! A rule is never tested by asserting that a permitted write succeeded. It is
//! tested by asserting what the caller who may **not** do it gets — because a
//! rule that quietly stopped running still lets the first kind of test pass.

#![allow(clippy::unwrap_used, clippy::expect_used)]

