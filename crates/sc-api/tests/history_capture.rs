const ANN: &str = "00000000-0000-4000-8000-0000000000a1";

async fn sql(db: &TestDb, statements: &str) -> Result<()> {
    db.client()
        .await?
        .batch_execute(statements)
        .await
        .map_err(|e| Error::database(format!("{e:?}")))
}

/// `todo` and `audit`, both with history on, and one row in `todo` written
/// before history was.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    sql(
        db,
        "CREATE TABLE todo (id bigint generated by default as identity primary key,
                            title text, done bool NOT NULL DEFAULT false);
         CREATE TABLE audit (id bigint generated by default as identity primary key,
                             what text);
         INSERT INTO todo (title) VALUES ('milk');",
    )
    .await?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    catalog.reload().await?;
    for table in ["todo", "audit"] {
        let op = schema_edit::Operation::AlterTable {
            table: table.to_owned(),
            settings: schema_edit::TableSettings {
                history_enabled: Some(true),
                ..Default::default()
            },
        };
        schema_edit::apply(&catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    }
    Ok(catalog)
}

/// One entry: `(table, row_key, op, old_values, new_values)`.
type Entry = (String, String, String, Json, Json);

/// The entries of `changeset`, oldest first.
async fn entries(db: &TestDb, changeset: &str) -> Result<Vec<Entry>> {
    let rows = db
        .client()
        .await?
        .query(
            "SELECT table_name, row_key, op, coalesce(old_values, 'null'::jsonb),
                    coalesce(new_values, 'null'::jsonb)
               FROM _fd_changes WHERE changeset::text = $1 ORDER BY seq",
            &[&changeset],
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    Ok(rows
        .iter()
        .map(|r| (r.get(0), r.get(1), r.get(2), r.get(3), r.get(4)))
        .collect())
}

/// Every changeset, oldest first: `(id, source, user_id, session)`.
async fn changesets(db: &TestDb) -> Result<Vec<(String, String, Option<String>, Option<String>)>> {
    let rows = db
        .client()
        .await?
        .query(
            "SELECT id::text, source, user_id::text, session FROM _fd_changesets ORDER BY txid, at",
            &[],
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    Ok(rows
        .iter()
        .map(|r| (r.get(0), r.get(1), r.get(2), r.get(3)))
        .collect())
}

/// Ann, a signed-in user of role 80, in the ambient changeset.
fn ann() -> CallerContext {
    CallerContext::new(80, Some(json!({ "id": ANN, "role": 80 })))
}

fn request() -> Arc<Changeset> {
    Arc::new(Changeset::new(ChangesetSource::Request).session(Some("ann-session".into())))
}

/// On an update of `todo` made directly (not by itself), mark the row done
/// and write an audit row — as the admin, the way a trigger's action writes.
struct FollowUp(Arc<Catalog>);

#[async_trait::async_trait]
impl Action for FollowUp {
    fn name(&self) -> &str {
        "follow_up"
    }
    fn description(&self) -> &str {
        "Mark the row done and audit it"
    }
    fn config_spec(&self) -> Vec<FormField> {
        Vec::new()
    }
    async fn run(&self, ctx: &mut ActionContext<'_>) -> Result<Json> {
        if ctx.event.depth() > 0 {
            return Ok(Json::Null);
        }
        let row = ctx.event.row.clone().unwrap_or_default();
        let id = row["id"].to_string();
        // Admin authority, the event's user: what an action's writes carry.
        let admin = CallerContext::new(1, ctx.event.user.clone()).chained(ctx.chain.clone());
        let todo = self.0.require("todo")?;
        rows::update_row_ctx(&self.0, &todo, &id, &json!({ "done": true }), Some(&admin)).await?;
        let audit = self.0.require("audit")?;
        rows::create_row_ctx(&self.0, &audit, &json!({ "what": "done" }), Some(&admin)).await?;
        Ok(Json::Null)
    }
}

async fn with_follow_up(catalog: &Arc<Catalog>) -> Result<()> {
    let mut registry = ActionRegistry::new();
    registry.register(Arc::new(FollowUp(Arc::clone(catalog))))?;
    let dispatcher = Arc::new(TriggerDispatcher::new(Arc::new(registry)));
    bootstrap_triggers(catalog).await?;
    let trigger = Trigger::new("follow", EventKind::Update, "follow_up").on("todo");
    save_trigger(catalog, &dispatcher.registry(), &trigger).await?;
    dispatcher.reload(catalog).await?;
    catalog.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn sc_catalog::TableEvents>,
    )?;
    Ok(())
}

/// A request's update, its trigger's update of the same row and its write to a
/// second table: one changeset, one entry per row, and the user is the one who
/// made the request even though the trigger wrote as the admin.
#[tokio::test]
async fn a_request_and_the_triggers_it_fires_are_one_changeset() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    with_follow_up(&catalog).await?;
    let todo = catalog.require("todo")?;

    let request = request();
    changeset::scope(request.clone(), async {
        rows::update_row_ctx(
            &catalog,
            &todo,
            "1",
            &json!({ "title": "oat milk" }),
            Some(&ann()),
        )
        .await
    })
    .await?;

    let id = request.id.to_string();
    assert_eq!(
        changesets(&db).await?,
        vec![(
            id.clone(),
            "request".into(),
            Some(ANN.into()),
            Some("ann-session".into())
        )]
    );
    assert_eq!(
        entries(&db, &id).await?,
        vec![
            (
                "todo".into(),
                "1".into(),
                "u".into(),
                json!({ "title": "milk", "done": false }),
                json!({ "title": "oat milk", "done": true }),
            ),
            (
                "audit".into(),
                "1".into(),
                "i".into(),
                Json::Null,
                json!({ "id": 1, "what": "done" }),
            ),
        ]
    );
    Ok(())
}

/// An insert and a later update in one changeset are one insert of the final
/// row, even across transactions.
#[tokio::test]
async fn insert_then_update_is_one_insert_of_the_final_row() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let todo = catalog.require("todo")?;
    let request = request();
    changeset::scope(request.clone(), async {
        let row = rows::create_row_ctx(&catalog, &todo, &json!({ "title": "eggs" }), Some(&ann()))
            .await?;
        let id = row["id"].to_string();
        rows::update_row_ctx(&catalog, &todo, &id, &json!({ "done": true }), Some(&ann())).await
    })
    .await?;
    assert_eq!(
        entries(&db, &request.id.to_string()).await?,
        vec![(
            "todo".into(),
            "2".into(),
            "i".into(),
            Json::Null,
            json!({ "id": 2, "title": "eggs", "done": true }),
        )]
    );
    Ok(())
}

/// The number of entries in the log, all changesets.
async fn entry_count(db: &TestDb) -> Result<i64> {
    Ok(db
        .client()
        .await?
        .query_one("SELECT count(*) FROM _fd_changes", &[])
        .await
        .map_err(|e| Error::database(e.to_string()))?
        .get(0))
}

/// Within one transaction, an insert taken back is nothing at all; an update
/// that changes nothing records nothing, not even a changeset.
#[tokio::test]
async fn what_ends_where_it_started_in_one_transaction_leaves_nothing() -> Result<()> {
    let db = TestDb::new().await?;
    setup(&db).await?;
    sql(
        &db,
        "BEGIN;
         INSERT INTO todo (id, title) VALUES (10, 'never');
         UPDATE todo SET title = 'never ever' WHERE id = 10;
         DELETE FROM todo WHERE id = 10;
         COMMIT;",
    )
    .await?;
    assert_eq!(entry_count(&db).await?, 0);

    sql(&db, "UPDATE todo SET title = title").await?;
    assert_eq!(entry_count(&db).await?, 0);
    // The insert-and-delete minted one; the no-op update did not get as far.
    assert_eq!(changesets(&db).await?.len(), 1);
    Ok(())
}

/// Writes from `psql` belong to one `sql` changeset per transaction.
#[tokio::test]
async fn sql_writes_get_one_changeset_per_transaction() -> Result<()> {
    let db = TestDb::new().await?;
    setup(&db).await?;
    sql(
        &db,
        "BEGIN;
         INSERT INTO todo (title) VALUES ('bread');
         UPDATE todo SET done = true WHERE id = 1;
         INSERT INTO audit (what) VALUES ('by hand');
         COMMIT;
         UPDATE todo SET done = false WHERE id = 1;",
    )
    .await?;
    let sets = changesets(&db).await?;
    assert_eq!(sets.len(), 2, "{sets:?}");
    assert!(
        sets.iter().all(|(_, source, user, session)| source == "sql"
            && user.is_none()
            && session.is_none())
    );
    assert_eq!(entries(&db, &sets[0].0).await?.len(), 3);
    assert_eq!(
        entries(&db, &sets[1].0).await?,
        vec![(
            "todo".into(),
            "1".into(),
            "u".into(),
            json!({ "done": true }),
            json!({ "done": false }),
        )]
    );
    Ok(())
}

/// The keys a pull between `since` and now would see changed.
async fn pulled(
    catalog: &Catalog,
    since: &sc_catalog::SyncWatermark,
) -> Result<(Vec<String>, sc_catalog::SyncWatermark)> {
    let tx = SharedTx::begin_snapshot(catalog).await?;
    let now = sync_watermark(catalog, &tx).await?;
    let keys = changed_keys(catalog, &tx, "todo", since, &now).await?;
    tx.rollback().await?;
    Ok((keys.into_iter().collect(), now))
}

/// A changeset spread over two transactions: a pull taken between them still
/// receives the second, and a change taken back in the second leaves an
/// entry without values that the pull still sees.
#[tokio::test]
async fn a_pull_between_two_transactions_of_a_changeset_misses_nothing() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let todo = catalog.require("todo")?;
    let start = {
        let tx = SharedTx::begin_snapshot(&catalog).await?;
        let w = sync_watermark(&catalog, &tx).await?;
        tx.rollback().await?;
        w
    };
    let request = request();
    let write = |title: &'static str| {
        let (catalog, todo, request) = (catalog.clone(), todo.clone(), request.clone());
        async move {
            changeset::scope(request, async {
                rows::update_row_ctx(
                    &catalog,
                    &todo,
                    "1",
                    &json!({ "title": title }),
                    Some(&ann()),
                )
                .await
            })
            .await
        }
    };

    write("oat milk").await?;
    let (keys, between) = pulled(&catalog, &start).await?;
    assert_eq!(keys, vec!["1"]);

    // Back to where it was: the entry is kept, empty, and the next pull sees
    // the key again, so a device that pulled "oat milk" gets "milk" back.
    write("milk").await?;
    let (keys, _) = pulled(&catalog, &between).await?;
    assert_eq!(keys, vec!["1"]);
    assert_eq!(
        entries(&db, &request.id.to_string()).await?,
        vec![(
            "todo".into(),
            "1".into(),
            "u".into(),
            Json::Null,
            Json::Null
        )]
    );
    Ok(())
}

/// `sc.change_log = 'off'` records nothing, as a backup restore needs.
#[tokio::test]
async fn the_change_log_can_be_switched_off_for_a_transaction() -> Result<()> {
    let db = TestDb::new().await?;
    setup(&db).await?;
    sql(
        &db,
        "BEGIN; SET LOCAL sc.change_log = 'off';
         INSERT INTO todo (title) VALUES ('restored'); COMMIT;",
    )
    .await?;
    assert_eq!(entry_count(&db).await?, 0);
    Ok(())
}

/// `TABLES_RENAME.sql`'s H1 section moves a log of the old shape to the new
/// one, and running it again changes nothing.
#[tokio::test]
async fn the_rename_script_gives_old_entries_changesets() -> Result<()> {
    let db = TestDb::new().await?;
    setup(&db).await?;
    let script = include_str!("../../../TABLES_RENAME.sql");
    let section = &script[script
        .find("-- TODO-history H1")
        .expect("the H1 section is in TABLES_RENAME.sql")..];
    let section = &section[section.find("CREATE TABLE IF NOT EXISTS").unwrap()..];

    // The old shape, with a device's change, a transaction with an insert and
    // an update of the same row, and a lone update.
    sql(
        &db,
        "DROP TABLE _fd_changes; DROP TABLE _fd_changesets;
         CREATE TABLE _fd_changes (seq bigint generated by default as identity primary key,
           table_name text NOT NULL, row_key text NOT NULL, op text NOT NULL, fields jsonb,
           txid bigint NOT NULL, client_id uuid, mutation bigint,
           at timestamptz NOT NULL DEFAULT now());
         INSERT INTO _fd_changes (table_name, row_key, op, fields, txid, client_id, mutation)
         VALUES ('todo', '1', 'u', '[\"title\"]', 100, '6f1c9a3e-0000-4000-8000-000000000001', 7),
                ('todo', '2', 'i', NULL, 101, NULL, NULL),
                ('todo', '2', 'u', '[\"done\"]', 101, NULL, NULL),
                ('todo', '1', 'u', '[\"done\", \"title\"]', 102, NULL, NULL);",
    )
    .await?;
    sql(&db, section).await?;
    sql(&db, section).await?;

    let rows = db
        .client()
        .await?
        .query(
            "SELECT c.row_key, c.op, coalesce(c.new_values, 'null'::jsonb), s.source,
                    s.client_id::text, s.mutation
               FROM _fd_changes c JOIN _fd_changesets s ON s.id = c.changeset ORDER BY c.seq",
            &[],
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let got: Vec<(String, String, Json, String, Option<String>, Option<i64>)> = rows
        .iter()
        .map(|r| (r.get(0), r.get(1), r.get(2), r.get(3), r.get(4), r.get(5)))
        .collect();
    assert_eq!(
        got,
        vec![
            (
                "1".into(),
                "u".into(),
                json!({ "title": null }),
                "sync".into(),
                Some("6f1c9a3e-0000-4000-8000-000000000001".into()),
                Some(7)
            ),
            ("2".into(), "i".into(), Json::Null, "sql".into(), None, None),
            (
                "1".into(),
                "u".into(),
                json!({ "done": null, "title": null }),
                "sql".into(),
                None,
                None
            ),
        ]
    );
    // The old columns are gone, and the new trigger function records again.
    let catalog_again = {
        let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
        Catalog::init(driver as Arc<dyn DatabaseDriver>).await?
    };
    bootstrap_change_log(&catalog_again).await?;
    sql(&db, "INSERT INTO todo (title) VALUES ('after')").await?;
    assert_eq!(entry_count(&db).await?, 4);
    Ok(())
}
