const ADMIN: &str = "00000000-0000-4000-8000-0000000000ad";
const ANN: &str = "00000000-0000-4000-8000-0000000000a1";
const BOB: &str = "00000000-0000-4000-8000-0000000000b0";

async fn sql(db: &TestDb, statements: &str) -> Result<()> {
    db.client()
        .await?
        .batch_execute(statements)
        .await
        .map_err(|e| Error::database(format!("{e:?}")))
}

async fn alter(catalog: &Catalog, settings: schema_edit::TableSettings) -> Result<()> {
    let op = schema_edit::Operation::AlterTable {
        table: "notes".to_owned(),
        settings,
    };
    schema_edit::apply(catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    Ok(())
}

/// `notes(id, owner, body, extra, pin secret)`, history on, readable below the
/// admin only by its owner (`owner === user.id`).
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    sql(
        db,
        "CREATE TABLE notes (id bigint generated by default as identity primary key,
                             owner uuid, body text, extra text);",
    )
    .await?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    catalog.set_secret_key(SecretKey::generate()?);
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    catalog.reload().await?;
    schema_edit::apply(
        &catalog,
        &[schema_edit::Operation::AddField {
            table: "notes".to_owned(),
            field: schema_edit::FieldSpec {
                name: "pin".to_owned(),
                kind: DataFieldKind::Secret,
                ..Default::default()
            },
        }],
        &schema_edit::ApplyOptions::default(),
    )
    .await?;
    alter(
        &catalog,
        schema_edit::TableSettings {
            ownership_formula: Some("owner === user.id".into()),
            history_enabled: Some(true),
            ..Default::default()
        },
    )
    .await?;
    Ok(catalog)
}

fn user(id: &str, role: u8) -> User {
    User::new(id.parse().unwrap(), role).unwrap()
}

/// One action: one request changeset. The caller is built inside it, which
/// is where `CallerContext::new` picks the changeset up.
async fn act<T>(f: impl std::future::Future<Output = Result<T>>) -> Result<T> {
    changeset::scope(Arc::new(Changeset::new(ChangesetSource::Request)), f).await
}

/// `who` (an id) writing as the admin screens do: at the admin's role.
fn caller(who: &str) -> CallerContext {
    CallerContext::new(1, Some(json!({ "id": who, "role": 1 })))
}

async fn create(catalog: &Catalog, who: &str, body: Json) -> Result<String> {
    let notes = catalog.require("notes")?;
    let row = act(async { rows::create_row_ctx(catalog, &notes, &body, Some(&caller(who))).await })
        .await?;
    Ok(row["id"].to_string())
}

async fn update(catalog: &Catalog, who: &str, id: &str, body: Json) -> Result<()> {
    let notes = catalog.require("notes")?;
    act(async { rows::update_row_ctx(catalog, &notes, id, &body, Some(&caller(who))).await })
        .await?;
    Ok(())
}

async fn delete(catalog: &Catalog, who: &str, id: &str) -> Result<()> {
    let notes = catalog.require("notes")?;
    act(async { rows::delete_row_ctx(catalog, &notes, id, Some(&caller(who))).await }).await?;
    Ok(())
}

fn is_auth(e: &Error) -> bool {
    matches!(e.repr(), Repr::Auth(_))
}

fn is_not_found(e: &Error) -> bool {
    matches!(e.repr(), Repr::NotFound(_))
}

fn keys(deleted: &Json) -> Vec<String> {
    deleted
        .as_array()
        .unwrap()
        .iter()
        .map(|d| d["key"].as_str().unwrap().to_owned())
        .collect()
}

/// A table's history is the admin's by default. `history_min_role` opens it,
/// and each row is then checked against its read rule: the row as it is, or a
/// deleted row's image.
#[tokio::test]
async fn history_is_the_admins_until_opened_and_then_follows_the_read_rule() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let anns = create(&catalog, ADMIN, json!({ "owner": ANN, "body": "a" })).await?;
    let bobs = create(&catalog, ADMIN, json!({ "owner": BOB, "body": "b" })).await?;
    let gone_ann = create(&catalog, ADMIN, json!({ "owner": ANN, "body": "c" })).await?;
    update(&catalog, ADMIN, &anns, json!({ "body": "a2" })).await?;
    delete(&catalog, ADMIN, &bobs).await?;
    delete(&catalog, ADMIN, &gone_ann).await?;

    let (ann, bob, admin) = (user(ANN, 80), user(BOB, 80), user(ADMIN, 1));
    let as_ann = HistoryReader::new(&catalog, Some(&ann), None);
    let as_bob = HistoryReader::new(&catalog, Some(&bob), None);
    let as_admin = HistoryReader::new(&catalog, Some(&admin), None);
    let anonymous = HistoryReader::new(&catalog, None, None);

    // By default, only the admin.
    let err = as_ann.row_history("notes", &anns).await.unwrap_err();
    assert!(is_auth(&err), "{err}");
    assert!(is_auth(
        &as_ann.deleted_rows("notes", None, 0).await.unwrap_err()
    ));
    assert_eq!(
        as_admin
            .row_history("notes", &anns)
            .await?
            .as_array()
            .unwrap()
            .len(),
        2
    );
    assert_eq!(
        keys(&as_admin.deleted_rows("notes", None, 0).await?),
        vec![gone_ann.clone(), bobs.clone()]
    );

    alter(
        &catalog,
        schema_edit::TableSettings {
            history_min_role: Some(80),
            ..Default::default()
        },
    )
    .await?;

    // Opened to role 80: Ann sees her rows, live and deleted, and not Bob's.
    let history = as_ann.row_history("notes", &anns).await?;
    assert_eq!(history.as_array().unwrap().len(), 2);
    assert_eq!(history[0]["changeset"]["user_id"], json!(ADMIN));
    // A reader below the admin is told who by id, not by email.
    assert_eq!(history[0]["changeset"]["user_email"], Json::Null);
    let err = as_ann.row_history("notes", &bobs).await.unwrap_err();
    assert!(is_not_found(&err), "{err}");
    assert!(as_ann.row_history("notes", &gone_ann).await.is_ok());
    assert_eq!(
        keys(&as_ann.deleted_rows("notes", None, 0).await?),
        vec![gone_ann.clone()]
    );
    // The deleted row's image is what decides for Bob, too.
    assert_eq!(
        keys(&as_bob.deleted_rows("notes", None, 0).await?),
        vec![bobs.clone()]
    );
    assert!(as_bob.row_history("notes", &bobs).await.is_ok());
    assert!(is_not_found(
        &as_bob.row_as_of("notes", &anns, "1").await.unwrap_err()
    ));
    // The bound is applied after the check, so a page is of rows they may see.
    assert_eq!(
        keys(&as_ann.deleted_rows("notes", Some(1), 0).await?),
        vec![gone_ann.clone()]
    );

    // Someone signed in below role 80, or nobody at all, still may not.
    assert!(is_auth(
        &anonymous.row_history("notes", &anns).await.unwrap_err()
    ));
    let carl = user("00000000-0000-4000-8000-0000000000c0", 90);
    let as_carl = HistoryReader::new(&catalog, Some(&carl), None);
    assert!(is_auth(
        &as_carl.row_history("notes", &anns).await.unwrap_err()
    ));
    // Changesets span tables: the admin's alone.
    assert!(is_auth(
        &as_ann
            .list_changesets(Default::default())
            .await
            .unwrap_err()
    ));
    assert!(as_admin.list_changesets(Default::default()).await.is_ok());
    Ok(())
}

/// A table without history has none to read, even for the admin.
#[tokio::test]
async fn a_table_without_history_is_refused_by_name() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    alter(
        &catalog,
        schema_edit::TableSettings {
            history_enabled: Some(false),
            ..Default::default()
        },
    )
    .await?;
    let admin = user(ADMIN, 1);
    let err = HistoryReader::new(&catalog, Some(&admin), None)
        .row_history("notes", "1")
        .await
        .unwrap_err();
    assert!(
        err.to_string().contains("does not keep row history"),
        "{err}"
    );
    Ok(())
}

/// The seq of the entry with version `version` in a history (newest first).
fn seq_of(history: &Json, version: i64) -> String {
    history
        .as_array()
        .unwrap()
        .iter()
        .find(|e| e["version"] == json!(version))
        .unwrap()["seq"]
        .to_string()
}

/// `as_of` starts from the row now (or nothing, once deleted) and undoes the
/// later entries, newest first, across several changesets.
#[tokio::test]
async fn as_of_rebuilds_a_row_across_several_changesets() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let id = create(
        &catalog,
        ANN,
        json!({ "owner": ANN, "body": "one", "extra": "x" }),
    )
    .await?;
    update(&catalog, ANN, &id, json!({ "body": "two" })).await?;
    update(&catalog, BOB, &id, json!({ "body": "three", "extra": "y" })).await?;
    let admin = user(ADMIN, 1);
    let reader = HistoryReader::new(&catalog, Some(&admin), None);

    let history = reader.row_history("notes", &id).await?;
    let ops: Vec<&str> = history
        .as_array()
        .unwrap()
        .iter()
        .map(|e| e["op"].as_str().unwrap())
        .collect();
    assert_eq!(ops, ["u", "u", "i"]);
    assert_eq!(history[0]["version"], json!(3));
    assert_eq!(
        history[0]["changes"],
        json!([
            { "field": "body", "old": "two", "new": "three", "removed": false },
            { "field": "extra", "old": "x", "new": "y", "removed": false },
        ])
    );

    let at = |version| seq_of(&history, version);
    let body = |rebuilt: &Json| rebuilt["row"]["body"].clone();
    assert_eq!(
        body(&reader.row_as_of("notes", &id, &at(1)).await?),
        json!("one")
    );
    let second = reader.row_as_of("notes", &id, &at(2)).await?;
    assert_eq!(
        (body(&second), second["row"]["extra"].clone()),
        (json!("two"), json!("x"))
    );
    assert_eq!(
        body(&reader.row_as_of("notes", &id, &at(3)).await?),
        json!("three")
    );
    // Before the insert there was no row.
    assert_eq!(
        reader.row_as_of("notes", &id, "0").await?["row"],
        Json::Null
    );
    assert_eq!(
        reader.row_as_of("notes", &id, "2000-01-01").await?["row"],
        Json::Null
    );

    // Once deleted: nothing now, and the last version just before the delete.
    delete(&catalog, ANN, &id).await?;
    let history = reader.row_history("notes", &id).await?;
    assert_eq!(history[0]["op"], json!("d"));
    assert_eq!(history[0]["version"], json!(4));
    let deleted_at = history[0]["seq"].to_string();
    assert_eq!(
        reader.row_as_of("notes", &id, &deleted_at).await?["row"],
        Json::Null
    );
    let before = reader.row_as_of("notes", &id, &seq_of(&history, 3)).await?;
    assert_eq!(body(&before), json!("three"));
    assert_eq!(before["row"]["id"], json!(id.parse::<i64>().unwrap()));
    // A time works as well as a seq: now is after everything.
    let now = chrono::Utc::now().to_rfc3339();
    assert_eq!(
        reader.row_as_of("notes", &id, &now).await?["row"],
        Json::Null
    );
    assert!(
        reader
            .row_as_of("notes", &id, "last tuesday")
            .await
            .is_err()
    );
    Ok(())
}

/// A column dropped since the entry was written stays in the log, and is shown
/// as removed: in a history entry, a rebuilt row and a deleted row.
#[tokio::test]
async fn a_column_dropped_since_shows_as_removed() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let kept = create(
        &catalog,
        ANN,
        json!({ "owner": ANN, "body": "b", "extra": "e" }),
    )
    .await?;
    update(&catalog, ANN, &kept, json!({ "extra": "f" })).await?;
    let gone = create(
        &catalog,
        ANN,
        json!({ "owner": ANN, "body": "g", "extra": "h" }),
    )
    .await?;
    delete(&catalog, ANN, &gone).await?;
    schema_edit::apply(
        &catalog,
        &[schema_edit::Operation::DropField {
            table: "notes".to_owned(),
            field: "extra".to_owned(),
        }],
        &schema_edit::ApplyOptions::default(),
    )
    .await?;
    let admin = user(ADMIN, 1);
    let reader = HistoryReader::new(&catalog, Some(&admin), None);

    let history = reader.row_history("notes", &kept).await?;
    assert_eq!(
        history[0]["changes"],
        json!([{ "field": "extra", "old": "e", "new": "f", "removed": true }])
    );
    let first = reader
        .row_as_of("notes", &kept, &seq_of(&history, 1))
        .await?;
    assert!(first["row"].get("extra").is_none(), "{first}");
    assert_eq!(first["removed"], json!({ "extra": "e" }));
    assert_eq!(first["row"]["body"], json!("b"));

    let deleted = reader.deleted_rows("notes", None, 0).await?;
    assert_eq!(deleted[0]["removed"], json!({ "extra": "h" }));
    assert!(deleted[0]["row"].get("extra").is_none());
    Ok(())
}

/// A secret is its sentinel in every answer: a history entry, a rebuilt row,
/// a deleted row and a changeset.
#[tokio::test]
async fn secrets_are_the_sentinel_in_history() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let id = create(&catalog, ANN, json!({ "owner": ANN, "pin": "1234" })).await?;
    update(&catalog, ANN, &id, json!({ "pin": "5678" })).await?;
    let admin = user(ADMIN, 1);
    let reader = HistoryReader::new(&catalog, Some(&admin), None);
    let history = reader.row_history("notes", &id).await?;
    let first = reader.row_as_of("notes", &id, &seq_of(&history, 1)).await?;
    delete(&catalog, ANN, &id).await?;
    let deleted = reader.deleted_rows("notes", None, 0).await?;
    let changesets = reader.list_changesets(Default::default()).await?;
    let one = reader
        .changeset(changesets[0]["id"].as_str().unwrap())
        .await?;
    let everything = json!([history, first, deleted, one]).to_string();
    assert!(
        !everything.contains("1234") && !everything.contains("5678"),
        "{everything}"
    );
    assert_eq!(
        history[0]["changes"],
        json!([{ "field": "pin", "old": SECRET_SENTINEL, "new": SECRET_SENTINEL, "removed": false }])
    );
    assert_eq!(first["row"]["pin"], json!(SECRET_SENTINEL));
    assert_eq!(deleted[0]["row"]["pin"], json!(SECRET_SENTINEL));
    Ok(())
}

/// Changesets, newest first, filtered by user, table, source and time; one
/// changeset read back with its entries.
#[tokio::test]
async fn changesets_are_listed_filtered_and_read() -> Result<()> {
    let db = TestDb::new().await?;
    let catalog = setup(&db).await?;
    let before = chrono::Utc::now();
    let id = create(&catalog, ANN, json!({ "owner": ANN, "body": "a" })).await?;
    update(&catalog, BOB, &id, json!({ "body": "b" })).await?;
    sql(&db, "UPDATE notes SET body = 'by hand'").await?;
    let admin = user(ADMIN, 1);
    let reader = HistoryReader::new(&catalog, Some(&admin), None);
    let list = |query: &[(&str, &str)]| {
        let query: Vec<(String, String)> = query
            .iter()
            .map(|(k, v)| ((*k).to_owned(), (*v).to_owned()))
            .collect();
        let reader = &reader;
        async move {
            let filter = sc_api::history::changeset_filter(&query)?;
            reader.list_changesets(filter).await
        }
    };

    let all = list(&[]).await?;
    let sources: Vec<&str> = all
        .as_array()
        .unwrap()
        .iter()
        .map(|c| c["source"].as_str().unwrap())
        .collect();
    assert_eq!(sources, ["sql", "request", "request"]);
    assert_eq!(all[0]["tables"], json!(["notes"]));
    assert_eq!(all[0]["entries"], json!(1));
    assert_eq!(all[1]["user_id"], json!(BOB));
    assert_eq!(list(&[("user", BOB)]).await?.as_array().unwrap().len(), 1);
    assert_eq!(
        list(&[("source", "sql")]).await?.as_array().unwrap().len(),
        1
    );
    assert_eq!(
        list(&[("table", "notes")]).await?.as_array().unwrap().len(),
        3
    );
    assert_eq!(
        list(&[("table", "other")]).await?.as_array().unwrap().len(),
        0
    );
    assert_eq!(
        list(&[("limit", "2"), ("offset", "1")])
            .await?
            .as_array()
            .unwrap()
            .len(),
        2
    );
    let since = before.to_rfc3339();
    assert_eq!(
        list(&[("since", &since)]).await?.as_array().unwrap().len(),
        3
    );
    assert_eq!(
        list(&[("since", "2999-01-01")])
            .await?
            .as_array()
            .unwrap()
            .len(),
        0
    );
    assert!(list(&[("user", "ann")]).await.is_err());

    let one = reader.changeset(all[1]["id"].as_str().unwrap()).await?;
    assert_eq!(one["source"], json!("request"));
    assert_eq!(
        one["entries"][0]["changes"],
        json!([{ "field": "body", "old": "a", "new": "b", "removed": false }])
    );
    let missing = Uuid::new_v4().to_string();
    assert!(is_not_found(&reader.changeset(&missing).await.unwrap_err()));
    assert!(is_not_found(&reader.changeset("nope").await.unwrap_err()));
    Ok(())
}
