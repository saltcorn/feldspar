//! Row history H2: reading (design §14.12 "Reading"). Who may read a table's
//! history and which rows of it, a row rebuilt as it was, deleted rows, a
//! dropped column, secrets, and changesets.
#![allow(clippy::unwrap_used, clippy::expect_used)]

