/// Run `code` against `host` (and a file host on the same caller) in the real
/// engine, answering what it returned.
async fn run_js(
    cat: &Catalog,
    host: &TableHost<'_>,
    caller: &Principal,
    code: &str,
) -> Result<Json> {
    let files = sc_api::code_host::FileStoreHost::new(cat).for_caller(caller);
    sc_expr::CodeRuntime::new()
        .run(sc_expr::CodeCall {
            code: code.to_owned(),
            host: Some(host),
            files: Some(&files),
            ..sc_expr::CodeCall::default()
        })
        .await
}

#[tokio::test]
async fn a_scheduled_trigger_reads_one_users_rows_through_as_user() -> Result<()> {
    let w = setup().await?;
    let system = Principal::recorded(Role::PUBLIC, None).with_system_cause("a test's schedule");
    let host = TableHost::new(&w.cat).for_caller(&system);
    let code = format!(
        r#"const titles = (rows) => rows.map((b) => b.title);
           const ada = "{ada}";
           return {{
             all: titles(await db.books.orderBy("id").rows()),
             by_id: titles(await db.books.asUser(ada).orderBy("id").rows()),
             by_row: titles(await db.asUser({{ id: ada }}).books.orderBy("id").rows()),
             sql: titles(await db.asUser("{bob}").sql("select title from books order by id")),
           }};"#,
        ada = w.ada.id(),
        bob = w.bob.id(),
    );
    let out = run_js(&w.cat, &host, &system, &code).await?;
    assert_eq!(
        out,
        json!({
            // The system's own view, then each named user's, as Postgres's
            // policies decide it (the statement runs at the named user's
            // settings).
            "all": ["Dune", "Emma", "Ilium"],
            "by_id": ["Dune", "Ilium"],
            "by_row": ["Dune", "Ilium"],
            "sql": ["Emma"],
        })
    );
    Ok(())
}

#[tokio::test]
async fn a_role_80_callers_as_user_of_an_admin_is_refused_on_every_surface() -> Result<()> {
    let w = setup().await?;
    let ada = Principal::recorded(w.ada.role(), Some(w.ada.fields_json()));
    let host = TableHost::new(&w.cat).for_caller(&ada);
    let code = format!(
        r#"const said = async (f) => {{ try {{ await f(); return "ran"; }} catch (e) {{ return e.message; }} }};
           const admin = "{admin}";
           return {{
             db: await said(() => db.notes.asUser(admin).rows()),
             sql: await said(() => db.asUser(admin).sql("select 1 as n")),
             fs: await said(() => fs("nowhere").asUser(admin).open("a.txt").text()),
             own: await said(() => db.books.asUser("{ada}").rows()),
           }};"#,
        admin = w.admin.id(),
        ada = w.ada.id(),
    );
    let out = run_js(&w.cat, &host, &ada, &code).await?;
    for surface in ["db", "sql", "fs"] {
        let said = out[surface].as_str().unwrap_or_default();
        assert!(said.contains("may not act as"), "{surface}: {out}");
    }
    // Naming herself is her own view.
    assert_eq!(out["own"], json!("ran"), "{out}");
    Ok(())
}
