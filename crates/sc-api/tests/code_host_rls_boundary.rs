//! A code body over a table with row-level security (TODO-type-hardening H8,
//! §7.3a): nothing elevates.
//!
//! - An explicit `asAdmin()` over an RLS table is refused, naming the table,
//!   while the default authority of a body sees what its cause sees (H8.2).
//! - `forUser` / a named user may not hold more authority than the cause, on
//!   every table (H8.2), and `asUser(id)` narrows a system job to one user
//!   (H8.8).
//!
//! A real database with real policies and real users, because each claim is
//! about what Postgres is asked under which settings.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use sc_types::Role;
use std::sync::Arc;

use sc_api::code_host::TableHost;
use sc_auth::User;
use sc_catalog::{
    Catalog, Principal, TableMeta, bootstrap_table_meta, enable_rls, save_table_meta,
};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::Result;
use sc_expr::CodeHost;
use sc_test_harness::TestDb;
use serde_json::{Value as Json, json};

struct World {
    cat: Arc<Catalog>,
    admin: User,
    ada: User,
    bob: User,
    _db: TestDb,
}

/// `books` has RLS (`owner === user.id`): two of ada's and one of bob's.
/// `notes` has none, and the admin's floors: what a named user's authority is
/// checked on when RLS has nothing to say.
async fn setup() -> Result<World> {
    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(
            "CREATE TABLE books (id bigint generated by default as identity primary key, \
                 title text, owner uuid); \
             CREATE TABLE notes (id bigint generated by default as identity primary key, \
                 what text);",
        )
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let cat = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(cat.teardown_hook());
    sc_auth::bootstrap(&cat).await?;
    bootstrap_table_meta(&cat).await?;
    cat.reload().await?;
    sc_auth::save_role(&cat, &sc_auth::RoleDef::new(Role::of(80), "User")).await?;
    let admin =
        sc_auth::create_user(&cat, "root@example.com", "a long password", Role::ADMIN).await?;
    let ada =
        sc_auth::create_user(&cat, "ada@example.com", "a long password", Role::of(80)).await?;
    let bob =
        sc_auth::create_user(&cat, "bob@example.com", "a long password", Role::of(80)).await?;
    db.client()
        .await?
        .batch_execute(&format!(
            "INSERT INTO books (title, owner) VALUES ('Dune', '{a}'), ('Emma', '{b}'), \
                 ('Ilium', '{a}');",
            a = ada.id(),
            b = bob.id(),
        ))
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    let mut books = TableMeta::new("books");
    books.set_ownership_formula(Some("owner === user.id"));
    books.set_rls_enabled(true);
    save_table_meta(&cat, &books).await?;
    enable_rls(&cat, &cat.require("books")?).await?;
    Ok(World {
        cat,
        admin,
        ada,
        bob,
        _db: db,
    })
}

/// A body's host, caused by `user`.
fn host_for<'a>(cat: &'a Catalog, user: &User) -> TableHost<'a> {
    TableHost::new(cat).caused_by(user.role(), Some(user.fields_json()))
}

/// A scheduled trigger's host: nobody at the public role, caused by the system.
fn scheduled(cat: &Catalog) -> TableHost<'_> {
    TableHost::new(cat)
        .for_caller(&Principal::recorded(Role::PUBLIC, None).with_system_cause("a test's schedule"))
}

fn titles(rows: &Json) -> Vec<String> {
    rows.as_array()
        .unwrap()
        .iter()
        .map(|r| r["title"].as_str().unwrap().to_owned())
        .collect()
}

fn read(authority: Json) -> Json {
    json!({
        "op": "select", "table": "books", "authority": authority,
        "select": ["title"], "order": [ { "field": "id" } ],
    })
}

// ---------------------------------------------------------------------------
// H8.2: explicit `asAdmin()` over an RLS table
// ---------------------------------------------------------------------------

#[tokio::test]
async fn as_admin_on_an_rls_table_is_refused_naming_it() -> Result<()> {
    let w = setup().await?;
    for host in [
        host_for(&w.cat, &w.ada),
        host_for(&w.cat, &w.admin),
        scheduled(&w.cat),
    ] {
        let refused = host
            .call(read(json!("admin")))
            .await
            .expect_err("asAdmin() is refused on an RLS table")
            .to_string();
        assert!(
            refused.contains("`books` has row-level security") && refused.contains("asAdmin()"),
            "{refused}"
        );
        // A write too, before anything is written.
        let refused = host
            .call(json!({
                "op": "insert", "table": "books", "authority": "admin",
                "values": { "title": "Forged", "owner": "nobody" },
            }))
            .await
            .expect_err("asAdmin() is refused on an RLS table")
            .to_string();
        assert!(
            refused.contains("`books` has row-level security"),
            "{refused}"
        );
    }

    // The default authority — a trigger's body's — is not refused: it is
    // elevated over the cause, so on `books` it sees what the cause sees.
    assert_eq!(
        titles(
            &host_for(&w.cat, &w.ada)
                .call(read(json!("default")))
                .await?
        ),
        vec!["Dune", "Ilium"]
    );
    assert_eq!(
        titles(&scheduled(&w.cat).call(read(json!("default"))).await?),
        vec!["Dune", "Emma", "Ilium"]
    );
    // And `asAdmin()` over a table without RLS still reaches every row.
    let counted = host_for(&w.cat, &w.ada)
        .call(json!({
            "op": "aggregate", "table": "notes", "authority": "admin",
            "aggregate": [ { "alias": "n", "fn": "count" } ],
        }))
        .await?;
    assert_eq!(counted, json!({ "n": 0 }));
    Ok(())
}

// ---------------------------------------------------------------------------
// H8.2: a named user may not hold more authority than the cause
// ---------------------------------------------------------------------------

#[tokio::test]
async fn a_named_user_with_more_authority_than_the_cause_is_refused_on_every_table() -> Result<()> {
    let w = setup().await?;
    // A role-80 caller naming the administrator: refused, on a table without
    // RLS as well — `forUser` was the way a request-supplied id became admin.
    for table in ["notes", "books"] {
        let refused = host_for(&w.cat, &w.ada)
            .call(json!({
                "op": "select", "table": table, "authority": { "user": w.admin.id().to_string() },
            }))
            .await
            .expect_err("ada may not act as the admin")
            .to_string();
        assert!(refused.contains("may not act as"), "{table}: {refused}");
    }
    // Naming another role-80 user is refused too: only the system or an
    // administrator may name somebody else.
    let refused = host_for(&w.cat, &w.ada)
        .call(read(json!({ "user": w.bob.id().to_string() })))
        .await
        .expect_err("ada may not act as bob")
        .to_string();
    assert!(refused.contains("may not act as"), "{refused}");
    // Naming herself is allowed, and is her view.
    assert_eq!(
        titles(
            &host_for(&w.cat, &w.ada)
                .call(read(json!({ "user": w.ada.id().to_string() })))
                .await?
        ),
        vec!["Dune", "Ilium"]
    );
    // An administrator may name anyone.
    assert_eq!(
        titles(
            &host_for(&w.cat, &w.admin)
                .call(read(json!({ "user": w.bob.id().to_string() })))
                .await?
        ),
        vec!["Emma"]
    );
    Ok(())
}

// ---------------------------------------------------------------------------
// H8.3: a statement cannot forge the caller context
// ---------------------------------------------------------------------------

#[tokio::test]
async fn db_sql_that_sets_the_caller_context_is_refused_and_runs_nothing() -> Result<()> {
    let w = setup().await?;
    let host = host_for(&w.cat, &w.ada);
    for sql in [
        "WITH x AS (SELECT set_config('sc.role','1',true)) SELECT * FROM books, x",
        "select pg_catalog.set_config('sc.user', '{}', true)",
        "SET LOCAL sc.role = '1'",
        "DO $$ BEGIN PERFORM set_config('sc.role', '1', true); END $$",
        "CREATE OR REPLACE FUNCTION f() RETURNS text LANGUAGE sql AS 'select 1::text'",
    ] {
        let refused = host
            .call(json!({ "op": "sql", "sql": sql }))
            .await
            .expect_err(sql)
            .to_string();
        assert!(
            refused.contains("is refused because it"),
            "{sql}: {refused}"
        );
    }
    // Reshaping the policies is refused with the reply that says who may.
    let refused = host
        .call(json!({ "op": "sql", "sql": "ALTER TABLE books DISABLE ROW LEVEL SECURITY" }))
        .await
        .expect_err("not from a statement")
        .to_string();
    assert_eq!(refused, sc_query::rls_refusal("books").to_string());
    // And the table still has its policies: ada still sees her two rows.
    assert_eq!(
        titles(
            &host
                .call(json!({ "op": "sql", "sql": "select title from books order by id" }))
                .await?
        ),
        vec!["Dune", "Ilium"]
    );
    Ok(())
}

#[test]
fn a_custom_sql_query_that_sets_the_caller_context_is_refused_on_save() {
    let query: sc_api::CustomQuery = serde_json::from_value(json!({
        "name": "forged",
        "method": "GET",
        "path": "/forged",
        "code": "WITH x AS (SELECT set_config('sc.role','1',true)) SELECT * FROM books, x",
    }))
    .expect("a query");
    let refused = sc_api::validate_custom_queries(&[query], &[])
        .expect_err("refused on save")
        .to_string();
    assert!(
        refused.contains("custom query `forged`") && refused.contains("set_config"),
        "{refused}"
    );
}

