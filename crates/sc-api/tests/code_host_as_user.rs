#[tokio::test]
async fn a_delegated_aggregate_over_an_untranslatable_formula_says_where_to_put_the_work()
-> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    // `.includes(…)` is a function call, so this formula cannot become SQL: it has
    // to be decided row by row, in the evaluator.
    own_books(&cat, "owner.includes(user.email)", false).await?;
    let host = with_engine(as_reader(&cat, "ada@example.com"));

    // The read is fine — the formula runs per row.
    let rows = ask(
        &host,
        json!({
            "op": "select", "table": "books", "authority": "user",
            "select": ["title"], "order": [ { "field": "id" } ],
        }),
    )
    .await?;
    assert_eq!(titles(&rows), vec!["Dune", "Ilium"]);

    // The aggregate is not, and §5 says so as an instruction rather than an
    // apology: a count over rows it cannot filter would be a number nobody can
    // check, and the code body is where a per-row decision can be made.
    let refused = ask(
        &host,
        json!({
            "op": "aggregate", "table": "books", "authority": "user",
            "aggregate": [ { "alias": "value", "fn": "count" } ],
        }),
    )
    .await
    .expect_err("an aggregate cannot carry a per-row formula");
    let message = refused.to_string();
    assert!(
        message.contains("cannot be aggregated for you"),
        "{message}"
    );
    assert!(message.contains("`.rows()`"), "{message}");
    assert!(message.contains("code body"), "{message}");

    // A grouped aggregate is refused for the very same reason — the guard is
    // asked before the grouping, because the question is which *rows* it may
    // range over — and says the same thing about where the work goes instead.
    let refused = ask(
        &host,
        json!({
            "op": "aggregate", "table": "books", "authority": "user",
            "group": ["owner"],
            "aggregate": [ { "alias": "n", "fn": "count" } ],
        }),
    )
    .await
    .expect_err("a grouped aggregate cannot carry a per-row formula either");
    assert!(
        refused.to_string().contains("cannot be aggregated for you"),
        "{refused}"
    );
    Ok(())
}

/// A **custom query's** host defaults to the caller: a plan that names no
/// authority, or names `default`, is narrowed by the ownership formula exactly
/// as `asUser()` is, and only an explicit `admin` reads the whole table. A
/// trigger's host keeps the admin default for the same plans.
#[tokio::test]
async fn a_hosts_default_authority_decides_a_plan_that_names_none() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;
    let read = |authority: Option<&str>| {
        let mut plan = json!({
            "op": "select", "table": "books",
            "select": ["id", "title"], "order": [ { "field": "id" } ],
        });
        if let Some(authority) = authority {
            plan["authority"] = json!(authority);
        }
        plan
    };

    let query = as_reader(&cat, "ada@example.com").defaulting_to(Authority::User);
    for authority in [None, Some("default"), Some("user")] {
        assert_eq!(
            titles(&ask(&query, read(authority)).await?),
            vec!["Dune", "Ilium"],
            "{authority:?}: a custom query reads as its caller"
        );
    }
    assert_eq!(
        titles(&ask(&query, read(Some("admin"))).await?),
        vec!["Dune", "Emma", "Ilium", "Ubik"],
        "`asAdmin()` is the explicit way out"
    );

    let trigger = as_reader(&cat, "ada@example.com");
    for authority in [None, Some("default")] {
        assert_eq!(
            titles(&ask(&trigger, read(authority)).await?),
            vec!["Dune", "Emma", "Ilium", "Ubik"],
            "{authority:?}: a trigger still reads as the admin"
        );
    }
    Ok(())
}

/// The same rule from a real JavaScript body: `db.books` with nothing said is
/// the caller's view in a query, `db.asAdmin()` is the table, and a write the
/// formula does not grant is refused rather than made.
#[tokio::test]
async fn a_query_bodys_db_acts_as_the_caller_unless_it_says_as_admin() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;
    let host = as_reader(&cat, "bob@example.com").defaulting_to(Authority::User);
    let runtime = CodeRuntime::new();
    let out = runtime
        .run(CodeCall {
            code: r#"
                const mine = await db.books.select("title").orderBy("id").rows();
                const all = await db.asAdmin().books.count();
                let refused = null;
                try {
                  await db.books.insert({ title: "Mine now", pages: 1, owner: "ada@example.com" });
                } catch (e) {
                  refused = String(e.message || e);
                }
                return { mine: mine.map((b) => b.title), all: all, refused: refused !== null };
            "#
            .to_owned(),
            host: Some(&host),
            ..CodeCall::default()
        })
        .await?;
    assert_eq!(
        out,
        json!({ "mine": ["Emma", "Ubik"], "all": 4, "refused": true }),
        "bob's rows by default, the table under asAdmin(), and no insert as ada"
    );
    assert_eq!(
        rows_of(&db, "SELECT title FROM books WHERE title = 'Mine now'").await,
        Vec::<Vec<Option<String>>>::new(),
        "the refused insert wrote nothing"
    );
    Ok(())
}

#[tokio::test]
async fn a_delegated_read_that_needs_the_formula_engine_completes_from_a_code_body() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner.includes(user.email)", false).await?;
    let host = with_engine(as_reader(&cat, "bob@example.com"));

    // The regression test for decision 1. This body runs on a **code** isolate
    // and suspends on the host call; the host call runs a delegated read whose
    // ownership formula only the **formula** isolate can decide. Two runtimes, so
    // the isolate waiting is never the one the formula needs. One isolate serving
    // both would hang here — which is why this is a test with a timeout around it
    // rather than a comment.
    let runtime = CodeRuntime::new();
    let out = tokio::time::timeout(
        std::time::Duration::from_secs(20),
        runtime.run(CodeCall {
            code: r#"
                const mine = await db.asUser().books.select("title").orderBy("id").rows();
                const all  = await db.books.count();
                return { mine: mine.map((b) => b.title), all: all };
            "#
            .to_owned(),
            host: Some(&host),
            ..CodeCall::default()
        }),
    )
    .await
    .expect("a delegated read from a code body must not deadlock")?;

    assert_eq!(
        out,
        json!({ "mine": ["Emma", "Ubik"], "all": 4 }),
        "the delegated read is bob's rows and the undelegated count is the table's"
    );
    Ok(())
}

#[tokio::test]
async fn a_delegated_stream_is_refused_when_the_formula_decides_row_by_row() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner.includes(user.email)", false).await?;
    let host = with_engine(as_reader(&cat, "bob@example.com"));

    // §5's asymmetry, in the place it bites a stream. This formula only the
    // evaluator can decide, so a delegated read of `books` is bounded *after* the
    // rows come back — which means a batch of it would fetch the whole table,
    // hand back what survived, and do it again for the next batch. Not streaming,
    // and quadratic while looking like it. So it is refused, and the refusal says
    // what to do instead.
    let refused = ask(
        &host,
        json!({ "op": "select", "table": "books", "authority": "user", "cursor": true }),
    )
    .await
    .expect_err("a formula the database cannot carry cannot bound a batch");
    assert!(
        refused.to_string().contains("cannot be streamed"),
        "{refused}"
    );
    assert!(refused.to_string().contains(".rows()"), "{refused}");

    // And the way out is real: the same read unstreamed answers bob's rows, by
    // the reified path, exactly as it did before.
    let rows = ask(
        &host,
        json!({ "op": "select", "table": "books", "authority": "user", "order": [{ "field": "id" }] }),
    )
    .await?;
    assert_eq!(titles(&rows), vec!["Emma", "Ubik"]);

    // The refusal is about **delegation**, not about the table: the trigger's own
    // authority streams it, because no formula narrows an admin's read.
    let batch = ask(
        &host,
        json!({ "op": "select", "table": "books", "cursor": true, "limit": 2 }),
    )
    .await?;
    assert_eq!(titles(&batch["rows"]), vec!["Dune", "Emma"]);
    assert_eq!(
        batch["cursor"],
        json!([2]),
        "the next batch resumes after Emma"
    );
    Ok(())
}

#[tokio::test]
async fn a_delegated_stream_of_an_rls_table_is_bounded_by_the_policies() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", true).await?;
    let host = as_reader(&cat, "ada@example.com");

    // Row-level security is carried *inside* the statement by definition, so each
    // batch is bounded over the rows the policies leave — the case a stream can
    // serve, and the reason the guard asks how the rule travels rather than
    // whether there is one.
    let first = ask(
        &host,
        json!({ "op": "select", "table": "books", "authority": "user",
                "cursor": true, "limit": 1 }),
    )
    .await?;
    assert_eq!(titles(&first["rows"]), vec!["Dune"]);

    let next = ask(
        &host,
        json!({ "op": "select", "table": "books", "authority": "user",
                "cursor": true, "limit": 1, "after": first["cursor"].clone() }),
    )
    .await?;
    assert_eq!(
        titles(&next["rows"]),
        vec!["Ilium"],
        "bob's rows are not skipped over — they were never in the stream"
    );

    let last = ask(
        &host,
        json!({ "op": "select", "table": "books", "authority": "user",
                "cursor": true, "limit": 1, "after": next["cursor"].clone() }),
    )
    .await?;
    assert!(titles(&last["rows"]).is_empty());
    assert_eq!(last["cursor"], Json::Null, "and the stream says it is done");
    Ok(())
}
