#[tokio::test]
async fn a_delegated_insert_outside_the_formula_writes_nothing() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;
    // A delegated **write** is checked against a single row — the one proposed —
    // and that check is the evaluator's whether or not the formula would also
    // translate, so the engine is not optional here the way it is for a read.
    // (Which is what phase 5 has to hand `run_js_code`.)
    let host = with_engine(as_reader(&cat, "ada@example.com"));

    // §7.3's write rule, checked against the proposed row: a row ada could not
    // then read is a row ada may not write.
    let refused = ask(
        &host,
        json!({
            "op": "insert", "table": "books", "authority": "user",
            "values": { "title": "Nostromo", "owner": "bob@example.com" },
        }),
    )
    .await
    .expect_err("outside what ada may write");
    assert!(
        refused.to_string().contains("outside what you may write"),
        "{refused}"
    );

    // A table with no ownership formula at all is the other half of the same
    // rule: below the write floor and with nothing to extend it, a delegated
    // write is refused — while the trigger's own authority writes the audit row
    // it exists to write, which is why admin is the default.
    let audit = ask(
        &host,
        json!({
            "op": "insert", "table": "audit", "authority": "user",
            "values": { "what": "ada tried" },
        }),
    )
    .await
    .expect_err("ada may not write `audit`");
    assert!(audit.to_string().contains("audit"), "{audit}");
    ask(
        &host,
        json!({ "op": "insert", "table": "audit", "values": { "what": "the trigger did" } }),
    )
    .await?;

    // A row of ada's own goes in.
    let written = ask(
        &host,
        json!({
            "op": "insert", "table": "books", "authority": "user",
            "values": { "title": "Nostromo", "owner": "ada@example.com" },
        }),
    )
    .await?;
    assert_eq!(written["title"], json!("Nostromo"));

    assert_eq!(
        rows_of(&db, "SELECT title FROM books ORDER BY id").await,
        vec![
            vec![Some("Dune".to_owned())],
            vec![Some("Emma".to_owned())],
            vec![Some("Ilium".to_owned())],
            vec![Some("Ubik".to_owned())],
            vec![Some("Nostromo".to_owned())],
        ],
        "the refused inserts wrote nothing"
    );
    assert_eq!(
        rows_of(&db, "SELECT what FROM audit").await,
        vec![vec![Some("the trigger did".to_owned())]],
    );
    Ok(())
}

#[tokio::test]
async fn a_delegated_write_cannot_reach_a_row_the_caller_cannot_see() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;
    let host = with_engine(as_reader(&cat, "ada@example.com"));

    // An update is checked twice — on the row as it is, and on the row as it
    // would become — so it cannot move a row out of the caller's own ownership.
    let moved = ask(
        &host,
        json!({
            "op": "update", "table": "books", "authority": "user",
            "where": { "title": "Dune" }, "values": { "owner": "bob@example.com" },
        }),
    )
    .await
    .expect_err("that update would give the row away");
    assert!(
        moved.to_string().contains("out of what you may reach"),
        "{moved}"
    );

    // A bulk write resolves its rows through the **delegated** read, so a row the
    // caller cannot see is never a row they can update by predicate. Not an
    // error: bob's rows simply are not among the matched ones.
    let by_predicate = ask(
        &host,
        json!({
            "op": "update", "table": "books", "authority": "user",
            "where": { "pages": { "gt": 100 } }, "values": { "pages": 1 },
        }),
    )
    .await?;
    assert_eq!(
        by_predicate["updated"],
        json!(2),
        "ada's two rows, not the table's four"
    );
    let deleted = ask(
        &host,
        json!({
            "op": "delete", "table": "books", "authority": "user",
            "where": { "owner": "bob@example.com" },
        }),
    )
    .await?;
    assert_eq!(deleted, json!({ "deleted": 0, "ids": [] }));

    // …and ada's own update went through, one event per row.
    assert_eq!(
        rows_of(&db, "SELECT pages::text FROM books ORDER BY id").await,
        vec![
            vec![Some("1".to_owned())],
            vec![Some("474".to_owned())],
            vec![Some("1".to_owned())],
            vec![Some("224".to_owned())],
        ],
    );
    Ok(())
}

/// A trigger action that records the chain and depth of the event it was handed.
struct Recorder(Arc<std::sync::Mutex<Vec<Json>>>);

#[async_trait::async_trait]
impl Action for Recorder {
    fn name(&self) -> &str {
        "record"
    }
    fn description(&self) -> &str {
        "Record the event's chain, for a test to read back"
    }
    fn config_spec(&self) -> Vec<FormField> {
        Vec::new()
    }
    async fn run(&self, ctx: &mut ActionContext<'_>) -> Result<Json> {
        let seen = json!({ "chain": ctx.chain, "depth": ctx.event.depth() });
        self.0.lock().unwrap().push(seen.clone());
        Ok(seen)
    }
}

#[tokio::test]
async fn a_delegated_write_is_an_event_at_the_depth_its_chain_says() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;

    let seen = Arc::new(std::sync::Mutex::new(Vec::new()));
    let mut registry = ActionRegistry::new();
    registry.register(Arc::new(Recorder(Arc::clone(&seen))) as Arc<dyn Action>)?;
    let dispatcher = Arc::new(TriggerDispatcher::new(Arc::new(registry)));
    bootstrap_triggers(&cat).await?;
    save_trigger(
        &cat,
        &dispatcher.registry(),
        &Trigger::new("watch", EventKind::Insert, "record").on("books"),
    )
    .await?;
    dispatcher.reload(&cat).await?;
    cat.add_table_events(
        sc_catalog::TRIGGER_EVENTS,
        Arc::clone(&dispatcher) as Arc<dyn sc_catalog::TableEvents>,
    )?;

    // A delegated write goes through `ownership::insert_row_as` rather than
    // straight to the row layer — and it has to carry the same chain the
    // undelegated one does, or `Event::firing`'s cascade bound would restart at
    // zero and a body that writes the table that fired it would never stop.
    let host = with_engine(as_reader(&cat, "ada@example.com")).chained(vec!["watch".to_owned()]);
    ask(
        &host,
        json!({
            "op": "insert", "table": "books", "authority": "user",
            "values": { "title": "Nostromo", "owner": "ada@example.com" },
        }),
    )
    .await?;

    let seen = seen.lock().unwrap().clone();
    assert_eq!(seen.len(), 1, "the table's own trigger observed the write");
    assert_eq!(
        seen[0]["chain"],
        json!(["watch", "watch"]),
        "the delegated write's event descends from the trigger that made it"
    );
    assert_eq!(seen[0]["depth"], json!(1), "one deeper, not back at zero");
    Ok(())
}

