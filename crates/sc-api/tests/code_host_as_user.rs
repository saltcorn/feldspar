//! `asUser()`: a code body's database access delegated to the event's caller
//! (the milestone "Tables in code", phase 4).
//!
//! Nothing here can be proved against a plan. The whole claim of §5 is that a
//! delegated operation goes through [`sc_api::ownership`]'s `*_as` functions —
//! §7.3's rule, the same functions the agent tools use — and every consequence
//! that matters is a consequence of *those* running: the formula narrows a read
//! in the `WHERE` where it can and row by row where it cannot, an update is
//! checked on the row as it is and on the row as it would become, a withheld row
//! is the same not-found an absent one gets, and an RLS table's policies decide
//! inside a caller-context transaction. So: a real database, real policies, and
//! for the reified path the real V8 engine.
//!
//! The last test is the one this milestone's decision 1 exists for. A delegated
//! read whose ownership formula the translator refuses has to run the **formula**
//! isolate from inside a host call that a **code** thread is blocked on. One
//! isolate serving both would deadlock there, waiting for itself; the test runs
//! the body through the real `CodeRuntime` so that a regression is a hang the
//! suite reports rather than a subtlety nobody re-derives.
#![allow(clippy::unwrap_used, clippy::expect_used)]

