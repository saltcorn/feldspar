/// Two owners with two books each, so an ownership formula has something to
/// divide, and an `audit` table nobody owns — what a delegated write is refused
/// on and an admin's is not.
const SCHEMA: &str = "\
    CREATE TABLE books (id bigint generated by default as identity primary key, \
        title text, pages bigint, owner text); \
    CREATE TABLE audit (id bigint generated by default as identity primary key, what text); \
    INSERT INTO books (title, pages, owner) VALUES \
        ('Dune',   412, 'ada@example.com'), \
        ('Emma',   474, 'bob@example.com'), \
        ('Ilium',  576, 'ada@example.com'), \
        ('Ubik',   224, 'bob@example.com');";

/// The catalog over a fresh database with [`SCHEMA`] in it and the overlay table
/// bootstrapped, ready for an ownership formula.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| sc_error::Error::database(e.to_string()))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let cat = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(cat.teardown_hook());
    bootstrap_table_meta(&cat).await?;
    Ok(cat)
}

/// Put an ownership formula on `books`, optionally as row-level security so the
/// database's own policies are what decide.
async fn own_books(cat: &Catalog, formula: &str, rls: bool) -> Result<()> {
    let mut books = TableMeta::new("books");
    books.set_ownership_formula(Some(formula));
    if rls {
        books.set_rls_enabled(true);
    }
    save_table_meta(cat, &books).await?;
    if rls {
        enable_rls(cat, &cat.require("books")?).await?;
    }
    assert!(
        cat.require("books")?.ownership.is_some(),
        "the formula is live"
    );
    Ok(())
}

/// A host whose event was caused by `email` at role 40 — below `books`' admin-only
/// floors, so this caller's access is whatever the ownership formula grants and
/// nothing else. The caller object is the shape an event carries: the id as a
/// uuid string, the role, and the fields a formula reads.
fn as_reader<'a>(cat: &'a Catalog, email: &str) -> TableHost<'a> {
    TableHost::new(cat).caused_by(
        40,
        Some(json!({
            "id": uuid::Uuid::new_v4().to_string(),
            "role": 40,
            "email": email,
        })),
    )
}

/// That host with the real formula engine behind it, for a formula the translator
/// refuses.
fn with_engine(host: TableHost<'_>) -> TableHost<'_> {
    host.with_evaluator(Some(Arc::new(DenoEvaluator::new()) as Arc<dyn JsEvaluator>))
}

/// One plan, answered — what `__scDbCall(plan)` gets back.
async fn ask(host: &TableHost<'_>, plan: Json) -> Result<Json> {
    host.call(plan).await
}

/// The `title` of every row of an answer, in the order they came back.
fn titles(rows: &Json) -> Vec<String> {
    rows.as_array()
        .cloned()
        .unwrap_or_default()
        .iter()
        .map(|r| r["title"].as_str().unwrap_or_default().to_owned())
        .collect()
}

/// Every row of a table, by the shortest route that is not the code host itself.
async fn rows_of(db: &TestDb, sql: &str) -> Vec<Vec<Option<String>>> {
    db.client()
        .await
        .unwrap()
        .query(sql, &[])
        .await
        .unwrap()
        .iter()
        .map(|row| {
            (0..row.len())
                .map(|i| row.get::<_, Option<String>>(i))
                .collect()
        })
        .collect()
}

