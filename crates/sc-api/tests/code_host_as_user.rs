#[tokio::test]
async fn a_delegated_read_sees_only_the_rows_the_formula_grants() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;
    let host = as_reader(&cat, "ada@example.com");

    // The same plan, twice, differing in one field. `asUser()`…
    let plan = json!({
        "op": "select", "table": "books", "authority": "user",
        "select": ["id", "title"], "order": [ { "field": "id" } ],
    });
    assert_eq!(
        titles(&ask(&host, plan.clone()).await?),
        vec!["Dune", "Ilium"],
        "the ownership formula narrowed the read to this caller's rows"
    );

    // …and `asAdmin()`, which is the default and reads everything. This is the
    // difference the whole phase is about, on one host and one body.
    let mut admin = plan.clone();
    admin["authority"] = json!("admin");
    assert_eq!(
        titles(&ask(&host, admin).await?),
        vec!["Dune", "Emma", "Ilium", "Ubik"],
    );

    // A row the formula withholds is the same **nothing** an absent row is: a
    // delegated `.get(pk)` cannot become a way to probe which rows exist.
    let probed = ask(
        &host,
        json!({ "op": "select", "table": "books", "authority": "user", "pk": 2, "limit": 1 }),
    )
    .await?;
    assert_eq!(
        probed,
        json!([]),
        "`.get(2)` is bob's row, so it is nothing"
    );

    // An aggregate is the same rule expressed inside the statement: the
    // translated formula rides in the `WHERE`, so a delegated count counts the
    // caller's rows and not the table's.
    let counted = ask(
        &host,
        json!({
            "op": "aggregate", "table": "books", "authority": "user",
            "aggregate": [ { "alias": "value", "fn": "count" } ],
        }),
    )
    .await?;
    assert_eq!(counted, json!({ "value": 2 }));

    // Grouping does not change the rule, it partitions what is left of it: the
    // formula narrows the rows, and only then are the groups formed. Ada's two
    // books group into one owner; the table's four would group into two.
    let grouped = ask(
        &host,
        json!({
            "op": "aggregate", "table": "books", "authority": "user",
            "group": ["owner"],
            "aggregate": [ { "alias": "n", "fn": "count" } ],
            "order": [ { "field": "owner" } ],
        }),
    )
    .await?;
    assert_eq!(grouped, json!([{ "owner": "ada@example.com", "n": 2 }]));
    Ok(())
}

#[tokio::test]
async fn a_delegated_read_of_an_rls_table_sees_what_the_policies_allow() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    // The same formula, enforced by the database: the read runs in a
    // caller-context transaction and the policies decide. `sc-api` applies no
    // predicate of its own here, which is exactly why this needs its own test —
    // a delegated read that forgot the context would see everything.
    own_books(&cat, "owner === user.email", true).await?;
    let host = as_reader(&cat, "bob@example.com");

    let rows = ask(
        &host,
        json!({
            "op": "select", "table": "books", "authority": "user",
            "select": ["title"], "order": [ { "field": "id" } ],
        }),
    )
    .await?;
    assert_eq!(titles(&rows), vec!["Emma", "Ubik"]);

    // And the admin's own path still reads the whole table: `ROLE_ADMIN` clears
    // the policy's role floor, as the admin API's row editor does.
    let all = ask(
        &host,
        json!({
            "op": "select", "table": "books",
            "select": ["title"], "order": [ { "field": "id" } ],
        }),
    )
    .await?;
    assert_eq!(all.as_array().map(Vec::len), Some(4));
    Ok(())
}

#[tokio::test]
async fn a_scheduled_triggers_delegation_reads_as_the_public_role() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    own_books(&cat, "owner === user.email", false).await?;

    // A scheduled or startup event carries nobody, so there is no one to act as.
    // §5's answer is the honest one rather than an error: the read is public's,
    // and public owns no rows. (Which is why `asAdmin()` is the default — this is
    // what a body that delegated by habit would get.)
    let scheduled = with_engine(TableHost::new(&cat));
    let plan = json!({
        "op": "select", "table": "books", "authority": "user", "select": ["title"],
    });
    assert_eq!(
        titles(&ask(&scheduled, plan.clone()).await?),
        Vec::<String>::new(),
    );

    // The same trigger's undelegated read is the admin's, and reads the table.
    let mut admin = plan;
    admin["authority"] = json!("admin");
    assert_eq!(
        ask(&scheduled, admin).await?.as_array().map(Vec::len),
        Some(4)
    );
    Ok(())
}

