//! `db.asImport()`: a code body's writes made **as an import**, against a real
//! database and through the real code runtime.
//!
//! The report this answers: a delta sync written as a `run_js_code` trigger
//! could not stop an application's own audit trigger from stamping `updated_at
//! = now()` on every row it wrote, because the trigger reads `sc.import` and
//! `db.sql()` refuses `set_config`. Under `db.asImport()` every statement runs
//! with `sc.import = '1'`, set with the rest of the caller context, and its
//! writes are one changeset with source `import`, still in the change log.
#![allow(clippy::unwrap_used, clippy::expect_used)]

use std::sync::Arc;

use sc_api::code_host::TableHost;
use sc_api::schema_edit;
use sc_catalog::{Catalog, bootstrap_change_log, bootstrap_field_meta, bootstrap_table_meta};
use sc_db::DatabaseDriver;
use sc_db_postgres::PgDriver;
use sc_error::{Error, Result};
use sc_expr::{CodeCall, CodeRuntime};
use sc_test_harness::TestDb;
use serde_json::json;

/// `items`, with history on, and an application's own audit trigger of the
/// reporter's shape: `updated_at` is stamped on every update unless the
/// transaction says it is an import.
async fn setup(db: &TestDb) -> Result<Arc<Catalog>> {
    db.client()
        .await?
        .batch_execute(
            "CREATE TABLE items (id bigint generated by default as identity primary key,
                                 name text, updated_at timestamptz);
             INSERT INTO items (name, updated_at) VALUES ('a', '2020-01-01T00:00:00Z'),
                                                         ('b', '2020-01-01T00:00:00Z');
             CREATE FUNCTION zz_hub_audit() RETURNS trigger LANGUAGE plpgsql AS $$
             BEGIN
               IF coalesce(current_setting('sc.import', true), '') <> '1' THEN
                 NEW.updated_at := now();
               END IF;
               RETURN NEW;
             END $$;
             CREATE TRIGGER zz_hub_audit BEFORE UPDATE ON items
               FOR EACH ROW EXECUTE FUNCTION zz_hub_audit();",
        )
        .await
        .map_err(|e| Error::database(format!("{e:?}")))?;
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
    db.on_teardown(catalog.teardown_hook());
    bootstrap_table_meta(&catalog).await?;
    bootstrap_field_meta(&catalog).await?;
    bootstrap_change_log(&catalog).await?;
    catalog.reload().await?;
    let op = schema_edit::Operation::AlterTable {
        table: "items".to_owned(),
        settings: schema_edit::TableSettings {
            history_enabled: Some(true),
            ..Default::default()
        },
    };
    schema_edit::apply(&catalog, &[op], &schema_edit::ApplyOptions::default()).await?;
    Ok(catalog)
}

#[tokio::test]
async fn a_write_as_an_import_keeps_its_own_updated_at_and_is_still_recorded() -> Result<()> {
    let db = TestDb::new().await?;
    let cat = setup(&db).await?;
    let host = TableHost::new(&cat);
    let out = CodeRuntime::new()
        .run(CodeCall {
            code: r#"
                const kept = "2024-05-06T07:08:09Z";
                // An ordinary write: the audit trigger stamps it.
                await db.items.where({ id: 1 }).update({ name: "a1", updated_at: kept });
                // As an import, by the chain and by the body's own SQL.
                await db.asImport().items.where({ id: 2 }).update({ name: "b1", updated_at: kept });
                await db.asImport().sql(
                  "update items set name = $1, updated_at = $2::timestamptz where id = $3",
                  ["a2", kept, 1]);
                // One query of a plain handle can say it too.
                await db.items.asImport().insert({ name: "c", updated_at: kept });
                const seen = await db.sql("select coalesce(current_setting('sc.import', true), '') as v");
                const seenImport = await db.asImport().sql(
                  "select coalesce(current_setting('sc.import', true), '') as v");
                return { plain: seen[0].v, imported: seenImport[0].v };
            "#
            .to_owned(),
            host: Some(&host),
            ..CodeCall::default()
        })
        .await?;
    assert_eq!(out, json!({ "plain": "", "imported": "1" }));

    let client = db.client().await?;
    let kept: Vec<(i64, String, bool)> = client
        .query(
            "SELECT id, name, updated_at = '2024-05-06T07:08:09Z'::timestamptz
               FROM items ORDER BY id",
            &[],
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?
        .iter()
        .map(|r| (r.get(0), r.get(1), r.get(2)))
        .collect();
    assert_eq!(
        kept,
        vec![
            // The plain update was stamped; the import over it kept its value.
            (1, "a2".to_owned(), true),
            (2, "b1".to_owned(), true),
            (3, "c".to_owned(), true),
        ]
    );

    // The plain write and the imports are recorded in different changesets:
    // the imports in one, whose source is `import`. Nothing was switched off.
    let recorded: Vec<(String, String, i64)> = client
        .query(
            "SELECT cs.source, c.row_key, count(*)
               FROM _fd_changes c JOIN _fd_changesets cs ON cs.id = c.changeset
              WHERE c.table_name = 'items'
              GROUP BY cs.source, c.row_key ORDER BY cs.source, c.row_key",
            &[],
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?
        .iter()
        .map(|r| (r.get(0), r.get(1), r.get(2)))
        .collect();
    let sources: Vec<&str> = recorded.iter().map(|(s, _, _)| s.as_str()).collect();
    assert!(
        sources.contains(&"import"),
        "the import was recorded: {recorded:?}"
    );
    let imports: Vec<&str> = recorded
        .iter()
        .filter(|(s, _, _)| s == "import")
        .map(|(_, k, _)| k.as_str())
        .collect();
    assert_eq!(imports, vec!["1", "2", "3"], "{recorded:?}");
    let import_changesets: i64 = client
        .query_one(
            "SELECT count(*) FROM _fd_changesets WHERE source = 'import'",
            &[],
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?
        .get(0);
    assert_eq!(import_changesets, 1, "a run's imports are one changeset");
    Ok(())
}
