#[async_trait]
impl ApiProvider for RestProvider {
    fn name(&self) -> &str {
        REST_PROVIDER
    }

    fn mount(&self) -> String {
        self.mount.clone()
    }

    fn endpoints(&self) -> &EndpointSet {
        &self.endpoints
    }

    async fn handle(
        &self,
        req: ApiRequest,
        cat: &Arc<Catalog>,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        match self.dispatch(req, cat, user).await {
            // A signed-in caller who is refused is *forbidden*, not
            // unauthenticated: signing in again would change nothing. The row
            // layer and the invitation rules refuse with `Error::auth` because
            // they sit below any notion of HTTP; this is where it gets one.
            Err(e) if user.is_some() && matches!(e.repr(), Repr::Auth(_)) => {
                Ok(ApiResponse::error(403, e.to_string()))
            }
            other => other,
        }
    }

    async fn run_hook(
        &self,
        name: &str,
        body: Json,
        cat: &Arc<Catalog>,
        user: Option<&User>,
    ) -> Option<Result<ApiResponse>> {
        let query = self.custom_routes.get(name)?;
        let action = query.language.action()?;
        let req = ApiRequest {
            method: Method::Post,
            path: format!("{}{}", self.mount.trim_end_matches('/'), query.path),
            query: Vec::new(),
            body,
            raw: None,
            headers: Vec::new(),
            links: None,
            client_ip: None,
            preview: false,
        };
        Some(self.run_custom_code(query, action, &req, cat, user).await)
    }

    async fn open_stream(
        &self,
        name: &str,
        params: Json,
        client_ip: Option<std::net::IpAddr>,
        recheck: bool,
        cat: &Arc<Catalog>,
        user: Option<&User>,
    ) -> Option<StreamOpening> {
        let query = self.custom_routes.get(name)?;
        if query.response_type != custom::ResponseType::Stream {
            return None;
        }
        let action = query.language.action()?;
        let endpoint = self.endpoints.find(name)?;
        if enforce_auth(&endpoint.auth, user).is_some() {
            return Some(StreamOpening::Denied);
        }
        let req = ApiRequest {
            method: query.method,
            path: format!("{}{}", self.mount.trim_end_matches('/'), query.path),
            query: Vec::new(),
            body: params,
            raw: None,
            headers: Vec::new(),
            links: None,
            client_ip,
            preview: false,
        };
        if !recheck && let Err(limited) = self.custom_rate_limit(query, &req, user) {
            return Some(StreamOpening::RateLimited {
                retry_after: limited.retry_after_secs(),
            });
        }
        let Some(dispatcher) = self.dispatcher.as_ref() else {
            return Some(StreamOpening::Denied);
        };
        let scope = match custom::code_scope(query, &req) {
            Ok(scope) => scope,
            Err(e) => return Some(StreamOpening::Invalid(e.to_string())),
        };
        let caller = ownership::caller_context(user);
        let result = dispatcher
            .run_code(
                cat,
                action,
                &query.name,
                &query.code,
                scope,
                Some(&caller),
                self.application,
                self.file_urls.clone(),
            )
            .await;
        Some(match result {
            Ok(value) => match sc_expr::take_code_response(value) {
                Ok(sc_expr::CodeResponse {
                    stream: Some(stream),
                    ..
                }) => StreamOpening::Granted(stream),
                _ => StreamOpening::Denied,
            },
            // `httpError(...)` is the body's way of saying no; anything else
            // thrown is logged for the author, and the page is told the same.
            Err(e) => {
                if e.http_reply().is_none() {
                    eprintln!(
                        "feldspar: stream query `{}` failed: {}",
                        query.name,
                        e.chain()
                    );
                }
                StreamOpening::Denied
            }
        })
    }
}

impl RestProvider {
    /// Route one request to its handler, the endpoint's auth enforced first.
    async fn dispatch(
        &self,
        req: ApiRequest,
        cat: &Arc<Catalog>,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        let (endpoint, params) = match self.resolve(&req) {
            Ok(found) => found,
            Err(rejection) => return Ok(rejection),
        };

        // Authorization first, always: every API surface goes through the §7
        // layer, and nothing below this line runs until it passes.
        if let Some(rejection) = enforce_auth(&endpoint.auth, user) {
            return Ok(rejection);
        }

        match &endpoint.handler {
            HandlerRef::Named(_) if endpoint.name == LOGIN => self.login(&req, cat).await,
            HandlerRef::Named(_) if endpoint.name == SIGNUP => self.signup(&req, cat).await,
            HandlerRef::Named(_) if endpoint.name == GUEST_SESSION => {
                self.start_guest_session(&req, cat, user).await
            }
            HandlerRef::Named(_) if endpoint.name == INVITE && self.invite_min_role.is_some() => {
                password::invite(&req, cat, user, self.mailer.as_ref()).await
            }
            HandlerRef::Named(_) if endpoint.name == FORGOT_PASSWORD => {
                password::forgot_password(&req, cat, self.mailer.as_ref()).await
            }
            HandlerRef::Named(_) if endpoint.name == SET_PASSWORD => {
                password::set_password(&req, cat).await
            }
            HandlerRef::Named(_) if endpoint.name == LOGOUT => {
                Ok(ApiResponse::end_session(json!({ "ok": true })))
            }
            HandlerRef::Named(_)
                if [SYNC_REGISTER, SYNC_PULL, SYNC_PUSH].contains(&endpoint.name.as_str()) =>
            {
                // `LoggedIn` is enforced above, so a caller is present here.
                let user = user.ok_or_else(|| Error::auth("sign in to sync"))?;
                let application = self.application.ok_or_else(|| {
                    Error::config("offline sync needs the application this API serves")
                })?;
                let evaluator = self.evaluator.as_ref();
                let answer = match endpoint.name.as_str() {
                    SYNC_REGISTER => {
                        crate::sync::register(cat, application, user, &req.body).await?
                    }
                    SYNC_PULL => {
                        crate::sync::pull(
                            cat,
                            application,
                            &self.tables,
                            user,
                            evaluator,
                            &req.body,
                        )
                        .await?
                    }
                    _ => {
                        crate::sync::push(
                            cat,
                            application,
                            &self.tables,
                            user,
                            evaluator,
                            &req.body,
                        )
                        .await?
                    }
                };
                Ok(ApiResponse::ok(answer))
            }
            HandlerRef::Named(_) if endpoint.name == WHOAMI => Ok(ApiResponse::ok(
                // `LoggedIn` is enforced above, so a caller is present here.
                user.map_or(Json::Null, user_summary_json),
            )),
            HandlerRef::Named(_) => match self.routes.get(&endpoint.name) {
                Some(route) => self.run(route, &params, &req, cat, user).await,
                None => match self.trigger_routes.get(&endpoint.name) {
                    Some(trigger) => self.run_trigger(trigger, &req, cat, user).await,
                    // A named handler with no projected route of either kind: the
                    // set was extended with a route this provider cannot run.
                    None => Ok(ApiResponse::error(
                        501,
                        format!("endpoint `{}` has no implementation", endpoint.name),
                    )),
                },
            },
            // Custom routes authored as guest code are carried by the model but
            // not executable yet (design §13.4).
            HandlerRef::GuestCode { language, .. } => Ok(ApiResponse::error(
                501,
                format!("custom {language} routes are not implemented yet"),
            )),
            HandlerRef::Custom(name) => match self.custom_routes.get(name) {
                Some(query) => self.run_custom(query, &req, cat, user).await,
                // A `Sql` endpoint registered by something other than
                // `with_queries` — the set was extended with a route this
                // provider has no query for.
                None => Ok(ApiResponse::error(
                    501,
                    format!("custom query `{name}` has no definition here"),
                )),
            },
        }
    }
}

/// Check a caller against an [`AuthRequirement`], returning a rejection when it
/// does not pass. Mirrors the server's own dispatch check, in the provider's
/// JSON vocabulary.
fn enforce_auth(auth: &AuthRequirement, user: Option<&User>) -> Option<ApiResponse> {
    if auth.admits(user) {
        return None;
    }
    Some(match user {
        None => ApiResponse::error(401, "authentication required"),
        Some(_) => ApiResponse::error(403, "insufficient privilege"),
    })
}

/// A `PathSpec` rooted at the provider's mount.
fn path_at(mount: &str) -> PathSpec {
    PathSpec::root().lit(mount)
}

/// Normalise a mount to a single leading slash and no trailing slash.
fn normalize_mount(raw: &str) -> String {
    let trimmed = raw.trim_matches('/');
    if trimmed.is_empty() {
        "/".to_owned()
    } else {
        format!("/{trimmed}")
    }
}

/// One table as a generated consumer sees it (§13.1): the shape of its rows, so
/// a client can type them, and the keys among them that point at *another*
/// projected table, so an embedded `?select=author(name)` can be typed too.
///
/// `exposed` is the set of table names this API projects. A key into a table
/// outside it keeps its scalar type and gains no relation: the API has no way to
/// read that table, so an embed through the key is not something a caller can
/// ask for here.
fn resource_model(table: &Table, exposed: &std::collections::HashSet<&str>) -> ResourceModel {
    let mut model = ResourceModel::new(&table.name);
    for field in &table.fields {
        // The password hash is no API's (`user_rows`), so no row type has it.
        if crate::user_rows::is_hidden_column(table, &field.base.name) {
            continue;
        }
        let ty = field
            .base
            .type_
            .as_basic()
            .map_or(ValueType::Text, ValueType::from_basic);
        let mut rf = ResourceField::new(&field.base.name, ty);
        rf.required = field.required;
        rf.has_default = field.has_default();
        rf.primary_key = field.primary_key;
        // A calculated field is read on the way out and refused on the way in
        // (`rows::reject_calc_writes`), so it belongs in a row and in no write.
        rf.read_only = matches!(field.kind, DataFieldKind::Calc { .. });
        rf.write_only = field.is_secret();
        if let DataFieldKind::Key { target_table, .. } = &field.kind
            && exposed.contains(target_table.0.as_str())
        {
            rf.references = Some(target_table.0.clone());
        }
        model.fields.push(rf);
    }
    model.synced = table.sync_enabled();
    model
}

/// The endpoint (and generated client method) name for an operation on a table:
/// `list` + `blog_posts` → `listBlogPosts`. Table names are unique, so these are
/// unique too; the result is a valid TypeScript identifier as long as the table
/// name is alphanumeric-ish, which the catalog's own naming already requires.
///
/// Public because generated code has to call these methods by name: `sc-app`'s
/// React scaffold writes hooks that invoke `listTasks`/`createTasks`/…, and
/// recomputing the convention there would be a second copy of it, free to drift
/// from the endpoints the client is actually generated with.
pub fn op_name(op: &str, table: &str) -> String {
    let mut out = String::from(op);
    for word in table
        .split(|c: char| !c.is_alphanumeric())
        .filter(|w| !w.is_empty())
    {
        let mut chars = word.chars();
        if let Some(first) = chars.next() {
            out.extend(first.to_uppercase());
            out.push_str(chars.as_str());
        }
    }
    out
}

