    /// Project the application's **custom SQL queries** (§13.4), one endpoint
    /// each, on top of the table and trigger routes.
    ///
    /// A `Result` rather than a builder that cannot fail, because a name a table
    /// endpoint already holds would otherwise be a panic in a running server:
    /// [`EndpointSet::register`] refuses duplicates, and the collision is
    /// reachable — a table gains a column and is reprojected beside a query an
    /// admin named after it. Saving the application refuses that combination
    /// first ([`custom::validate_custom_queries`]); this is the same rule at the
    /// other end, turning what would be a crash into a mount error naming both.
    pub fn with_queries(mut self, queries: Vec<CustomQuery>) -> Result<RestProvider> {
        for query in queries {
            if self.endpoints.find(&query.name).is_some() {
                return Err(Error::config(format!(
                    "custom query `{}` has the same name as an endpoint this \
                     API already projects; rename the query",
                    query.name
                )));
            }
            self.endpoints
                .register(custom::custom_endpoint(&self.mount, &query));
            self.custom_routes.insert(query.name.clone(), query);
        }
        Ok(self)
    }

    /// Run an admin-authored SQL query (§13.4).
    ///
    /// The endpoint's `MinRole` — the query's own floor, admin unless the admin
    /// said otherwise — was enforced before this ran. What happens here is the
    /// rest of [`custom`]'s authority note: the caller's arguments are coerced
    /// to their declared types and **bound**, the statement runs inside the
    /// caller-context transaction so an RLS-protected table's policies still
    /// decide what it can see, and a `GET` runs `READ ONLY` so a write behind
    /// one fails rather than happening.
    async fn run_custom(
        &self,
        query: &CustomQuery,
        req: &ApiRequest,
        cat: &Catalog,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        if query.response_type == custom::ResponseType::Stream {
            // Opened over the live socket (TODO F7); a fetch of it is a
            // mistake worth naming.
            return Ok(ApiResponse::error(
                400,
                format!(
                    "`{}` opens a live stream; open it over the application's live \
                     socket with the generated client's `{}(params, handlers)`",
                    query.name, query.name
                ),
            ));
        }
        if let Err(limited) = self.custom_rate_limit(query, req, user) {
            return Ok(ApiResponse::too_many_requests(limited));
        }
        if let Some(action) = query.language.action() {
            return self.run_custom_code(query, action, req, cat, user).await;
        }
        let statement = custom::custom_statement(cat, query, req)?;
        let caller = ownership::caller_context(user);
        let rows = if query.read_only() {
            sc_catalog::run_in_context_read_only(cat, &caller, &statement).await
        } else {
            sc_catalog::run_in_context(cat, &caller, &statement).await
        }?;
        Ok(ApiResponse::ok(custom::rows_to_json(&rows)))
    }

    /// Count one call of `query` against its rate limits (TODO F4.3): per
    /// client IP when the transport knows it, and per signed-in user. Both are
    /// hit, so a refused call still counts against the other — a caller over
    /// either limit is turned away, and spending one does not refill the other.
    fn custom_rate_limit(
        &self,
        query: &CustomQuery,
        req: &ApiRequest,
        user: Option<&User>,
    ) -> std::result::Result<(), sc_ratelimit::Limited> {
        let limits = query.effective_rate_limit();
        let scope = format!(
            "query:{}:{}:{}",
            self.application.map(|a| a.to_string()).unwrap_or_default(),
            self.mount,
            query.name
        );
        let limiter = sc_ratelimit::global();
        let mut outcome = Ok(());
        if let (Some(rate), Some(ip)) = (limits.per_ip, req.client_ip) {
            outcome = outcome.and(limiter.hit(&format!("{scope}:ip:{ip}"), rate));
        }
        if let (Some(rate), Some(user)) = (limits.per_user, user) {
            outcome = outcome.and(limiter.hit(&format!("{scope}:user:{}", user.id), rate));
        }
        outcome
    }

    /// Run a JavaScript or Python custom query (§13.4): its body, on the
    /// action a trigger's body of that language runs on, through *the*
    /// dispatcher — so it has the same host surfaces, bounds and authority an
    /// exposed trigger's body has, and the caller travels with it as `user`.
    ///
    /// What the body returns is the response. A body that throws is an error
    /// answer, as an exposed trigger's is: somebody is waiting for this one.
    async fn run_custom_code(
        &self,
        query: &CustomQuery,
        action: &str,
        req: &ApiRequest,
        cat: &Catalog,
        user: Option<&User>,
    ) -> Result<ApiResponse> {
        let dispatcher = self.dispatcher.as_ref().ok_or_else(|| {
            Error::config(format!(
                "custom query `{}` is {} code, but no trigger dispatcher is \
                 available in this context to run it",
                query.name,
                query.language.as_str()
            ))
        })?;
        let scope = custom::code_scope(query, req)?;
        let caller = ownership::caller_context(user);
        let result = dispatcher
            .run_code(
                cat,
                action,
                &query.name,
                &query.code,
                scope,
                Some(&caller),
                self.application,
                self.file_urls.clone(),
            )
            .await;
        let answer = code_answer(result, cat, user).await;
        if req.preview
            && let Ok(response) = &answer
        {
            check_preview_returns(query, response);
        }
        answer
    }

