#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_client_is_generated_against_the_applications_own_mount() {
        let ts = generate_graphql_client("/gql");
        assert!(
            ts.contains(r#"export const GRAPHQL_ENDPOINT = "/gql";"#),
            "{ts}"
        );
        // The mount appears once, so there is nowhere else for a request to go.
        assert_eq!(ts.matches("/gql").count(), 1, "{ts}");
    }

    #[test]
    fn it_carries_the_same_csrf_cookie_and_header_the_rest_client_does() {
        let ts = generate_graphql_client("/graphql");
        assert!(ts.contains(crate::auth::CSRF_COOKIE), "{ts}");
        assert!(ts.contains(crate::auth::CSRF_HEADER), "{ts}");
        assert!(ts.contains(r#"credentials: "same-origin""#), "{ts}");
        // Every GraphQL request is a POST, so — unlike the REST client's — the
        // header is not conditional on the method.
        assert!(ts.contains(r#"method: "POST""#), "{ts}");
    }

    #[test]
    fn it_imports_nothing() {
        // Decision 7: an application's dependencies are the developer's
        // business, so the generated client adds none — not even a type-only
        // import, which would still put a package in `package.json`.
        let ts = generate_graphql_client("/graphql");
        for line in ts.lines() {
            assert!(
                !line.trim_start().starts_with("import "),
                "the generated client should import nothing: {line}"
            );
        }
    }

    #[test]
    fn it_is_generated_deterministically() {
        assert_eq!(
            generate_graphql_client("/graphql"),
            generate_graphql_client("/graphql")
        );
    }
}
