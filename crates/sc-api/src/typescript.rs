// A `select` changes the shape of what comes back, so what a read *returns* is a
// function of the string the caller wrote: `list({ select: "title,author(name)" })`
// answers `{ title, author: { name } }` and nothing else. The types below are
// that function, evaluated by the compiler — which is why there is one `list`
