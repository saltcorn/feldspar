//! TypeScript consumer generation (design §13.1).
//!
//! [`generate_client`] turns an [`EndpointSet`] into a single TypeScript module
//! containing (a) request/response **type declarations** for every endpoint,
//! (b) a **row interface per table** the set carries a
//! [`ResourceModel`](crate::ResourceModel) for, and (c) a typed **API-consumer
//! client** — an `ApiClient` interface plus a `createClient` factory that calls
//! the endpoints over `fetch`. Both the admin UI and every code-framework
//! application get a type-checked client generated this way, so the client
//! cannot drift from the server contract.
//!
//! **A table is one object, not four methods.** An endpoint set that knows which
//! tables are behind it emits `api.tasks.list()` / `.create()` / `.update()` /
//! `.delete()` over a generated `TasksRow`, rather than `listTasks()` … returning
//! `unknown`. Endpoints with no table behind them — the app's own auth, exposed
//! triggers, custom SQL queries — stay loose methods, because that is what they
//! are.
//!
//! **A `select` is typed by the compiler.** `?select=title,author(name)` changes
//! the shape of what comes back, so `list`'s return type is computed *from the
//! select string* (see the `Selected<…>` types this emits). That is why there is
//! one `list` and not one method for rows and another for embeds: the string the
//! caller writes is the one the type is read from.
//!
//! The output is deterministic (endpoints in registration order) and is valid
//! strict-mode TypeScript: the factory's implementation is contextually typed by
//! the `ApiClient` interface, so a mismatch between a declared endpoint and the
//! generated call is a compile error — which is what the type-check test asserts.

