/// The file the generic half of a generated client lives in, beside the
/// `client.ts` that imports it.
///
/// Public because every emitter writes the pair: the scaffold's runtime
/// directory, an app's configured client path, and the two checked-in admin
/// clients all put this next to the client they generate.
pub const CLIENT_HELPER_FILE: &str = "helper.ts";

/// The generic half of a generated client: how a request is made, how a failure
/// is reported, and the types a table's reads are expressed in.
///
/// It is the *same text* for every application — nothing in it depends on an
/// endpoint or a table — so it is a file of its own rather than a hundred lines
/// of preamble in front of the part that is actually about this application.
/// [`generate_client`] imports from it by the name [`CLIENT_HELPER_FILE`].
pub fn client_helper() -> String {
    let mut out = String::new();
    out.push_str("// Code generated by sc-api. DO NOT EDIT.\n");
    out.push_str("// Regenerate with the sc-api TypeScript generator (design §13.1).\n");
    out.push_str(
        "//\n\
         // The half of a generated client that is the same in every application. \
         `client.ts`\n\
         // beside it is the half that is this one's: its endpoints, its tables and \
         their\n\
         // rows.\n\n",
    );
    out.push_str(REQUEST_HELPERS_HEAD);
    // The double-submit CSRF check every mutating request must satisfy (§16).
    // The session cookie is what authenticates a browser client, so the server
    // refuses a state-changing request that does not echo the non-`HttpOnly`
    // CSRF cookie in the header — including `login` itself, which is a POST like
    // any other. Emitting it here rather than leaving it to each consumer is the
    // point: a client generated from the server's own endpoint set should be able
    // to call the server it was generated from.
    //
    // Where there is no `document` — a React Native app on a phone, a node
    // script — there is no cookie to read either, so the token is the one the
    // server last sent in its `x-csrf-token` **response header** (every response
    // carries it; see `sc-server`'s `security` module). `trackCsrf` wraps the
    // client's `fetch` to remember it, so the first request a native app makes —
    // its `whoami` at startup, or even a refused `login` — arms the next one.
    let _ = write!(
        out,
        r#"/** The CSRF token the server last named in a response, for a client that
 * cannot read the cookie. */
let rememberedCsrf: string | undefined;

function csrfToken(): string | undefined {{
  if (typeof document !== "undefined") {{
    for (const part of document.cookie.split(";")) {{
      const [name, ...rest] = part.trim().split("=");
      if (name === "{cookie}") return decodeURIComponent(rest.join("="));
    }}
  }}
  return rememberedCsrf;
}}

/** `fetchImpl`, remembering the CSRF token each response names — how a client
 * with no `document.cookie` learns what its next write must echo.
 *
 * A write refused `403` with a token it did not send is sent **once more** with
 * that token: a native app reopened while still signed in has its session but
 * not the token it remembered, and its first write is how it finds out. */
export function trackCsrf(fetchImpl: typeof fetch): typeof fetch {{
  return (async (input: Parameters<typeof fetch>[0], init?: Parameters<typeof fetch>[1]) => {{
    const res = await fetchImpl(input, init);
    const token = res.headers.get("{header}");
    if (token) rememberedCsrf = token;
    const sent = new Headers(init?.headers).get("{header}");
    if (res.status === 403 && token && token !== sent) {{
      const headers = new Headers(init?.headers);
      headers.set("{header}", token);
      return fetchImpl(input, {{ ...init, headers }});
    }}
    return res;
  }}) as typeof fetch;
}}

/** The headers a request carries: its content type, its CSRF token, and — where
 * there is no `document`, i.e. a native app — that it is not a browser, so the
 * server lets its login outlive the app being closed. */
export function requestHeaders(method: string, hasBody: boolean): Record<string, string> {{
  const headers: Record<string, string> = {{}};
  if (hasBody) headers["content-type"] = "application/json";
  if (typeof document === "undefined") headers["{client_header}"] = "{native}";
  if (method !== "GET" && method !== "HEAD") {{
    const token = csrfToken();
    if (token) headers["{header}"] = token;
  }}
  return headers;
}}

"#,
        cookie = crate::auth::CSRF_COOKIE,
        header = crate::auth::CSRF_HEADER,
        client_header = crate::auth::CLIENT_KIND_HEADER,
        native = crate::auth::NATIVE_CLIENT,
    );
    out.push_str(READ_TYPES);
    out.push_str(LIVE_TYPES);
    out.push_str(LIVE_ROWS);
    out.push_str(UPLOAD_HELPERS);
    out
}

/// The tus client behind `api.uploads.<slot>(file, options)` (TODO F2.11,
/// §2.3): an application's upload slots take a file of any size in resumable
/// chunks, and this is the half of that which runs in the page.
///
/// What it does, deliberately:
///
/// - **Chunks** of `chunkSize` (5 MiB by default), each one `PATCH`, with
///   `onProgress(sent, total)` after every one.
/// - **Resumes across a dropped connection.** A failed chunk — the network, a
///   5xx, an offset the server disagrees with — is followed by a `HEAD` that
///   says what arrived, and the upload goes on from there, up to `retries`
///   failures in a row with a growing pause between them.
/// - **Resumes across a reload.** The upload's URL is remembered in
///   `localStorage` under a fingerprint of the slot and the file (name, size,
///   modification time), so uploading the same file again picks up where the
///   last attempt stopped. Storage that throws (a private window) only costs
///   that.
/// - **Stops on `signal`** without abandoning the upload, so it can be resumed
///   later; an upload the server refused (a 4xx at creation) is not retried.
const UPLOAD_HELPERS: &str = r#"
/** How {@link upload} sends a file. */
export interface UploadOptions {
  /** Called after each chunk: bytes the server has, and the file's size. */
  onProgress?: (sent: number, total: number) => void;
  /** Stops the upload (it stays resumable) and rejects with an `AbortError`. */
  signal?: AbortSignal;
  /** Failed chunks in a row to retry before giving up (default 5). */
  retries?: number;
  /** Bytes per `PATCH` (default 5 MiB). */
  chunkSize?: number;
  /** The name to upload under, when the `Blob` is not a `File` with one. */
  filename?: string;
}

/** A finished upload: where the file is in its store, and the URL it is served
 * at (null when no route of the application serves it). */
export interface UploadResult {
  path: string;
  url: string | null;
}

const TUS_VERSION = "1.0.0";

function uploadAborted(): Error {
  const e = new Error("the upload was stopped");
  e.name = "AbortError";
  return e;
}

/** UTF-8, then base64 — what tus metadata values are. */
function tusValue(value: string): string {
  const bytes = new TextEncoder().encode(value);
  let binary = "";
  for (let i = 0; i < bytes.length; i++) binary += String.fromCharCode(bytes[i]);
  return btoa(binary);
}

function rememberUpload(key: string, location: string | null): void {
  try {
    if (typeof localStorage === "undefined") return;
    if (location === null) localStorage.removeItem(key);
    else localStorage.setItem(key, location);
  } catch {
    // No storage (a private window, a native app): only resuming after a
    // reload is lost.
  }
}

function rememberedUpload(key: string): string | null {
  try {
    return typeof localStorage === "undefined" ? null : localStorage.getItem(key);
  } catch {
    return null;
  }
}

/** `location` against the URL it answered, so a relative `Location` works for
 * a client with an absolute `baseUrl`. */
function resolveLocation(location: string, from: string): string {
  if (/^https?:\/\//.test(location) || !location.startsWith("/")) return location;
  const origin = /^(https?:\/\/[^/]+)/.exec(from);
  return origin ? origin[1] + location : location;
}

function pause(ms: number, signal?: AbortSignal): Promise<void> {
  return new Promise((resolve, reject) => {
    if (signal?.aborted) return reject(uploadAborted());
    const timer = setTimeout(resolve, ms);
    signal?.addEventListener("abort", () => {
      clearTimeout(timer);
      reject(uploadAborted());
    }, { once: true });
  });
}

/** Upload `file` to the upload slot whose create URL is `slotUrl`, resuming
 * after dropped connections and reloads. What `api.uploads.<slot>` calls. */
export async function upload(
  fetchImpl: typeof fetch,
  slotUrl: string,
  file: Blob,
  options: UploadOptions = {},
): Promise<UploadResult> {
  const total = file.size;
  const chunkSize = Math.max(1, options.chunkSize ?? 5 * 1024 * 1024);
  const retries = Math.max(0, options.retries ?? 5);
  const signal = options.signal;
  const named = file as Blob & { name?: string; lastModified?: number };
  const filename = options.filename ?? named.name ?? "upload";
  const fingerprint = `feldspar-upload:${slotUrl}:${filename}:${total}:${named.lastModified ?? ""}`;
  const headers = (method: string, extra: Record<string, string> = {}) => ({
    ...requestHeaders(method, false),
    "tus-resumable": TUS_VERSION,
    ...extra,
  });
  if (signal?.aborted) throw uploadAborted();

  // What the server has of an upload, or null when it no longer knows it.
  const offsetOf = async (location: string): Promise<number | null> => {
    const res = await fetchImpl(location, { method: "HEAD", headers: headers("HEAD"), signal });
    if (!res.ok) return null;
    const offset = Number(res.headers.get("upload-offset"));
    return Number.isFinite(offset) ? offset : null;
  };

  let location = rememberedUpload(fingerprint);
  let offset = 0;
  if (location !== null) {
    const known = await offsetOf(location).catch((e: unknown) => {
      if (signal?.aborted) throw uploadAborted();
      throw e;
    });
    if (known === null) location = null;
    else offset = known;
  }
  if (location === null) {
    const res = await fetchImpl(slotUrl, {
      method: "POST",
      headers: headers("POST", {
        "upload-length": String(total),
        "upload-metadata": `filename ${tusValue(filename)},filetype ${tusValue(file.type || "application/octet-stream")}`,
      }),
      signal,
    });
    if (res.status !== 201) throw await clientError("upload", res);
    const given = res.headers.get("location");
    if (!given) throw new Error("upload failed: the server named no upload URL");
    location = resolveLocation(given, slotUrl);
    rememberUpload(fingerprint, location);
  }
  options.onProgress?.(offset, total);

  let failures = 0;
  for (;;) {
    if (signal?.aborted) throw uploadAborted();
    const end = Math.min(offset + chunkSize, total);
    let res: Response | null = null;
    try {
      res = await fetchImpl(location, {
        method: "PATCH",
        headers: headers("PATCH", {
          "upload-offset": String(offset),
          "content-type": "application/offset+octet-stream",
        }),
        body: file.slice(offset, end),
        signal,
      });
    } catch {
      if (signal?.aborted) throw uploadAborted();
      res = null;
    }
    if (res !== null && res.ok) {
      failures = 0;
      const now = Number(res.headers.get("upload-offset"));
      offset = Number.isFinite(now) ? now : end;
      options.onProgress?.(offset, total);
      if (offset >= total) {
        rememberUpload(fingerprint, null);
        return {
          path: res.headers.get("feldspar-file-path") ?? "",
          url: res.headers.get("feldspar-file-url"),
        };
      }
      continue;
    }
    // A refusal that another try will not change: the slot, the size, the type.
    if (res !== null && res.status >= 400 && res.status < 500 && res.status !== 409 && res.status !== 423) {
      if (res.status === 404) rememberUpload(fingerprint, null);
      throw await clientError("upload", res);
    }
    failures += 1;
    if (failures > retries) {
      throw res === null
        ? new Error("upload failed: the connection kept dropping")
        : await clientError("upload", res);
    }
    await pause(Math.min(500 * 2 ** (failures - 1), 10_000), signal);
    // What arrived before the failure is kept: ask, and go on from there.
    const known = await offsetOf(location).catch(() => null);
    if (known !== null) offset = known;
  }
}
"#;

/// One stream an application exposes to its pages (TODO "Streams" §10, TODO.md
/// "Live updates"), as the client generator needs it: what it is called, where
/// the live socket is, and what an element's `value` looks like.
///
/// A plain value rather than a `sc_stream::Stream`, and deliberately: this
/// crate types an endpoint set, and what it needs from a stream is a name, a
/// path and a shape. The caller that *has* streams — `sc-app`, which resolves
/// the app's declared subset against the stored rows and the provider registry
/// — translates the element type into a [`TypeSchema`] on the way in, which is
/// the same vocabulary every other generated type is written in.
#[derive(Debug, Clone, PartialEq)]
pub struct StreamExport {
    /// The stream's name — what it is subscribed to by, and what its accessor
    /// `live.{name}` is called.
    pub name: String,
    /// The live socket's path on this application, e.g. `/api/live` — the same
    /// for every stream of an application, which holds one socket for all of
    /// them.
    pub path: String,
    /// The shape of the envelope's `value`, from the stream's element type.
    pub value: TypeSchema,
    /// How a page subscribes to it: with no topic, or naming a row.
    pub topics: StreamTopics,
    /// Whether its topics have presence (`live.<s>.join(…)`, L4.4).
    pub presence: bool,
    /// Whether a page may publish on it (`live.<s>.publish(…)`, L4.4) — the
    /// setting; the server still decides per subscriber.
    pub client_publish: bool,
}

impl StreamExport {
    /// The accessor's type: how it is subscribed, and — on a stream whose
    /// settings allow them — joined and published to. `envelope` is the
    /// stream's envelope type.
    fn accessor_type(&self, envelope: &str) -> String {
        if let StreamTopics::Document { root_kind, .. } = &self.topics {
            return format!("LiveDocumentStream<\"{}\">", document_kind(root_kind));
        }
        let row = self.topics == StreamTopics::Row;
        let mut parts = vec![format!(
            "{}<{envelope}>",
            if row { "LiveRowStream" } else { "LiveStream" }
        )];
        if self.presence {
            parts.push(format!(
                "{}<{envelope}>",
                if row {
                    "LiveRowPresence"
                } else {
                    "LivePresence"
                }
            ));
        }
        // A user topic never takes a page's publish (§3 rule 7).
        if self.client_publish && self.topics != StreamTopics::User {
            parts.push(format!(
                "{}<{envelope}>",
                if row { "LiveRowPublish" } else { "LivePublish" }
            ));
        }
        parts.join(" & ")
    }
}

/// How a page names what it subscribes to on a stream (TODO.md "Live updates"
/// §6) — `sc-stream`'s `TopicSpec` as the client generator needs it, in a crate
/// that cannot name that one.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub enum StreamTopics {
    /// No topic: one flow for every subscriber (`live.boiler.subscribe(h)`).
    #[default]
    Single,
    /// The subscriber's own topic, never named (`live.job_status.subscribe(h)`).
    User,
    /// A row's key (`live.board_activity.subscribe(7, h)`).
    Row,
    /// The changes to `table`'s rows, subscribed with the REST read's filter
    /// (`live.cards_live.subscribe({ where: { board: "eq.7" } }, h)`, L3.10).
    /// When the endpoint set reads `table`, the change's row is typed as that
    /// table's row, the filter as its read's `Filters`, and the table's own
    /// object on the client carries the stream as `changes` — which is what
    /// `useLiveRows(api.cards, …)` subscribes through.
    Changes {
        /// The table whose changes the stream carries.
        table: String,
    },
    /// A collaborative document per row (L5.6): the accessor is a
    /// `LiveDocumentStream` that hands a page Yjs updates in base64, and the
    /// generated `live-doc.ts` (which imports `yjs`, as nothing else does)
    /// turns it into a `Y.Doc`. `root` and `root_kind` are the stream's
    /// settings, carried so the binding and the server cannot drift.
    Document {
        /// The root shared type's name.
        root: String,
        /// `text` or `xml`.
        root_kind: String,
    },
}

/// A document stream's root kind as its accessor's type parameter: `xml` or
/// `text`, anything else read as `text`.
fn document_kind(root_kind: &str) -> &'static str {
    if root_kind == "xml" { "xml" } else { "text" }
}

/// Generate a TypeScript client module from an endpoint set.
///
/// The module imports the generic half of itself from [`CLIENT_HELPER_FILE`],
/// which [`client_helper`] emits and every caller writes beside this one.
pub fn generate_client(set: &EndpointSet) -> String {
    generate_client_with_streams(set, &[])
}

/// [`generate_client`] plus `live.{name}` per stream the application exposes
/// (TODO.md "Live updates" §6).
///
/// The socket is **beside** the endpoint set rather than in it: an
/// [`Endpoint`] is a typed request/response pair and a subscription has no
/// shape in that model — the same split the IDE's language server and the admin
/// chat already made. The streams are in the same generated module because that
/// is where the element type earns its keep: an app that declares a stream of
/// `{ temperature: float }` gets a callback whose argument is typed, checked by
/// the same compiler that checks its reads. Every accessor shares the client's
/// one [`LiveConnection`](LIVE_TYPES), so a page that watches three streams
/// holds one socket.
pub fn generate_client_with_streams(set: &EndpointSet, streams: &[StreamExport]) -> String {
    generate_app_client(set, streams, &[])
}

/// One upload slot an application declares (TODO F2.11, §2.3), as the client
/// generator needs it: the method name and the slot's create URL.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct UploadExport {
    /// The slot's name — an identifier, and the method's name under
    /// `api.uploads`.
    pub name: String,
    /// `{mount}/_upload/{name}`, the URL an upload is created at.
    pub path: String,
}

/// [`generate_client_with_streams`] plus `uploads.{name}(file, options)` per
/// upload slot the application declares (TODO F2.11): a resumable tus upload
/// resolving to the stored file's `{ path, url }`.
pub fn generate_app_client(
    set: &EndpointSet,
    streams: &[StreamExport],
    uploads: &[UploadExport],
) -> String {
    let mut out = String::new();

    out.push_str("// Code generated by sc-api. DO NOT EDIT.\n");
    out.push_str("// Regenerate with the sc-api TypeScript generator (design §13.1).\n\n");

    // The endpoints a table speaks for: those appear as that table's own
    // methods, so they get neither a loose method nor per-endpoint types.
    let owned: HashSet<&str> = set
        .resources()
        .flat_map(ResourceModel::endpoint_names)
        .collect();
    let loose: Vec<&Endpoint> = set
        .iter()
        .filter(|e| !owned.contains(e.name.as_str()))
        .collect();
    let tables = table_clients(set, &loose);
    let changes: Vec<Option<ChangesTyping>> = streams
        .iter()
        .map(|stream| ChangesTyping::of(stream, &tables))
        .collect();

    // --- what this client borrows from the helper ---------------------------
    // Exactly what it goes on to name, and nothing more: an import of a helper
    // this client has no use for is a `noUnusedLocals` failure in generated
    // code, about generated code, in somebody else's project.
    let mut values: Vec<&str> = Vec::new();
    if !set.is_empty() {
        values.extend(["clientError", "requestHeaders", "trackCsrf"]);
    } else if !uploads.is_empty() {
        values.push("trackCsrf");
    }
    if !uploads.is_empty() {
        values.push("upload");
    }
    if !streams.is_empty() {
        values.extend(["LiveConnection", "liveUrl"]);
    }
    let mut types: Vec<&str> = vec!["ClientOptions"];
    let is_document = |s: &StreamExport| matches!(s.topics, StreamTopics::Document { .. });
    if streams
        .iter()
        .zip(&changes)
        .any(|(s, typing)| typing.is_none() && s.topics != StreamTopics::Row && !is_document(s))
    {
        types.push("LiveStream");
    }
    if streams.iter().any(is_document) {
        types.push("LiveDocumentStream");
    }
    if streams.iter().any(|s| s.topics == StreamTopics::Row) {
        types.push("LiveRowStream");
    }
    // The presence and publishing halves the accessors' types name.
    let accessors: Vec<String> = streams
        .iter()
        .zip(&changes)
        .filter(|(_, typing)| typing.is_none())
        .map(|(stream, _)| stream.accessor_type("E"))
        .collect();
    for name in [
        "LivePresence",
        "LiveRowPresence",
        "LivePublish",
        "LiveRowPublish",
    ] {
        let named = format!("{name}<");
        if accessors
            .iter()
            .any(|accessor| accessor.split(" & ").any(|part| part.starts_with(&named)))
        {
            types.push(name);
        }
    }
    if changes.iter().any(Option::is_some) {
        types.extend(["LiveChange", "LiveChangesStream", "LiveEnvelope"]);
    }
    if !uploads.is_empty() {
        types.extend(["UploadOptions", "UploadResult"]);
    }
    if !tables.is_empty() {
        types.push("Selected");
        if tables
            .iter()
            .any(|t| t.model.ops.create.is_some() || t.model.ops.update.is_some())
        {
            types.push("Insertable");
        }
        if tables.iter().any(|t| t.model.ops.delete.is_some()) {
            types.push("Deleted");
        }
        if tables.iter().any(|t| !t.model.ops.files.is_empty()) {
            types.push("FileApi");
        }
        for (param, name) in [("filter", "Filters"), ("order", "Order")] {
            if tables.iter().any(|t| t.declares_query_param(set, param)) {
                types.push(name);
            }
        }
    }
    types.sort_unstable();
    let borrowed: Vec<String> = values
        .into_iter()
        .map(str::to_owned)
        .chain(types.into_iter().map(|t| format!("type {t}")))
        .collect();
    let _ = writeln!(
        out,
        "import {{ {} }} from \"./{}\";\n",
        borrowed.join(", "),
        CLIENT_HELPER_FILE.trim_end_matches(".ts")
    );
    // Re-exported so a consumer has one module to import from: the vocabulary a
    // caller writes a read in belongs to the client they are calling, whichever
    // file it is declared in.
    out.push_str("export type { ClientOptions } from \"./helper\";\n");
    if !uploads.is_empty() {
        out.push_str("export type { UploadOptions, UploadResult } from \"./helper\";\n");
    }
    if !streams.is_empty() {
        out.push_str(
            "export { LiveConnection, LiveRows } from \"./helper\";\n\
             export type { LiveChange, LiveChangesQuery, LiveChangesStream, LiveEnvelope, LiveError, \
             LiveHandlers, LiveJoinHandlers, LiveMember, LiveOptions, LivePresence, LivePublish, \
             LiveReady, LiveRoom, LiveRowPresence, LiveRowPublish, LiveRowStream, LiveRowsOptions, \
             LiveRowsState, LiveStatus, LiveStream, LiveSubscription, LiveTable, LiveTopic, \
             LiveValue } from \"./helper\";\n",
        );
    }
    if !tables.is_empty() {
        out.push_str(
            "export type { Deleted, FileApi, FilterOp, FilterValue, Filters, Insertable, Order, \
             OrderKey, Selected, TableSchema } from \"./helper\";\n",
        );
    }
    out.push('\n');

    // --- per-endpoint request/response type declarations --------------------
    // Binary bodies get no named type: the client speaks `BodyInit` (upload) and
    // `Blob` (download) directly, which are the platform's own names for them.
    for ep in &loose {
        let pascal = to_pascal_case(&ep.name);
        if takes_query(ep) {
            let _ = writeln!(out, "export type {pascal}Query = {};", query_type(ep));
        }
        if takes_body(ep) && !ep.binary_input {
            let _ = writeln!(out, "export type {pascal}Request = {};", request_type(ep));
        }
        if !ep.output.is_empty() && !ep.binary_output {
            let _ = writeln!(
                out,
                "export type {pascal}Response = {};",
                ts_type(&ep.output)
            );
        }
    }
    out.push('\n');

    // --- the exposed streams: one envelope type each ------------------------
    // The §4 envelope, field for field, with `value` typed from this stream's
    // element type. It is a wire contract, so it is written out rather than
    // referred to: the same JSON the Observe screen renders and a trigger's
    // `only_if` reads.
    //
    // A stream of a table's changes is the exception: its value is one change
    // to a row, and the row is the table's own row type when the client reads
    // that table — the same type `list` answers with, so a page cannot hold a
    // read's rows and a stream's rows as two different things.
    for (stream, typing) in streams.iter().zip(&changes) {
        if let Some(typing) = typing {
            let _ = writeln!(
                out,
                "/** One change of the `{}` stream (rows of `{}`), in its envelope. */\n\
                 export type {}Envelope = LiveEnvelope<LiveChange<{}, {}>>;\n",
                stream.name,
                typing.table,
                stream_type_name(&stream.name),
                typing.row,
                typing.key_type,
            );
            continue;
        }
        let _ = writeln!(
            out,
            "/** One element of the `{}` stream, in its envelope. */\n\
             export type {}Envelope = {{\n\
             \x20 stream: string;\n\
             \x20 /** The topic it was published on, for a stream with topics. */\n\
             \x20 topic?: string;\n\
             \x20 value: {};\n\
             \x20 /** When *this server* saw it — not a claim about when it was produced. */\n\
             \x20 received_at: string;\n\
             \x20 /** The provider's own metadata (MQTT's topic, QoS, retain), absent when it has none. */\n\
             \x20 source?: unknown;\n\
             }};\n",
            stream.name,
            stream_type_name(&stream.name),
            element_value_type(&stream.value),
        );
    }
    if !streams.is_empty() {
        out.push_str("/** The streams this application exposes, one accessor each. */\n");
        out.push_str("export interface LiveStreams {\n");
        for (stream, typing) in streams.iter().zip(&changes) {
            if let Some(typing) = typing {
                let _ = writeln!(
                    out,
                    "  /** The `{}` stream: changes to `{}`, subscribed with a read's filter. */\n  \
                     readonly {}: LiveChangesStream<{}, {}>;",
                    stream.name, typing.table, stream.name, typing.schema, typing.key_type,
                );
                continue;
            }
            let what = match stream.topics {
                StreamTopics::Single | StreamTopics::Changes { .. } => "stream",
                StreamTopics::User => "stream; each subscriber gets their own topic",
                StreamTopics::Row => "stream; subscribe naming a row's key",
                StreamTopics::Document { .. } => {
                    "document stream; open one row's document with `live-doc.ts`"
                }
            };
            let _ = writeln!(
                out,
                "  /** The `{}` {what}. */\n  readonly {}: {};",
                stream.name,
                stream.name,
                stream.accessor_type(&format!("{}Envelope", stream_type_name(&stream.name))),
            );
        }
        out.push_str("}\n\n");
    }

    // --- the tables: a row type and an object of methods each ---------------
    for table in &tables {
        out.push_str(&table.types(set, table_changes(table, streams, &changes).as_ref()));
    }

    // --- ApiClient interface ------------------------------------------------
    out.push_str("export interface ApiClient {\n");
    for ep in &loose {
        let _ = writeln!(out, "  {};", method_signature(ep));
        if let Some(sig) = url_helper_signature(ep) {
            let _ = writeln!(out, "  {sig};");
        }
    }
    for table in &tables {
        let _ = writeln!(out, "  /** The `{}` table. */", table.model.name);
        let _ = writeln!(out, "  {}: {}Api;", table.property, table.pascal);
    }
    if !streams.is_empty() {
        out.push_str(
            "  /** The streams this application exposes, over one live socket opened on first use. */\n\
             \x20 live: LiveStreams;\n",
        );
    }
    if !uploads.is_empty() {
        out.push_str(
            "  /** The application's upload slots: resumable uploads of any size the slot allows. */\n  uploads: {\n",
        );
        for slot in uploads {
            let _ = writeln!(
                out,
                "    /** Upload a file to the `{}` slot, resuming after a dropped connection. */\n    {}(file: Blob, options?: UploadOptions): Promise<UploadResult>;",
                slot.name, slot.name
            );
        }
        out.push_str("  };\n");
    }
    out.push_str("}\n\n");

    // An application that enables no API provider has an empty endpoint set, and
    // a client with nothing to call: the factory is still there, so the code
    // importing it still compiles, and it returns nothing because there is
    // nothing to return.
    if set.is_empty() && streams.is_empty() && uploads.is_empty() {
        out.push_str(
            "export function createClient(_options: ClientOptions = {}): ApiClient {\n             \x20 // This application enables no API provider, so it has no endpoints.\n             \x20 return {};\n             }\n",
        );
        return out;
    }

    out.push_str("export function createClient(options: ClientOptions = {}): ApiClient {\n");
    out.push_str("  const baseUrl = options.baseUrl ?? \"\";\n");
    // An application that exposes only streams never calls `fetch`, and an
    // unused binding is a `noUnusedLocals` error in somebody else's project.
    if !set.is_empty() || !uploads.is_empty() {
        out.push_str("  const doFetch = trackCsrf(options.fetch ?? fetch);\n");
    }
    // One connection for every stream, opened on the first `subscribe`: a page
    // that never subscribes never connects.
    if let Some(stream) = streams.first() {
        let _ = writeln!(
            out,
            "  const connection = new LiveConnection(liveUrl(baseUrl, \"{}\"), options.live);",
            stream.path,
        );
    }
    // The accessors are bound before the tables, because a table whose changes
    // the application exposes carries its stream as `changes` — the same object
    // as `live.<stream>`.
    //
    // A stream's name is letters, digits and `_`, never starting with a digit
    // (`check_stream_name`), so it is a property name as it stands.
    if !streams.is_empty() {
        out.push_str("  const live: LiveStreams = {\n");
        for (stream, typing) in streams.iter().zip(&changes) {
            if let Some(typing) = typing {
                let _ = writeln!(
                    out,
                    "    {}: connection.changesStream<{}, {}>(\"{}\", \"{}\", \"{}\"),",
                    stream.name,
                    typing.schema,
                    typing.key_type,
                    stream.name,
                    typing.table,
                    typing.key_column,
                );
                continue;
            }
            if let StreamTopics::Document { root, root_kind } = &stream.topics {
                let _ = writeln!(
                    out,
                    "    {}: connection.documentStream<\"{}\">(\"{}\", {}, \"{}\"),",
                    stream.name,
                    document_kind(root_kind),
                    stream.name,
                    serde_json::Value::String(root.clone()),
                    document_kind(root_kind),
                );
                continue;
            }
            let accessor = match stream.topics {
                StreamTopics::Single
                | StreamTopics::User
                | StreamTopics::Changes { .. }
                | StreamTopics::Document { .. } => "stream",
                StreamTopics::Row => "rowStream",
            };
            let _ = writeln!(
                out,
                "    {}: connection.{accessor}<{}Envelope>(\"{}\"),",
                stream.name,
                stream_type_name(&stream.name),
                stream.name,
            );
        }
        out.push_str("  };\n");
    }
    // Each table is bound to a name before the client is assembled, so `get` can
    // call `list` without going through `this` — a generated method's `this` is
    // whatever the caller destructured it onto, which is nothing worth relying on.
    for table in &tables {
        out.push_str(&table.implementation(set, table_changes(table, streams, &changes).as_ref()));
    }
    out.push_str("  return {\n");
    for ep in &loose {
        emit_method_impl(&mut out, ep);
        emit_url_helper_impl(&mut out, ep);
    }
    for table in &tables {
        let _ = writeln!(out, "    {},", table.property);
    }
    if !streams.is_empty() {
        out.push_str("    live,\n");
    }
    if !uploads.is_empty() {
        out.push_str("    uploads: {\n");
        for slot in uploads {
            let _ = writeln!(
                out,
                "      {}: (file: Blob, opts?: UploadOptions) => upload(doFetch, `${{baseUrl}}{}`, file, opts),",
                slot.name, slot.path
            );
        }
        out.push_str("    },\n");
    }
    out.push_str("  };\n");
    out.push_str("}\n");

    out
}

/// The `ApiClient` interface signature for one endpoint, e.g.
/// `listRows(table: string): Promise<ListRowsResponse>`.
fn method_signature(ep: &Endpoint) -> String {
    let pascal = to_pascal_case(&ep.name);
    let mut params: Vec<String> = ep
        .path
        .params()
        .map(|(name, ty)| format!("{name}: {}", ty.ts_type()))
        .collect();
    if ep.binary_input {
        // An upload takes whatever `fetch` can send raw: a `Blob`/`File` from an
        // `<input type=file>`, an `ArrayBuffer`, a string.
        params.push("body: BodyInit".to_owned());
    } else if takes_body(ep) {
        let opt = if body_arg_optional(ep) { "?" } else { "" };
        params.push(format!("body{opt}: {pascal}Request"));
    }
    // The query parameters arrive as one options object, last — and the argument
    // itself is optional when every parameter in it is, so declaring a `select`
    // nobody has to pass does not put an empty `{}` at every call site.
    if takes_query(ep) {
        let opt = if query_arg_optional(ep) { "?" } else { "" };
        params.push(format!("{QUERY_ARG}{opt}: {pascal}Query"));
    }
    let ret = if ep.binary_output {
        "Blob".to_owned()
    } else if ep.output.is_empty() {
        "void".to_owned()
    } else {
        format!("{pascal}Response")
    };
    format!("{}({}): Promise<{ret}>", ep.name, params.join(", "))
}

/// Emit the factory's implementation of one endpoint method.
fn emit_method_impl(out: &mut String, ep: &Endpoint) {
    let pascal = to_pascal_case(&ep.name);
    let mut param_names: Vec<String> = ep.path.params().map(|(n, _)| n.to_owned()).collect();
    if takes_body(ep) {
        param_names.push("body".to_owned());
    }
    if takes_query(ep) {
        param_names.push(QUERY_ARG.to_owned());
    }

    let _ = writeln!(out, "    async {}({}) {{", ep.name, param_names.join(", "));
    let result = if ep.binary_output {
        Returns::Blob
    } else if ep.output.is_empty() {
        Returns::Nothing
    } else {
        Returns::Json(format!("{pascal}Response"))
    };
    emit_request(out, ep, &Request::new(&result));
    out.push_str("    },\n");
}

/// Whether an endpoint gets a `<name>Url(params)` helper beside its method: a
/// `GET` that answers with bytes or a file (TODO F2.10), whose URL is what an
/// `<img src>`, a `<video>` or a download link wants.
fn has_url_helper(ep: &Endpoint) -> bool {
    ep.binary_output && ep.method == Method::Get
}

/// The interface signature of an endpoint's URL helper, e.g.
/// `shareFileUrl(query?: ShareFileQuery): string`.
fn url_helper_signature(ep: &Endpoint) -> Option<String> {
    if !has_url_helper(ep) {
        return None;
    }
    let pascal = to_pascal_case(&ep.name);
    let mut params: Vec<String> = ep
        .path
        .params()
        .map(|(name, ty)| format!("{name}: {}", ty.ts_type()))
        .collect();
    if takes_query(ep) {
        let opt = if query_arg_optional(ep) { "?" } else { "" };
        params.push(format!("{QUERY_ARG}{opt}: {pascal}Query"));
    }
    Some(format!("{}Url({}): string", ep.name, params.join(", ")))
}

/// Emit the factory's implementation of an endpoint's URL helper: the URL the
/// method itself would fetch, built the same way.
fn emit_url_helper_impl(out: &mut String, ep: &Endpoint) {
    if !has_url_helper(ep) {
        return;
    }
    let mut param_names: Vec<String> = ep.path.params().map(|(n, _)| n.to_owned()).collect();
    if takes_query(ep) {
        param_names.push(QUERY_ARG.to_owned());
    }
    let _ = writeln!(out, "    {}Url({}) {{", ep.name, param_names.join(", "));
    let pad = "      ";
    emit_query_encoding(out, ep, pad);
    let suffix = if takes_query(ep) {
        "${qs ? `?${qs}` : \"\"}"
    } else {
        ""
    };
    let _ = writeln!(
        out,
        "{pad}return `${{baseUrl}}{}{suffix}`;",
        url_template(ep)
    );
    out.push_str("    },\n");
}

/// What a generated method does with the response body.
enum Returns {
    /// Read it as JSON and assert it is this type.
    Json(String),
    /// Read it as bytes.
    Blob,
    /// Read nothing.
    Nothing,
}

/// How one generated method calls its endpoint: what it does with the answer,
/// what it sends as the body, and how far in the statements are indented (a
/// table's file column nests one object deeper than everything else).
struct Request<'a> {
    result: &'a Returns,
    /// The expression the request body is taken from.
    body: &'a str,
    /// The indentation of the method's statements, in spaces.
    indent: usize,
}

impl<'a> Request<'a> {
    /// A call from a method of the returned client object: body in `body`,
    /// statements six spaces in.
    fn new(result: &'a Returns) -> Request<'a> {
        Request {
            result,
            body: "body",
            indent: 6,
        }
    }

    /// The same call, sending `body` and indented `indent` spaces.
    fn from(mut self, body: &'a str, indent: usize) -> Request<'a> {
        self.body = body;
        self.indent = indent;
        self
    }
}

/// Emit a method's body: query encoding, the `fetch` call, the error check and
/// the return. Shared by loose endpoint methods and a table's own, which differ
/// only in the signature above them and the type asserted below.
fn emit_request(out: &mut String, ep: &Endpoint, req: &Request<'_>) {
    let pad = " ".repeat(req.indent);
    emit_query_encoding(out, ep, &pad);
    let suffix = if !takes_query(ep) {
        ""
    } else {
        // Nested template literal: the `?` disappears with the last parameter,
        // so an all-optional options object that was left empty produces exactly
        // the URL the endpoint had before it declared any.
        "${qs ? `?${qs}` : \"\"}"
    };
    let _ = writeln!(
        out,
        "{pad}const res = await doFetch(`${{baseUrl}}{}{suffix}`, {{",
        url_template(ep)
    );
    let _ = writeln!(out, "{pad}  method: \"{}\",", ep.method.as_str());
    let has_body = takes_body(ep);
    // A binary body goes out as-is with no JSON content type — `fetch` derives
    // one from a `Blob` itself — so `hasBody` is false for the header helper
    // (which only decides the JSON content type; CSRF rides on the method).
    let _ = writeln!(
        out,
        "{pad}  headers: requestHeaders(\"{}\", {}),",
        ep.method.as_str(),
        has_body && !ep.binary_input
    );
    if ep.binary_input && req.body == "body" {
        // The parameter is already called `body`, which is the property's name.
        let _ = writeln!(out, "{pad}  body,");
    } else if ep.binary_input {
        let _ = writeln!(out, "{pad}  body: {},", req.body);
    } else if has_body && body_arg_optional(ep) {
        // An open body nobody has to pass: an omitted one is sent as `{}`.
        let _ = writeln!(out, "{pad}  body: JSON.stringify({} ?? {{}}),", req.body);
    } else if has_body {
        let _ = writeln!(out, "{pad}  body: JSON.stringify({}),", req.body);
    }
    let _ = writeln!(out, "{pad}}});");
    let _ = writeln!(
        out,
        "{pad}if (!res.ok) throw await clientError(\"{}\", res);",
        ep.name
    );
    match req.result {
        Returns::Blob => {
            let _ = writeln!(out, "{pad}return await res.blob();");
        }
        Returns::Nothing => {
            let _ = writeln!(out, "{pad}return;");
        }
        Returns::Json(ty) => {
            let _ = writeln!(out, "{pad}return (await res.json()) as {ty};");
        }
    }
}

/// Emit the `URLSearchParams` construction for an endpoint's query parameters.
///
/// Encoding is `URLSearchParams`'s, not a hand-rolled concatenation: a filter
/// value legitimately contains `&`, `=`, `+` and spaces (`title=eq.rock & roll`),
/// and a client that pasted those into the URL would send a *different* query
/// than the caller wrote. A repeated parameter appends once per element, which
/// is what makes `?published=gte.…&published=lt.…` expressible at all.
fn emit_query_encoding(out: &mut String, ep: &Endpoint, pad: &str) {
    if !takes_query(ep) {
        return;
    }
    if open_query(ep) {
        // An open options object: every key the caller set is a parameter,
        // declared or not. A code query's declared parameters are scalars, so
        // one pair per key covers them too.
        let base = if query_arg_optional(ep) {
            format!("{QUERY_ARG} ?? {{}}")
        } else {
            QUERY_ARG.to_owned()
        };
        let _ = writeln!(out, "{pad}const search = new URLSearchParams();");
        let _ = writeln!(
            out,
            "{pad}for (const [key, value] of Object.entries({base})) \
             if (value !== undefined && value !== null) search.append(key, String(value));"
        );
        let _ = writeln!(out, "{pad}const qs = search.toString();");
        return;
    }
    // When the whole options object is optional the caller may have omitted it,
    // so every read goes through `?.`.
    let base = if query_arg_optional(ep) {
        format!("{QUERY_ARG}?.")
    } else {
        format!("{QUERY_ARG}.")
    };
    let _ = writeln!(out, "{pad}const search = new URLSearchParams();");
    for p in &ep.query {
        let name = &p.name;
        if p.map {
            // The caller's own keys, each becoming a pair of its own — a filter
            // map is `?published=gte.2020-01-01`, not `?filter=…`.
            let _ = writeln!(
                out,
                "{pad}for (const [key, value] of Object.entries({base}{name} ?? {{}})) \
                 search.append(key, String(value));"
            );
        } else if p.repeated {
            let _ = writeln!(
                out,
                "{pad}for (const value of {base}{name} ?? []) search.append(\"{name}\", String(value));"
            );
        } else if p.required {
            // A required parameter implies the options object is required too,
            // so `base` is a plain `.` here and the value is always there.
            let _ = writeln!(out, "{pad}search.append(\"{name}\", String({base}{name}));");
        } else {
            // `null` as well as `undefined`: a caller threading a nullable value
            // through means "no value", and `String(null)` would send "null".
            let _ = writeln!(
                out,
                "{pad}if ({base}{name} !== undefined && {base}{name} !== null) \
                 search.append(\"{name}\", String({base}{name}));"
            );
        }
    }
    let _ = writeln!(out, "{pad}const qs = search.toString();");
}

/// The TypeScript type of an endpoint's query options object.
fn query_type(ep: &Endpoint) -> String {
    let members: Vec<String> = ep
        .query
        .iter()
        .map(|p| {
            let ty = if p.map {
                format!("Record<string, {}>", p.ty.ts_type())
            } else if p.repeated {
                format!("Array<{}>", p.ty.ts_type())
            } else {
                p.ty.ts_type().to_owned()
            };
            let opt = if p.required { "" } else { "?" };
            format!("{}{opt}: {ty}", p.name)
        })
        .collect();
    open_type(
        &format!("{{ {} }}", members.join("; ")),
        members.is_empty(),
        open_query(ep),
    )
}

/// The TypeScript type of an endpoint's JSON request body.
fn request_type(ep: &Endpoint) -> String {
    open_type(&ts_type(&ep.input), ep.input.is_empty(), open_body(ep))
}

/// `declared`, widened to take any other key when the arguments are open:
/// `{ a: number } & Record<string, unknown>`, or just the record when nothing
/// was declared.
fn open_type(declared: &str, nothing_declared: bool, open: bool) -> String {
    match (open, nothing_declared) {
        (false, _) => declared.to_owned(),
        (true, true) => "Record<string, unknown>".to_owned(),
        (true, false) => format!("{declared} & Record<string, unknown>"),
    }
}

/// Whether the endpoint's open arguments travel as a JSON body (every method
/// that has one).
fn open_body(ep: &Endpoint) -> bool {
    ep.open_args && ep.method.has_body()
}

/// Whether the endpoint's open arguments travel in the query string (`GET`,
/// `DELETE`).
fn open_query(ep: &Endpoint) -> bool {
    ep.open_args && !ep.method.has_body()
}

/// Whether the generated method takes a `body` argument.
fn takes_body(ep: &Endpoint) -> bool {
    ep.binary_input || !ep.input.is_empty() || open_body(ep)
}

/// Whether the generated method takes a `query` options argument.
fn takes_query(ep: &Endpoint) -> bool {
    !ep.query.is_empty() || open_query(ep)
}

/// Whether the `body` argument may be omitted — an open body none of whose
/// declared fields is required.
fn body_arg_optional(ep: &Endpoint) -> bool {
    open_body(ep)
        && match &ep.input {
            TypeSchema::Struct(fields) => fields
                .iter()
                .all(|f| matches!(f.schema, TypeSchema::Optional(_))),
            _ => false,
        }
}

/// Whether the options argument itself may be omitted — true when no query
/// parameter is required.
fn query_arg_optional(ep: &Endpoint) -> bool {
    !ep.query.iter().any(|p| p.required)
}

/// The name of the generated methods' query-options argument.
const QUERY_ARG: &str = "query";

/// The request URL as a JS template-literal body (path params interpolated and
/// escaped), e.g. `/api/tables/${encodeURIComponent(table)}/rows/${encodeURIComponent(id)}`.
///
/// Escaped because a name is free text: an agent called `Admin copilot`, or a
/// view with a `#` or `/` in it, must arrive as one segment. The server decodes
/// every path parameter before a handler sees it.
fn url_template(ep: &Endpoint) -> String {
    let mut out = String::from("/");
    for (i, seg) in ep.path.segments.iter().enumerate() {
        if i > 0 {
            out.push('/');
        }
        match seg {
            PathSegment::Literal(s) => out.push_str(s),
            PathSegment::Param { name, .. } => {
                let _ = write!(out, "${{encodeURIComponent({name})}}");
            }
        }
    }
    out
}

/// Render a [`TypeSchema`] as an inline TypeScript type.
fn ts_type(schema: &TypeSchema) -> String {
    match schema {
        TypeSchema::Value(v) => v.ts_type().to_owned(),
        TypeSchema::Struct(fields) if fields.is_empty() => "Record<string, never>".to_owned(),
        TypeSchema::Struct(fields) => {
            let members: Vec<String> = fields
                .iter()
                .map(|f| match &f.schema {
                    // An optional field is both `?`-optional and `| null`.
                    TypeSchema::Optional(inner) => {
                        format!("{}?: {} | null", f.name, ts_type(inner))
                    }
                    other => format!("{}: {}", f.name, ts_type(other)),
                })
                .collect();
            format!("{{ {} }}", members.join("; "))
        }
        TypeSchema::Array(inner) => format!("Array<{}>", ts_type(inner)),
        TypeSchema::Optional(inner) => format!("{} | null", ts_type(inner)),
    }
}

/// The TypeScript for an element's `value` — [`ts_type`], but a declared key
/// that may be null is `name: T | null` rather than `name?: T | null`.
///
/// The difference is §4's promise and it is worth the eight lines: **a declared
/// key that is absent is `null`**, so an element of a stream that declared five
/// keys has five keys. `?` would say the property might not be there, which is
/// true of a request body's optional field and false of every element that ever
/// arrives here — and it would make every consumer write `?? null` for a case
/// the server has already ruled out.
fn element_value_type(schema: &TypeSchema) -> String {
    match schema {
        TypeSchema::Struct(fields) if !fields.is_empty() => {
            let members: Vec<String> = fields
                .iter()
                .map(|f| format!("{}: {}", f.name, ts_type(&f.schema)))
                .collect();
            format!("{{ {} }}", members.join("; "))
        }
        other => ts_type(other),
    }
}

/// Convert a `camelCase` operation name to `PascalCase` for type names.
/// The prefix a stream's types are named with: its name in PascalCase,
/// `job_status` → `JobStatus`, so its envelope is `JobStatusEnvelope`. A stream
/// name is letters, digits and `_` (`check_stream_name`), so splitting on `_`
/// is the whole of it; a name that is all underscores keeps one, to stay a name.
fn stream_type_name(name: &str) -> String {
    let joined: String = name
        .split('_')
        .filter(|part| !part.is_empty())
        .map(to_pascal_case)
        .collect();
    if joined.is_empty() {
        "_".to_owned()
    } else {
        joined
    }
}

fn to_pascal_case(name: &str) -> String {
    let mut chars = name.chars();
    match chars.next() {
        Some(first) => first.to_uppercase().collect::<String>() + chars.as_str(),
        None => String::new(),
    }
}

// --- table changes ----------------------------------------------------------

/// How a stream of a table's changes is typed in the client (L3.10).
struct ChangesTyping {
    /// The table the changes are to.
    table: String,
    /// The `TableSchema` its filter and rows are read against: `CardsSchema`
    /// when the client reads the table, else one written inline from the
    /// element type — a stream exposed by an app with no REST read of the
    /// table still types its rows; it just has nothing to refetch with.
    schema: String,
    /// The row type a change carries.
    row: String,
    /// The primary key's TypeScript type, `LiveTopic` when it is not known.
    key_type: String,
    /// The primary key's column, which a change's `key` is a value of — empty
    /// when the client does not read the table. Only `useLiveRows` needs it,
    /// and that needs the table's read anyway.
    key_column: String,
}

impl ChangesTyping {
    /// The typing of `stream`, or `None` when it is not a stream of changes.
    fn of(stream: &StreamExport, tables: &[TableClient<'_>]) -> Option<ChangesTyping> {
        let StreamTopics::Changes { table } = &stream.topics else {
            return None;
        };
        if let Some(client) = tables.iter().find(|t| &t.model.name == table) {
            return Some(ChangesTyping {
                table: table.clone(),
                schema: format!("{}Schema", client.pascal),
                row: format!("{}Row", client.pascal),
                key_type: client.key_type().unwrap_or("LiveTopic").to_owned(),
                key_column: client.model.primary_key.clone().unwrap_or_default(),
            });
        }
        let row = change_row_type(&stream.value);
        Some(ChangesTyping {
            table: table.clone(),
            schema: format!("{{ row: {row}; rels: {{}} }}"),
            row,
            key_type: "LiveTopic".to_owned(),
            key_column: String::new(),
        })
    }
}

/// The row of a change's element type (`{op, key, row}`) as TypeScript: the
/// table's columns as the provider derived them.
fn change_row_type(value: &TypeSchema) -> String {
    let TypeSchema::Struct(fields) = value else {
        return "Record<string, unknown>".to_owned();
    };
    match fields.iter().find(|f| f.name == "row").map(|f| &f.schema) {
        Some(TypeSchema::Optional(inner)) => element_value_type(inner),
        Some(row @ TypeSchema::Struct(_)) => element_value_type(row),
        _ => "Record<string, unknown>".to_owned(),
    }
}

/// A table's own stream of changes, which its object on the client carries.
struct TableChanges<'a> {
    stream: &'a str,
    typing: &'a ChangesTyping,
}

/// The stream `table` carries as `changes`, if the application exposes one:
/// the first in the order the application lists them, when it exposes more.
fn table_changes<'a>(
    table: &TableClient<'_>,
    streams: &'a [StreamExport],
    changes: &'a [Option<ChangesTyping>],
) -> Option<TableChanges<'a>> {
    streams.iter().zip(changes).find_map(|(stream, typing)| {
        let typing = typing.as_ref()?;
        (typing.table == table.model.name && !typing.key_column.is_empty()).then_some(
            TableChanges {
                stream: &stream.name,
                typing,
            },
        )
    })
}

