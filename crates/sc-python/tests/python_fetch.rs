//! `fetch` from a **Python** body, against a real socket and the real action
//! (phase 3.1 and 3.5).
//!
//! `python_db_live.rs`'s argument, applied to the second surface: what can be
//! wrong here is what was sent and what was made of the reply, and a mocked
//! client would assert those about a request that never happened. So this file
//! holds the production pieces — the `run_python_code` action from the registry,
//! the five hosts it builds from an `ActionContext`, `CodeFetchHost` and its
//! `reqwest` client — and a one-shot listener that reports the bytes it read.
//! It is `sc-core-actions/tests/code_fetch.rs` question for question, in the
//! other language, because the `FetchHost` under both is the same one.
//!
//! Asserted here: a body's GET and POST arrive as written; the response's
//! status, headers and JSON come back; a non-2xx is a value rather than an
//! exception, so a retry is something the body writes; a request the endpoint
//! never answers fails inside the body's own time limit and is catchable as a
//! `FetchError`; bytes that are not text arrive as `bytes`; the fetch budget's
//! refusal names the bound; and a body with no network at all says so as a
//! `NameError`.

