/// Authors, their books, an audit table for a trigger to write into, and notes
/// an ownership formula divides — `run_js_code.rs`'s tables, so the two suites
/// ask their questions of the same rows.
const SCHEMA: &str = "\
    CREATE TABLE authors (id bigint generated by default as identity primary key, \
        name text, tier text); \
    CREATE TABLE books (id bigint generated by default as identity primary key, \
        title text not null, pages bigint, author bigint references authors(id)); \
    CREATE TABLE audit (id bigint generated by default as identity primary key, \
        what text, who text); \
    CREATE TABLE notes (id bigint generated by default as identity primary key, \
        what text, owner text); \
    INSERT INTO authors (name, tier) VALUES ('Ada', 'gold'), ('Bob', 'silver'); \
    INSERT INTO books (title, pages, author) VALUES \
        ('Dune', 412, 1), \
        ('Emma', 474, 1), \
        ('Ficciones', 174, 2), \
        ('Solaris', NULL, 2); \
    INSERT INTO notes (what, owner) VALUES \
        ('ada one', 'ada@example.com'), \
        ('bob one', 'bob@example.com'), \
        ('ada two', 'ada@example.com');";

/// The caller every body here runs on behalf of: ada, at a role well below
/// admin, so `as_user()` has something to be different from.
fn ada() -> Json {
    json!({
        "id": "6b1c2d64-3f3a-4a52-9a8b-0f4d2b7f1a11",
        "role": 40,
        "email": "ada@example.com",
    })
}

/// The database, the catalog, and the JavaScript engine an ownership formula is
/// decided on.
struct Live {
    catalog: Arc<Catalog>,
    evaluator: Arc<dyn JsEvaluator>,
    db: TestDb,
}

impl Live {
    async fn new() -> Result<Live> {
        let db = TestDb::new().await?;
        db.client()
            .await?
            .batch_execute(SCHEMA)
            .await
            .map_err(|e| Error::database(e.to_string()))?;
        let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
        let catalog = Arc::new(Catalog::init(driver as Arc<dyn DatabaseDriver>).await?);
        Ok(Live {
            catalog,
            evaluator: Arc::new(DenoEvaluator::new()) as Arc<dyn JsEvaluator>,
            db,
        })
    }

    /// `owner === user.email` live on `notes`, which is what `as_user()` has to
    /// obey and what the body's own authority does not.
    async fn own_the_notes(&self) -> Result<()> {
        bootstrap_table_meta(&self.catalog).await?;
        let mut notes = TableMeta::new("notes");
        notes.set_ownership_formula(Some("owner === user.email"));
        save_table_meta(&self.catalog, &notes).await?;
        assert!(
            self.catalog.require("notes")?.ownership.is_some(),
            "the formula is live"
        );
        Ok(())
    }

    /// The host an action builds for one run: this catalog, caused by ada, with
    /// the formula engine behind a delegated read.
    fn host(&self) -> TableHost<'_> {
        TableHost::new(&self.catalog)
            .caused_by(40, Some(ada()))
            .with_evaluator(Some(Arc::clone(&self.evaluator)))
    }

    /// Run a Python body over that host and answer what it returned.
    async fn run(&self, code: &str) -> Result<Json> {
        let host = self.host();
        PythonRuntime::new()
            .run(CodeCall {
                code: code.to_owned(),
                host: Some(&host as &dyn sc_expr::CodeHost),
                bindings: [("payload".to_owned(), json!({ "least": 200 }))]
                    .into_iter()
                    .collect(),
                ..CodeCall::default()
            })
            .await
    }

    /// The same, for a body that is meant to fail: the message it failed with.
    async fn fails(&self, code: &str) -> String {
        self.run(code)
            .await
            .expect_err("this body was supposed to fail")
            .to_string()
    }

    /// The same question as a **JavaScript** body, on the engine that runs one —
    /// phase 2.7's other half.
    async fn run_js(&self, code: &str) -> Result<Json> {
        let host = self.host();
        self.evaluator
            .run_code(CodeCall {
                code: code.to_owned(),
                host: Some(&host as &dyn sc_expr::CodeHost),
                bindings: [("payload".to_owned(), json!({ "least": 200 }))]
                    .into_iter()
                    .collect(),
                ..CodeCall::default()
            })
            .await
    }

    /// One column of one table, read back with SQL rather than through the
    /// surface under test.
    async fn column(&self, sql: &str) -> Result<Vec<String>> {
        let rows = self
            .db
            .client()
            .await?
            .query(sql, &[])
            .await
            .map_err(|e| Error::database(e.to_string()))?;
        Ok(rows.iter().map(|r| r.get::<_, String>(0)).collect())
    }
}

