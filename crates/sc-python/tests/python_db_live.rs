#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn iter_walks_more_rows_than_one_batch_and_stops_where_the_loop_does() -> Result<()> {
    let live = Live::new().await?;
    // Enough rows that a batch of five is several host calls rather than one.
    live.db
        .client()
        .await?
        .batch_execute(
            "INSERT INTO books (title, pages, author) \
             SELECT 'B' || lpad(n::text, 3, '0'), n, 1 FROM generate_series(1, 25) n;",
        )
        .await
        .map_err(|e| Error::database(e.to_string()))?;

    let out = live
        .run(
            r#"
walked = [b["title"] for b in db.books.where(title__like="B%").order_by("title").iter(batch=5)]
# A loop that stops early has paid for only what it read: nothing is fetched
# until the loop asks for it.
early = []
for b in db.books.where(title__like="B%").order_by("title").iter(batch=5):
    early.append(b["title"])
    if len(early) == 3:
        break
# Iterating the query itself is the same walk, and a query is reusable.
q = db.books.where(title__like="B%").order_by("title")
twice = [len([b for b in q]), len([b for b in q])]
return {"walked": walked, "early": early, "twice": twice}
"#,
        )
        .await?;
    let walked = out["walked"].as_array().expect("a list");
    assert_eq!(walked.len(), 25, "every row, over several batches");
    assert_eq!(walked[0], json!("B001"));
    assert_eq!(walked[24], json!("B025"));
    assert_eq!(out["early"], json!(["B001", "B002", "B003"]));
    assert_eq!(out["twice"], json!([25, 25]));

    // And the unstreamed read answers exactly the same rows in the same order,
    // which is the property a cursor has to preserve.
    let out = live
        .run(
            "walked = [b[\"title\"] for b in db.books.where(title__like=\"B%\")\
             .order_by(\"title\").iter(batch=5)]\n\
             whole = [b[\"title\"] for b in db.books.where(title__like=\"B%\")\
             .order_by(\"title\").select(\"title\").rows()]\n\
             return walked == whole",
        )
        .await?;
    assert_eq!(out, json!(true));
    Ok(())
}

