#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn every_chain_method_and_terminal_answers_the_real_rows() -> Result<()> {
    let live = Live::new().await?;

    // The reads: a narrowed, projected, sorted, bounded select, and then each
    // scalar terminal over the same table.
    let out = live
        .run(
            r#"
long = (db.books
    .where(pages__gte=payload["least"])
    .select("title", "pages")
    .order_by("pages", "desc")
    .limit(2)
    .rows())
paged = db.books.order_by("title").offset(1).limit(2).select("title").rows()
return {
    "long": [b["title"] for b in long],
    "paged": [b["title"] for b in paged],
    "first": db.books.order_by("title").first()["title"],
    "got": db.books.get(3)["title"],
    "missing": db.books.get(999),
    "exists": db.books.where(title="Dune").exists(),
    "absent": db.books.where(title="Nothing").exists(),
    "n": db.books.count(),
    "pages": db.books.sum("pages"),
    "least": db.books.min("pages"),
    "most": db.books.max("pages"),
}
"#,
        )
        .await?;
    assert_eq!(
        out,
        json!({
            "long": ["Emma", "Dune"],
            "paged": ["Emma", "Ficciones"],
            "first": "Dune",
            "got": "Ficciones",
            "missing": Json::Null,
            "exists": true,
            "absent": false,
            "n": 4,
            // `sum` over a bigint column is an exact decimal on the wire, not a
            // float that might not be — the JavaScript body sees the same.
            "pages": "1060",
            "least": 174,
            "most": 474,
        })
    );

    // And the writes, each read back with SQL rather than believed from the
    // body's own answer.
    let out = live
        .run(
            r#"
made = db.books.insert(title="Ubik", pages=224, author=2)
changed = db.books.where(title="Ubik").update(pages=225)
gone = db.books.where(title="Solaris").delete()
return {"made": made["title"], "changed": changed, "gone": gone}
"#,
        )
        .await?;
    // A write answers what the **host** answers, which is what a JavaScript body
    // gets: the new row for an insert, and how many rows changed *and which* for
    // an update or a delete — the keys are the caller's evidence and the surface
    // does not reshape them on the way past.
    assert_eq!(
        out,
        json!({
            "made": "Ubik",
            "changed": { "updated": 1, "ids": [5] },
            "gone": { "deleted": 1, "ids": [4] },
        })
    );
    assert_eq!(
        live.column("SELECT title FROM books ORDER BY title")
            .await?,
        vec!["Dune", "Emma", "Ficciones", "Ubik"]
    );
    assert_eq!(
        live.column("SELECT pages::text FROM books WHERE title = 'Ubik'")
            .await?,
        vec!["225"]
    );
    Ok(())
}

#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn the_two_where_spellings_and_the_keyword_operators_choose_the_same_rows() -> Result<()> {
    let live = Live::new().await?;

    let out = live
        .run(
            r#"
import saltcorn as sc

def titles(query):
    return sorted(b["title"] for b in query.select("title").rows())

return {
    "eq": titles(db.books.where(title="Dune")),
    "ne": titles(db.books.where(title__ne="Dune")),
    "gt": titles(db.books.where(pages__gt=412)),
    "gte": titles(db.books.where(pages__gte=412)),
    "lt": titles(db.books.where(pages__lt=412)),
    "lte": titles(db.books.where(pages__lte=412)),
    "in": titles(db.books.where(title__in=["Dune", "Emma"])),
    "nin": titles(db.books.where(title__nin=["Dune", "Emma"])),
    # A pattern is SQL's, bound as the text it is rather than wrapped: what the
    # body writes is what LIKE gets.
    "like": titles(db.books.where(title__like="%mm%")),
    "ilike": titles(db.books.where(title__ilike="dun%")),
    "is_null": titles(db.books.where(pages__is_null=True)),
    # The dict DSL every other surface speaks, and the formula for what it
    # cannot say — the same rows as the keywords above.
    "dict": titles(db.books.where({"pages": {"gte": 412}})),
    "formula": titles(db.books.where("pages >= 412")),
    # Several kwargs and several calls are ANDed; or_/not_ say the rest.
    "and": titles(db.books.where(author=1).where(pages__lt=450)),
    "or": titles(db.books.where(sc.or_({"title": "Dune"}, {"title": "Solaris"}))),
    "not": titles(db.books.where(sc.not_({"author": 1}))),
}
"#,
        )
        .await?;
    assert_eq!(
        out,
        json!({
            "eq": ["Dune"],
            "ne": ["Emma", "Ficciones", "Solaris"],
            "gt": ["Emma"],
            "gte": ["Dune", "Emma"],
            "lt": ["Ficciones"],
            "lte": ["Dune", "Ficciones"],
            "in": ["Dune", "Emma"],
            "nin": ["Ficciones", "Solaris"],
            "like": ["Emma"],
            "ilike": ["Dune"],
            "is_null": ["Solaris"],
            "dict": ["Dune", "Emma"],
            "formula": ["Dune", "Emma"],
            "and": ["Dune"],
            "or": ["Dune", "Solaris"],
            "not": ["Ficciones", "Solaris"],
        })
    );
    Ok(())
}

