/// The same question, asked from a JavaScript body and from a Python body,
/// answers the same rows — **because it is the same plan**.
///
/// This is the property the whole adapter shape exists for: `CodeCall` and the
/// five host traits were never JavaScript's, so a second language is a second
/// implementation of one trait and there is no second place for authority,
/// budgets or events to be decided. If the two ever disagreed here, one of them
/// would have grown a lowering of its own — which is the failure this test is
/// watching for, and it is why the two bodies are written idiomatically in their
/// own language rather than transliterated.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn the_same_question_in_two_languages_answers_the_same_rows() -> Result<()> {
    let live = Live::new().await?;
    live.own_the_notes().await?;

    let python = live
        .run(
            r#"
long = (db.books
    .where(pages__gte=payload["least"])
    .select("title", "authorⱵname", tier="authorⱵtier")
    .order_by("pages", "desc")
    .limit(10)
    .rows())
by_author = (db.books
    .group_by("author")
    .aggregate(total="sum(pages)", n="count()")
    .order_by("author")
    .rows())
return {
    "long": long,
    "by_author": by_author,
    "n": db.books.count(),
    "pages": db.books.sum("pages"),
    "first": db.books.order_by("title").first(),
    "mine": db.as_user().notes.select("what").order_by("id").rows(),
}
"#,
        )
        .await?;

    let javascript = live
        .run_js(
            r#"
const long = await db.books
  .where({ pages: { gte: payload.least } })
  .select("title", "authorⱵname", { tier: "authorⱵtier" })
  .orderBy("pages", "desc")
  .limit(10)
  .rows();
const byAuthor = await db.books
  .groupBy("author")
  .aggregate({ total: "sum(pages)", n: "count()" })
  .orderBy("author")
  .rows();
return {
  long,
  by_author: byAuthor,
  n: await db.books.count(),
  pages: await db.books.sum("pages"),
  first: await db.books.orderBy("title").first(),
  mine: await db.asUser().notes.select("what").orderBy("id").rows(),
};
"#,
        )
        .await?;

    assert_eq!(python, javascript, "the two languages disagreed");
    // And not vacuously: the answer is the rows, including the join path, the
    // exact decimal and the ownership formula's verdict.
    assert_eq!(python["long"][0]["authorⱵname"], json!("Ada"));
    assert_eq!(python["pages"], json!("1060"));
    assert_eq!(
        python["mine"],
        json!([{ "what": "ada one" }, { "what": "ada two" }])
    );
    Ok(())
}

