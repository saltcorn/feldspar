//! `db` from a Python body, against a **real** database (phase 2.6 and 2.7).
//!
//! `python_db.rs` pins the lowering: every chain method against a recorder, so a
//! plan can be read and compared with the JavaScript one. What a recorder cannot
//! answer is whether the plan a chain lowers to is one this server's host
//! actually executes, and against which rows — a spelling mistake in an operator,
//! a projection the host reads differently, an aggregate whose argument never
//! reaches SQL would all pass there and fail here.
//!
//! So this file holds the production pieces and nothing else: the catalog over
//! Postgres, the `TableHost` an action builds, the ownership formula on the V8
//! isolate, the dispatcher a write's event reaches. It mirrors
//! `sc-core-actions/tests/run_js_code.rs`, question for question, and ends with
//! the one that is the point of the milestone — the same question in the two
//! languages, answered the same way, **because it is the same plan**.

