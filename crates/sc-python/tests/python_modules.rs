/// What the fixture declares, read the way a server reads it: through the
/// distribution's **entry point**, with `on_load` called and its settings
/// answered in this system's own field vocabulary.
#[tokio::test]
async fn a_plugin_declares_an_action_a_function_a_provider_and_its_own_settings() -> Result<()> {
    let _guard = ONE_AT_A_TIME.lock().await;
    skip_without!(
        have_toolchain().await,
        "python3 with pip is not on the PATH"
    );
    skip_without!(
        cfg!(feature = "python-host"),
        "built without an interpreter"
    );
    let host = host(shared_environment().await);

    let manifest = host
        .load(PACKAGE, &json!({ "api_key": "secret", "greeting": "hi" }))
        .await?;

    // Nothing went wrong that the plugin could see. An `on_load` that failed, an
    // `async def` action, a package that declared nothing — all of those are
    // issues here rather than a load that failed, so an admin still gets the
    // settings form that is where they would fix it.
    assert!(manifest.issues.is_empty(), "{:?}", manifest.issues);
    assert_eq!(manifest.name, PACKAGE);
    // The package the declarations were made in, which is not the distribution's
    // name and not the module the entry point named.
    assert_eq!(manifest.plugin_name.as_deref(), Some("sc_plugin_fixture"));

    let actions: Vec<&str> = manifest.actions.iter().map(|a| a.name.as_str()).collect();
    assert_eq!(actions, ["fixture_note", "insert_row"]);
    let note = &manifest.actions[0];
    assert_eq!(note.description, "Note something about a row");
    assert_eq!(note.config_fields.len(), 1);
    assert_eq!(note.config_fields[0]["name"], json!("note"));
    assert_eq!(note.config_fields[0]["required"], json!(true));

    // The **signature**, read with `inspect` — the one place this API is better
    // than the JavaScript one rather than merely different.
    let shout = manifest
        .functions
        .iter()
        .find(|f| f.name == "fixture_shout")
        .expect("the fixture supplies it");
    assert_eq!(shout.description, "Shout a string");
    assert!(!shout.is_async);
    assert_eq!(shout.arguments.len(), 1);
    assert_eq!(shout.arguments[0].name, "text");
    assert_eq!(shout.arguments[0].type_name.as_deref(), Some("string"));
    let add = manifest
        .functions
        .iter()
        .find(|f| f.name == "fixture_add")
        .expect("the fixture supplies it");
    assert_eq!(
        add.arguments
            .iter()
            .map(|a| a.type_name.as_deref())
            .collect::<Vec<_>>(),
        [Some("int"), Some("int")]
    );

    assert_eq!(manifest.table_providers.len(), 1);
    assert_eq!(manifest.table_providers[0].name, PROVIDER);
    assert_eq!(
        manifest.table_providers[0].config_fields[0]["name"],
        json!("min_size")
    );

    // Its own settings, in **this system's** vocabulary: `secret` is a flag on
    // the declaration rather than a `fieldview: "password"` to be guessed at.
    let settings: Vec<&str> = manifest
        .config_fields
        .iter()
        .map(|f| f["name"].as_str().unwrap_or_default())
        .collect();
    assert_eq!(settings, ["api_key", "greeting"]);
    assert_eq!(manifest.config_fields[0]["secret"], json!(true));
    assert_eq!(manifest.config_fields[1]["default"], json!("hello"));

    // Nothing this version does not load: a Python plugin has no decorator for a
    // view or a type, so there is nothing to count as unsupported.
    assert!(manifest.unsupported.is_empty());
    Ok(())
}

/// §11: a load is a **re-import**, and `on_load` is called again with the new
/// configuration — which is how a settings change reaches the client a plugin
/// built at load time.
#[tokio::test]
async fn a_configuration_change_reloads_the_package_and_calls_on_load_again() -> Result<()> {
    let _guard = ONE_AT_A_TIME.lock().await;
    skip_without!(
        have_toolchain().await,
        "python3 with pip is not on the PATH"
    );
    skip_without!(
        cfg!(feature = "python-host"),
        "built without an interpreter"
    );
    let host = host(shared_environment().await);

    host.load(PACKAGE, &json!({ "api_key": "one", "greeting": "first" }))
        .await?;
    let first = host.call(PACKAGE, "fixture_loaded", Vec::new()).await?;
    assert_eq!(first["greeting"], json!("first"));
    assert_eq!(first["loads"], json!(1), "`on_load` ran");

    // Loaded again with a different configuration. `on_load` saw the new one —
    // and `loads` is **1 again rather than 2**, which is the evidence that the
    // package was dropped from `sys.modules` and imported afresh: its own
    // module-level state did not survive, exactly as §11 says a reload behaves
    // for a pure-Python package.
    let manifest = host
        .load(PACKAGE, &json!({ "api_key": "two", "greeting": "second" }))
        .await?;
    assert!(manifest.issues.is_empty(), "{:?}", manifest.issues);
    let second = host.call(PACKAGE, "fixture_loaded", Vec::new()).await?;
    assert_eq!(second["greeting"], json!("second"));
    assert_eq!(second["loads"], json!(1), "the package was imported again");
    Ok(())
}

/// §2: the five surfaces are bound **for the duration of a call**, and a call
/// that was lent none says so at the call site.
///
/// A function and a table provider are lent none — the first is hoisted into a
/// formula and the second is called from inside a query, and neither has a
/// caller's authority to lend — so the fixture's action reaching `sc.db` outside
/// a trigger is refused rather than quietly writing as the admin.
#[tokio::test]
async fn a_module_call_that_was_lent_no_surfaces_is_refused_at_the_call_site() -> Result<()> {
    let _guard = ONE_AT_A_TIME.lock().await;
    skip_without!(
        have_toolchain().await,
        "python3 with pip is not on the PATH"
    );
    skip_without!(
        cfg!(feature = "python-host"),
        "built without an interpreter"
    );
    let host = host(shared_environment().await);
    host.load(PACKAGE, &json!({ "api_key": "one" })).await?;

    let refused = host
        .run(PACKAGE, "fixture_note", args("a note"), Default::default())
        .await
        .expect_err("no surfaces were lent")
        .to_string();
    assert!(refused.contains("database access"), "{refused}");
    // And the frames are the **plugin's own**, not fifteen of runtime: the file
    // that made the call, and the line in it.
    assert!(refused.contains("plugin.py"), "{refused}");
    Ok(())
}

