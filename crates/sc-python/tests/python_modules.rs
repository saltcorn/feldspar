/// A module function reached both ways it can be reached, through the
/// **composite** host — so what is asserted is also §8's merge: neither caller
/// knows there are two languages of module.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn a_python_modules_function_is_called_from_a_body_and_from_a_formula() -> Result<()> {
    let _guard = ONE_AT_A_TIME.lock().await;
    skip_without!(
        have_toolchain().await,
        "python3 with pip is not on the PATH"
    );
    skip_without!(
        cfg!(feature = "python-host"),
        "built without an interpreter"
    );
    let dir = shared_environment().await;

    let db = TestDb::new().await?;
    let catalog = catalog_of(&db).await?;
    bootstrap_triggers(&catalog).await?;
    bootstrap_table_meta(&catalog).await?;
    catalog
        .create_table(
            "article",
            &[DataField::plain("notes", TypeRef::Basic(BasicType::Text))],
        )
        .await?;
    install_row(&catalog, json!({ "api_key": "k" })).await?;

    let host = host(dir);
    let mut registry = builtin_actions()?;
    let loaded = load_set(&catalog, &host, &mut registry).await?;
    let functions = Arc::new(PyModuleFunctions::new(&host, &loaded));
    assert_eq!(functions.functions().len(), 3);
    // Through the composite of §8, which is what a server installs: one host
    // over both languages, routed by the module a plan names.
    catalog.set_module_functions(Arc::new(ModuleFnHosts::new(vec![
        Arc::clone(&functions) as Arc<dyn ModuleFnHost>
    ])))?;

    // --- from a formula, hoisted ------------------------------------------
    let shape = SchemaShape::new()
        .table(
            "article",
            TableShape::new()
                .field("id")
                .field("notes")
                .primary_key("id"),
        )
        .module_function("fixture_shout", PACKAGE);
    let formula = Formula::parse("fixture_shout(notes)").unwrap();
    let analysis = formula.validate(&shape, "article").unwrap();
    let table = catalog.require("article")?;
    let mut values: BTreeMap<String, Value> =
        BTreeMap::from([("notes".to_owned(), Value::Text("hello".to_owned()))]);
    prefetch_bindings(&catalog, &table, &analysis, &shape, &mut values).await?;
    assert_eq!(
        values.get("fixture_shout(notes)").map(value_to_json),
        Some(Json::String("HELLO!".to_owned()))
    );

    // --- from a code body, through `modfn` --------------------------------
    let registry = Arc::new(registry);
    let dispatcher = Arc::new(
        TriggerDispatcher::new(Arc::clone(&registry))
            .with_adapter(Arc::new(PythonRuntime::new()) as Arc<dyn CodeAdapter>),
    );
    let trigger = Trigger::new("shout", EventKind::None, "run_python_code").config(
        "code",
        r#"
return {
    "short": modfn.fixture_shout(payload["what"]),
    "named": modfn("sc-plugin-fixture").fixture_add(2, 3),
    "known": sorted(f["name"] for f in modfn.functions),
}
"#,
    );
    save_trigger(&catalog, &registry, &trigger).await?;
    dispatcher.reload(&catalog).await?;
    let result = dispatcher
        .run_trigger(&catalog, "shout", json!({ "what": "quiet" }), None)
        .await?;
    assert_eq!(result["short"], json!("QUIET!"));
    assert_eq!(result["named"], json!(5));
    assert_eq!(
        result["known"],
        json!(["fixture_add", "fixture_loaded", "fixture_shout"])
    );
    Ok(())
}

