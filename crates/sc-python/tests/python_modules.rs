//! Phase 6 of the Python code adapter: **plugin modules**.
//!
//! The milestone's second half of the definition of done, and every one of these
//! tests runs it rather than a piece of it: a real distribution, `pip`-installed
//! from a directory into a real virtual environment, imported on the real
//! interpreter, and then asked for exactly what a server asks a module for — an
//! action fired by a trigger, a function reached from a body and from a formula,
//! and a table read, filtered and written through the catalog.
//!
//! The fixture is `tests/fixtures/sc_plugin_pkg`, which supplies one of each
//! thing a Python plugin can supply, plus one action named after a built-in
//! because "reported and not installed" is a rule that needs a plugin which
//! breaks it. Nothing here reaches PyPI: the fixture's PEP 517 backend builds
//! its wheel with `zipfile` and has no requirements, so pip's build isolation
//! has nothing to download.
//!
//! # Why these tests share one environment, and take a lock
//!
//! There is **one** interpreter in a process (§1) and one `sys.modules` in it,
//! and a load is a re-import (§11). Two of these tests running at once would
//! therefore reset each other's plugin state half way through — which is not a
//! bug in the runtime, it is what one interpreter means, and the honest way to
//! test around it is to run them one at a time. So the environment is built once
//! and every test holds a lock for its length.

