/// The milestone's own sentence: a Python plugin's action appears in the trigger
/// form with its own settings, fires on an event, and reaches `db`.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn a_python_modules_action_fires_from_a_trigger_and_writes_through_db() -> Result<()> {
    let _guard = ONE_AT_A_TIME.lock().await;
    skip_without!(
        have_toolchain().await,
        "python3 with pip is not on the PATH"
    );
    skip_without!(
        cfg!(feature = "python-host"),
        "built without an interpreter"
    );
    let dir = shared_environment().await;

    let db = TestDb::new().await?;
    db.client()
        .await?
        .batch_execute(SCHEMA)
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    let catalog = catalog_of(&db).await?;
    bootstrap_triggers(&catalog).await?;
    install_row(&catalog, json!({ "api_key": "sk-live", "greeting": "hi" })).await?;

    let host = host(dir);
    let mut registry = builtin_actions()?;
    let loaded = load_set(&catalog, &host, &mut registry).await?;
    assert_eq!(loaded.len(), 1);
    let module = &loaded[0];

    // Its action is in the registry the dispatcher runs from, with the settings
    // the plugin declared — translated into the same `FormField`s every other
    // configurable thing here uses, so the trigger form renders it with no code
    // that knows what a Python module is.
    let action = registry.get("fixture_note").expect("registered");
    let spec = action.config_spec();
    assert_eq!(spec.len(), 1);
    assert_eq!(spec[0].name(), "note");
    assert!(spec[0].required);

    // And the one that claims a built-in's name is **reported and not
    // installed**: `insert_row` is still the built-in.
    assert_eq!(
        module.issues.len(),
        1,
        "only the collision is wrong: {:?}",
        module.issues
    );
    assert!(
        module.issues[0].contains("insert_row"),
        "{:?}",
        module.issues
    );
    assert_eq!(registry.get("insert_row").unwrap().description(), {
        let builtins = builtin_actions()?;
        builtins.get("insert_row").unwrap().description().to_owned()
    });

    // Now fire it, exactly as an admin's Run button would.
    let registry = Arc::new(registry);
    let dispatcher = Arc::new(
        TriggerDispatcher::new(Arc::clone(&registry))
            .with_adapter(Arc::new(PythonRuntime::new()) as Arc<dyn CodeAdapter>),
    );
    let trigger = Trigger::new("note it", EventKind::None, "fixture_note").config("note", "chased");
    save_trigger(&catalog, &registry, &trigger).await?;
    dispatcher.reload(&catalog).await?;

    let caller = CallerContext::new(1, Some(json!({ "email": "ada@example.com" })));
    let result = dispatcher
        .run_trigger(&catalog, "note it", json!({ "who": "ada" }), Some(&caller))
        .await?;

    // What the plugin returned: its own configured setting, the **module's**
    // settings which no trigger can change, and the count it read back through
    // the same `db` it wrote with.
    assert_eq!(result["noted"], json!("chased"));
    assert_eq!(result["greeting"], json!("hi"));
    assert_eq!(result["key"], json!("sk-live"));
    assert_eq!(result["trigger"], json!("note it"));
    assert_eq!(result["notes"], json!(1));

    // And the row is really there, written through the row layer.
    let rows = db
        .client()
        .await?
        .query("SELECT what FROM notes", &[])
        .await
        .map_err(|e| Error::database(e.to_string()))?;
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0].get::<_, String>(0), "chased");

    // The settings form the Modules tab renders: the secret is **redacted** on
    // the way out, and submitting the sentinel back keeps what is stored.
    let redacted = redacted_configuration(module);
    assert_ne!(redacted["api_key"], json!("sk-live"));
    assert_eq!(redacted["greeting"], json!("hi"));
    let merged =
        sc_types::merge_secrets(&module.config_spec, &module.module.configuration, &redacted);
    assert_eq!(merged["api_key"], json!("sk-live"));
    Ok(())
}

