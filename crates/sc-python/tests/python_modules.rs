/// The distribution the fixture installs as, as pip and `_fd_modules` name it.
const PACKAGE: &str = "sc-plugin-fixture";
/// The table provider it supplies.
const PROVIDER: &str = "Fixture rows";

/// One table for the fixture's action to write into.
const SCHEMA: &str = "
    CREATE TABLE notes (id bigint generated by default as identity primary key,
        what text, who text);
";

/// Say why a test did nothing, and return, so a skip is visible under
/// `-- --nocapture` rather than looking like a pass.
macro_rules! skip_without {
    ($cond:expr, $why:expr) => {
        if !$cond {
            eprintln!("skipping: {}", $why);
            return Ok(());
        }
    };
}

/// A JSON object as the attribute map every stored configuration is.
fn configuration(value: Json) -> sc_types::Attrs {
    match value {
        Json::Object(map) => map,
        _ => sc_types::Attrs::new(),
    }
}

fn fixture_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/sc_plugin_pkg")
}

/// Whether this machine can build an environment at all.
async fn have_toolchain() -> bool {
    let bin = PathBuf::from(sc_python::DEFAULT_PYTHON_BIN);
    sc_python::have_python(&bin).await && sc_python::have_pip(&bin).await
}

/// The one environment these tests share, with the fixture installed in it.
///
/// Built once for the whole binary: a `pip install` costs seconds, and every
/// test here wants the same distribution in the same place. It is *not* removed
/// afterwards for the same reason it is shared — the interpreter has its
/// `site-packages` on `sys.path` for the life of the process.
static ENVIRONMENT: tokio::sync::OnceCell<PathBuf> = tokio::sync::OnceCell::const_new();

/// Held for the length of every test: one interpreter, one `sys.modules`, and a
/// load is a re-import.
static ONE_AT_A_TIME: tokio::sync::Mutex<()> = tokio::sync::Mutex::const_new(());

async fn shared_environment() -> &'static Path {
    ENVIRONMENT
        .get_or_init(|| async {
            let dir =
                std::env::temp_dir().join(format!("sc-python-modules-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&dir);
            let environment = environment_at(&dir);
            environment
                .install(PythonSource::Local, &fixture_dir().display().to_string())
                .await
                .expect("the fixture plugin installs");
            dir
        })
        .await
        .as_path()
}

fn environment_at(dir: &Path) -> PythonEnvironment {
    PythonEnvironment::new(
        &PythonEnv {
            dir: Some(dir.to_path_buf()),
            bin: None,
        },
        None,
    )
    .expect("an explicit --python-dir needs no default")
}

/// A runtime pointed at the shared environment, and a module host over it.
fn host(dir: &Path) -> Arc<PyModuleHost> {
    let python = Arc::new(PythonRuntime::new().with_env(PythonEnv {
        dir: Some(dir.to_path_buf()),
        bin: None,
    }));
    Arc::new(PyModuleHost::new(python))
}

/// The `_fd_modules` row an admin's install would have written.
async fn install_row(catalog: &Catalog, configuration: Json) -> Result<()> {
    bootstrap_modules(catalog).await?;
    let mut module = Module::new(
        PACKAGE,
        ModuleSource::Local,
        fixture_dir().display().to_string(),
    )
    .in_language(ModuleLanguage::Python);
    module.version = Some("0.2.0".to_owned());
    if let Json::Object(configuration) = configuration {
        module.configuration = configuration;
    }
    save_module(catalog, &module).await
}

/// Load every Python module in `catalog` into `registry`, over `host`.
async fn load_set(
    catalog: &Catalog,
    host: &Arc<PyModuleHost>,
    registry: &mut ActionRegistry,
) -> Result<Vec<LoadedModule>> {
    let surfaces = Arc::new(CodeSurfaces::new()?);
    Ok(PyModuleSet::load(catalog, host, &surfaces, registry)
        .await?
        .into_modules())
}

async fn catalog_of(db: &TestDb) -> Result<Arc<Catalog>> {
    let driver = Arc::new(PgDriver::from_pool(db.pool().clone()));
    Ok(Arc::new(
        Catalog::init(driver as Arc<dyn DatabaseDriver>).await?,
    ))
}

