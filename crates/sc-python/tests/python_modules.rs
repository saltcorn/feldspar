/// A table whose `_fd_tables` row names a Python provider: its columns are the
/// plugin's answer, its rows are read and filtered through the ordinary query
/// path, and all three writes work because the class defines all three methods.
#[tokio::test(flavor = "multi_thread", worker_threads = 4)]
async fn a_table_backed_by_a_python_provider_is_read_filtered_and_written() -> Result<()> {
    let _guard = ONE_AT_A_TIME.lock().await;
    skip_without!(
        have_toolchain().await,
        "python3 with pip is not on the PATH"
    );
    skip_without!(
        cfg!(feature = "python-host"),
        "built without an interpreter"
    );
    let dir = shared_environment().await;

    let db = TestDb::new().await?;
    let catalog = catalog_of(&db).await?;
    bootstrap_table_meta(&catalog).await?;
    install_row(&catalog, json!({ "api_key": "k" })).await?;

    let host = host(dir);
    let mut registry = ActionRegistry::new();
    let loaded = load_set(&catalog, &host, &mut registry).await?;
    let providers = Arc::new(PyModuleTableProviders::new(&host, &loaded));
    assert_eq!(providers.providers().len(), 1);
    assert_eq!(providers.providers()[0].config_spec[0].name(), "min_size");
    // The composite again: one provider host over both languages.
    catalog.set_table_providers(Arc::new(TableProviderHosts::new(vec![
        Arc::clone(&providers) as Arc<dyn TableProviderHost>,
    ])))?;

    // The row that *is* the table.
    let mut meta = TableMeta::new("fixtures").label("Fixtures");
    meta.set_provider(Some(
        &ProvidedTableDef::new(PACKAGE, PROVIDER)
            .configuration(configuration(json!({ "min_size": 0 }))),
    ));
    save_table_meta(&catalog, &meta).await?;

    let table = catalog.require("fixtures")?;
    assert!(
        catalog.provided_table_issues().is_empty(),
        "{:?}",
        catalog.provided_table_issues()
    );
    // Its columns are what `fields(configuration)` answered, including which of
    // them is the key — without one, no write could name a row.
    let columns: Vec<&str> = table.fields.iter().map(|f| f.base.name.as_str()).collect();
    assert_eq!(columns, ["id", "name", "size"]);
    assert_eq!(table.primary_key, ["id"]);
    // And it is writable, because the class defines all three write methods.
    assert_eq!(table.provided_writes(), ProvidedWrites::ALL);

    let provider = catalog.provider(&table)?;

    // --- read, filtered ----------------------------------------------------
    let mut select = Select::from(Source::table("fixtures"));
    select.filter = Some(Expr::binary(BinOp::Gt, Expr::col("size"), Expr::lit(5_i64)));
    let rows: Vec<_> = provider.query(&select).await?.try_collect().await?;
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0].get("name"), Some(&Value::Text("beta".into())));

    // --- insert ------------------------------------------------------------
    let insert = Insert::row(
        "fixtures",
        vec!["name".to_owned(), "size".to_owned()],
        vec![Expr::lit("gamma"), Expr::lit(9_i64)],
    )
    .returning(vec![Projection::all()]);
    let rows: Vec<_> = provider
        .write(&Statement::from(insert))
        .await?
        .try_collect()
        .await?;
    assert_eq!(rows.len(), 1);
    // The key the plugin assigned, which nothing here sent.
    assert_eq!(rows[0].get("id"), Some(&Value::Int(3)));

    // --- update ------------------------------------------------------------
    let update = Update {
        table: "fixtures".to_owned(),
        assignments: vec![Assignment::new("name", Expr::lit("edited"))],
        filter: Some(Expr::col("id").eq(Expr::lit(1_i64))),
        returning: vec![Projection::all()],
    };
    let rows: Vec<_> = provider
        .write(&Statement::from(update))
        .await?
        .try_collect()
        .await?;
    assert_eq!(rows.len(), 1);
    assert_eq!(rows[0].get("name"), Some(&Value::Text("edited".into())));

    // --- delete ------------------------------------------------------------
    let delete = Delete {
        table: "fixtures".to_owned(),
        filter: Some(Expr::col("id").eq(Expr::lit(2_i64))),
        returning: vec![Projection::all()],
    };
    let rows: Vec<_> = provider
        .write(&Statement::from(delete))
        .await?
        .try_collect()
        .await?;
    assert_eq!(rows.len(), 1);

    // What is left, read again through the whole path.
    let rows: Vec<_> = provider
        .query(&Select::from(Source::table("fixtures")))
        .await?
        .try_collect()
        .await?;
    let names: Vec<String> = rows
        .iter()
        .filter_map(|row| match row.get("name") {
            Some(Value::Text(name)) => Some(name.clone()),
            _ => None,
        })
        .collect();
    assert_eq!(names, ["edited", "gamma"]);
    Ok(())
}

