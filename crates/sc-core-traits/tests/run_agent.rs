/// The milestone's **done when**: a row is inserted, the trigger fires, the
/// agent runs with a prompt built from that row, and the run it left behind is
/// readable afterwards.
#[tokio::test]
async fn an_insert_starts_an_agent_with_a_prompt_built_from_the_row() -> Result<()> {
    let (env, providers) = setup([
        Reply::calls(
            "insert_into_summaries",
            json!({ "post": "Hello", "summary": "A greeting." }),
        ),
        Reply::says(ANSWER),
    ])
    .await?;
    save_trigger(&env.catalog, &registry(&env), &summarise_trigger()).await?;
    env.reload_triggers().await?;

    // An ordinary write through the row layer — which is what raises the event.
    let posts = env.catalog.require("posts")?;
    sc_api::insert_row_as(
        &env.catalog,
        &posts,
        &json!({ "title": "Hello", "body": "The first post." }),
        sc_auth::ROLE_ADMIN,
        None,
        None,
        &[],
        &sc_api::rows::Executor::Pooled,
    )
    .await?;

    // One run, of that agent, finished.
    let runs = list_runs(&env.catalog, "summariser").await?;
    assert_eq!(runs.len(), 1, "the insert should have started one run");
    let run = &runs[0];
    assert_eq!(run.state, RunState::Done);
    // Nobody was there: a triggered run carries the trigger's authority, and the
    // row says so (decision 5).
    assert_eq!(run.user, None);
    // The history list has something to show it as, which a run created by
    // `Runner::start` alone would not have.
    assert!(run.description.contains("summarise_post"), "{run:?}");

    // The row's data reached the prompt — checked in the run's transcript…
    let messages = run.agent_loop()?.messages().to_vec();
    let sc_llm::LlmMessage::User { content, .. } = &messages[0] else {
        panic!("the run should open with the prompt: {messages:?}")
    };
    assert_eq!(content, r#"Summarise the post "Hello": The first post."#);
    // …and in the request the model was actually sent, which is the boundary the
    // claim is about. The system prompt is the agent's own.
    let request = providers.last().requests().remove(0);
    assert_eq!(request.messages, messages[..1]);
    assert_eq!(request.system.as_deref(), Some("You summarise posts."));

    // The agent's tool ran with the trigger's authority and wrote its row
    // through the ordinary write path.
    assert_eq!(
        summaries(&env).await?,
        vec![("Hello".to_owned(), "A greeting.".to_owned())]
    );

    // And the whole exchange is on the run: prompt, tool call, tool result,
    // answer.
    assert_eq!(messages.len(), 4, "{messages:?}");
    assert!(matches!(
        &messages[2],
        sc_llm::LlmMessage::ToolResult { name, .. } if name == "insert_into_summaries"
    ));
    let sc_llm::LlmMessage::Assistant { content, .. } = &messages[3] else {
        panic!("the model's answer should end it: {messages:?}")
    };
    assert_eq!(content, ANSWER);
    Ok(())
}

/// Asked directly, the action **answers**: the final assistant message and the
/// run id, not a stream (§11.5).
#[tokio::test]
async fn running_the_trigger_directly_returns_the_answer_and_the_run_id() -> Result<()> {
    let (env, providers) = setup([Reply::says(ANSWER)]).await?;
    // A `none` trigger, because a directly-run table trigger has no row — and a
    // prompt over the payload is what such a trigger's whole vocabulary is.
    let trigger = Trigger::new("summarise_now", EventKind::None, "run_agent")
        .config(CFG_AGENT, "summariser")
        .config(CFG_PROMPT, "`Summarise: ${payload.title}`");
    save_trigger(&env.catalog, &registry(&env), &trigger).await?;
    env.reload_triggers().await?;

    let result = env
        .dispatcher
        .as_ref()
        .expect("a dispatcher")
        .run_trigger(
            &env.catalog,
            "summarise_now",
            json!({ "title": "Ubik" }),
            None,
        )
        .await?;

    assert_eq!(result["agent"], json!("summariser"));
    assert_eq!(result["answer"], json!(ANSWER));
    assert_eq!(result["conclusion"], json!("answered"));

    // The run id resolves to the run, which is what makes a triggered
    // conversation readable in the chat panel afterwards.
    let id = result["run"].as_str().expect("a run id");
    let run =
        sc_agent::require_run(&env.catalog, sc_agent::RunId(id.parse().expect("a uuid"))).await?;
    assert_eq!(run.subject, "summariser");
    assert_eq!(run.state, RunState::Done);
    assert_eq!(providers.runs(), 1);
    Ok(())
}

/// A prompt that computed nothing is refused rather than asked — an agent sent
/// an empty question spends a provider call to answer nothing.
#[tokio::test]
async fn a_prompt_that_computes_nothing_refuses_before_the_model_is_called() -> Result<()> {
    let (env, providers) = setup([Reply::says(ANSWER)]).await?;
    let trigger = Trigger::new("summarise_now", EventKind::None, "run_agent")
        .config(CFG_AGENT, "summariser")
        .config(CFG_PROMPT, "payload.missing");
    save_trigger(&env.catalog, &registry(&env), &trigger).await?;
    env.reload_triggers().await?;

    let err = env
        .dispatcher
        .as_ref()
        .expect("a dispatcher")
        .run_trigger(&env.catalog, "summarise_now", json!({}), None)
        .await
        .unwrap_err();
    assert!(err.to_string().contains(CFG_PROMPT), "{err}");
    // Nothing was connected and no run was left half-written.
    assert_eq!(providers.runs(), 0);
    assert_eq!(list_runs(&env.catalog, "summariser").await?.len(), 0);
    Ok(())
}

/// An agent that ends `Stuck` did not do what the trigger asked, and nobody was
/// watching: the action fails with the reason, and the run keeps the transcript.
#[tokio::test]
async fn a_stuck_agent_is_the_actions_failure_with_its_reason() -> Result<()> {
    // Three calls to a tool the agent does not have: the malformed-call cap.
    let (env, _providers) = setup(std::iter::repeat_n(
        Reply::calls("delete_everything", json!({})),
        3,
    ))
    .await?;
    let trigger = Trigger::new("summarise_now", EventKind::None, "run_agent")
        .config(CFG_AGENT, "summariser")
        .config(CFG_PROMPT, "`Summarise: ${payload.title}`");
    save_trigger(&env.catalog, &registry(&env), &trigger).await?;
    env.reload_triggers().await?;

    let err = env
        .dispatcher
        .as_ref()
        .expect("a dispatcher")
        .run_trigger(
            &env.catalog,
            "summarise_now",
            json!({ "title": "Ubik" }),
            None,
        )
        .await
        .unwrap_err();
    let message = err.to_string();
    assert!(message.contains("got stuck"), "{message}");
    assert!(message.contains("3 malformed tool calls"), "{message}");

    let runs = list_runs(&env.catalog, "summariser").await?;
    assert_eq!(runs.len(), 1);
    assert_eq!(runs[0].state, RunState::Done);
    assert!(matches!(
        runs[0].conclusion(),
        Some(sc_agent::Conclusion::Stuck { .. })
    ));
    Ok(())
}

/// The configuration is checked **on save**, in front of the admin: an agent
/// that does not exist, and a prompt naming something the event will not have.
#[tokio::test]
async fn the_configuration_is_refused_on_save() -> Result<()> {
    let (env, _providers) = setup([]).await?;

    let unknown = Trigger::new("t1", EventKind::None, "run_agent")
        .config(CFG_AGENT, "assistant")
        .config(CFG_PROMPT, "'hello'");
    let err = save_trigger(&env.catalog, &registry(&env), &unknown)
        .await
        .unwrap_err();
    assert!(err.to_string().contains("assistant"), "{err}");

    // `row` is not in scope on an event with no row, so a prompt that reads it
    // is a message on the form rather than a firing that fails.
    let no_row = Trigger::new("t2", EventKind::None, "run_agent")
        .config(CFG_AGENT, "summariser")
        .config(CFG_PROMPT, "`${row.title}`");
    let err = save_trigger(&env.catalog, &registry(&env), &no_row)
        .await
        .unwrap_err();
    assert!(err.to_string().contains("row"), "{err}");

    // And a bare identifier is refused by name: a formula that only reads the
    // event ranges over no table, so `title` is not `row.title` spelled shorter.
    let bare = Trigger::new("t3", EventKind::Insert, "run_agent")
        .on("posts")
        .config(CFG_AGENT, "summariser")
        .config(CFG_PROMPT, "title");
    let err = save_trigger(&env.catalog, &registry(&env), &bare)
        .await
        .unwrap_err();
    assert!(err.to_string().contains("title"), "{err}");
    Ok(())
}

/// …and **on load**: an agent deleted after the trigger was saved leaves the
/// trigger out of the live set with a reason, rather than failing when a row is
/// inserted.
#[tokio::test]
async fn deleting_the_agent_leaves_the_trigger_out_of_the_live_set_with_a_reason() -> Result<()> {
    let (env, providers) = setup([Reply::says(ANSWER)]).await?;
    save_trigger(&env.catalog, &registry(&env), &summarise_trigger()).await?;
    env.reload_triggers().await?;

    let stored = load_agent_by_name(&env.catalog, "summariser")
        .await?
        .expect("the agent");
    assert!(delete_agent(&env.catalog, stored.id).await?);
    env.reload_triggers().await?;

    let triggers = env.dispatcher.as_ref().expect("a dispatcher").triggers()?;
    let issue = triggers
        .issues()
        .iter()
        .find(|i| i.trigger == "summarise_post")
        .expect("the trigger should be listed as broken")
        .problem
        .clone();
    assert!(issue.contains("summariser"), "{issue}");

    // It is out of the live set, so the insert that would have fired it does not
    // — and the failure is one the admin can see and repair rather than one a
    // writer discovers.
    assert!(triggers.require("summarise_post").is_err());
    let posts = env.catalog.require("posts")?;
    sc_api::insert_row_as(
        &env.catalog,
        &posts,
        &json!({ "title": "Hello", "body": "…" }),
        sc_auth::ROLE_ADMIN,
        None,
        None,
        &[],
        &sc_api::rows::Executor::Pooled,
    )
    .await?;
    assert_eq!(providers.runs(), 0);
    Ok(())
}

