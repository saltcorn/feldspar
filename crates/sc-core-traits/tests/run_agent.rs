/// Posts that are written, and the summaries an agent files about them.
const SCHEMA: &str = "
    CREATE TABLE posts (
        id bigint generated by default as identity primary key,
        title text,
        body text
    );
    CREATE TABLE summaries (
        id bigint generated by default as identity primary key,
        post text,
        summary text
    );
";

/// What the scripted model answers with once it has filed its summary.
const ANSWER: &str = "Filed a summary.";

// --- a model that answers, and remembers what it was asked -------------------

/// A connector that hands out a fresh script per run and keeps every provider it
/// made.
///
/// Fresh per run because a triggered run connects once and a test may fire the
/// trigger more than once; kept because "the row's data reached the prompt" is a
/// claim about the **request the model saw**, and the only way to check it at
/// that boundary is to still have the provider afterwards.
struct Scripted {
    script: Vec<Reply>,
    made: Mutex<Vec<Arc<FakeProvider>>>,
}

impl Scripted {
    fn new(script: impl IntoIterator<Item = Reply>) -> Arc<Scripted> {
        Arc::new(Scripted {
            script: script.into_iter().collect(),
            made: Mutex::new(Vec::new()),
        })
    }

    /// The provider the most recent run talked to.
    fn last(&self) -> Arc<FakeProvider> {
        let made = self.made.lock().unwrap();
        Arc::clone(made.last().expect("a run should have connected a provider"))
    }

    /// Every provider made, in the order the runs connected.
    fn all(&self) -> Vec<Arc<FakeProvider>> {
        self.made.lock().unwrap().clone()
    }

    /// How many runs connected.
    fn runs(&self) -> usize {
        self.made.lock().unwrap().len()
    }
}

#[async_trait::async_trait]
impl ProviderConnector for Scripted {
    async fn connect(
        &self,
        _catalog: &Catalog,
        _agent: &Agent,
        _role: sc_agent::ModelRole,
    ) -> Result<ConnectedModel> {
        let provider = Arc::new(FakeProvider::new(self.script.clone()));
        self.made.lock().unwrap().push(Arc::clone(&provider));
        Ok(ConnectedModel::unconfigured(
            provider as Arc<dyn LlmProvider>,
        ))
    }
}

// --- the world under test ----------------------------------------------------

/// The agent the trigger runs: one grant, to file a summary.
fn summariser() -> Agent {
    Agent::new("summariser", "main")
        .system_prompt("You summarise posts.")
        .with_trait(EnabledTrait::new("insert_row").config("table", "summaries"))
}

/// `run_agent` configured to summarise the row that was just written.
///
/// A **template literal**, not `'…' + row.title`: arithmetic is null-guarded in
/// this language (§7.3), so a concatenation with a null column would compute
/// null and the run would be refused for having nothing to ask.
fn summarise_trigger() -> Trigger {
    Trigger::new("summarise_post", EventKind::Insert, "run_agent")
        .on("posts")
        .config(CFG_AGENT, "summariser")
        .config(
            CFG_PROMPT,
            "`Summarise the post \"${row.title}\": ${row.body}`",
        )
}

/// An environment whose dispatcher can run agents, with `summariser` stored.
async fn setup(script: impl IntoIterator<Item = Reply>) -> Result<(Env, Arc<Scripted>)> {
    let providers = Scripted::new(script);
    let mut actions: ActionRegistry = builtin_actions()?;
    register_agent_actions(
        &mut actions,
        Arc::new(builtin_traits()?),
        Arc::clone(&providers) as Arc<dyn ProviderConnector>,
    )?;
    let env = Env::with_schema(SCHEMA).await?.with_triggers(actions)?;
    save_agent(&env.catalog, &env.registry, &summariser()).await?;
    Ok((env, providers))
}

/// The action registry the dispatcher was built over.
fn registry(env: &Env) -> Arc<ActionRegistry> {
    env.dispatcher.as_ref().expect("a dispatcher").registry()
}

/// The summaries the agent filed, oldest first.
async fn summaries(env: &Env) -> Result<Vec<(String, String)>> {
    let mut rows = env.rows("summaries").await?;
    rows.sort_by_key(|r| r["id"].as_i64().unwrap_or_default());
    Ok(rows
        .iter()
        .map(|r| {
            (
                r["post"].as_str().unwrap_or_default().to_owned(),
                r["summary"].as_str().unwrap_or_default().to_owned(),
            )
        })
        .collect())
}

