//! `run_agent`: an agent as a trigger body, against a real database (TODO Phase
//! 6, §11.5).
//!
//! What is pinned here:
//!
//! - the milestone's **done when** — an insert on a table fires a trigger that
//!   runs an agent, the row's data reaches the prompt (checked where it matters:
//!   in the request the model was actually sent), and the run is readable
//!   afterwards out of `_fd_runs`, which is where the chat panel's history reads
//!   it from;
//! - a triggered run carries the **trigger's authority** (decision 5): its tools
//!   run, its row is written, and the run records no user because nobody was
//!   there;
//! - the action **returns** the final message and the run id rather than
//!   streaming, so a directly-run trigger answers its caller;
//! - and the configuration is checked **on save and on load**: an unknown agent,
//!   a prompt naming something that is not in the event's scope, and an agent
//!   deleted after the trigger was saved, which leaves the trigger out of the
//!   live set with a reason instead of failing when a row is inserted.

