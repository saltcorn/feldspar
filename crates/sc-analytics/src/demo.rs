//! The Analytics UI's demo data (analytics TODO A1.18): a small, deterministic
//! set of tables for trying it — what `feldspar demo analytics [--replace]`
//! makes, and what the milestones' definition-of-done tests run over. Here
//! rather than in the CLI so that a server test can make the same rows; each
//! later milestone adds its tables here (districts and incidents in A5).
//!
//! `neighbourhoods`, `houses` and `viewings` (A1), shaped as the models
//! tutorial (`docs/tutorial-models.md`) has them — so its datasets, models and
//! `predict("House prices")` work over the demo as they do over rows typed by
//! hand — plus the columns the Analytics UI's tutorial reaches for: a year
//! built, and a date for each viewing.
//!
//! `patients` and `measurements` (A2): a blood pressure measured before and
//! after a treatment, for the paired tests, with a treatment that works — a
//! little for the low dose, more for the high one, hardly at all for the
//! placebo. And `events` (A2): a million requests to a web site, generated by
//! one `INSERT … SELECT` over a recursive CTE so that it takes a second or two
//! rather than a million round trips, for a histogram of a large table and a
//! scatter plot that has to sample. The CTE is the same text on Postgres and
//! SQLite: integer arithmetic only (a quadratic hash of the row number, so
//! two columns of it show no lattice when plotted against each other), and a
//! division by `10.0` that both backends round to the same double.
//!
//! **Datasets too.** The Data explorer reads datasets, not tables, so the demo
//! also makes three: `Houses`, `Measurements` (with each patient's treatment
//! and the change in pressure) and `Events`. A dataset of that name that is
//! already there is kept as it is — it may be the admin's own — and the
//! report says so.
//!
//! **Synthetic and deterministic.** Every row comes from a fixed-seed
//! generator, so two runs make the same rows and a tutorial can say what a
//! filter leaves. A price is a linear function of area, bedrooms, the
//! neighbourhood's income and age, plus noise, so a regression over it finds
//! something; about one house in seven is unsold, with no price, for a model
//! to predict.
//!
//! `districts` and `incidents` (A5): twelve districts of an invented city —
//! the Voronoi cells of twelve seeded points, clipped to the city's extent
//! ([`DEMO_EXTENT`]) — and a few thousand incidents, points with a category
//! and a date, gathered around four hot spots over a scattering everywhere,
//! so that a count per district has something to tell. They need PostGIS:
//! where the database has none (SQLite, or Postgres without the extension)
//! the rest of the demo is made and the report says why these two were not
//! ([`DemoReport::skipped`]). Two more datasets, `Districts` and `Incidents`,
//! come with them.
//!
//! **Nothing is touched without `--replace`.** A database that already has one
//! of the demo's tables is refused, naming it: they are ordinary tables, and
//! one of them may be the admin's own. With `--replace`, they are dropped and
//! made again; datasets are never dropped.

