/// Everything the generator needs about the application it is writing a project
/// for, gathered once by the caller (which is the half that has a [`Catalog`]).
///
/// It is a struct rather than six parameters because the two entry points below
/// take the same six, and because each new generated file has wanted one more:
/// `schema.sql` needs the rendered DDL, the README needs the app's subdomain and
/// the mount its custom queries hang off. Everything in it is borrowed and
/// nothing in it is I/O, so the generator stays pure.
///
/// [`Catalog`]: sc_catalog::Catalog
pub struct ProjectContext<'a> {
    /// The project directory within the store (`todo`) — the npm package name
    /// and what the app's paths are derived from.
    pub project: &'a str,
    /// The application this project serves: its name and subdomain go in the
    /// documentation, and its API list decides which mount the `add-query`
    /// command in that documentation names.
    pub app: &'a Application,
    /// The tables the app declares.
    pub tables: &'a [Table],
    /// The app's whole API surface — what the client and hooks are generated
    /// from, and the source of truth for which tables the project may talk to.
    pub endpoints: &'a EndpointSet,
    /// Its GraphQL projection, for an app that enables the provider.
    pub graphql: Option<&'a AppGraphql>,
    /// The streams the app exposes, typed (TODO "Streams" §10).
    ///
    /// Beside the endpoints rather than in them — a subscription is not a
    /// request/response pair — and carried for the reason `schema_sql` is:
    /// resolving a stream needs the [`Catalog`] this generator does not have.
    ///
    /// [`Catalog`]: sc_catalog::Catalog
    pub streams: &'a [StreamExport],
    /// The `CREATE TABLE` statements for [`tables`](ProjectContext::tables), as
    /// the **driver** renders them
    /// ([`app_schema_sql`](crate::app_schema_sql)).
    pub schema_sql: &'a str,
    /// Where this deployment serves its applications
    /// ([`Catalog::public_origin`](sc_catalog::Catalog::public_origin)), so the
    /// documentation can name the URL to open rather than describing one.
    ///
    /// `None` when this process was not told the base domain — a server started
    /// without one serves no applications at all — and the documentation then
    /// says what to substitute.
    pub origin: Option<PublicOrigin>,
    /// The application's `SKILL.md`, generated by
    /// [`generate_skill`](crate::generate_skill).
    ///
    /// Carried rather than generated here for the reason `schema_sql` is: it is
    /// read off the live tool surface, which needs the [`Catalog`] this
    /// generator deliberately does not have.
    ///
    /// [`Catalog`]: sc_catalog::Catalog
    pub skill: &'a str,
    /// This installation's roles, most privileged first
    /// ([`list_roles`](sc_auth::list_roles)).
    ///
    /// The documentation names them because `feldspar auth token --role NAME`
    /// takes one, and a reader inside a project directory has no other way to
    /// find out what this server calls its roles. Not a contract — an admin may
    /// add or rename one tomorrow — which is why the generated README says when
    /// the list was taken.
    pub roles: &'a [Role],
}

impl ProjectContext<'_> {
    /// What the project calls itself: the npm package name, the `<title>` and the
    /// header the app comes up with.
    ///
    /// The project directory when there is one, and the app's **subdomain** when
    /// the project is the store root (see
    /// [`CFG_PROJECT`](crate::react::CFG_PROJECT)). A `package.json` with an empty
    /// `name` is one npm refuses to install, so the blank directory needs a name
    /// from somewhere — and the subdomain is the app's other machine-readable
    /// identity, already a DNS label and so already a legal package name, unlike
    /// [`Application::name`](crate::Application::name) (`"My Blog"`).
    pub(super) fn project_name(&self) -> &str {
        if !self.project.is_empty() {
            return self.project;
        }
        if !self.app.subdomain.is_empty() {
            return &self.app.subdomain;
        }
        "app"
    }

    /// The mount custom SQL queries are added to — the app's REST API, the one
    /// provider that serves them (§13.4).
    ///
    /// `None` for an app with no REST API: the documentation then spells the
    /// command without `--api`, which is also the form the CLI wants when there
    /// is nothing to disambiguate.
    fn query_mount(&self) -> Option<&str> {
        self.app
            .apis
            .iter()
            .find(|a| a.provider == sc_api::REST_PROVIDER)
            .map(|a| a.mount.as_str())
    }

    /// The URL this application is served at, written out — or, when this
    /// process was never told the base domain, a placeholder naming the one
    /// thing the reader has to substitute.
    ///
    /// Never a guess. A generated document that said `http://localhost:3032`
    /// because that is the usual answer would be wrong on every deployment that
    /// is not this one, and wrong in the file a reader trusts most.
    pub(super) fn app_url_or_placeholder(&self) -> String {
        match &self.origin {
            Some(origin) => origin.url_for(&self.app.subdomain),
            None => format!("http://{}.<the server's base domain>", self.app.subdomain),
        }
    }

    /// The base domain this deployment serves its applications under, when the
    /// process that wrote this document was told one.
    fn base_domain(&self) -> Option<&str> {
        self.origin.as_ref().map(|o| o.base_domain.as_str())
    }

    /// The roles as one line: `Admin (1), Editor (40), Public (100)`.
    fn role_line(&self) -> String {
        self.roles
            .iter()
            .map(|r| format!("{} ({})", r.name, r.role))
            .collect::<Vec<_>>()
            .join(", ")
    }

    /// The roles as a bullet list, each with the number every `min_role` is
    /// written in and whatever the admin wrote about it.
    fn role_bullets(&self) -> String {
        self.roles
            .iter()
            .map(|r| {
                let description = if r.description.trim().is_empty() {
                    String::new()
                } else {
                    format!(" — {}", r.description.trim())
                };
                format!("- **`{}`** (role {}){description}\n", r.name, r.role)
            })
            .collect()
    }

    /// The name this installation gives the admin role — `Admin` unless somebody
    /// renamed it, which they are allowed to do.
    fn admin_role_name(&self) -> &str {
        self.roles
            .iter()
            .find(|r| r.role == ROLE_ADMIN)
            .map_or("Admin", |r| r.name.as_str())
    }

    /// The sentence after the URL: nothing when it is the real one, and where to
    /// find the missing piece when it is not.
    fn origin_note(&self) -> &'static str {
        match self.origin {
            Some(_) => "",
            None => {
                " — the server that generated this was started without a \
                     `--base-domain`, so substitute the base domain of the one \
                     serving it"
            }
        }
    }
}

/// The files under `src/feldspar/`: the typed client, the typed hooks, the
/// schema of the tables the app declares, the README that says what this
/// directory is — and, for an app that enables the GraphQL provider, its client
/// and its schema.
///
/// Emitted by the scaffold *and* by every subsequent build, which is what keeps
/// them honest when the app's tables change. The GraphQL schema is written
/// **only** for an app that enables the provider: an app without one has no
/// GraphQL contract, and a `schema.graphql` sitting in its tree describing an API
/// it does not serve would be a lie its editor believed.
pub fn runtime_files(ctx: &ProjectContext<'_>) -> Vec<GeneratedFile> {
    let mut files = vec![
        GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/hooks.ts"),
            hooks_ts(ctx.tables, ctx.endpoints),
        ),
        GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/store.ts"),
            store_ts(ctx.tables, ctx.endpoints),
        ),
        GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/{RUNTIME_I18N_FILE}"),
            format!("{GENERATED_HEADER}{I18N_TSX}"),
        ),
        GeneratedFile::new(
            format!("{REACT_RUNTIME_SUBDIR}/{RUNTIME_README_FILE}"),
            runtime_readme(ctx),
        ),
    ];
    files.extend(common_runtime_files(
        ctx,
        REACT_RUNTIME_SUBDIR,
        REACT_CLIENT_FILE,
    ));
    files
}

/// The half of the generated runtime that is **not** the framework's: the typed
/// client, the helper it imports, the schema of the tables the app declares, the
/// map of the administrative half — and, for an app that enables the GraphQL
/// provider, its client and its schema.
///
/// Split out from [`runtime_files`] because a framework declared by a module
/// needs exactly these files and must not write them itself. Every one of them is
/// generated from the application's own [`EndpointSet`] by the same generator the
/// admin SPA's client comes from; a module reproducing that would be a module
/// free to disagree with this server about this server's API, and the disagreement
/// would surface as a project that does not compile against its own client.
///
/// `runtime` is the directory they go in, relative to the **project**, and
/// `client_file` what the client is called in it — both the framework's, so a
/// declared one can put its generated code where its own conventions expect.
///
/// The GraphQL schema is written **only** for an app that enables the provider:
/// an app without one has no GraphQL contract, and a `schema.graphql` sitting in
/// its tree describing an API it does not serve would be a lie its editor
/// believed.
pub fn common_runtime_files(
    ctx: &ProjectContext<'_>,
    runtime: &str,
    client_file: &str,
) -> Vec<GeneratedFile> {
    let at = |name: &str| {
        if runtime.is_empty() {
            name.to_owned()
        } else {
            format!("{runtime}/{name}")
        }
    };
    let mut files = vec![
        GeneratedFile::new(
            at(client_file),
            generate_client_with_streams(ctx.endpoints, ctx.streams),
        ),
        GeneratedFile::new(at(CLIENT_HELPER_FILE), client_helper()),
        GeneratedFile::new(
            at(RUNTIME_SCHEMA_FILE),
            format!("{GENERATED_SQL_HEADER}{}", ctx.schema_sql),
        ),
        GeneratedFile::new(at(RUNTIME_MESSAGES_FILE), messages_ts(ctx)),
        GeneratedFile::new(at(RUNTIME_SKILL_FILE), ctx.skill.to_owned()),
    ];
    if let Some(graphql) = ctx.graphql {
        files.push(GeneratedFile::new(
            at(GRAPHQL_CLIENT_FILE),
            generate_graphql_client(&graphql.mount),
        ));
        files.push(GeneratedFile::new(
            at(GRAPHQL_SCHEMA_FILE),
            format!("{GENERATED_SDL_HEADER}{}", graphql.sdl),
        ));
    }
    files
}

/// The tables the generated project may have pages and hooks for: those the
/// app's API actually exposes.
///
/// **The endpoint set is the source of truth, not the table list**, and the
/// difference is not academic. An application declares tables *and* API
/// providers; a table it declares but does not expose has no `listTasks` on the
/// generated client, so a page calling one would not compile — which is exactly
/// what a real app hit. Deriving "what can this project talk to?" from the same
/// value the client is generated from makes that class of mismatch unable to
/// occur, where re-deriving it from the tables only made the two agree *by
/// coincidence* while they happened to be computed the same way.
pub(super) fn exposed_tables<'a>(tables: &'a [Table], endpoints: &EndpointSet) -> Vec<&'a Table> {
    tables
        .iter()
        .filter(|t| endpoints.find(&op_name("list", &t.name)).is_some())
        .collect()
}

/// Whether this application can sign anyone in.
///
/// The name of the endpoint an application that offers sign-up projects.
const SIGNUP_ENDPOINT: &str = "signup";

/// The invitation endpoint, projected where the REST settings allow it.
const INVITE_ENDPOINT: &str = "invite";

/// The scaffold's auth layer is generated code calling `login` / `logout` /
/// `whoami` through the typed client, so it can only exist when the application
/// exposes them — which today means the REST provider (§13.4). An app that does
/// not gets the anonymous shell instead of a login screen whose three calls do
/// not compile: **authenticated by default** (§13.3) is a statement about a
/// scaffold's *routes*, and it cannot lock a door that has no key.
///
/// All three or none: a partial set is a provider having changed under us, and
/// generating half an auth layer against it is how you get the error this branch
/// exists to prevent.
pub fn has_auth(endpoints: &EndpointSet) -> bool {
    sc_api::AUTH_ENDPOINTS
        .iter()
        .all(|name| endpoints.find(name).is_some())
}

/// The whole project: the runtime plus everything written once.
pub fn project_files(ctx: &ProjectContext<'_>) -> Vec<GeneratedFile> {
    let project = ctx.project_name();
    let exposed = exposed_tables(ctx.tables, ctx.endpoints);
    let auth = has_auth(ctx.endpoints);
    let mut files = vec![
        GeneratedFile::new("package.json", package_json(project)),
        GeneratedFile::new("vite.config.ts", VITE_CONFIG),
        GeneratedFile::new("tsconfig.json", tsconfig(ctx.graphql.is_some())),
        GeneratedFile::new("index.html", index_html(project)),
        GeneratedFile::new(".gitignore", GITIGNORE),
        // The project root's, not the generated directory's: written here and
        // never again, because the developer and their agents own it.
        GeneratedFile::new(AGENTS_FILE, agents_md(ctx)),
        GeneratedFile::new(CLAUDE_FILE, format!("@{AGENTS_FILE}\n")),
        GeneratedFile::new("src/main.tsx", main_tsx(auth)),
        GeneratedFile::new("src/App.tsx", app_tsx(project, auth)),
        GeneratedFile::new("src/routes.tsx", routes_tsx(&exposed, auth)),
        GeneratedFile::new("src/app.css", APP_CSS),
    ];
    if auth {
        files.push(GeneratedFile::new("src/auth.tsx", AUTH_TSX));
        files.push(GeneratedFile::new("src/Login.tsx", LOGIN_TSX));
        files.push(GeneratedFile::new("src/SetPassword.tsx", SET_PASSWORD_TSX));
    }
    for table in &exposed {
        files.push(GeneratedFile::new(
            format!("src/pages/{}.tsx", pascal(&table.name)),
            page_tsx(table, ctx.endpoints),
        ));
    }
    files.extend(runtime_files(ctx));
    files
}

