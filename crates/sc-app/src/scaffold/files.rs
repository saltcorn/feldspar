//! The files a scaffolded React project is made of (TODO §2.3).
//!
//! Every function here is **pure**: table metadata and an endpoint set in, file
//! contents out. Nothing touches a file store, so the whole generator is
//! assertable in unit tests, and the store-writing half ([`super`]) has no
//! templates in it.
//!
//! Two kinds of file come out, and the difference is load-bearing (§2.1):
//!
//! - **Generated runtime** under `src/feldspar/` — the typed client and the hooks
//!   over it, plus the GraphQL client and schema of an app that enables that
//!   provider. Rewritten on every build, so a table added later shows up in the
//!   types. Carries a "DO NOT EDIT" header because it means it.
//! - **The project itself** — `package.json`, the Vite/TS config, the app shell,
//!   the login screen, the routes and one page per table. Written **once**, at
//!   scaffold time, and never touched again. This is the admin's code from the
//!   moment it exists, which is why it is generated against their *actual*
//!   tables: a scaffold that comes up showing a placeholder counter is a
//!   template, while one that comes up showing their rows is a working app they
//!   can edit.
//!
//! The shell comes in two shapes, decided by [`has_auth`]: the authenticated one
//! §13.3 describes, and — for an application that exposes no auth endpoints — an
//! anonymous one with no auth layer at all.

